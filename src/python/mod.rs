#[derive(Debug)]
struct PythonReference {
    module_path: String,
    type_ref: String,
}

fn message_python_ref(type_info: &PlannedTypeInfo) -> Option<PythonReference> {
    let module_path =
        python_module_path_for_file_name(type_info.file_name.as_deref(), &type_info.package)?;
    let relative_name = relative_descriptor_name(&type_info.full_name, &type_info.package);
    Some(PythonReference {
        type_ref: format!("{module_path}.{relative_name}"),
        module_path,
    })
}

fn enum_python_ref(type_info: &PlannedTypeInfo) -> Option<PythonReference> {
    let module_path =
        python_module_path_for_file_name(type_info.file_name.as_deref(), &type_info.package)?;
    let relative_name = relative_descriptor_name(&type_info.full_name, &type_info.package);
    Some(PythonReference {
        type_ref: format!("{module_path}.{relative_name}.ValueType"),
        module_path,
    })
}

fn python_module_path_for_file_name(file_name: Option<&str>, package: &str) -> Option<String> {
    if let Some(file_name) = file_name {
        let mut module_path = file_name.replace('/', ".");
        if let Some(stripped) = module_path.strip_suffix(".proto") {
            module_path = format!("{stripped}_pb2");
        }
        if let Some(suffix) = module_path.strip_prefix("temporal.") {
            module_path = format!("temporalio.{suffix}");
        }
        return Some(module_path);
    }

    if package.is_empty() {
        None
    } else if let Some(suffix) = package.strip_prefix("temporal.") {
        Some(format!("temporalio.{suffix}"))
    } else {
        Some(package.to_string())
    }
}

fn render_package(
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    services: &[RenderedService<'_>],
    support_fragments: &[SupportFragmentSpec],
    language_imports: &[LanguageImportSpec],
) -> Result<GeneratedFiles> {
    let mut files = BTreeMap::new();
    render_support_package(&mut files, support_fragments)?;
    let model_names = enums
        .iter()
        .map(|enumeration| enumeration.name.clone())
        .chain(flags.iter().map(|flag_set| flag_set.name.clone()))
        .chain(variants.iter().map(|variant| variant.name.clone()))
        .chain(models.iter().map(|model| model.name.clone()))
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let resource_operation_owners = resource_operation_owners(services);
    let resource_names = services
        .iter()
        .flat_map(|service| {
            service
                .resources
                .iter()
                .map(|resource| resource.type_name.clone())
        })
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let support_names = support_export_names(support_fragments);

    insert_generated_file(
        &mut files,
        "__init__.py",
        render_package_init(services, &resource_names, &resource_operation_owners),
    )?;
    insert_generated_file(
        &mut files,
        "models.py",
        render_models_module(
            enums,
            flags,
            variants,
            models,
            &support_names,
            language_imports,
        ),
    )?;
    insert_generated_file(
        &mut files,
        "_resources/__init__.py",
        render_resources_package_init(services),
    )?;
    insert_generated_file(&mut files, "service.py", render_service_module(services))?;
    insert_generated_file(
        &mut files,
        "operations/__init__.py",
        render_operations_package_init(),
    )?;

    for service in services {
        for resource in &service.resources {
            let bound_operations = resource_bound_operations(service, resource);
            insert_generated_file(
                &mut files,
                format!("_resources/{}.py", resource_module_name(resource)),
                render_resource_module_file(
                    service,
                    resource,
                    &bound_operations,
                    &model_names,
                    &resource_names,
                    &support_names,
                    language_imports,
                ),
            )?;
        }
        for operation in &service.operations {
            if resource_operation_owners.contains_key(&operation_key(service.name, operation.name))
            {
                continue;
            }
            insert_generated_file(
                &mut files,
                format!("operations/{}.py", operation.attr_name),
                render_operation_module(
                    service,
                    operation,
                    &model_names,
                    &resource_names,
                    &support_names,
                    language_imports,
                ),
            )?;
        }
    }

    Ok(GeneratedFiles::directory(files))
}

fn operation_key(service_name: &str, operation_name: &str) -> String {
    format!("{service_name}::{operation_name}")
}

fn python_resource_type_id(service: &RenderedService<'_>, resource: &PlannedResource) -> String {
    format!("{}::resource::{}", service.name, resource.name)
}

fn resource_module_name(resource: &PlannedResource) -> String {
    python_ident(&resource.name.to_snake_case())
}

fn resource_operation_owners(services: &[RenderedService<'_>]) -> BTreeMap<String, String> {
    let mut owners = BTreeMap::new();
    for service in services {
        for resource in &service.resources {
            let resource_module = resource_module_name(resource);
            for method in &resource.methods {
                if let PlannedResourceMethodBindingSpec::Operation { operation_name, .. } =
                    &method.binding
                {
                    owners.insert(
                        operation_key(service.name, operation_name),
                        resource_module.clone(),
                    );
                }
            }
        }
    }
    owners
}

fn insert_generated_file(
    files: &mut BTreeMap<std::path::PathBuf, String>,
    path: impl Into<std::path::PathBuf>,
    contents: String,
) -> Result<()> {
    let path = path.into();
    if files.insert(path.clone(), contents).is_some() {
        return Err(Error::GeneratedFileConflict { path });
    }
    Ok(())
}

fn render_support_package(
    files: &mut BTreeMap<std::path::PathBuf, String>,
    support_fragments: &[SupportFragmentSpec],
) -> Result<Vec<String>> {
    let mut module_names = Vec::new();
    for fragment in support_fragments {
        let module_name = support_module_name(fragment)?;
        insert_generated_file(
            files,
            format!("_support/{module_name}.py"),
            fragment.contents.clone(),
        )?;
        module_names.push(module_name);
    }

    if !module_names.is_empty() {
        let mut output = String::new();
        render_generated_file_header(&mut output);
        output.push('\n');
        for module_name in &module_names {
            output.push_str("from .");
            output.push_str(module_name);
            output.push_str(" import *  # noqa: F401,F403\n");
        }
        insert_generated_file(files, "_support/__init__.py", output)?;
    }

    Ok(module_names)
}

fn support_module_name(fragment: &SupportFragmentSpec) -> Result<String> {
    let path = Path::new(&fragment.path);
    let Some(file_name) = path.file_name() else {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support path must have a file name".to_string(),
        });
    };
    let Some(file_name) = file_name.to_str() else {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support path must be valid UTF-8".to_string(),
        });
    };
    let Some(module_name) = Path::new(file_name).file_stem() else {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support path must have a module stem".to_string(),
        });
    };
    let Some(module_name) = module_name.to_str() else {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support path must be valid UTF-8".to_string(),
        });
    };
    if Path::new(file_name)
        .extension()
        .and_then(|extension| extension.to_str())
        != Some("py")
    {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "Python support files must end with `.py`".to_string(),
        });
    }
    if module_name.is_empty() {
        return Err(Error::InvalidGeneratedPath {
            path: path.to_path_buf(),
            reason: "support module name cannot be empty".to_string(),
        });
    }
    Ok(module_name.to_string())
}

fn render_generated_file_header(output: &mut String) {
    output.push_str(GENERATED_HEADER);
    output.push_str("\n# pyright: reportAny=false");
    output.push_str("\n\n");
    output.push_str("from __future__ import annotations\n");
}

