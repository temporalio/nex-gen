fn function_type_parameters(
    functions: &[RenderedFunctionField],
    output_type_parameters: &BTreeSet<String>,
) -> Vec<PythonTypeParameter> {
    let mut parameters = BTreeSet::new();
    for function in functions {
        for case in function_overload_cases(function, output_type_parameters) {
            parameters.extend(case.type_parameters);
        }
    }
    parameters.into_iter().collect()
}

fn render_function_type_parameter_definitions(
    output: &mut String,
    functions: &[RenderedFunctionField],
    output_type_parameters: &BTreeSet<String>,
) {
    let parameters = function_type_parameters(functions, output_type_parameters);
    if parameters.is_empty() {
        return;
    }

    for parameter in parameters {
        match parameter {
            PythonTypeParameter::TypeVar(name) => {
                output.push_str(&name);
                output.push_str(" = typing.TypeVar(");
                output.push_str(&python_string_literal(&name));
                output.push_str(")\n");
            }
            PythonTypeParameter::TypeVarTuple(name) => {
                output.push_str(&name);
                output.push_str(" = typing_extensions.TypeVarTuple(");
                output.push_str(&python_string_literal(&name));
                output.push_str(")\n");
            }
        }
    }
}

fn render_package_init(
    services: &[RenderedService<'_>],
    resource_names: &[String],
    resource_operation_owners: &BTreeMap<String, String>,
) -> String {
    let operation_function_names = services
        .iter()
        .flat_map(|service| {
            service
                .operations
                .iter()
                .map(|operation| operation.attr_name.clone())
        })
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let public_names = std::iter::once("models".to_string())
        .chain(resource_names.iter().cloned())
        .chain(operation_function_names.iter().cloned())
        .collect::<Vec<_>>();
    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    if !services.is_empty() {
        output.push_str("from . import service as _service\n");
    }
    output.push_str("from . import models\n");
    render_named_python_import(&mut output, "._resources", resource_names);
    if !services.is_empty() {
        for service in services {
            for operation in &service.operations {
                let imports = vec![operation.attr_name.clone()];
                let module = if let Some(resource_owner) =
                    resource_operation_owners.get(&operation_key(service.name, operation.name))
                {
                    format!("._resources.{resource_owner}")
                } else {
                    format!(".operations.{}", operation.attr_name)
                };
                render_named_python_import(&mut output, &module, &imports);
            }
        }
    }
    output.push_str("\n__all__ = [\n");
    for name in &public_names {
        output.push_str("    ");
        output.push_str(&python_string_literal(name));
        output.push_str(",\n");
    }
    output.push_str("    \"__nexus_operation_registry__\",\n");
    output.push_str("]\n");
    output.push_str("\n\n__nexus_operation_registry__ = {\n");
    for service in services {
        for operation in &service.operations {
            output.push_str("    (\n");
            output.push_str("        \"");
            output.push_str(service.name);
            output.push_str("\",\n");
            output.push_str("        \"");
            output.push_str(operation.wire_name);
            output.push_str("\",\n");
            output.push_str("    ): ");
            output.push_str("_service.");
            output.push_str(service.name);
            output.push('.');
            output.push_str(&operation.attr_name);
            output.push_str(",\n");
        }
    }
    output.push_str("}\n");
    output
}

fn render_service_definition(output: &mut String, service: &RenderedService<'_>) {
    output.push_str("@service\n");
    output.push_str("class ");
    output.push_str(service.name);
    output.push_str(":\n");

    if service.operations.is_empty() {
        output.push_str("    pass\n");
        return;
    }

    for (operation_index, operation) in service.operations.iter().enumerate() {
        output.push_str("    ");
        output.push_str(&operation.attr_name);
        output.push_str(": Operation[\n");
        output.push_str("        ");
        output.push_str(&service_type_ref(&operation.input_ref));
        output.push_str(",\n");
        output.push_str("        ");
        output.push_str(&service_type_ref(&operation.output_ref));
        output.push_str(",\n");
        output.push_str("    ] = Operation(name=");
        output.push_str(&python_string_literal(operation.wire_name));
        output.push_str(")\n");

        if operation_index + 1 != service.operations.len() {
            output.push('\n');
        }
    }
}

fn service_type_ref(type_ref: &str) -> String {
    type_ref
        .strip_prefix("models.")
        .unwrap_or(type_ref)
        .to_string()
}

fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("class ");
    output.push_str(&enumeration.name);
    output.push_str("(enum.IntEnum):\n");

    if enumeration.values.is_empty() {
        output.push_str("    pass\n");
        return;
    }

    for value in &enumeration.values {
        output.push_str("    ");
        output.push_str(&value.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push('\n');
    }
}

fn render_flags(output: &mut String, flags: &RenderedFlags) {
    output.push_str("class ");
    output.push_str(&flags.name);
    output.push_str("(enum.IntFlag):\n");

    if flags.flags.is_empty() {
        output.push_str("    pass\n");
        return;
    }

    for flag in &flags.flags {
        output.push_str("    ");
        output.push_str(&flag.name);
        output.push_str(" = 1 << ");
        output.push_str(&flag.bit.to_string());
        output.push('\n');
    }
}

fn render_variant(output: &mut String, variant: &RenderedVariant) {
    output.push_str(variant.name.as_str());
    output.push_str(" = ");
    if variant.cases.is_empty() {
        output.push_str("typing.Never\n");
        return;
    }
    if variant.cases.len() > 1 {
        output.push_str("(\n    ");
    }
    for (index, case) in variant.cases.iter().enumerate() {
        if index > 0 {
            output.push_str("\n    | ");
        }
        output.push_str("tuple[typing.Literal[");
        output.push_str(&python_string_literal(&case.name));
        output.push(']');
        if let Some(payload_annotation) = &case.payload_annotation {
            output.push_str(", ");
            output.push_str(payload_annotation);
        }
        output.push(']');
    }
    if variant.cases.len() > 1 {
        output.push_str("\n)");
    }
    output.push('\n');
}

fn render_model(output: &mut String, model: &RenderedModel) {
    if model_needs_keyword_only_dataclass(model) {
        output.push_str("@dataclasses.dataclass(slots=True, kw_only=True)\n");
    } else {
        output.push_str("@dataclasses.dataclass(slots=True)\n");
    }
    output.push_str("class ");
    output.push_str(&model.name);
    output.push_str(":\n");

    if model.fields.is_empty() {
        let mut wrote_method = false;
        if model.capabilities.from_proto {
            let proto_ref = model
                .proto_ref
                .as_deref()
                .expect("from_proto models should have a proto reference");
            output.push_str("    @classmethod\n");
            output.push_str("    def from_proto(\n");
            output.push_str("        cls,\n");
            output.push_str("        _proto: ");
            output.push_str(proto_ref);
            output.push_str(",\n");
            output.push_str("    ) -> ");
            output.push_str(&model.name);
            output.push_str(":\n");
            output.push_str("        return cls()\n");
            wrote_method = true;
        }
        if model.capabilities.to_proto {
            let proto_ref = model
                .proto_ref
                .as_deref()
                .expect("to_proto models should have a proto reference");
            if wrote_method {
                output.push('\n');
            }
            output.push_str("    def to_proto(self) -> ");
            output.push_str(proto_ref);
            output.push_str(":\n");
            output.push_str("        message = ");
            output.push_str(proto_ref);
            output.push_str("()\n");
            for field in &model.sourced_fields {
                for line in &field.to_proto_lines {
                    output.push_str("        ");
                    output.push_str(line);
                    output.push('\n');
                }
            }
            output.push_str("        return message\n");
        }
        if !wrote_method && !model.capabilities.to_proto {
            output.push_str("    pass\n");
        }
        return;
    }

    for field in &model.fields {
        output.push_str("    ");
        output.push_str(&field.attr_name);
        output.push_str(": ");
        output.push_str(&python_parameter_annotation(
            &field.annotation,
            &field.default_kind,
        ));
        if let Some(default_expr) = &field.default_expr {
            render_python_default_expr(output, default_expr, "    ");
        }
        output.push('\n');
    }

    let mut wrote_method = false;
    if model.capabilities.from_proto {
        let proto_ref = model
            .proto_ref
            .as_deref()
            .expect("from_proto models should have a proto reference");
        output.push_str("\n");
        output.push_str("    @classmethod\n");
        output.push_str("    def from_proto(\n");
        output.push_str("        cls,\n");
        output.push_str("        proto: ");
        output.push_str(proto_ref);
        output.push_str(",\n");
        output.push_str("    ) -> ");
        output.push_str(&model.name);
        output.push_str(":\n");

        for field in &model.fields {
            for line in &field.from_proto_setup_lines {
                output.push_str("        ");
                output.push_str(line);
                output.push('\n');
            }
        }

        output.push_str("        return cls(\n");
        for field in &model.fields {
            output.push_str("            ");
            output.push_str(&field.attr_name);
            output.push_str("=");
            output.push_str(&field.from_proto_expr);
            output.push_str(",\n");
        }
        output.push_str("        )\n");
        wrote_method = true;
    }
    if model.capabilities.to_proto {
        let proto_ref = model
            .proto_ref
            .as_deref()
            .expect("to_proto models should have a proto reference");
        output.push_str("\n");
        if wrote_method {
            output.push('\n');
        }
        output.push_str("    def to_proto(self) -> ");
        output.push_str(proto_ref);
        output.push_str(":\n");
        output.push_str("        message = ");
        output.push_str(proto_ref);
        output.push_str("()\n");
        for field in &model.fields {
            for line in &field.to_proto_lines {
                output.push_str("        ");
                output.push_str(line);
                output.push('\n');
            }
        }
        for field in &model.sourced_fields {
            for line in &field.to_proto_lines {
                output.push_str("        ");
                output.push_str(line);
                output.push('\n');
            }
        }
        output.push_str("        return message\n");
    }
}

fn model_needs_keyword_only_dataclass(model: &RenderedModel) -> bool {
    let mut saw_defaulted_field = false;
    for field in &model.fields {
        if field.default_expr.is_some() {
            saw_defaulted_field = true;
        } else if saw_defaulted_field {
            return true;
        }
    }
    false
}

fn render_resource(
    output: &mut String,
    resource: &PlannedResource,
    bound_operations: &[ResourceBoundOperation<'_>],
) {
    output.push_str("@dataclasses.dataclass\n");
    output.push_str("class ");
    output.push_str(&resource.type_name);
    output.push_str(":\n");
    for field in &resource.fields {
        output.push_str("    ");
        output.push_str(&python_field_name(&field.name));
        output.push_str(": ");
        output.push_str(&python_resource_field_annotation(
            &field.kind,
            field.optional,
            field.function.as_ref(),
        ));
        output.push('\n');
    }

    if resource.methods.is_empty() {
        output.push_str("\n    pass\n");
        return;
    }

    for method in &resource.methods {
        output.push_str("\n");
        render_resource_class_method(output, resource, method, bound_operations);
    }
}

fn render_resource_class_method(
    output: &mut String,
    resource: &PlannedResource,
    method: &PlannedResourceMethod,
    bound_operations: &[ResourceBoundOperation<'_>],
) {
    let result_annotation = python_resource_method_result_annotation(method);
    output.push_str("    async def ");
    output.push_str(&python_field_name(&method.name));
    output.push_str("(\n");
    output.push_str("        self,\n");
    for param in &method.params {
        output.push_str("        ");
        output.push_str(&python_field_name(&param.name));
        output.push_str(": ");
        output.push_str(&python_resource_field_annotation(
            &param.kind,
            param.optional,
            param.function.as_ref(),
        ));
        if param.optional {
            output.push_str(" = None");
        }
        output.push_str(",\n");
    }
    output.push_str("    ) -> ");
    output.push_str(&result_annotation);
    output.push_str(":\n");

    match &method.binding {
        PlannedResourceMethodBindingSpec::Operation { operation_name, .. } => {
            let operation = bound_operations
                .iter()
                .find(|bound_operation| bound_operation.operation.name == operation_name)
                .map(|bound_operation| bound_operation.operation)
                .expect("bound resource operation should be rendered in the same module");
            render_resource_method_operation_body(output, method, operation);
        }
        PlannedResourceMethodBindingSpec::Stub => {
            output.push_str("        raise NotImplementedError(");
            output.push_str(&python_string_literal(&format!(
                "{}.{} is not yet implemented",
                resource.name,
                python_field_name(&method.name)
            )));
            output.push_str(")\n");
        }
    }
}

fn render_resource_method_operation_body(
    output: &mut String,
    method: &PlannedResourceMethod,
    operation: &RenderedOperation<'_>,
) {
    let result_annotation = python_resource_method_result_annotation(method);
    let PlannedResourceMethodBindingSpec::Operation {
        request_plan,
        direct_return,
        ..
    } = &method.binding
    else {
        return;
    };

    let operation_attr_name = request_operation_function_name(operation);
    let request_expr = render_request_plan_python(request_plan);
    output.push_str("        request = ");
    if let Some(unpacked_input) = &operation.unpacked_input {
        output.push_str(&unpacked_input.model_name);
    } else {
        output.push_str(&operation.input_annotation);
    }
    output.push_str("(\n");
    match request_plan {
        RequestPlan::Construct { fields, .. } => {
            for field in fields {
                output.push_str("            ");
                output.push_str(&python_field_name(&field.field_name));
                output.push('=');
                output.push_str(&render_request_plan_python(&field.value));
                output.push_str(",\n");
            }
        }
        RequestPlan::Source(_) => {
            output.push_str("            value=");
            output.push_str(&request_expr);
            output.push_str(",\n");
        }
    }
    output.push_str("        )\n");
    if *direct_return {
        if result_annotation == "None" {
            output.push_str("        await ");
            output.push_str(&operation_attr_name);
            output.push_str("(request)\n");
        } else {
            output.push_str("        return await ");
            output.push_str(&operation_attr_name);
            output.push_str("(request)\n");
        }
    } else {
        output.push_str("        handle = await ");
        output.push_str(&operation_attr_name);
        output.push_str("(request)\n");
        if result_annotation == "None" {
            output.push_str("        await handle\n");
        } else {
            output.push_str("        return await handle\n");
        }
    }
}

fn python_resource_method_result_annotation(method: &PlannedResourceMethod) -> String {
    let Some(result) = &method.result else {
        return "None".to_string();
    };
    let annotation = match &result.kind {
        PlannedResourceMethodResultKind::Resource { type_name } => type_name.clone(),
        PlannedResourceMethodResultKind::Value(kind) => {
            python_resource_field_annotation(kind, result.optional, None)
        }
    };
    if result.optional && !annotation.contains("| None") {
        format!("{annotation} | None")
    } else {
        annotation
    }
}

fn python_resource_field_annotation(
    kind: &PlannedFieldKind,
    optional: bool,
    function: Option<&FunctionFieldSpec>,
) -> String {
    let base = if let Some(function) = function {
        python_function_field_annotation(
            function,
            function
                .alternate_type
                .as_ref()
                .map(python_authored_type_annotation),
        )
    } else {
        match kind {
            PlannedFieldKind::Singular(value) => python_resource_value_annotation(value),
            PlannedFieldKind::Repeated(value) => {
                format!(
                    "collections.abc.Sequence[{}]",
                    python_resource_value_annotation(value)
                )
            }
            PlannedFieldKind::Map { key, value } => format!(
                "collections.abc.Mapping[{}, {}]",
                python_resource_value_annotation(key),
                python_resource_value_annotation(value)
            ),
        }
    };
    if optional {
        format!("{base} | None")
    } else {
        base
    }
}

fn python_resource_value_annotation(value: &PlannedValueType) -> String {
    match value {
        PlannedValueType::Scalar(PlannedScalarType::Float) => "float".to_string(),
        PlannedValueType::Scalar(PlannedScalarType::Int32 | PlannedScalarType::Int64) => {
            "int".to_string()
        }
        PlannedValueType::Scalar(PlannedScalarType::Bool) => "bool".to_string(),
        PlannedValueType::Scalar(PlannedScalarType::String) => "str".to_string(),
        PlannedValueType::Scalar(PlannedScalarType::Bytes) => "bytes".to_string(),
        PlannedValueType::Enum(enum_type) => enum_type
            .replacement
            .as_ref()
            .and_then(python_replacement_type_name)
            .or_else(|| enum_type.name.clone())
            .unwrap_or_else(|| "int".to_string()),
        PlannedValueType::Flags(flags_type) => flags_type.name.clone(),
        PlannedValueType::Variant(variant_type) => variant_type.name.clone(),
        PlannedValueType::Message(message_type) => message_type
            .replacement
            .as_ref()
            .and_then(python_replacement_type_name)
            .unwrap_or_else(|| message_type.model_name.clone()),
        PlannedValueType::Tuple(items) => format!(
            "tuple[{}]",
            items
                .iter()
                .map(python_resource_value_annotation)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        PlannedValueType::Result { ok, err } => python_result_annotation(
            ok.as_ref()
                .map(|ok| python_resource_value_annotation(ok).to_string()),
            err.as_ref()
                .map(|err| python_resource_value_annotation(err).to_string()),
        ),
        PlannedValueType::External {
            type_name,
            fallback,
        } => type_name
            .for_language(Language::Python)
            .map(str::to_string)
            .unwrap_or_else(|| python_resource_value_annotation(fallback)),
        PlannedValueType::Unknown => "object".to_string(),
    }
}

fn render_request_plan_python(plan: &RequestPlan) -> String {
    render_request_plan(
        plan,
        python_field_name,
        |name, value| format!("{name}={value}"),
        |message_name, fields| {
            let model_name = message_model_name(message_name);
            if fields.is_empty() {
                format!("{model_name}()")
            } else {
                format!("{model_name}({})", fields.join(", "))
            }
        },
        |name| format!("self.{}", python_field_name(name)),
        python_field_name,
    )
}

fn resource_return_binding_expr_python(binding: &PlannedOperationResourceFieldBinding) -> String {
    match &binding.source {
        ResolvedResourceBindingSource::RequestField {
            field_name,
            proto_field_name,
            hidden,
        } => {
            if *hidden {
                let expr = format!("request_proto.{proto_field_name}");
                if binding.optional {
                    format!("{expr} or None")
                } else {
                    expr
                }
            } else {
                format!("request.{}", python_field_name(field_name))
            }
        }
        ResolvedResourceBindingSource::ResultField {
            proto_field_name, ..
        } => {
            let expr = format!("result.{proto_field_name}");
            if binding.optional {
                format!("{expr} or None")
            } else {
                expr
            }
        }
    }
}

#[derive(Debug, Clone)]
struct RenderedFunctionOverloadCase {
    callable_field_name: String,
    args_field_name: String,
    callable_annotation: String,
    positional_args: Vec<RenderedFunctionOverloadPositionalArg>,
    args_annotation: Option<String>,
    args_optional: bool,
    result_type_parameter: Option<String>,
    type_parameters: Vec<PythonTypeParameter>,
}

#[derive(Debug, Clone)]
struct RenderedFunctionOverloadPositionalArg {
    name: String,
    annotation: String,
    variadic: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
enum PythonTypeParameter {
    TypeVar(String),
    TypeVarTuple(String),
}

fn render_function_unpacked_overloads(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    unpacked_input: &RenderedUnpackedInput,
) {
    let overload_combinations = collect_function_overload_combinations(
        &unpacked_input.functions,
        &operation.output_type_parameters,
    );

    for (index, overload_cases) in overload_combinations.iter().enumerate() {
        render_function_unpacked_overload(output, operation, unpacked_input, overload_cases);
        if index + 1 != overload_combinations.len() {
            output.push('\n');
        }
    }
}

fn collect_function_overload_combinations(
    functions: &[RenderedFunctionField],
    output_type_parameters: &BTreeSet<String>,
) -> Vec<Vec<RenderedFunctionOverloadCase>> {
    let per_function_cases = functions
        .iter()
        .map(|function| function_overload_cases(function, output_type_parameters))
        .collect::<Vec<_>>();
    let mut combinations = Vec::new();
    let mut current = Vec::new();
    collect_function_overload_combinations_recursive(
        &per_function_cases,
        0,
        &mut current,
        &mut combinations,
    );
    combinations
}

fn collect_function_overload_combinations_recursive(
    per_function_cases: &[Vec<RenderedFunctionOverloadCase>],
    index: usize,
    current: &mut Vec<RenderedFunctionOverloadCase>,
    combinations: &mut Vec<Vec<RenderedFunctionOverloadCase>>,
) {
    if index == per_function_cases.len() {
        combinations.push(current.clone());
        return;
    }

    for case in &per_function_cases[index] {
        current.push(case.clone());
        collect_function_overload_combinations_recursive(
            per_function_cases,
            index + 1,
            current,
            combinations,
        );
        current.pop();
    }
}

fn function_overload_cases(
    function: &RenderedFunctionField,
    output_type_parameters: &BTreeSet<String>,
) -> Vec<RenderedFunctionOverloadCase> {
    let result_type_parameter = function
        .result_type_parameter
        .clone()
        .filter(|name| output_type_parameters.contains(name));
    let result_annotation = if result_type_parameter.is_some() {
        &function.result_annotation
    } else {
        &function.erased_result_annotation
    };
    let mut cases = Vec::new();
    if let Some(alternate_annotation) = &function.alternate_annotation {
        cases.push(RenderedFunctionOverloadCase {
            callable_field_name: function.callable_field_name.clone(),
            args_field_name: function.args_field_name.clone(),
            callable_annotation: alternate_annotation.clone(),
            positional_args: python_alternate_function_positional_args(function),
            args_annotation: python_alternate_function_args_annotation(function),
            args_optional: true,
            result_type_parameter: None,
            type_parameters: Vec::new(),
        });
    }

    match &function.args {
        RenderedFunctionArgs::Varargs { prefix } if function.primary => {
            let type_parameter_prefix = function_overload_parameter_prefix(function);
            let function_args = format!("{type_parameter_prefix}Args");
            let callable_args = python_varargs_callable_arg_list(prefix, &function_args);
            let mut type_parameters = Vec::new();
            if let Some(result_type_parameter) = &result_type_parameter {
                type_parameters.push(PythonTypeParameter::TypeVar(result_type_parameter.clone()));
            }
            type_parameters.push(PythonTypeParameter::TypeVarTuple(function_args.clone()));
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[[{}], {}]",
                    callable_args, result_annotation
                ),
                positional_args: vec![RenderedFunctionOverloadPositionalArg {
                    name: "positional_args".to_string(),
                    annotation: format!("typing_extensions.Unpack[{function_args}]"),
                    variadic: true,
                }],
                args_annotation: None,
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                type_parameters,
            });
            let type_parameters = result_type_parameter
                .iter()
                .map(|name| PythonTypeParameter::TypeVar(name.clone()))
                .collect();
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[..., {}]",
                    result_annotation
                ),
                positional_args: Vec::new(),
                args_annotation: Some("list[typing.Any]".to_string()),
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                type_parameters,
            });
        }
        RenderedFunctionArgs::Varargs { prefix } => {
            let type_parameter_prefix = function_overload_parameter_prefix(function);
            let first_arg = format!("{type_parameter_prefix}Arg");
            let callable_prefix = prefix
                .iter()
                .map(|parameter| parameter.annotation.clone())
                .collect::<Vec<_>>();
            let no_arg_callable_args = python_callable_arg_list(&callable_prefix);
            let mut one_arg_callable_prefix = callable_prefix;
            one_arg_callable_prefix.push(first_arg.clone());
            let one_arg_callable_args = python_callable_arg_list(&one_arg_callable_prefix);
            let type_parameters = result_type_parameter
                .iter()
                .map(|name| PythonTypeParameter::TypeVar(name.clone()))
                .collect();
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[[{}], {}]",
                    no_arg_callable_args, result_annotation
                ),
                positional_args: Vec::new(),
                args_annotation: None,
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                type_parameters,
            });
            let mut type_parameters = Vec::new();
            if let Some(result_type_parameter) = &result_type_parameter {
                type_parameters.push(PythonTypeParameter::TypeVar(result_type_parameter.clone()));
            }
            type_parameters.push(PythonTypeParameter::TypeVar(first_arg.clone()));
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[[{}], {}]",
                    one_arg_callable_args, result_annotation
                ),
                positional_args: Vec::new(),
                args_annotation: Some(first_arg.clone()),
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                type_parameters,
            });
            let type_parameters = result_type_parameter
                .iter()
                .map(|name| PythonTypeParameter::TypeVar(name.clone()))
                .collect();
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[..., {}]",
                    result_annotation
                ),
                positional_args: Vec::new(),
                args_annotation: Some("list[typing.Any]".to_string()),
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                type_parameters,
            });
        }
        RenderedFunctionArgs::Typed { parameters } => {
            let args_annotation = python_function_args_list_annotation(
                parameters
                    .iter()
                    .map(|parameter| parameter.annotation.as_str())
                    .collect::<Vec<_>>()
                    .as_slice(),
            );
            let type_parameters = result_type_parameter
                .iter()
                .map(|name| PythonTypeParameter::TypeVar(name.clone()))
                .collect();
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: python_rendered_function_callable_annotation_with_result(
                    function,
                    result_annotation,
                ),
                positional_args: if function.primary {
                    parameters
                        .iter()
                        .map(|parameter| RenderedFunctionOverloadPositionalArg {
                            name: parameter.name.clone(),
                            annotation: parameter.annotation.clone(),
                            variadic: false,
                        })
                        .collect()
                } else {
                    Vec::new()
                },
                args_annotation: if function.primary {
                    None
                } else if parameters.len() == 1 {
                    Some(parameters[0].annotation.clone())
                } else {
                    Some(args_annotation.clone())
                },
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                type_parameters,
            });
        }
    }

    cases
}

fn python_alternate_function_positional_args(
    function: &RenderedFunctionField,
) -> Vec<RenderedFunctionOverloadPositionalArg> {
    if !function.primary {
        return Vec::new();
    }
    match &function.args {
        RenderedFunctionArgs::Typed { parameters } => parameters
            .iter()
            .map(|parameter| RenderedFunctionOverloadPositionalArg {
                name: parameter.name.clone(),
                annotation: parameter.annotation.clone(),
                variadic: false,
            })
            .collect(),
        RenderedFunctionArgs::Varargs { .. } => {
            vec![RenderedFunctionOverloadPositionalArg {
                name: "positional_args".to_string(),
                annotation: "object".to_string(),
                variadic: true,
            }]
        }
    }
}

fn python_alternate_function_args_annotation(function: &RenderedFunctionField) -> Option<String> {
    match (&function.args, function.primary) {
        (RenderedFunctionArgs::Typed { .. }, true) => None,
        _ => Some("list[typing.Any] | None".to_string()),
    }
}

fn python_rendered_function_callable_annotation_with_result(
    function: &RenderedFunctionField,
    result_annotation: &str,
) -> String {
    match &function.args {
        RenderedFunctionArgs::Varargs { .. } => {
            format!("collections.abc.Callable[..., {}]", result_annotation)
        }
        RenderedFunctionArgs::Typed { parameters } => format!(
            "collections.abc.Callable[[{}], {}]",
            parameters
                .iter()
                .map(|parameter| parameter.annotation.clone())
                .collect::<Vec<_>>()
                .join(", "),
            result_annotation
        ),
    }
}

