pub(crate) fn generate(
    api_plan: &PlannedSpec,
    support_fragments: &[SupportFragmentSpec],
    mode: GenerationMode,
) -> Result<GeneratedFiles> {
    reject_support_namespaces(Language::Python, support_fragments)?;
    let language_imports = collect_python_language_imports(api_plan);
    let mut enums = IndexMap::new();
    let mut flags = IndexMap::new();
    let mut variants = IndexMap::new();
    let mut models = IndexMap::new();
    let services = api_plan
        .services
        .iter()
        .map(|service| {
            let operations = service
                .operations
                .iter()
                .map(|operation| {
                    resolve_operation(
                        operation,
                        api_plan,
                        &mut enums,
                        &mut flags,
                        &mut variants,
                        &mut models,
                    )
                })
                .collect::<Result<Vec<_>>>()?;

            Ok(RenderedService {
                name: &service.name,
                wire_name: &service.wire_name,
                doc: service
                    .doc
                    .for_language(Language::Python)
                    .map(str::to_string),
                endpoint: service.data.endpoint.clone(),
                experimental: service.experimental,
                delay_load_temporalio_workflow: service.delay_load_temporalio_workflow,
                operations,
                resources: service
                    .resources
                    .iter()
                    .map(|resource| resource.data.clone())
                    .collect(),
            })
        })
        .collect::<Result<Vec<_>>>()?;

    for service in &services {
        for resource in &service.resources {
            ensure_resource_field_types(
                resource,
                api_plan,
                &mut enums,
                &mut flags,
                &mut variants,
                &mut models,
            );
        }
    }
    for record in api_plan.records.values() {
        let model_type = TypeSpec::Record(PlannedRecordType {
            full_name: record.full_name.clone(),
            model_name: record.name.clone(),
        });
        resolve_message_value_conversion(
            &model_type,
            api_plan,
            &mut enums,
            &mut flags,
            &mut variants,
            &mut models,
        );
    }
    let model_refs = models.values().collect::<Vec<_>>();
    let model_fragments = render_model_fragments(model_refs.as_slice(), api_plan)?;

    render_package(
        enums.values().collect::<Vec<_>>().as_slice(),
        flags.values().collect::<Vec<_>>().as_slice(),
        variants.values().collect::<Vec<_>>().as_slice(),
        &model_fragments,
        &services,
        support_fragments,
        &language_imports,
        mode,
    )
}

fn collect_python_language_imports(api_plan: &PlannedSpec) -> Vec<LanguageImportSpec> {
    let mut imports = BTreeSet::new();
    for variant in api_plan.variants.values() {
        for case in &variant.cases {
            if let Some(payload) = &case.payload {
                collect_value_type_imports(payload, &mut imports);
            }
        }
    }
    for record in api_plan.records.values() {
        if let Some(proto) = &record.data.proto {
            collect_proto_type_imports(proto, &mut imports);
        }
        for field in record.fields.values() {
            if let Some(annotation) = &field.annotation {
                collect_python_import(annotation, &mut imports);
            }
            if let Some(annotation) = &field.flattened_annotation {
                collect_python_import(annotation, &mut imports);
            }
        }
        for (_, field) in record.public_fields() {
            if let Some(function) = &field.function {
                collect_function_imports(function, &mut imports);
            }
            collect_value_type_imports(&field.field_type, &mut imports);
        }
        for (_, sourced_field, _) in record.sourced_fields() {
            collect_value_type_imports(&sourced_field.field_type, &mut imports);
        }
    }
    for service in &api_plan.services {
        for operation in &service.operations {
            if let Some(input) = operation_input_model(operation) {
                collect_model_type_imports(input, &mut imports);
            }
            if let Some(output) = operation.output_type()
                && let Some(model_type) = output.operation_model()
            {
                collect_model_type_imports(model_type, &mut imports);
            }
            if let Some(transform) = &operation.output_transform {
                collect_python_import(&transform.type_name, &mut imports);
            }
        }
        for resource in service.resources.iter().map(|resource| &resource.data) {
            for field in &resource.fields {
                collect_value_type_imports(&field.kind, &mut imports);
                if let Some(function) = &field.function {
                    collect_function_imports(function, &mut imports);
                }
            }
            for method in &resource.methods {
                for param in &method.params {
                    collect_value_type_imports(&param.kind, &mut imports);
                    if let Some(function) = &param.function {
                        collect_function_imports(function, &mut imports);
                    }
                }
                if let Some(result) = &method.result {
                    if let PlannedResourceMethodResultKind::Value(kind) = &result.kind {
                        collect_value_type_imports(kind, &mut imports);
                    }
                }
            }
        }
    }
    imports.into_iter().collect()
}

fn collect_proto_type_imports(
    proto: &PlannedProtoTypeInfo,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    collect_python_import(&proto.type_name, imports);
}

fn collect_model_type_imports(
    model_type: &PlannedType,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    if let Some(proto) = model_type.proto_message() {
        collect_proto_type_imports(&proto.proto, imports);
        if let Some(replacement) = &proto.replacement {
            collect_type_replacement_imports(replacement, imports);
        }
        if let Some(authored_type) = &proto.authored_type {
            collect_authored_type_imports(authored_type, imports);
        }
    }
}

fn collect_type_replacement_imports(
    replacement: &TypeReplacementSpec,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    collect_python_import(&replacement.type_name, imports);
    collect_python_import(&replacement.from_proto, imports);
    collect_python_import(&replacement.to_proto, imports);
}

fn collect_value_type_imports(value: &PlannedType, imports: &mut BTreeSet<LanguageImportSpec>) {
    match value {
        PlannedType::Enum(_) => {}
        PlannedType::Flags(_) | PlannedType::Variant(_) => {}
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(enumeration))) => {
            collect_proto_type_imports(&enumeration.proto, imports);
            if let Some(replacement) = &enumeration.replacement {
                collect_type_replacement_imports(replacement, imports);
            }
        }
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(_)))
        | PlannedType::External(ExternalTypeSpec::Json(_))
        | PlannedType::Record(_) => {
            collect_model_type_imports(value, imports);
        }
        PlannedType::Resource(resource) => {
            if let Some(proto) = &resource.proto {
                collect_model_type_imports(proto, imports);
            }
        }
        PlannedType::Option(inner) | PlannedType::List(inner) => {
            collect_value_type_imports(inner, imports)
        }
        PlannedType::Map(key, value) => {
            collect_value_type_imports(key, imports);
            collect_value_type_imports(value, imports);
        }
        PlannedType::Tuple(items) => {
            for item in items {
                collect_value_type_imports(item, imports);
            }
        }
        PlannedType::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_value_type_imports(ok, imports);
            }
            if let Some(err) = err {
                collect_value_type_imports(err, imports);
            }
        }
        PlannedType::External(ExternalTypeSpec::Alias {
            type_name, target, ..
        }) => {
            collect_python_import(type_name, imports);
            collect_value_type_imports(target, imports);
        }
        PlannedType::Bool
        | PlannedType::Int(_)
        | PlannedType::Float
        | PlannedType::String
        | PlannedType::Bytes => {}
    }
}

fn collect_function_imports(
    function: &FunctionFieldSpec<PlannedTypeFamily>,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    if let FunctionResultSpec::Annotation(result) = &function.result {
        collect_python_import(result, imports);
    }
    collect_function_args_imports(&function.args, imports);
    if let Some(alternate_type) = &function.alternate_type {
        collect_authored_type_imports(alternate_type, imports);
    }
    if let Some(descriptor) = &function.type_descriptor {
        collect_python_import(&descriptor.value_type, imports);
        collect_python_import(&descriptor.args_type, imports);
    }
}

fn collect_function_args_imports(
    args: &FunctionArgsSpec<PlannedTypeFamily>,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    let fields = match args {
        FunctionArgsSpec::Varargs { prefix, .. } => prefix,
        FunctionArgsSpec::Fixed(fields) => fields,
    };
    for field in fields {
        collect_authored_type_imports(&field.field_type, imports);
    }
}

fn collect_authored_type_imports(
    field_type: &PlannedType,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    match field_type {
        TypeSpec::Option(inner) | TypeSpec::List(inner) => {
            collect_authored_type_imports(inner, imports);
        }
        TypeSpec::Tuple(items) => {
            for item in items {
                collect_authored_type_imports(item, imports);
            }
        }
        TypeSpec::Map(key, value) => {
            collect_authored_type_imports(key, imports);
            collect_authored_type_imports(value, imports);
        }
        TypeSpec::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_authored_type_imports(ok, imports);
            }
            if let Some(err) = err {
                collect_authored_type_imports(err, imports);
            }
        }
        TypeSpec::External(ExternalTypeSpec::Alias {
            target, type_name, ..
        }) => {
            collect_python_import(type_name, imports);
            collect_authored_type_imports(target, imports);
        }
        TypeSpec::Bool
        | TypeSpec::Int(_)
        | TypeSpec::Float
        | TypeSpec::String
        | TypeSpec::Bytes
        | TypeSpec::External(ExternalTypeSpec::Proto(_))
        | TypeSpec::External(ExternalTypeSpec::Json(_))
        | TypeSpec::Record(_)
        | TypeSpec::Enum(_)
        | TypeSpec::Flags(_)
        | TypeSpec::Variant(_)
        | TypeSpec::Resource(_) => {}
    }
}

fn collect_python_import(spec: &LanguageStringSpec, imports: &mut BTreeSet<LanguageImportSpec>) {
    if let Some(module) = spec.import_for_language(Language::Python) {
        imports.insert(LanguageImportSpec {
            language: Language::Python,
            reference: module.to_string(),
            module: module.to_string(),
            name: None,
            type_only: false,
            import_style: LanguageImportStyle::Module,
        });
        return;
    }

    let Some(expression) = spec.for_language(Language::Python) else {
        return;
    };
    for module_path in python_qualified_module_paths(expression) {
        imports.insert(LanguageImportSpec {
            language: Language::Python,
            reference: module_path.clone(),
            module: module_path,
            name: None,
            type_only: false,
            import_style: LanguageImportStyle::Module,
        });
    }
}

fn python_qualified_module_paths(expression: &str) -> BTreeSet<String> {
    let chars = expression.char_indices().collect::<Vec<_>>();
    let mut module_paths = BTreeSet::new();
    let mut index = 0;
    while index < chars.len() {
        let (start_byte, ch) = chars[index];
        if !is_python_identifier_start(ch) {
            index += 1;
            continue;
        }

        let before = expression[..start_byte].chars().next_back();
        if before.is_some_and(|before| is_python_identifier_char(before) || before == '.') {
            index += 1;
            continue;
        }

        let mut end = index + 1;
        while end < chars.len() {
            let ch = chars[end].1;
            if is_python_identifier_char(ch) || ch == '.' {
                end += 1;
            } else {
                break;
            }
        }
        let end_byte = chars
            .get(end)
            .map(|(byte, _)| *byte)
            .unwrap_or(expression.len());
        let qualified_name = expression[start_byte..end_byte].trim_end_matches('.');
        if let Some(module_path) = python_module_path_for_qualified_name(qualified_name) {
            module_paths.insert(module_path.to_string());
        }
        index = end;
    }
    module_paths
}

fn python_module_path_for_qualified_name(qualified_name: &str) -> Option<&str> {
    let (module_path, _) = qualified_name.rsplit_once('.')?;
    if is_builtin_python_import(module_path) {
        return None;
    }
    Some(module_path)
}

fn is_builtin_python_import(module_path: &str) -> bool {
    matches!(
        module_path,
        "collections.abc" | "typing" | "typing_extensions"
    )
}

fn is_python_identifier_start(ch: char) -> bool {
    ch.is_ascii_alphabetic() || ch == '_'
}

fn reject_support_namespaces(
    language: Language,
    support_fragments: &[SupportFragmentSpec],
) -> Result<()> {
    if let Some(namespace) = support_fragments
        .iter()
        .find_map(|fragment| fragment.namespace.as_deref())
    {
        return Err(Error::UnsupportedSupportNamespace {
            language,
            namespace: namespace.to_string(),
        });
    }
    Ok(())
}

fn ensure_resource_field_types(
    resource: &PlannedResource,
    api_plan: &PlannedSpec,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) {
    for field in &resource.fields {
        ensure_resource_field_type(&field.kind, api_plan, enums, flags, variants, models);
    }
    for method in &resource.methods {
        for param in &method.params {
            ensure_resource_field_type(&param.kind, api_plan, enums, flags, variants, models);
        }
    }
}

fn ensure_resource_field_type(
    kind: &PlannedType,
    api_plan: &PlannedSpec,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) {
    match kind {
        PlannedType::List(value) => {
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models);
        }
        PlannedType::Map(key, value) => {
            resolve_planned_value_type(key, api_plan, enums, flags, variants, models);
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models);
        }
        value => {
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models);
        }
    }
}

