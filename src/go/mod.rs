/// Resolves a planned operation by ensuring all types referenced by its input
/// and output messages are present in the rendered type collections, and
/// returns a [`RenderedOperation`] carrying the operation metadata.
fn resolve_operation<'a>(
    operation: &'a PlannedOperation,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<RenderedOperation<'a>> {
    resolve_message_types(
        &operation.input,
        api_plan,
        enums,
        flags,
        variants,
        models,
        package,
    )?;
    let input_type = resolve_message_go_type(&operation.input, package);
    let go_output_transform = operation.output_transform.as_ref().and_then(|transform| {
        Some((
            transform.type_name.for_language(Language::Go)?,
            transform.transform.for_language(Language::Go)?,
        ))
    });
    let raw_output_type = if go_output_transform.is_some() {
        match &operation.output {
            PlannedOperationOutput::Message(output) => {
                if go_proto_ref(&output.info).is_some() {
                    None
                } else {
                    resolve_message_types(
                        output, api_plan, enums, flags, variants, models, package,
                    )?;
                    Some(resolve_message_go_type(output, package))
                }
            }
            PlannedOperationOutput::Resource { type_name } => Some(type_name.clone()),
            PlannedOperationOutput::None => None,
        }
    } else {
        None
    };

    let output_type = match &operation.output {
        PlannedOperationOutput::Message(output) => {
            if let Some(resource_return) = &operation.output_resource_return {
                // The operation returns a resource constructed from the proto
                // response -- use the resource type name.
                Some(resource_return.resource_type_name.clone())
            } else if let Some((transform_type, _)) = go_output_transform {
                // Output transforms expose their transformed type to callers,
                // while the raw operation output is still resolved below for
                // result decoding.
                Some(package.go_type_expr(transform_type))
            } else {
                resolve_message_types(output, api_plan, enums, flags, variants, models, package)?;
                Some(resolve_message_go_type(output, package))
            }
        }
        PlannedOperationOutput::Resource { type_name } => Some(type_name.clone()),
        PlannedOperationOutput::None => None,
    };

    // Build unpacked input params from the rendered model, if the input type
    // is a generated model (not an external/replacement type).
    let unpacked_input = models.get(&operation.input.info.full_name).map(|model| {
        let planned_fields = api_plan
            .models
            .get(&operation.input.info.full_name)
            .map(|planned_model| planned_model.fields.as_slice());
        model
            .fields
            .iter()
            .enumerate()
            .map(|(index, field)| {
                let planned_field = planned_fields.and_then(|fields| fields.get(index));
                let function = planned_field.and_then(|planned_field| match &planned_field.role {
                    PlannedFieldRole::Function(function) if planned_field.required => {
                        Some(function.clone())
                    }
                    _ => None,
                });
                let function_args =
                    planned_field.and_then(|planned_field| match &planned_field.role {
                        PlannedFieldRole::FunctionArgs(function) => Some(function.clone()),
                        _ => None,
                    });
                let embed_in_options = planned_field.is_some_and(|planned_field| {
                    !planned_field.required
                        && field_kind_is_flattened_message(&planned_field.kind, api_plan)
                });
                let default_punning_zero = planned_field
                    .filter(|planned_field| !planned_field.required && !embed_in_options)
                    .and_then(|planned_field| {
                        public_default_punning_zero_for_field(&planned_field.kind, &field.go_type)
                    });
                let public_go_type = if default_punning_zero.is_some() {
                    field
                        .go_type
                        .strip_prefix('*')
                        .unwrap_or(&field.go_type)
                        .to_string()
                } else {
                    field.go_type.clone()
                };
                RenderedUnpackedParam {
                    field_name: field.name.clone(),
                    doc: field.doc.clone(),
                    param_name: go_unexported_name(&field.name),
                    go_type: field.go_type.clone(),
                    public_go_type,
                    default_punning_zero,
                    function,
                    function_args,
                    required: field.required,
                    embed_in_options,
                }
            })
            .collect()
    });

    Ok(RenderedOperation {
        name: operation.name.as_str(),
        wire_name: operation.wire_name.as_str(),
        doc: operation.doc.for_language(Language::Go),
        return_doc: operation.return_doc.for_language(Language::Go),
        func_name: go_unexported_name(&operation.name),
        input_type,
        output_type,
        raw_output_type,
        output_transform_expr: go_output_transform.map(|(_, expr)| expr),
        output_transform_type: go_output_transform
            .map(|(type_name, _)| package.go_type_expr(type_name)),
        unpacked_input,
        proto_binding: None,
    })
}

fn field_kind_is_flattened_message(kind: &PlannedFieldKind, api_plan: &ApiPlan) -> bool {
    let PlannedFieldKind::Singular(PlannedValueType::Message(message)) = kind else {
        return false;
    };
    api_plan
        .models
        .get(&message.info.full_name)
        .is_some_and(|model| model.flatten_in_api)
}

fn public_default_punning_zero_for_field(
    kind: &PlannedFieldKind,
    internal_go_type: &str,
) -> Option<String> {
    let public_go_type = internal_go_type.strip_prefix('*')?;
    if let Some(zero) = public_default_punning_zero_for_go_type(public_go_type) {
        return Some(zero.to_string());
    }
    match kind {
        PlannedFieldKind::Singular(value) => {
            public_default_punning_zero_for_value(value, public_go_type)
        }
        PlannedFieldKind::Repeated(_) | PlannedFieldKind::Map { .. } => None,
    }
}

fn public_default_punning_zero_for_value(
    value: &PlannedValueType,
    public_go_type: &str,
) -> Option<String> {
    match value {
        PlannedValueType::Scalar(scalar) => public_default_punning_zero_for_scalar(scalar),
        PlannedValueType::Enum(_) | PlannedValueType::Flags(_) => Some("0".to_string()),
        PlannedValueType::External { .. } => {
            public_default_punning_zero_for_go_type(public_go_type).map(str::to_string)
        }
        PlannedValueType::Variant(_)
        | PlannedValueType::Message(_)
        | PlannedValueType::Tuple(_)
        | PlannedValueType::Result { .. }
        | PlannedValueType::Unknown => None,
    }
}

fn public_default_punning_zero_for_scalar(scalar: &PlannedScalarType) -> Option<String> {
    match scalar {
        PlannedScalarType::Bool => Some("false".to_string()),
        PlannedScalarType::String => Some("\"\"".to_string()),
        PlannedScalarType::Int32 | PlannedScalarType::Int64 | PlannedScalarType::Float => {
            Some("0".to_string())
        }
        PlannedScalarType::Bytes => None,
    }
}

fn public_default_punning_zero_for_go_type(public_go_type: &str) -> Option<&'static str> {
    match public_go_type {
        "string" => Some("\"\""),
        "bool" => Some("false"),
        "int" | "int8" | "int16" | "int32" | "int64" | "uint" | "uint8" | "uint16" | "uint32"
        | "uint64" | "float32" | "float64" | "time.Duration" => Some("0"),
        _ => None,
    }
}

/// Computes the proto binding for an operation message: the proto type
/// expression and the native<->proto conversion expressions. Returns `None`
/// when the message is not proto-backed or cannot be converted.
fn operation_message_binding(
    message: &PlannedMessageType,
    operation_name: &str,
    direction: &str,
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
    package: &GoPackageContext,
) -> Result<Option<(String, GoValueConversion)>> {
    // Messages without proto descriptor info (WIT-native records) are sent
    // natively rather than through proto -- not a proto binding at all.
    let Some(proto_ref) = go_proto_ref(&message.info) else {
        return Ok(None);
    };
    let alias = imports.register(&proto_ref);
    let proto_type = format!("*{}", proto_ref.qualified(&alias));
    let conversion =
        go_message_conversion(message, api_plan, imports, package).map_err(|reason| {
            Error::UnsupportedGoProtoConversion {
                context: format!("operation `{operation_name}` {direction}"),
                reason,
            }
        })?;
    Ok(Some((proto_type, conversion)))
}

fn operation_message_proto_type(
    message: &PlannedMessageType,
    imports: &mut GoImportCollector,
) -> Option<String> {
    let proto_ref = go_proto_ref(&message.info)?;
    let alias = imports.register(&proto_ref);
    Some(format!("*{}", proto_ref.qualified(&alias)))
}

/// Populates proto bindings on operations whose input/output messages are
/// proto-backed, registering required imports.
fn populate_operation_bindings(
    api_plan: &ApiPlan,
    services: &mut [RenderedService<'_>],
    imports: &mut GoImportCollector,
    package: &GoPackageContext,
) -> Result<()> {
    for (service, planned_service) in services.iter_mut().zip(api_plan.services.iter()) {
        for (rendered_op, planned_op) in service
            .operations
            .iter_mut()
            .zip(planned_service.operations.iter())
        {
            let Some((_input_proto_type, input_conv)) = operation_message_binding(
                &planned_op.input,
                &planned_op.name,
                "input",
                api_plan,
                imports,
                package,
            )?
            else {
                continue;
            };
            // Override converters take a pointer to the native value; generated
            // model converters use a value receiver (`request.ToProto()`).
            let input_arg = match input_conv.kind {
                GoConversionKind::OverrideConverter => "&request".to_string(),
                _ => "request".to_string(),
            };
            let input_to_proto = (input_conv.to_proto)(&input_arg);
            let has_go_output_transform =
                planned_op
                    .output_transform
                    .as_ref()
                    .is_some_and(|transform| {
                        transform.type_name.for_language(Language::Go).is_some()
                            && transform.transform.for_language(Language::Go).is_some()
                    });
            let resource_return = if let Some(resource_return) = &planned_op.output_resource_return
            {
                let resource = service
                    .resources
                    .iter()
                    .find(|resource| resource.type_name == resource_return.resource_type_name)
                    .ok_or_else(|| Error::InvalidResource {
                        service: planned_service.name.clone(),
                        resource: resource_return.resource_type_name.clone(),
                        reason: "resource-returning operation references an unknown resource"
                            .to_string(),
                    })?;
                Some(build_rendered_resource_return(
                    planned_service.name.as_str(),
                    resource_return,
                    resource,
                    api_plan,
                    imports,
                    package,
                )?)
            } else {
                None
            };

            let (output_proto_type, output_from_proto, output_returns_pointer) = match &planned_op
                .output
            {
                PlannedOperationOutput::Message(output) => {
                    if planned_op.output_resource_return.is_some() {
                        let Some(proto_type) = operation_message_proto_type(output, imports) else {
                            continue;
                        };
                        (Some(proto_type), None, false)
                    } else if has_go_output_transform {
                        (operation_message_proto_type(output, imports), None, false)
                    } else {
                        match operation_message_binding(
                            output,
                            &planned_op.name,
                            "output",
                            api_plan,
                            imports,
                            package,
                        )? {
                            Some((proto_type, conv)) => {
                                // `result` is declared as a proto value;
                                // converters take a pointer to the proto message.
                                let from = (conv.from_proto)("&result");
                                let returns_pointer = conv.from_proto_returns_pointer;
                                (Some(proto_type), Some(from), returns_pointer)
                            }
                            None => continue,
                        }
                    }
                }
                PlannedOperationOutput::Resource { .. } => continue,
                PlannedOperationOutput::None => (None, None, false),
            };

            rendered_op.proto_binding = Some(OperationProtoBinding {
                input_to_proto,
                output_proto_type,
                output_from_proto,
                output_returns_pointer,
                resource_return,
            });
        }
    }
    Ok(())
}

fn build_rendered_resource_return(
    service_name: &str,
    resource_return: &PlannedOperationResourceReturn,
    resource: &PlannedResource,
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
    package: &GoPackageContext,
) -> Result<RenderedResourceReturn> {
    let mut local_lines = Vec::new();
    let mut field_initializers = Vec::new();

    for binding in &resource_return.bindings {
        let field = resource
            .fields
            .iter()
            .find(|field| field.name == binding.field_name)
            .ok_or_else(|| Error::InvalidResource {
                service: service_name.to_string(),
                resource: resource_return.resource_type_name.clone(),
                reason: format!(
                    "resource-returning operation references unknown field `{}`",
                    binding.field_name
                ),
            })?;
        let expr = match &binding.source {
            ResolvedResourceBindingSource::RequestField {
                field_name,
                proto_field_name,
                hidden,
            } => {
                if *hidden {
                    let (lines, expr) = resource_return_proto_field_source(
                        field,
                        "requestProto",
                        proto_field_name,
                        api_plan,
                        imports,
                        package,
                    )
                    .map_err(|reason| Error::UnsupportedGoProtoConversion {
                        context: format!(
                            "resource return field `{}.{}`",
                            resource_return.resource_type_name, binding.field_name
                        ),
                        reason,
                    })?;
                    local_lines.extend(lines);
                    expr
                } else {
                    format!("request.{}", go_field_name(field_name))
                }
            }
            ResolvedResourceBindingSource::ResultField {
                proto_field_name, ..
            } => {
                let (lines, expr) = resource_return_proto_field_source(
                    field,
                    "result",
                    proto_field_name,
                    api_plan,
                    imports,
                    package,
                )
                .map_err(|reason| Error::UnsupportedGoProtoConversion {
                    context: format!(
                        "resource return field `{}.{}`",
                        resource_return.resource_type_name, binding.field_name
                    ),
                    reason,
                })?;
                local_lines.extend(lines);
                expr
            }
        };

        field_initializers.push(RenderedResourceFieldInitializer {
            field_name: go_field_name(&binding.field_name),
            expr,
        });
    }

    Ok(RenderedResourceReturn {
        resource_type_name: resource_return.resource_type_name.clone(),
        local_lines,
        field_initializers,
    })
}

fn resource_return_proto_field_source(
    field: &PlannedResourceField,
    source: &str,
    proto_field_name: &str,
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
    package: &GoPackageContext,
) -> GoConversionResult<(Vec<String>, String)> {
    let local = resource_return_local_name(&field.name);
    let proto_field = go_proto_field_name(proto_field_name);
    let getter = format!("{source}.Get{proto_field}()");
    let native_type = resolve_resource_field_kind(&field.kind, field.optional, package);

    match &field.kind {
        PlannedFieldKind::Singular(value) => {
            let conversion = go_value_conversion(value, api_plan, imports, package)?;
            Ok(resource_return_singular_proto_source(
                field,
                value,
                &conversion,
                &getter,
                &local,
                &native_type,
                "return nil, err",
            ))
        }
        PlannedFieldKind::Repeated(value) => {
            let conversion = go_value_conversion(value, api_plan, imports, package)?;
            let converted = (conversion.from_proto)("item");
            let mut lines = vec![
                format!("var {local} {native_type}"),
                format!("for _, item := range {getter} {{"),
            ];
            match conversion.kind {
                GoConversionKind::OverrideConverter => {
                    if !conversion.from_proto_returns_pointer {
                        if conversion.fallible {
                            lines.push(format!("\tconverted, err := {converted}"));
                            lines.push("\tif err != nil {".to_string());
                            lines.push("\t\treturn nil, err".to_string());
                            lines.push("\t}".to_string());
                            lines.push(format!("\t{local} = append({local}, converted)"));
                        } else {
                            lines.push(format!("\t{local} = append({local}, {converted})"));
                        }
                    } else {
                        if conversion.fallible {
                            lines.push(format!("\tconverted, err := {converted}"));
                            lines.push("\tif err != nil {".to_string());
                            lines.push("\t\treturn nil, err".to_string());
                            lines.push("\t}".to_string());
                            lines.push("\tif converted != nil {".to_string());
                        } else {
                            lines.push(format!(
                                "\tif converted := {converted}; converted != nil {{"
                            ));
                        }
                        lines.push(format!("\t\t{local} = append({local}, *converted)"));
                        lines.push("\t}".to_string());
                    }
                }
                _ => {
                    if conversion.fallible {
                        lines.push(format!("\tconverted, err := {converted}"));
                        lines.push("\tif err != nil {".to_string());
                        lines.push("\t\treturn nil, err".to_string());
                        lines.push("\t}".to_string());
                        lines.push(format!("\t{local} = append({local}, converted)"));
                    } else {
                        lines.push(format!("\t{local} = append({local}, {converted})"));
                    }
                }
            }
            lines.push("}".to_string());
            Ok((lines, local))
        }
        PlannedFieldKind::Map { key: _, value } => {
            let conversion = go_value_conversion(value, api_plan, imports, package)?;
            let converted = (conversion.from_proto)("v");
            let mut lines = vec![
                format!("var {local} {native_type}"),
                format!("if len({getter}) > 0 {{"),
                format!("\t{local} = make({native_type}, len({getter}))"),
                format!("\tfor k, v := range {getter} {{"),
            ];
            match conversion.kind {
                GoConversionKind::OverrideConverter => {
                    if !conversion.from_proto_returns_pointer {
                        if conversion.fallible {
                            lines.push(format!("\t\tconverted, err := {converted}"));
                            lines.push("\t\tif err != nil {".to_string());
                            lines.push("\t\t\treturn nil, err".to_string());
                            lines.push("\t\t}".to_string());
                            lines.push(format!("\t\t{local}[k] = converted"));
                        } else {
                            lines.push(format!("\t\t{local}[k] = {converted}"));
                        }
                    } else {
                        if conversion.fallible {
                            lines.push(format!("\t\tconverted, err := {converted}"));
                            lines.push("\t\tif err != nil {".to_string());
                            lines.push("\t\t\treturn nil, err".to_string());
                            lines.push("\t\t}".to_string());
                            lines.push("\t\tif converted != nil {".to_string());
                        } else {
                            lines.push(format!(
                                "\t\tif converted := {converted}; converted != nil {{"
                            ));
                        }
                        lines.push(format!("\t\t\t{local}[k] = *converted"));
                        lines.push("\t\t}".to_string());
                    }
                }
                _ => {
                    if conversion.fallible {
                        lines.push(format!("\t\tconverted, err := {converted}"));
                        lines.push("\t\tif err != nil {".to_string());
                        lines.push("\t\t\treturn nil, err".to_string());
                        lines.push("\t\t}".to_string());
                        lines.push(format!("\t\t{local}[k] = converted"));
                    } else {
                        lines.push(format!("\t\t{local}[k] = {converted}"));
                    }
                }
            }
            lines.push("\t}".to_string());
            lines.push("}".to_string());
            Ok((lines, local))
        }
    }
}

fn resource_return_singular_proto_source(
    field: &PlannedResourceField,
    value: &PlannedValueType,
    conversion: &GoValueConversion,
    getter: &str,
    local: &str,
    native_type: &str,
    error_return: &str,
) -> (Vec<String>, String) {
    let converted = (conversion.from_proto)(getter);
    let uses_pointer = field.optional && native_type.starts_with('*');

    match conversion.kind {
        GoConversionKind::OverrideConverter => {
            if !conversion.from_proto_returns_pointer {
                if uses_pointer {
                    if conversion.fallible {
                        (
                            vec![
                                format!("converted, err := {converted}"),
                                "if err != nil {".to_string(),
                                format!("\t{error_return}"),
                                "}".to_string(),
                                format!("{local} := &converted"),
                            ],
                            local.to_string(),
                        )
                    } else {
                        (
                            vec![
                                format!("converted := {converted}"),
                                format!("{local} := &converted"),
                            ],
                            local.to_string(),
                        )
                    }
                } else if conversion.fallible {
                    (
                        vec![
                            format!("{local}, err := {converted}"),
                            "if err != nil {".to_string(),
                            format!("\t{error_return}"),
                            "}".to_string(),
                        ],
                        local.to_string(),
                    )
                } else {
                    (vec![format!("{local} := {converted}")], local.to_string())
                }
            } else if uses_pointer {
                if conversion.fallible {
                    (
                        vec![
                            format!("{local}, err := {converted}"),
                            "if err != nil {".to_string(),
                            format!("\t{error_return}"),
                            "}".to_string(),
                        ],
                        local.to_string(),
                    )
                } else {
                    (vec![format!("{local} := {converted}")], local.to_string())
                }
            } else {
                let mut lines = vec![format!("var {local} {native_type}")];
                if conversion.fallible {
                    lines.push(format!("converted, err := {converted}"));
                    lines.push("if err != nil {".to_string());
                    lines.push(format!("\t{error_return}"));
                    lines.push("}".to_string());
                    lines.push("if converted != nil {".to_string());
                } else {
                    lines.push(format!("if converted := {converted}; converted != nil {{"));
                }
                lines.push(format!("\t{local} = *converted"));
                lines.push("}".to_string());
                (lines, local.to_string())
            }
        }
        GoConversionKind::ModelConverter => {
            if uses_pointer {
                let mut lines = vec![
                    format!("var {local} {native_type}"),
                    format!("if {getter} != nil {{"),
                ];
                if conversion.fallible {
                    lines.push(format!("\tconverted, err := {converted}"));
                    lines.push("\tif err != nil {".to_string());
                    lines.push(format!("\t\t{error_return}"));
                    lines.push("\t}".to_string());
                } else {
                    lines.push(format!("\tconverted := {converted}"));
                }
                lines.push(format!("\t{local} = &converted"));
                lines.push("}".to_string());
                (lines, local.to_string())
            } else {
                if conversion.fallible {
                    (
                        vec![
                            format!("{local}, err := {converted}"),
                            "if err != nil {".to_string(),
                            format!("\t{error_return}"),
                            "}".to_string(),
                        ],
                        local.to_string(),
                    )
                } else {
                    (vec![format!("{local} := {converted}")], local.to_string())
                }
            }
        }
        GoConversionKind::Scalar | GoConversionKind::Enum => {
            if uses_pointer {
                let value_local = format!("{local}Value");
                let zero = resource_return_zero_value_expr(value);
                (
                    vec![
                        format!("{value_local} := {converted}"),
                        format!("var {local} {native_type}"),
                        format!("if {value_local} != {zero} {{"),
                        format!("\t{local} = &{value_local}"),
                        "}".to_string(),
                    ],
                    local.to_string(),
                )
            } else {
                (vec![format!("{local} := {converted}")], local.to_string())
            }
        }
    }
}

fn resource_return_zero_value_expr(value: &PlannedValueType) -> &'static str {
    match value {
        PlannedValueType::Scalar(PlannedScalarType::Bool) => "false",
        PlannedValueType::Scalar(PlannedScalarType::String) => "\"\"",
        PlannedValueType::Scalar(PlannedScalarType::Bytes) => "nil",
        PlannedValueType::Scalar(_) | PlannedValueType::Enum(_) => "0",
        _ => "nil",
    }
}

fn resource_return_local_name(field_name: &str) -> String {
    go_unexported_name(&go_field_name(field_name))
}

/// Resolves a [`PlannedMessageType`] to its Go type expression, accounting for
/// type replacements and authored types. Used for operation input/output types.
fn resolve_message_go_type(message: &PlannedMessageType, package: &GoPackageContext) -> String {
    if let Some(replacement) = &message.replacement {
        if let Some(type_name) = go_replacement_type_name(replacement, package) {
            return type_name;
        }
    }
    if let Some(authored_type) = &message.authored_type {
        return go_authored_type_annotation(authored_type);
    }
    message.model_name.clone()
}

/// Ensures a message type and all of its transitive field types are resolved.
/// Messages with type replacements or authored types are skipped because they
/// map to externally-defined Go types rather than generated structs.
fn resolve_message_types(
    message: &PlannedMessageType,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<()> {
    if message.replacement.is_some() || message.authored_type.is_some() {
        return Ok(());
    }

    ensure_rendered_model(message, api_plan, enums, flags, variants, models, package)
}

