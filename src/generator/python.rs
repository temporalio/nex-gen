fn function_type_parameters(
    functions: &[RenderedFunctionField],
    output_type_parameters: &BTreeSet<String>,
) -> Vec<PythonTypeParameter> {
    let mut parameters = BTreeSet::new();
    for function in functions {
        for case in function_overload_cases(function, output_type_parameters) {
            parameters.extend(case.type_parameters);
        }
    }
    parameters.into_iter().collect()
}

fn render_function_type_parameter_definitions(
    output: &mut String,
    functions: &[RenderedFunctionField],
    output_type_parameters: &BTreeSet<String>,
) {
    let parameters = function_type_parameters(functions, output_type_parameters);
    if parameters.is_empty() {
        return;
    }

    for parameter in parameters {
        match parameter {
            PythonTypeParameter::TypeVar(name) => {
                output.push_str(&name);
                output.push_str(" = typing.TypeVar(");
                output.push_str(&python_string_literal(&name));
                output.push_str(")\n");
            }
            PythonTypeParameter::TypeVarTuple(name) => {
                output.push_str(&name);
                output.push_str(" = typing_extensions.TypeVarTuple(");
                output.push_str(&python_string_literal(&name));
                output.push_str(")\n");
            }
        }
    }
}

fn render_package_init(
    services: &[RenderedService<'_>],
    _resource_names: &[String],
    resource_operation_owners: &BTreeMap<String, String>,
) -> String {
    let operation_function_names = services
        .iter()
        .flat_map(|service| {
            service
                .operations
                .iter()
                .map(|operation| operation.attr_name.clone())
        })
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    if !services.is_empty() {
        output.push_str("from . import service as _service\n");
    }
    if !services.is_empty() {
        for service in services {
            for operation in &service.operations {
                let imports = vec![operation.attr_name.clone()];
                let module = if let Some(resource_owner) =
                    resource_operation_owners.get(&operation_key(service.name, operation.name))
                {
                    format!("._resources.{resource_owner}")
                } else {
                    format!(".operations.{}", operation.attr_name)
                };
                render_named_python_import(&mut output, &module, &imports);
            }
        }
    }
    output.push_str("\n__all__ = [\n");
    for name in &operation_function_names {
        output.push_str("    ");
        output.push_str(&python_string_literal(name));
        output.push_str(",\n");
    }
    output.push_str("]\n");
    output.push_str("\n\n__nexus_operation_registry__ = {\n");
    for service in services {
        for operation in &service.operations {
            output.push_str("    (\n");
            output.push_str("        \"");
            output.push_str(service.wire_name);
            output.push_str("\",\n");
            output.push_str("        \"");
            output.push_str(operation.wire_name);
            output.push_str("\",\n");
            output.push_str("    ): ");
            output.push_str("_service.");
            output.push_str(service.name);
            output.push('.');
            output.push_str(&operation.attr_name);
            output.push_str(",\n");
        }
    }
    output.push_str("}\n");
    output
}

fn render_service_definition(output: &mut String, service: &RenderedService<'_>) {
    if service.wire_name == service.name {
        output.push_str("@service\n");
    } else {
        output.push_str("@service(name=");
        output.push_str(&python_string_literal(service.wire_name));
        output.push_str(")\n");
    }
    output.push_str("class ");
    output.push_str(service.name);
    output.push_str(":\n");
    render_python_docstring(
        output,
        "    ",
        service.doc.as_deref(),
        &[],
        None,
        service.experimental,
    );

    if service.operations.is_empty() {
        if !service.experimental {
            output.push_str("    pass\n");
        }
        return;
    }

    for (operation_index, operation) in service.operations.iter().enumerate() {
        if operation.experimental {
            output.push_str("    # ");
            output.push_str(".. warning:: ");
            output.push_str(EXPERIMENTAL_WARNING);
            output.push('\n');
        }
        output.push_str("    ");
        output.push_str(&operation.attr_name);
        output.push_str(": Operation[\n");
        output.push_str("        ");
        output.push_str(&service_type_ref(operation_input_type_ref(operation)));
        output.push_str(",\n");
        output.push_str("        ");
        output.push_str(&service_type_ref(&operation.output_ref));
        output.push_str(",\n");
        output.push_str("    ] = Operation(name=");
        output.push_str(&python_string_literal(operation.wire_name));
        output.push_str(")\n");
        if service.doc.is_some() {
            render_python_docstring(output, "    ", operation.doc.as_deref(), &[], None, false);
        }

        if operation_index + 1 != service.operations.len() {
            output.push('\n');
        }
    }
}

fn service_type_ref(type_ref: &str) -> String {
    type_ref
        .strip_prefix("models.")
        .unwrap_or(type_ref)
        .to_string()
}

fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("class ");
    output.push_str(&enumeration.name);
    output.push_str("(enum.IntEnum):\n");

    if enumeration.values.is_empty() {
        output.push_str("    pass\n");
        return;
    }

    for value in &enumeration.values {
        output.push_str("    ");
        output.push_str(&value.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push('\n');
    }
}

fn render_flags(output: &mut String, flags: &RenderedFlags) {
    output.push_str("class ");
    output.push_str(&flags.name);
    output.push_str("(enum.IntFlag):\n");

    if flags.flags.is_empty() {
        output.push_str("    pass\n");
        return;
    }

    for flag in &flags.flags {
        output.push_str("    ");
        output.push_str(&flag.name);
        output.push_str(" = 1 << ");
        output.push_str(&flag.bit.to_string());
        output.push('\n');
    }
}

fn render_variant(output: &mut String, variant: &RenderedVariant) {
    output.push_str(variant.name.as_str());
    output.push_str(" = ");
    if variant.cases.is_empty() {
        output.push_str("typing.Never\n");
        return;
    }
    if variant.cases.len() > 1 {
        output.push_str("(\n    ");
    }
    for (index, case) in variant.cases.iter().enumerate() {
        if index > 0 {
            output.push_str("\n    | ");
        }
        output.push_str("tuple[typing.Literal[");
        output.push_str(&python_string_literal(&case.name));
        output.push(']');
        if let Some(payload_annotation) = &case.payload_annotation {
            output.push_str(", ");
            output.push_str(payload_annotation);
        }
        output.push(']');
    }
    if variant.cases.len() > 1 {
        output.push_str("\n)");
    }
    output.push('\n');
}

fn render_resource(
    output: &mut String,
    resource: &PlannedResource,
    bound_operations: &[ResourceBoundOperation<'_>],
) {
    output.push_str("@dataclasses.dataclass\n");
    output.push_str("class ");
    output.push_str(&resource.type_name);
    output.push_str(":\n");
    for field in &resource.fields {
        output.push_str("    ");
        output.push_str(&python_field_name(&field.name));
        output.push_str(": ");
        output.push_str(&python_resource_field_annotation(
            &field.kind,
            field.optional,
            field.function.as_ref(),
        ));
        output.push('\n');
    }

    if resource.methods.is_empty() {
        output.push_str("\n    pass\n");
        return;
    }

    for method in &resource.methods {
        output.push_str("\n");
        render_resource_class_method(output, resource, method, bound_operations);
    }
}

fn render_resource_class_method(
    output: &mut String,
    resource: &PlannedResource,
    method: &PlannedResourceMethod,
    bound_operations: &[ResourceBoundOperation<'_>],
) {
    let result_annotation = python_resource_method_result_annotation(method);
    output.push_str("    async def ");
    output.push_str(&python_field_name(&method.name));
    output.push_str("(\n");
    output.push_str("        self,\n");
    for param in &method.params {
        output.push_str("        ");
        output.push_str(&python_field_name(&param.name));
        output.push_str(": ");
        output.push_str(&python_resource_field_annotation(
            &param.kind,
            param.optional,
            param.function.as_ref(),
        ));
        if param.optional {
            output.push_str(" = None");
        }
        output.push_str(",\n");
    }
    output.push_str("    ) -> ");
    output.push_str(&result_annotation);
    output.push_str(":\n");

    match &method.binding {
        PlannedResourceMethodBindingSpec::Operation { operation_name, .. } => {
            let operation = bound_operations
                .iter()
                .find(|bound_operation| bound_operation.operation.name == operation_name)
                .map(|bound_operation| bound_operation.operation)
                .expect("bound resource operation should be rendered in the same module");
            render_resource_method_operation_body(output, method, operation);
        }
        PlannedResourceMethodBindingSpec::Stub => {
            output.push_str("        raise NotImplementedError(");
            output.push_str(&python_string_literal(&format!(
                "{}.{} is not yet implemented",
                resource.name,
                python_field_name(&method.name)
            )));
            output.push_str(")\n");
        }
    }
}

fn render_resource_method_operation_body(
    output: &mut String,
    method: &PlannedResourceMethod,
    operation: &RenderedOperation<'_>,
) {
    let result_annotation = python_resource_method_result_annotation(method);
    let PlannedResourceMethodBindingSpec::Operation {
        request_plan,
        direct_return,
        ..
    } = &method.binding
    else {
        return;
    };

    let operation_attr_name = request_operation_function_name(operation);
    let request_expr = render_request_plan_python(request_plan);
    output.push_str("        request = ");
    if let Some(unpacked_input) = &operation.unpacked_input {
        output.push_str(&unpacked_input.model_name);
    } else {
        output.push_str(operation_input_annotation(operation));
    }
    output.push_str("(\n");
    match request_plan {
        RequestPlan::Construct { fields, .. } => {
            for field in fields {
                output.push_str("            ");
                output.push_str(&python_field_name(&field.field_name));
                output.push('=');
                output.push_str(&render_request_plan_python(&field.value));
                output.push_str(",\n");
            }
        }
        RequestPlan::Source(_) => {
            output.push_str("            value=");
            output.push_str(&request_expr);
            output.push_str(",\n");
        }
    }
    output.push_str("        )\n");
    if *direct_return {
        if result_annotation == "None" {
            output.push_str("        await ");
            output.push_str(&operation_attr_name);
            output.push_str("(request)\n");
        } else {
            output.push_str("        return await ");
            output.push_str(&operation_attr_name);
            output.push_str("(request)\n");
        }
    } else {
        output.push_str("        handle = await ");
        output.push_str(&operation_attr_name);
        output.push_str("(request)\n");
        if result_annotation == "None" {
            output.push_str("        await handle\n");
        } else {
            output.push_str("        return await handle\n");
        }
    }
}

fn python_resource_method_result_annotation(method: &PlannedResourceMethod) -> String {
    let Some(result) = &method.result else {
        return "None".to_string();
    };
    let annotation = match &result.kind {
        PlannedResourceMethodResultKind::Resource { type_name } => type_name.clone(),
        PlannedResourceMethodResultKind::Value(kind) => {
            python_resource_field_annotation(kind, result.optional, None)
        }
    };
    if result.optional && !annotation.contains("| None") {
        format!("{annotation} | None")
    } else {
        annotation
    }
}

fn python_resource_field_annotation(
    kind: &PlannedType,
    optional: bool,
    function: Option<&FunctionFieldSpec<PlannedTypeFamily>>,
) -> String {
    let base = if let Some(function) = function {
        python_function_field_annotation(
            function,
            function
                .alternate_type
                .as_ref()
                .map(python_authored_type_annotation),
        )
    } else {
        match kind {
            PlannedType::Option(value) | PlannedType::List(value) => {
                format!(
                    "collections.abc.Sequence[{}]",
                    python_resource_value_annotation(value)
                )
            }
            PlannedType::Map(key, value) => format!(
                "collections.abc.Mapping[{}, {}]",
                python_resource_value_annotation(key),
                python_resource_value_annotation(value)
            ),
            value => python_resource_value_annotation(value),
        }
    };
    if optional {
        format!("{base} | None")
    } else {
        base
    }
}

fn python_resource_value_annotation(value: &PlannedType) -> String {
    match value {
        PlannedType::Float => "float".to_string(),
        PlannedType::Int(_) => "int".to_string(),
        PlannedType::Bool => "bool".to_string(),
        PlannedType::String => "str".to_string(),
        PlannedType::Bytes => "bytes".to_string(),
        PlannedType::Enum(enum_type) => enum_type.name.clone(),
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(enum_type))) => {
            enum_type
                .replacement
                .as_ref()
                .and_then(python_proto::python_replacement_type_name)
                .unwrap_or_else(|| enum_type.name.clone())
        }
        PlannedType::Flags(flags_type) => flags_type.name.clone(),
        PlannedType::Variant(variant_type) => variant_type.name.clone(),
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(proto))) => proto
            .replacement
            .as_ref()
            .and_then(python_proto::python_replacement_type_name)
            .unwrap_or_else(|| proto.model_name.clone()),
        PlannedType::External(ExternalTypeSpec::Json(json_type)) => json_type.model_name.clone(),
        PlannedType::Record(record) => record.model_name.clone(),
        PlannedType::Resource(resource) => resource.type_name.clone(),
        PlannedType::Option(inner) | PlannedType::List(inner) => {
            format!(
                "collections.abc.Sequence[{}]",
                python_resource_value_annotation(inner)
            )
        }
        PlannedType::Map(key, value) => format!(
            "collections.abc.Mapping[{}, {}]",
            python_resource_value_annotation(key),
            python_resource_value_annotation(value)
        ),
        PlannedType::Tuple(items) => format!(
            "tuple[{}]",
            items
                .iter()
                .map(python_resource_value_annotation)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        PlannedType::Result { ok, err } => python_result_annotation(
            ok.as_ref()
                .map(|ok| python_resource_value_annotation(ok).to_string()),
            err.as_ref()
                .map(|err| python_resource_value_annotation(err).to_string()),
        ),
        PlannedType::External(ExternalTypeSpec::Alias {
            type_name, target, ..
        }) => type_name
            .for_language(Language::Python)
            .map(str::to_string)
            .unwrap_or_else(|| python_resource_value_annotation(target)),
    }
}

fn render_request_plan_python(plan: &RequestPlan) -> String {
    render_request_plan(
        plan,
        python_field_name,
        |name, value| format!("{name}={value}"),
        |message_name, fields| {
            let model_name = message_model_name(message_name);
            if fields.is_empty() {
                format!("{model_name}()")
            } else {
                format!("{model_name}({})", fields.join(", "))
            }
        },
        |name| format!("self.{}", python_field_name(name)),
        python_field_name,
    )
}

fn resource_return_binding_expr_python(binding: &PlannedOperationResourceFieldBinding) -> String {
    match &binding.source {
        ResolvedResourceBindingSource::RequestField {
            field_name,
            proto_field_name,
            hidden,
        } => {
            if *hidden {
                let expr = format!("wire_input.{proto_field_name}");
                if binding.optional {
                    format!("{expr} or None")
                } else {
                    expr
                }
            } else {
                format!("request.{}", python_field_name(field_name))
            }
        }
        ResolvedResourceBindingSource::ResultField {
            proto_field_name, ..
        } => {
            let expr = format!("result.{proto_field_name}");
            if binding.optional {
                format!("{expr} or None")
            } else {
                expr
            }
        }
    }
}

#[derive(Debug, Clone)]
struct RenderedFunctionOverloadCase {
    callable_field_name: String,
    args_field_name: String,
    callable_annotation: String,
    positional_args: Vec<RenderedFunctionOverloadPositionalArg>,
    args_annotation: Option<String>,
    args_optional: bool,
    result_type_parameter: Option<String>,
    self_type_parameter: Option<String>,
    type_parameters: Vec<PythonTypeParameter>,
}

#[derive(Debug, Clone)]
struct RenderedFunctionOverloadPositionalArg {
    name: String,
    annotation: String,
    variadic: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
enum PythonTypeParameter {
    TypeVar(String),
    TypeVarTuple(String),
}

fn render_function_unpacked_overloads(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    unpacked_input: &RenderedUnpackedInput,
) {
    let overload_combinations = collect_function_overload_combinations(
        &unpacked_input.functions,
        &operation.output_type_parameters,
    );

    for (index, overload_cases) in overload_combinations.iter().enumerate() {
        render_function_unpacked_overload(
            output,
            service,
            operation,
            unpacked_input,
            overload_cases,
        );
        if index + 1 != overload_combinations.len() {
            output.push('\n');
        }
    }
}

fn collect_function_overload_combinations(
    functions: &[RenderedFunctionField],
    output_type_parameters: &BTreeSet<String>,
) -> Vec<Vec<RenderedFunctionOverloadCase>> {
    let per_function_cases = functions
        .iter()
        .map(|function| function_overload_cases(function, output_type_parameters))
        .collect::<Vec<_>>();
    let mut combinations = Vec::new();
    let mut current = Vec::new();
    collect_function_overload_combinations_recursive(
        &per_function_cases,
        0,
        &mut current,
        &mut combinations,
    );
    combinations
}

fn collect_function_overload_combinations_recursive(
    per_function_cases: &[Vec<RenderedFunctionOverloadCase>],
    index: usize,
    current: &mut Vec<RenderedFunctionOverloadCase>,
    combinations: &mut Vec<Vec<RenderedFunctionOverloadCase>>,
) {
    if index == per_function_cases.len() {
        combinations.push(current.clone());
        return;
    }

    for case in &per_function_cases[index] {
        current.push(case.clone());
        collect_function_overload_combinations_recursive(
            per_function_cases,
            index + 1,
            current,
            combinations,
        );
        current.pop();
    }
}

fn function_overload_cases(
    function: &RenderedFunctionField,
    output_type_parameters: &BTreeSet<String>,
) -> Vec<RenderedFunctionOverloadCase> {
    let result_type_parameter = function
        .result_type_parameter
        .clone()
        .filter(|name| output_type_parameters.contains(name));
    let result_annotation = if result_type_parameter.is_some() {
        &function.result_annotation
    } else {
        &function.erased_result_annotation
    };
    let self_type_parameter = python_function_self_type_parameter(function);
    let mut cases = Vec::new();
    if let Some(alternate_annotation) = &function.alternate_annotation {
        if function.primary && matches!(function.args, RenderedFunctionArgs::Varargs { .. }) {
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: alternate_annotation.clone(),
                positional_args: python_alternate_function_positional_args(function),
                args_annotation: None,
                args_optional: false,
                result_type_parameter: None,
                self_type_parameter: None,
                type_parameters: Vec::new(),
            });
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: alternate_annotation.clone(),
                positional_args: Vec::new(),
                args_annotation: python_alternate_function_args_annotation(function),
                args_optional: true,
                result_type_parameter: None,
                self_type_parameter: None,
                type_parameters: Vec::new(),
            });
        } else {
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: alternate_annotation.clone(),
                positional_args: python_alternate_function_positional_args(function),
                args_annotation: python_alternate_function_args_annotation(function),
                args_optional: true,
                result_type_parameter: None,
                self_type_parameter: None,
                type_parameters: Vec::new(),
            });
        }
    }

    match &function.args {
        RenderedFunctionArgs::Varargs { prefix } if function.primary => {
            let type_parameter_prefix = function_overload_parameter_prefix(function);
            let function_args = format!("{type_parameter_prefix}Args");
            let callable_args = python_varargs_callable_arg_list(
                prefix,
                &function_args,
                self_type_parameter.as_ref(),
            );
            let mut type_parameters = Vec::new();
            if let Some(result_type_parameter) = &result_type_parameter {
                type_parameters.push(PythonTypeParameter::TypeVar(result_type_parameter.clone()));
            }
            if let Some(self_type_parameter) = &self_type_parameter {
                type_parameters.push(PythonTypeParameter::TypeVar(self_type_parameter.clone()));
            }
            type_parameters.push(PythonTypeParameter::TypeVarTuple(function_args.clone()));
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[[{}], {}]",
                    callable_args, result_annotation
                ),
                positional_args: vec![RenderedFunctionOverloadPositionalArg {
                    name: "positional_args".to_string(),
                    annotation: format!("typing_extensions.Unpack[{function_args}]"),
                    variadic: true,
                }],
                args_annotation: None,
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                self_type_parameter: self_type_parameter.clone(),
                type_parameters,
            });
            let type_parameters = result_type_parameter
                .iter()
                .map(|name| PythonTypeParameter::TypeVar(name.clone()))
                .chain(self_type_parameter.iter().filter_map(|name| {
                    if output_type_parameters.is_empty() {
                        None
                    } else {
                        Some(PythonTypeParameter::TypeVar(name.clone()))
                    }
                }))
                .collect();
            let (callable_annotation, case_self_type_parameter) =
                if self_type_parameter.is_some() && !output_type_parameters.is_empty() {
                    (
                        format!(
                            "collections.abc.Callable[[{}], {}]",
                            callable_args, result_annotation
                        ),
                        self_type_parameter.clone(),
                    )
                } else {
                    (
                        format!("collections.abc.Callable[..., {}]", result_annotation),
                        None,
                    )
                };
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation,
                positional_args: Vec::new(),
                args_annotation: Some("list[typing.Any]".to_string()),
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                self_type_parameter: case_self_type_parameter,
                type_parameters,
            });
        }
        RenderedFunctionArgs::Varargs { prefix } => {
            let type_parameter_prefix = function_overload_parameter_prefix(function);
            let first_arg = format!("{type_parameter_prefix}Arg");
            let callable_prefix = prefix
                .iter()
                .enumerate()
                .map(|(index, parameter)| {
                    self_type_parameter
                        .as_ref()
                        .filter(|_| index == 0)
                        .cloned()
                        .unwrap_or_else(|| parameter.annotation.clone())
                })
                .collect::<Vec<_>>();
            let no_arg_callable_args = python_callable_arg_list(&callable_prefix);
            let mut one_arg_callable_prefix = callable_prefix;
            one_arg_callable_prefix.push(first_arg.clone());
            let one_arg_callable_args = python_callable_arg_list(&one_arg_callable_prefix);
            let type_parameters = result_type_parameter
                .iter()
                .map(|name| PythonTypeParameter::TypeVar(name.clone()))
                .chain(
                    self_type_parameter
                        .iter()
                        .map(|name| PythonTypeParameter::TypeVar(name.clone())),
                )
                .collect();
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[[{}], {}]",
                    no_arg_callable_args, result_annotation
                ),
                positional_args: Vec::new(),
                args_annotation: None,
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                self_type_parameter: self_type_parameter.clone(),
                type_parameters,
            });
            let mut type_parameters = Vec::new();
            if let Some(result_type_parameter) = &result_type_parameter {
                type_parameters.push(PythonTypeParameter::TypeVar(result_type_parameter.clone()));
            }
            if let Some(self_type_parameter) = &self_type_parameter {
                type_parameters.push(PythonTypeParameter::TypeVar(self_type_parameter.clone()));
            }
            type_parameters.push(PythonTypeParameter::TypeVar(first_arg.clone()));
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[[{}], {}]",
                    one_arg_callable_args, result_annotation
                ),
                positional_args: Vec::new(),
                args_annotation: Some(first_arg.clone()),
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                self_type_parameter: self_type_parameter.clone(),
                type_parameters,
            });
            let type_parameters = result_type_parameter
                .iter()
                .map(|name| PythonTypeParameter::TypeVar(name.clone()))
                .collect();
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: format!(
                    "collections.abc.Callable[..., {}]",
                    result_annotation
                ),
                positional_args: Vec::new(),
                args_annotation: Some("list[typing.Any]".to_string()),
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                self_type_parameter: None,
                type_parameters,
            });
        }
        RenderedFunctionArgs::Typed { parameters } => {
            let args_annotation = python_function_args_list_annotation(
                parameters
                    .iter()
                    .map(|parameter| parameter.annotation.as_str())
                    .collect::<Vec<_>>()
                    .as_slice(),
            );
            let type_parameters = result_type_parameter
                .iter()
                .map(|name| PythonTypeParameter::TypeVar(name.clone()))
                .collect();
            cases.push(RenderedFunctionOverloadCase {
                callable_field_name: function.callable_field_name.clone(),
                args_field_name: function.args_field_name.clone(),
                callable_annotation: python_rendered_function_callable_annotation_with_result(
                    function,
                    result_annotation,
                ),
                positional_args: if function.primary {
                    parameters
                        .iter()
                        .map(|parameter| RenderedFunctionOverloadPositionalArg {
                            name: parameter.name.clone(),
                            annotation: parameter.annotation.clone(),
                            variadic: false,
                        })
                        .collect()
                } else {
                    Vec::new()
                },
                args_annotation: if function.primary {
                    None
                } else if parameters.len() == 1 {
                    Some(parameters[0].annotation.clone())
                } else {
                    Some(args_annotation.clone())
                },
                args_optional: false,
                result_type_parameter: result_type_parameter.clone(),
                self_type_parameter: None,
                type_parameters,
            });
        }
    }

    cases
}

fn python_alternate_function_positional_args(
    function: &RenderedFunctionField,
) -> Vec<RenderedFunctionOverloadPositionalArg> {
    if !function.primary {
        return Vec::new();
    }
    match &function.args {
        RenderedFunctionArgs::Typed { parameters } => parameters
            .iter()
            .map(|parameter| RenderedFunctionOverloadPositionalArg {
                name: parameter.name.clone(),
                annotation: parameter.annotation.clone(),
                variadic: false,
            })
            .collect(),
        RenderedFunctionArgs::Varargs { .. } => {
            vec![RenderedFunctionOverloadPositionalArg {
                name: "positional_args".to_string(),
                annotation: "object".to_string(),
                variadic: true,
            }]
        }
    }
}

fn python_alternate_function_args_annotation(function: &RenderedFunctionField) -> Option<String> {
    match (&function.args, function.primary) {
        (RenderedFunctionArgs::Typed { .. }, true) => None,
        _ => Some("list[typing.Any] | None".to_string()),
    }
}

fn python_rendered_function_callable_annotation_with_result(
    function: &RenderedFunctionField,
    result_annotation: &str,
) -> String {
    match &function.args {
        RenderedFunctionArgs::Varargs { .. } => {
            format!("collections.abc.Callable[..., {}]", result_annotation)
        }
        RenderedFunctionArgs::Typed { parameters } => format!(
            "collections.abc.Callable[[{}], {}]",
            parameters
                .iter()
                .map(|parameter| parameter.annotation.clone())
                .collect::<Vec<_>>()
                .join(", "),
            result_annotation
        ),
    }
}

fn python_function_self_type_parameter(function: &RenderedFunctionField) -> Option<String> {
    match &function.args {
        RenderedFunctionArgs::Varargs { prefix } if !prefix.is_empty() => {
            Some("SelfType".to_string())
        }
        _ => None,
    }
}

fn python_varargs_callable_arg_list(
    prefix: &[RenderedFunctionArg],
    varargs_name: &str,
    self_type_parameter: Option<&String>,
) -> String {
    let mut args = prefix
        .iter()
        .enumerate()
        .map(|(index, parameter)| {
            self_type_parameter
                .filter(|_| index == 0)
                .cloned()
                .unwrap_or_else(|| parameter.annotation.clone())
        })
        .collect::<Vec<_>>();
    args.push(format!("typing_extensions.Unpack[{varargs_name}]"));
    args.join(", ")
}

fn python_callable_arg_list(args: &[String]) -> String {
    if args.is_empty() {
        String::new()
    } else {
        args.join(", ")
    }
}

fn function_overload_parameter_prefix(function: &RenderedFunctionField) -> String {
    function.callable_field_name.to_upper_camel_case()
}

fn primary_function(functions: &[RenderedFunctionField]) -> Option<&RenderedFunctionField> {
    functions.iter().find(|function| function.primary)
}

fn python_function_positional_args_annotation(function: &RenderedFunctionField) -> String {
    match &function.args {
        RenderedFunctionArgs::Typed { parameters } => python_function_args_list_annotation(
            parameters
                .iter()
                .map(|parameter| parameter.annotation.as_str())
                .collect::<Vec<_>>()
                .as_slice(),
        )
        .trim_start_matches("list[")
        .trim_end_matches(']')
        .to_string(),
        RenderedFunctionArgs::Varargs { .. } => "object".to_string(),
    }
}

fn python_function_fixed_positional_args(
    function: &RenderedFunctionField,
) -> Option<&[RenderedFunctionArg]> {
    match &function.args {
        RenderedFunctionArgs::Typed { parameters } if function.primary => Some(parameters),
        _ => None,
    }
}

fn python_function_args_parameter_annotation(
    function: &RenderedFunctionField,
    primary_args: bool,
) -> String {
    match (&function.args, primary_args) {
        (RenderedFunctionArgs::Typed { parameters }, true) => {
            let annotations = parameters
                .iter()
                .map(|parameter| parameter.annotation.as_str())
                .collect::<Vec<_>>();
            format!(
                "{} | None",
                python_function_args_list_annotation(annotations.as_slice())
            )
        }
        (RenderedFunctionArgs::Typed { parameters }, false) => {
            if parameters.len() == 1 {
                format!("{} | None", parameters[0].annotation)
            } else {
                let annotations = parameters
                    .iter()
                    .map(|parameter| parameter.annotation.as_str())
                    .collect::<Vec<_>>();
                format!(
                    "{} | None",
                    python_function_args_list_annotation(annotations.as_slice())
                )
            }
        }
        (RenderedFunctionArgs::Varargs { .. }, true) => "list[typing.Any] | None".to_string(),
        (RenderedFunctionArgs::Varargs { .. }, false) => {
            "object | list[typing.Any] | None".to_string()
        }
    }
}

fn python_function_normalized_args_annotation(function: &RenderedFunctionField) -> String {
    match &function.args {
        RenderedFunctionArgs::Typed { parameters } => {
            let annotations = parameters
                .iter()
                .map(|parameter| parameter.annotation.as_str())
                .collect::<Vec<_>>();
            python_function_args_list_annotation(annotations.as_slice())
        }
        RenderedFunctionArgs::Varargs { .. } => "list[typing.Any]".to_string(),
    }
}

fn overload_case_for_callable<'a>(
    overload_cases: &'a [RenderedFunctionOverloadCase],
    callable_field_name: &str,
) -> Option<&'a RenderedFunctionOverloadCase> {
    overload_cases
        .iter()
        .find(|function_case| function_case.callable_field_name == callable_field_name)
}

fn render_function_unpacked_overload(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    unpacked_input: &RenderedUnpackedInput,
    overload_cases: &[RenderedFunctionOverloadCase],
) {
    render_function_unpacked_overload_case_doc(output, unpacked_input, overload_cases);
    output.push_str("@typing.overload\n");
    output.push_str("async def ");
    output.push_str(&operation.attr_name);
    output.push_str("(\n");
    render_endpoint_parameter(output, service);

    let primary_function = primary_function(&unpacked_input.functions);
    let primary_case = primary_function.and_then(|function| {
        overload_case_for_callable(overload_cases, &function.callable_field_name)
    });
    if let (Some(function), Some(function_case)) = (primary_function, primary_case) {
        output.push_str("    ");
        output.push_str(&function.callable_field_name);
        output.push_str(": ");
        output.push_str(&function_case.callable_annotation);
        output.push_str(",\n");
        for positional_arg in &function_case.positional_args {
            output.push_str("    ");
            if positional_arg.variadic {
                output.push('*');
            }
            output.push_str(&function_overload_positional_arg_render_name(
                positional_arg,
                unpacked_input,
                primary_function,
                primary_case,
                overload_cases,
            ));
            output.push_str(": ");
            output.push_str(&positional_arg.annotation);
            output.push_str(",\n");
        }
    }

    if !primary_case.is_some_and(|function_case| !function_case.positional_args.is_empty()) {
        output.push_str("    *,\n");
    }

    for field in &unpacked_input.parameters {
        if primary_function.is_some_and(|function| function.callable_field_name == field.attr_name)
        {
            continue;
        }
        if primary_function
            .and_then(python_function_fixed_positional_args)
            .is_some_and(|parameters| {
                parameters
                    .iter()
                    .any(|parameter| parameter.name == field.attr_name)
            })
        {
            continue;
        }
        if primary_function.is_some_and(|function| function.args_field_name == field.attr_name) {
            if let Some(function_case) = primary_case {
                if let Some(args_annotation) = &function_case.args_annotation {
                    output.push_str("    ");
                    output.push_str(&field.attr_name);
                    output.push_str(": ");
                    output.push_str(args_annotation);
                    if function_case.args_optional {
                        output.push_str(" = ...");
                    }
                    output.push_str(",\n");
                }
            }
            continue;
        }

        if let Some(function_case) = overload_cases
            .iter()
            .find(|function_case| function_case.callable_field_name == field.attr_name)
        {
            output.push_str("    ");
            output.push_str(&field.attr_name);
            output.push_str(": ");
            output.push_str(&function_case.callable_annotation);
            if field.default_kind != PythonFieldDefaultKind::Required {
                output.push_str(" = ...");
            }
            output.push_str(",\n");
            continue;
        }

        if let Some(function_case) = overload_cases
            .iter()
            .find(|function_case| function_case.args_field_name == field.attr_name)
        {
            if let Some(args_annotation) = &function_case.args_annotation {
                output.push_str("    ");
                output.push_str(&field.attr_name);
                output.push_str(": ");
                output.push_str(args_annotation);
                if function_case.args_optional {
                    output.push_str(" = ...");
                }
                output.push_str(",\n");
            }
            continue;
        }

        output.push_str("    ");
        output.push_str(&field.attr_name);
        output.push_str(": ");
        output.push_str(&python_parameter_annotation(
            &field.annotation,
            &field.default_kind,
        ));
        if field.default_kind != PythonFieldDefaultKind::Required {
            output.push_str(" = ...");
        }
        output.push_str(",\n");
    }

    output.push_str(") -> ");
    output.push_str(&function_unpacked_overload_return_annotation(
        service,
        operation,
        overload_cases,
    ));
    output.push_str(": ...\n");
}

fn function_overload_positional_arg_render_name(
    positional_arg: &RenderedFunctionOverloadPositionalArg,
    unpacked_input: &RenderedUnpackedInput,
    primary_function: Option<&RenderedFunctionField>,
    primary_case: Option<&RenderedFunctionOverloadCase>,
    overload_cases: &[RenderedFunctionOverloadCase],
) -> String {
    if positional_arg.variadic
        && positional_arg.name == "positional_args"
        && !function_unpacked_overload_renders_parameter_name(
            unpacked_input,
            primary_function,
            primary_case,
            overload_cases,
            "args",
        )
    {
        "args".to_string()
    } else {
        positional_arg.name.clone()
    }
}

fn function_unpacked_overload_renders_parameter_name(
    unpacked_input: &RenderedUnpackedInput,
    primary_function: Option<&RenderedFunctionField>,
    primary_case: Option<&RenderedFunctionOverloadCase>,
    overload_cases: &[RenderedFunctionOverloadCase],
    name: &str,
) -> bool {
    if let Some(function) = primary_function {
        if function.callable_field_name == name {
            return true;
        }
        if primary_case.is_some_and(|case| {
            case.positional_args.iter().any(|arg| arg.name == name)
                || (case.args_annotation.is_some() && case.args_field_name == name)
        }) {
            return true;
        }
    }

    for field in &unpacked_input.parameters {
        if primary_function.is_some_and(|function| function.callable_field_name == field.attr_name)
        {
            continue;
        }
        if primary_function
            .and_then(python_function_fixed_positional_args)
            .is_some_and(|parameters| {
                parameters
                    .iter()
                    .any(|parameter| parameter.name == field.attr_name)
            })
        {
            continue;
        }
        if primary_function.is_some_and(|function| function.args_field_name == field.attr_name) {
            if primary_case.is_some_and(|case| case.args_annotation.is_some())
                && field.attr_name == name
            {
                return true;
            }
            continue;
        }

        if overload_cases
            .iter()
            .any(|case| case.callable_field_name == field.attr_name)
        {
            if field.attr_name == name {
                return true;
            }
            continue;
        }

        if let Some(function_case) = overload_cases
            .iter()
            .find(|function_case| function_case.args_field_name == field.attr_name)
        {
            if function_case.args_annotation.is_some() && field.attr_name == name {
                return true;
            }
            continue;
        }

        if field.attr_name == name {
            return true;
        }
    }

    false
}

fn render_function_unpacked_overload_case_doc(
    output: &mut String,
    unpacked_input: &RenderedUnpackedInput,
    overload_cases: &[RenderedFunctionOverloadCase],
) {
    output.push_str("# Overload case:\n");
    for overload_case in ordered_function_overload_cases(unpacked_input, overload_cases) {
        output.push_str("# - ");
        output.push_str(&function_overload_case_doc(&overload_case));
        output.push('\n');
    }
}

fn ordered_function_overload_cases<'a>(
    unpacked_input: &RenderedUnpackedInput,
    overload_cases: &'a [RenderedFunctionOverloadCase],
) -> Vec<&'a RenderedFunctionOverloadCase> {
    let mut ordered = Vec::new();
    let mut rendered = BTreeSet::new();
    for field in &unpacked_input.parameters {
        if let Some(overload_case) = overload_cases
            .iter()
            .find(|overload_case| overload_case.callable_field_name == field.attr_name)
        {
            rendered.insert(overload_case.callable_field_name.clone());
            ordered.push(overload_case);
        }
    }
    for overload_case in overload_cases {
        if !rendered.contains(&overload_case.callable_field_name) {
            ordered.push(overload_case);
        }
    }
    ordered
}

fn function_overload_case_doc(overload_case: &RenderedFunctionOverloadCase) -> String {
    let callable_label = python_readable_name(&overload_case.callable_field_name);
    let callable_kind = if overload_case
        .callable_annotation
        .starts_with("collections.abc.Callable")
    {
        if overload_case.self_type_parameter.is_some() {
            "method callable"
        } else {
            "callable"
        }
    } else {
        "name"
    };
    let args_label = python_function_args_doc_label(
        &overload_case.callable_field_name,
        &overload_case.args_field_name,
    );
    format!(
        "{callable_label} {callable_kind} with {}",
        function_overload_args_doc(overload_case, &args_label)
    )
}

fn python_readable_name(name: &str) -> String {
    name.replace('_', " ")
}

fn python_function_args_doc_label(callable_field_name: &str, args_field_name: &str) -> String {
    if args_field_name == "args" {
        return format!("{} arguments", python_readable_name(callable_field_name));
    }
    if let Some(prefix) = args_field_name.strip_suffix("_args") {
        return format!("{} arguments", python_readable_name(prefix));
    }
    python_readable_name(args_field_name)
}

fn function_overload_args_doc(
    overload_case: &RenderedFunctionOverloadCase,
    args_label: &str,
) -> String {
    if !overload_case.positional_args.is_empty() {
        if overload_case
            .callable_annotation
            .starts_with("collections.abc.Callable")
            && overload_case
                .positional_args
                .iter()
                .any(|arg| arg.annotation != "object")
        {
            return format!("typed positional {args_label}");
        }
        return format!("positional {args_label}");
    }

    let Some(args_annotation) = &overload_case.args_annotation else {
        return format!("no {args_label}");
    };

    if args_annotation.contains("list[") {
        if overload_case.args_optional {
            format!("optional list-form {args_label}")
        } else {
            format!("list-form {args_label}")
        }
    } else {
        format!("a typed single {args_label}")
    }
}

fn function_unpacked_overload_return_annotation(
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    overload_cases: &[RenderedFunctionOverloadCase],
) -> String {
    let mut active_type_parameters = overload_cases
        .iter()
        .filter_map(|function_case| function_case.result_type_parameter.as_ref())
        .cloned()
        .collect::<BTreeSet<_>>();
    let self_type_parameter = overload_cases
        .iter()
        .find_map(|function_case| function_case.self_type_parameter.as_ref());
    if self_type_parameter.is_some() {
        active_type_parameters.extend(operation.output_type_parameters.iter().cloned());
    }
    let mut output_annotation = erase_inactive_python_type_parameters(
        &operation.overload_output_annotation,
        &operation.output_type_parameters,
        &active_type_parameters,
    );
    if let Some(self_type_parameter) = self_type_parameter {
        for output_type_parameter in &operation.output_type_parameters {
            output_annotation = replace_python_identifier(
                &output_annotation,
                output_type_parameter,
                self_type_parameter,
            );
        }
    }
    let output_annotation = temporalio_workflow_type_annotation(service, &output_annotation);
    if operation.output_transform_expr.is_some()
        || operation.output_resource_return.is_some()
        || operation.output_direct_result
    {
        output_annotation
    } else {
        format!(
            "{}[{output_annotation}]",
            temporalio_workflow_type_ref(service, "NexusOperationHandle")
        )
    }
}

fn erase_inactive_python_type_parameters(
    annotation: &str,
    type_parameters: &BTreeSet<String>,
    active_type_parameters: &BTreeSet<String>,
) -> String {
    let inactive_type_parameters = type_parameters
        .difference(active_type_parameters)
        .cloned()
        .collect::<BTreeSet<_>>();
    erase_python_type_parameters(annotation, &inactive_type_parameters)
}

fn erase_python_type_parameters(annotation: &str, type_parameters: &BTreeSet<String>) -> String {
    erase_python_type_parameters_with_replacement(annotation, type_parameters, "object")
}

fn erase_python_type_parameters_with_replacement(
    annotation: &str,
    type_parameters: &BTreeSet<String>,
    replacement: &str,
) -> String {
    type_parameters
        .iter()
        .fold(annotation.to_string(), |current, name| {
            replace_python_identifier(&current, name, replacement)
        })
}

fn python_annotation_uses_identifier(annotation: &str, identifier: &str) -> bool {
    annotation != replace_python_identifier(annotation, identifier, "typing.Any")
}

fn replace_python_identifier(source: &str, identifier: &str, replacement: &str) -> String {
    if identifier.is_empty() {
        return source.to_string();
    }

    let mut output = String::with_capacity(source.len());
    let mut index = 0;
    while let Some(relative_match_start) = source[index..].find(identifier) {
        let match_start = index + relative_match_start;
        let match_end = match_start + identifier.len();
        let before = source[..match_start].chars().next_back();
        let after = source[match_end..].chars().next();
        if before.is_some_and(|character| is_python_identifier_char(character) || character == '.')
            || after.is_some_and(is_python_identifier_char)
        {
            output.push_str(&source[index..match_end]);
        } else {
            output.push_str(&source[index..match_start]);
            output.push_str(replacement);
        }
        index = match_end;
    }
    output.push_str(&source[index..]);
    output
}

fn render_operation_functions(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
) {
    render_request_only_operation_function(output, service, operation);
    if let Some(unpacked_input) = &operation.unpacked_input {
        output.push('\n');
        if function_unpacked_needs_overloads(&unpacked_input.functions) {
            render_function_unpacked_overloads(output, service, operation, unpacked_input);
            output.push('\n');
        }
        render_unpacked_operation_function(output, service, operation, unpacked_input);
    }
}

fn function_unpacked_needs_overloads(functions: &[RenderedFunctionField]) -> bool {
    functions.iter().any(|function| {
        function.alternate_annotation.is_some()
            || matches!(function.args, RenderedFunctionArgs::Varargs { .. })
    })
}

fn request_operation_function_name(operation: &RenderedOperation<'_>) -> String {
    if operation.unpacked_input.is_some() {
        format!("_{}", operation.attr_name)
    } else {
        operation.attr_name.clone()
    }
}

