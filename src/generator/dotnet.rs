fn render_variant(output: &mut String, variant: &PlannedVariant) {
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    output.push_str("public abstract record ");
    output.push_str(&csharp_type_name(&variant.name));
    output.push_str("\n{\n");
    output.push_str("    private ");
    output.push_str(&csharp_type_name(&variant.name));
    output.push_str("() { }\n\n");
    for (index, case) in variant.cases.iter().enumerate() {
        let case_name = csharp_type_name(&case.name);
        output.push_str("    ");
        output.push_str(GENERATED_CODE_ATTRIBUTE);
        output.push('\n');
        output.push_str("    public sealed record ");
        output.push_str(&case_name);
        if let Some(payload) = &case.payload {
            let payload_type = dotnet_value_type(payload);
            output.push('(');
            output.push_str(&payload_type);
            output.push_str(" Value) : ");
        } else {
            output.push_str(" : ");
        }
        output.push_str(&csharp_type_name(&variant.name));
        output.push_str(";\n");
        if index + 1 < variant.cases.len() {
            output.push('\n');
        }
    }
    output.push_str("}\n\n");
}

fn render_model(
    output: &mut String,
    model: &PlannedModel,
    api_plan: &PlannedSpec,
    support_namespace: Option<&str>,
) {
    render_xml_summary(output, "", dotnet_doc(model.doc()), model.experimental);
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    let access = model_access(model, api_plan);
    output.push_str(access);
    output.push_str(" class ");
    let type_name = csharp_type_name(&model.name);
    output.push_str(&type_name);
    output.push_str("\n{\n");
    render_model_constructor(output, access, &type_name, model, api_plan);
    for (field_name, field) in model.public_fields() {
        render_field_xml_doc(output, "    ", field);
        output.push_str("    public ");
        output.push_str(&model_field_type(model, field_name, field, api_plan));
        output.push(' ');
        output.push_str(&field_property_name(field));
        if field.required {
            output.push_str(" { get; }\n");
        } else {
            output.push_str(" { get; init; }\n");
        }
    }
    if model_needs_to_proto_method(model) {
        if model.public_fields().next().is_some() {
            output.push('\n');
        }
        render_model_to_proto_method(output, model, api_plan, support_namespace);
    }
    output.push_str("}\n\n");
}

fn render_model_constructor(
    output: &mut String,
    access: &str,
    type_name: &str,
    model: &PlannedModel,
    api_plan: &PlannedSpec,
) {
    let required_fields = model
        .public_fields()
        .filter(|(_, field)| field.required)
        .collect::<Vec<_>>();
    if required_fields.is_empty() {
        return;
    }
    output.push_str("    ");
    output.push_str(access);
    output.push(' ');
    output.push_str(type_name);
    output.push('(');
    for (index, (field_name, field)) in required_fields.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&model_field_type(model, field_name, field, api_plan));
        output.push(' ');
        output.push_str(&csharp_parameter_name(&field.name));
    }
    output.push_str(")\n    {\n");
    for (_, field) in required_fields {
        output.push_str("        ");
        output.push_str(&field_property_name(field));
        output.push_str(" = ");
        output.push_str(&csharp_parameter_name(&field.name));
        output.push_str(";\n");
    }
    output.push_str("    }\n\n");
}

fn model_access(model: &PlannedModel, api_plan: &PlannedSpec) -> &'static str {
    if public_model_names(api_plan).contains(&model.full_name) {
        "public"
    } else {
        "internal"
    }
}

fn public_model_names(api_plan: &PlannedSpec) -> HashSet<String> {
    let mut names = HashSet::new();
    for service in &api_plan.services {
        for operation in &service.operations {
            collect_public_operation_models(&mut names, operation, api_plan);
        }
        for resource in &service.resources {
            collect_public_resource_models(&mut names, &resource.data, api_plan);
        }
    }

    loop {
        let before = names.len();
        for name in names.clone() {
            let Some(model) = api_plan.records.get(&name) else {
                continue;
            };
            for (_, field) in model.public_fields() {
                collect_public_field_kind_models(&mut names, &field.field_type, api_plan);
            }
        }
        if names.len() == before {
            break;
        }
    }

    names
}

fn collect_public_operation_models(
    names: &mut HashSet<String>,
    operation: &PlannedOperation,
    api_plan: &PlannedSpec,
) {
    let raw_input_type = operation_raw_input_type(operation.input_model(), api_plan);
    let high_level_input_type = operation_input_type(operation.input_model(), api_plan);
    let has_input = operation_has_input(operation, api_plan);
    if has_input
        && (high_level_input_type == raw_input_type
            || !operation_requires_high_level_request(operation))
        && operation_request_method_access(operation, RequestArgumentKind::Raw, api_plan)
            == "public"
    {
        collect_public_operation_input_models(
            names,
            operation.input_model(),
            &raw_input_type,
            api_plan,
        );
    }
    if has_input
        && high_level_input_type != raw_input_type
        && operation_request_method_access(operation, RequestArgumentKind::HighLevel, api_plan)
            == "public"
    {
        collect_public_operation_input_models(
            names,
            operation.input_model(),
            &high_level_input_type,
            api_plan,
        );
    }

    if let Some(output) = &operation.output
        && let Some(model_type) = output.operation_model()
        && operation.output_transform.is_none()
        && operation.data.output_resource_return.is_none()
        && operation_return_type(operation)
            == csharp_type_name(
                model_type
                    .model_name()
                    .expect("operation output should be a model"),
            )
    {
        collect_public_message_models(names, model_type, api_plan);
    }

    let Some(model) = api_plan.records.get(
        operation
            .input_model()
            .model_full_name()
            .expect("operation input should be a model"),
    ) else {
        return;
    };
    if !operation_has_flattened_convenience(operation, model, api_plan) {
        return;
    }
    for overload in flattened_overloads(model) {
        collect_public_flattened_parameter_models(names, model, api_plan, &overload);
    }
    collect_public_operation_options_models(names, model, api_plan);
}

fn collect_public_flattened_parameter_models(
    names: &mut HashSet<String>,
    model: &PlannedModel,
    api_plan: &PlannedSpec,
    overload: &FlattenedOverload,
) {
    for (field_name, field) in model.public_fields() {
        if field.function.is_none() {
            continue;
        }
        if let Some(nested_model) = flattened_nested_model(field, api_plan) {
            let _ = field_name;
            for (_, nested_field) in nested_model.public_fields() {
                if nested_field.function.is_some() {
                    collect_public_field_kind_models(names, &nested_field.field_type, api_plan);
                }
            }
            continue;
        }
        collect_public_field_kind_models(names, &field.field_type, api_plan);
        if matches!(
            overload.function_mode(field_name),
            FlattenedFunctionMode::String
        ) && let Some(function) = &field.function
        {
            for arg_field_name in &function.arg_fields {
                if let Some(arg_field) = model.fields.get(arg_field_name) {
                    collect_public_field_kind_models(names, &arg_field.field_type, api_plan);
                }
            }
        }
    }
}

fn collect_public_operation_options_models(
    names: &mut HashSet<String>,
    model: &PlannedModel,
    api_plan: &PlannedSpec,
) {
    if !model_has_options_fields(model, api_plan) {
        return;
    }
    for (field_name, field) in model.public_fields() {
        if let Some(nested_model) = flattened_nested_model(field, api_plan) {
            let _ = field_name;
            for (nested_field_name, nested_field) in nested_model.public_fields() {
                if field_is_options_field(nested_model, nested_field_name, nested_field) {
                    collect_public_field_kind_models(names, &nested_field.field_type, api_plan);
                }
            }
            continue;
        }
        if field_is_options_field(model, field_name, field) {
            collect_public_field_kind_models(names, &field.field_type, api_plan);
        }
    }
}

fn collect_public_resource_models(
    names: &mut HashSet<String>,
    resource: &PlannedResource,
    api_plan: &PlannedSpec,
) {
    for field in &resource.fields {
        collect_public_field_kind_models(names, &field.kind, api_plan);
    }
    for method in &resource.methods {
        for param in &method.params {
            collect_public_field_kind_models(names, &param.kind, api_plan);
        }
        if let Some(result) = &method.result
            && let PlannedResourceMethodResultKind::Value(kind) = &result.kind
        {
            collect_public_field_kind_models(names, kind, api_plan);
        }
    }
}

fn collect_public_field_kind_models(
    names: &mut HashSet<String>,
    kind: &PlannedType,
    api_plan: &PlannedSpec,
) {
    match kind {
        PlannedType::Option(value) | PlannedType::List(value) => {
            collect_public_value_models(names, value, api_plan)
        }
        PlannedType::Map(key, value) => {
            collect_public_value_models(names, key, api_plan);
            collect_public_value_models(names, value, api_plan);
        }
        value => collect_public_value_models(names, value, api_plan),
    }
}

fn collect_public_value_models(
    names: &mut HashSet<String>,
    value: &PlannedType,
    api_plan: &PlannedSpec,
) {
    match value {
        model_type @ (PlannedType::External(ExternalTypeSpec::Proto(
            PlannedProtoType::Message(_),
        ))
        | PlannedType::Record(_)) => collect_public_message_models(names, model_type, api_plan),
        PlannedType::Resource(_) => {}
        PlannedType::Tuple(items) => {
            for item in items {
                collect_public_value_models(names, item, api_plan);
            }
        }
        PlannedType::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_public_value_models(names, ok, api_plan);
            }
            if let Some(err) = err {
                collect_public_value_models(names, err, api_plan);
            }
        }
        PlannedType::External(ExternalTypeSpec::Alias {
            type_name,
            target: fallback,
            ..
        }) => {
            if type_name.for_language(Language::Dotnet).is_none() {
                collect_public_value_models(names, fallback, api_plan);
            }
        }
        _ => {}
    }
}

fn collect_public_message_models(
    names: &mut HashSet<String>,
    model_type: &PlannedType,
    api_plan: &PlannedSpec,
) {
    if model_type
        .proto_message()
        .is_some_and(|proto| proto.replacement.is_some())
    {
        return;
    }
    if let Some(full_name) = model_type.model_full_name()
        && api_plan.records.contains_key(full_name)
    {
        names.insert(full_name.to_string());
    }
}

fn collect_public_operation_input_models(
    names: &mut HashSet<String>,
    model_type: &PlannedType,
    input_type: &str,
    api_plan: &PlannedSpec,
) {
    if input_type
        == csharp_type_name(
            model_type
                .model_name()
                .expect("operation input should be a model"),
        )
    {
        collect_public_message_models(names, model_type, api_plan);
    }
}

fn render_resource(
    output: &mut String,
    service: &PlannedService,
    resource: &PlannedResource,
    api_plan: &PlannedSpec,
) {
    let type_name = csharp_type_name(&resource.type_name);
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    output.push_str("public class ");
    output.push_str(&type_name);
    output.push_str("\n{\n");
    output.push_str("    public ");
    output.push_str(&type_name);
    output.push('(');
    for (index, field) in resource.fields.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&resource_field_type(&field.kind, field.optional));
        output.push(' ');
        output.push_str(&csharp_parameter_name(&field.name));
    }
    output.push_str(")\n    {\n");
    for field in &resource.fields {
        output.push_str("        ");
        output.push_str(&csharp_type_name(&field.name));
        output.push_str(" = ");
        output.push_str(&csharp_parameter_name(&field.name));
        output.push_str(";\n");
    }
    output.push_str("    }\n\n");
    for field in &resource.fields {
        output.push_str("    public ");
        output.push_str(&resource_field_type(&field.kind, field.optional));
        output.push(' ');
        output.push_str(&csharp_type_name(&field.name));
        output.push_str(" { get; }\n");
    }
    if !resource.fields.is_empty() && !resource.methods.is_empty() {
        output.push('\n');
    }
    for method in &resource.methods {
        render_resource_method(output, service, method, api_plan);
    }
    output.push_str("}\n\n");
}

fn render_resource_method(
    output: &mut String,
    service: &PlannedService,
    method: &PlannedResourceMethod,
    api_plan: &PlannedSpec,
) {
    let operation = match &method.binding {
        PlannedResourceMethodBindingSpec::Operation { operation_name, .. } => service
            .operations
            .iter()
            .find(|operation| operation.name == *operation_name),
        PlannedResourceMethodBindingSpec::Stub => None,
    };
    let return_type = resource_method_task_return_type(method);
    output.push_str("    ");
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    output.push_str("    public ");
    output.push_str(&return_type);
    output.push(' ');
    output.push_str(&csharp_type_name(&method.name));
    output.push_str("Async");
    output.push('(');
    for (index, param) in method.params.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&resource_field_type(&param.kind, param.optional));
        output.push(' ');
        output.push_str(&csharp_parameter_name(&param.name));
    }
    output.push(')');
    match &method.binding {
        PlannedResourceMethodBindingSpec::Operation {
            operation_name: _,
            request_plan,
            ..
        } => {
            let operation =
                operation.expect("bound resource operation should exist on the service");
            output.push_str("\n    {\n");
            render_resource_method_operation_body(
                output,
                service,
                operation,
                request_plan,
                api_plan,
            );
            output.push_str("    }\n\n");
        }
        PlannedResourceMethodBindingSpec::Stub => {
            output.push_str(" => throw new NotSupportedException(\"Resource method is not bound to a Nexus operation.\");\n\n");
        }
    }
}

fn render_resource_method_operation_body(
    output: &mut String,
    service: &PlannedService,
    operation: &PlannedOperation,
    request_plan: &RequestPlan,
    api_plan: &PlannedSpec,
) {
    let operation_method_name = format!("{}Async", csharp_type_name(&operation.name));
    let operation_class_name = dotnet_operations_class_name(service);
    let args = resource_method_operation_call_args(operation, request_plan, api_plan)
        .expect("bound resource operation should have a renderable request plan");
    if args.len() == 1 {
        output.push_str("        var request = ");
        output.push_str(&args[0]);
        output.push_str(";\n");
    }
    output.push_str("        return ");
    output.push_str(&operation_class_name);
    output.push('.');
    output.push_str(&operation_method_name);
    output.push('(');
    if args.len() == 1 {
        output.push_str("request");
    } else {
        output.push_str(&args.join(", "));
    }
    output.push_str(");\n");
}

fn resource_method_operation_call_args(
    operation: &PlannedOperation,
    request_plan: &RequestPlan,
    api_plan: &PlannedSpec,
) -> Option<Vec<String>> {
    let model = api_plan_record_for_request_name(
        api_plan,
        operation
            .input_model()
            .model_full_name()
            .expect("operation input should be a model"),
    )?;
    if operation_has_flattened_convenience(operation, model, api_plan) {
        if model
            .public_fields()
            .any(|(_, field)| field.function.is_some())
        {
            return resource_method_flattened_operation_call_args(
                operation,
                request_plan,
                model,
                api_plan,
            );
        }
        if model_has_options_fields(model, api_plan)
            && let Some(expr) = resource_method_request_model_init_expr(
                request_plan,
                api_plan,
                Some(&operation_options_type_name(operation)),
                ResourceMethodRequestInitKind::OptionsFields,
            )
        {
            return Some(vec![expr]);
        }
    }

    resource_method_request_model_init_expr(
        request_plan,
        api_plan,
        None,
        ResourceMethodRequestInitKind::AllFields,
    )
    .map(|expr| vec![expr])
}

fn resource_method_flattened_operation_call_args(
    operation: &PlannedOperation,
    request_plan: &RequestPlan,
    model: &PlannedModel,
    api_plan: &PlannedSpec,
) -> Option<Vec<String>> {
    let source_exprs = resource_method_request_field_exprs(request_plan, model, api_plan)?;
    let overload = flattened_overloads(model)
        .into_iter()
        .find(|overload| !overload.has_expression_functions())?;
    let mut args = Vec::new();
    for (field_name, field) in model.public_fields() {
        if field.function.is_none() {
            continue;
        }
        if flattened_nested_model(field, api_plan).is_some() {
            return None;
        }
        args.push(resource_method_request_source_expr(
            &source_exprs,
            field_name,
            field,
        )?);
        if matches!(
            overload.function_mode(field_name),
            FlattenedFunctionMode::String
        ) && let Some(function) = &field.function
        {
            for arg_field_name in &function.arg_fields {
                let arg_field = model.fields.get(arg_field_name)?;
                args.push(
                    resource_method_request_source_expr(&source_exprs, arg_field_name, arg_field)
                        .or_else(|| (!arg_field.required).then(|| "null".to_string()))?,
                );
            }
        }
    }
    if model_has_options_fields(model, api_plan) {
        args.push(resource_method_request_model_init_expr(
            request_plan,
            api_plan,
            Some(&operation_options_type_name(operation)),
            ResourceMethodRequestInitKind::OptionsFields,
        )?);
    }
    Some(args)
}

#[derive(Clone, Copy)]
enum ResourceMethodRequestInitKind {
    AllFields,
    OptionsFields,
}

fn resource_method_request_model_init_expr(
    request_plan: &RequestPlan,
    api_plan: &PlannedSpec,
    type_name_override: Option<&str>,
    init_kind: ResourceMethodRequestInitKind,
) -> Option<String> {
    let RequestPlan::Construct {
        message_name,
        fields,
    } = request_plan
    else {
        return None;
    };
    let model = api_plan_record_for_request_name(api_plan, message_name)?;
    let mut field_exprs = Vec::new();
    for field in fields {
        let (model_field_name, model_field) =
            model.public_fields().find(|(field_name, candidate)| {
                candidate.name == field.field_name || *field_name == field.field_name
            })?;
        if matches!(init_kind, ResourceMethodRequestInitKind::OptionsFields)
            && !field_is_options_field(model, model_field_name, model_field)
        {
            continue;
        }
        field_exprs.push((
            model_field,
            resource_method_request_value_expr(&field.value, api_plan)?,
        ));
    }
    Some(model_init_expr(
        type_name_override.unwrap_or(&csharp_type_name(&model.name)),
        field_exprs,
    ))
}

fn api_plan_record_for_request_name<'a>(
    api_plan: &'a PlannedSpec,
    name: &str,
) -> Option<&'a PlannedModel> {
    api_plan.records.get(name).or_else(|| {
        let name = name.trim_start_matches('.');
        api_plan.records.values().find(|record| {
            matches!(
                record.source_type.as_ref(),
                Some(TypeSpec::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(
                    message
                )))) if message.proto.full_name == name
            )
        })
    })
}

fn resource_method_request_field_exprs(
    request_plan: &RequestPlan,
    model: &PlannedModel,
    api_plan: &PlannedSpec,
) -> Option<BTreeMap<String, String>> {
    let RequestPlan::Construct { fields, .. } = request_plan else {
        return None;
    };
    let mut source_exprs = BTreeMap::new();
    for field in fields {
        let (model_field_name, model_field) =
            model.public_fields().find(|(field_name, candidate)| {
                candidate.name == field.field_name || *field_name == field.field_name
            })?;
        let expr = resource_method_request_value_expr(&field.value, api_plan)?;
        source_exprs.insert(model_field.name.clone(), expr.clone());
        source_exprs.insert(model_field_name.to_string(), expr);
    }
    Some(source_exprs)
}

fn resource_method_request_source_expr(
    source_exprs: &BTreeMap<String, String>,
    field_name: &str,
    field: &RecordFieldSpec<PlannedTypeFamily>,
) -> Option<String> {
    source_exprs
        .get(&field.name)
        .or_else(|| source_exprs.get(field_name))
        .cloned()
}

fn resource_method_request_value_expr(
    request_plan: &RequestPlan,
    api_plan: &PlannedSpec,
) -> Option<String> {
    match request_plan {
        RequestPlan::Source(RequestPlanSource::ResourceField(name)) => Some(csharp_type_name(name)),
        RequestPlan::Source(RequestPlanSource::MethodParam(name)) => {
            Some(csharp_parameter_name(name))
        }
        RequestPlan::Construct { .. } => resource_method_request_model_init_expr(
            request_plan,
            api_plan,
            None,
            ResourceMethodRequestInitKind::AllFields,
        ),
    }
}

fn render_result_helper(output: &mut String) {
    output.push_str(GENERATED_CODE_ATTRIBUTE);
    output.push('\n');
    output.push_str("public sealed class NexusResult<TOk, TErr>\n{\n");
    output.push_str("    private NexusResult(bool isOk, TOk? ok, TErr? err)\n");
    output.push_str("    {\n        IsOk = isOk;\n        Ok = ok;\n        Err = err;\n    }\n\n");
    output.push_str("    public bool IsOk { get; }\n");
    output.push_str("    public TOk? Ok { get; }\n");
    output.push_str("    public TErr? Err { get; }\n\n");
    output.push_str("    public static NexusResult<TOk, TErr> FromOk(TOk value) => new(true, value, default);\n");
    output.push_str("    public static NexusResult<TOk, TErr> FromErr(TErr value) => new(false, default, value);\n");
    output.push_str("}\n\n");
}

fn operation_has_input(operation: &PlannedOperation, api_plan: &PlannedSpec) -> bool {
    let input = operation.input_model();
    api_plan
        .records
        .get(
            input
                .model_full_name()
                .expect("operation input should be a model"),
        )
        .is_none_or(|model| {
            model.public_fields().next().is_some()
                || matches!(
                    input,
                    PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(_)))
                )
        })
}

fn operation_input_type(model_type: &PlannedType, api_plan: &PlannedSpec) -> String {
    if model_type
        .proto_message()
        .is_some_and(|proto| proto.replacement.is_some())
    {
        return dotnet_message_type(model_type);
    }
    if let Some(full_name) = model_type.model_full_name()
        && api_plan.records.contains_key(full_name)
    {
        return csharp_type_name(
            model_type
                .model_name()
                .expect("operation input should be a model"),
        );
    }
    dotnet_message_type(model_type)
}

fn operation_return_type(operation: &PlannedOperation) -> String {
    if let Some(transform) = &operation.output_transform
        && let Some(type_name) = transform.type_name.for_language(Language::Dotnet)
    {
        return type_name.to_string();
    }
    if let Some(resource) = &operation.data.output_resource_return {
        return csharp_type_name(&resource.resource_type_name);
    }
    operation_output_type(operation)
}

fn operation_raw_input_type(model_type: &PlannedType, api_plan: &PlannedSpec) -> String {
    if let Some(type_name) = dotnet_planned_record_proto_type_name(model_type, api_plan) {
        return type_name;
    }
    dotnet_message_type(model_type)
}

fn operation_raw_return_type(operation: &PlannedOperation, api_plan: &PlannedSpec) -> String {
    let _ = api_plan;
    operation_output_type(operation)
}

fn operation_output_type(operation: &PlannedOperation) -> String {
    match &operation.output {
        Some(output) if output.operation_model().is_some() => {
            let model_type = output
                .operation_model()
                .expect("operation model presence checked");
            dotnet_message_type(model_type)
        }
        Some(PlannedType::Resource(resource)) => resource
            .proto
            .as_deref()
            .map(dotnet_message_type)
            .unwrap_or_else(|| csharp_type_name(&resource.type_name)),
        None => "void".to_string(),
        Some(_) => panic!("planned operation output should be proto, record, resource, or none"),
    }
}

fn operation_transform_expression(
    operation: &PlannedOperation,
    request_expr: &str,
    request_proto_expr: &str,
    result_expr: &str,
    api_plan: &PlannedSpec,
) -> String {
    if let Some(transform) = &operation.output_transform
        && let Some(expression) = transform.transform.for_language(Language::Dotnet)
    {
        return expression
            .replace("request", request_expr)
            .replace("result", result_expr);
    }
    if let Some(resource) = &operation.data.output_resource_return {
        let args = resource
            .bindings
            .iter()
            .map(|binding| {
                resource_return_binding_expr(
                    resource,
                    binding,
                    request_expr,
                    request_proto_expr,
                    result_expr,
                    api_plan,
                )
            })
            .collect::<Vec<_>>();
        return format!(
            "new {}({})",
            csharp_type_name(&resource.resource_type_name),
            args.join(", ")
        );
    }
    result_expr.to_string()
}

fn resource_return_binding_expr(
    resource: &crate::planning::PlannedOperationResourceReturn,
    binding: &PlannedOperationResourceFieldBinding,
    request_expr: &str,
    request_proto_expr: &str,
    result_expr: &str,
    api_plan: &PlannedSpec,
) -> String {
    match &binding.source {
        ResolvedResourceBindingSource::RequestField {
            field_name,
            proto_field_name,
            hidden,
        } => {
            if *hidden {
                let expr = format!(
                    "{request_proto_expr}.{}",
                    csharp_type_name(proto_field_name)
                );
                optional_resource_binding_expr(resource, binding, expr, api_plan)
            } else {
                format!("{request_expr}.{}", csharp_type_name(field_name))
            }
        }
        ResolvedResourceBindingSource::ResultField {
            proto_field_name, ..
        } => {
            let expr = format!("{result_expr}.{}", csharp_type_name(proto_field_name));
            optional_resource_binding_expr(resource, binding, expr, api_plan)
        }
    }
}

fn optional_resource_binding_expr(
    resource: &crate::planning::PlannedOperationResourceReturn,
    binding: &PlannedOperationResourceFieldBinding,
    expr: String,
    api_plan: &PlannedSpec,
) -> String {
    if binding.optional && resource_field_is_string(resource, &binding.field_name, api_plan) {
        format!("string.IsNullOrEmpty({expr}) ? null : {expr}")
    } else {
        expr
    }
}

fn resource_field_is_string(
    resource_return: &crate::planning::PlannedOperationResourceReturn,
    field_name: &str,
    api_plan: &PlannedSpec,
) -> bool {
    let Some(field_kind) = api_plan
        .services
        .iter()
        .flat_map(|service| service.resources.iter().map(|resource| &resource.data))
        .find(|resource| {
            resource.type_name == resource_return.resource_type_name
                || csharp_type_name(&resource.name) == resource_return.resource_type_name
        })
        .and_then(|resource| {
            resource
                .fields
                .iter()
                .find(|field| field.name == field_name)
        })
        .map(|field| &field.kind)
    else {
        return false;
    };
    matches!(field_kind, PlannedType::String)
}

fn model_needs_to_proto_method(model: &PlannedModel) -> bool {
    model.data.capabilities.to_proto
        && model.data.proto.as_ref().is_some_and(|proto| {
            dotnet_proto_type_name_for_info(proto) != csharp_type_name(&model.name)
        })
}

fn render_model_to_proto_method(
    output: &mut String,
    model: &PlannedModel,
    api_plan: &PlannedSpec,
    support_namespace: Option<&str>,
) {
    let raw_type = dotnet_proto_type_name_for_info(
        model
            .data
            .proto
            .as_ref()
            .expect("model to proto method requires proto backing"),
    );
    output.push_str("    public ");
    output.push_str(&raw_type);
    output.push_str(" ToProto()\n    {\n");
    output.push_str("        var proto = new ");
    output.push_str(&raw_type);
    output.push_str("();\n");
    for (field_name, sourced_field, source_expr) in model.sourced_fields() {
        output.push_str("        proto.");
        output.push_str(&csharp_type_name(field_name));
        output.push_str(" = ");
        let source_expr = qualify_dotnet_support_call(source_expr, support_namespace);
        output.push_str(&field_kind_to_proto_expr(
            &sourced_field.field_type,
            &source_expr,
            false,
            api_plan,
            support_namespace,
        ));
        output.push_str(";\n");
    }
    for (field_name, field) in model.public_fields() {
        render_field_to_proto_assignment(
            output,
            model,
            field_name,
            field,
            api_plan,
            support_namespace,
        );
    }
    output.push_str("        return proto;\n");
    output.push_str("    }\n\n");
}

fn render_field_to_proto_assignment(
    output: &mut String,
    model: &PlannedModel,
    field_name: &str,
    field: &RecordFieldSpec<PlannedTypeFamily>,
    api_plan: &PlannedSpec,
    support_namespace: Option<&str>,
) {
    let property_name = field_property_name(field);
    let source_expr = property_name.to_string();
    let target = format!("proto.{}", csharp_type_name(field_name));
    if field.required {
        output.push_str("        ");
        output.push_str(&target);
        output.push_str(" = ");
        output.push_str(&field_to_proto_expr(
            model,
            field_name,
            field,
            &source_expr,
            api_plan,
            support_namespace,
        ));
        output.push_str(";\n");
    } else {
        output.push_str("        if (");
        output.push_str(&source_expr);
        output.push_str(" is { } ");
        output.push_str(&csharp_parameter_name(&field.name));
        output.push_str(")\n        {\n");
        output.push_str("            ");
        output.push_str(&target);
        output.push_str(" = ");
        output.push_str(&field_to_proto_expr(
            model,
            field_name,
            field,
            &csharp_parameter_name(&field.name),
            api_plan,
            support_namespace,
        ));
        output.push_str(";\n");
        output.push_str("        }\n");
    }
}

fn field_to_proto_expr(
    model: &PlannedModel,
    field_name: &str,
    field: &RecordFieldSpec<PlannedTypeFamily>,
    source_expr: &str,
    api_plan: &PlannedSpec,
    support_namespace: Option<&str>,
) -> String {
    if function_args_field_uses_logical_storage(model, field_name, field) {
        let converter = function_args_to_proto_converter(field)
            .map(|converter| qualify_dotnet_support_reference(converter, support_namespace))
            .unwrap_or_else(|| {
                panic!(
                    "function args field `{}` missing .NET to-proto converter",
                    field_name
                )
            });
        return format!("{converter}({source_expr})");
    }
    field_kind_to_proto_expr(
        &field.field_type,
        source_expr,
        !field.required,
        api_plan,
        support_namespace,
    )
}

fn field_kind_to_proto_expr(
    kind: &PlannedType,
    source_expr: &str,
    optional: bool,
    api_plan: &PlannedSpec,
    support_namespace: Option<&str>,
) -> String {
    match kind {
        PlannedType::List(_) | PlannedType::Map(_, _) => source_expr.to_string(),
        value => value_to_proto_expr(value, source_expr, optional, api_plan, support_namespace),
    }
}

fn value_to_proto_expr(
    value: &PlannedType,
    source_expr: &str,
    optional: bool,
    api_plan: &PlannedSpec,
    support_namespace: Option<&str>,
) -> String {
    match value {
        model_type @ (PlannedType::External(ExternalTypeSpec::Proto(
            PlannedProtoType::Message(_),
        ))
        | PlannedType::Record(_)) => {
            if api_plan
                .records
                .get(model_type.model_full_name().expect("model-shaped value"))
                .is_some_and(|model| model_needs_to_proto_method(model))
            {
                format!("{source_expr}.ToProto()")
            } else {
                message_to_proto_expr(model_type, source_expr, support_namespace)
            }
        }
        PlannedType::Resource(_) => source_expr.to_string(),
        PlannedType::External(ExternalTypeSpec::Alias {
            target: fallback, ..
        }) => value_to_proto_expr(fallback, source_expr, optional, api_plan, support_namespace),
        _ => source_expr.to_string(),
    }
}

fn message_to_proto_expr(
    model_type: &PlannedType,
    source_expr: &str,
    support_namespace: Option<&str>,
) -> String {
    if matches!(
        model_type,
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(_)))
    ) && dotnet_message_type(model_type) != dotnet_proto_type_name_for_message(model_type)
    {
        if let Some(converter) = dotnet_to_proto_converter(model_type) {
            let converter = qualify_dotnet_support_reference(converter, support_namespace);
            return format!("{converter}({source_expr})");
        }
        format!("{source_expr}.ToProto()")
    } else {
        source_expr.to_string()
    }
}

fn model_uses_proto_extensions(model: &PlannedModel, api_plan: &PlannedSpec) -> bool {
    model
        .sourced_fields()
        .any(|(_, field, _)| field_kind_uses_proto_extensions(&field.field_type, api_plan))
        || model.public_fields().any(|(field_name, field)| {
            function_args_field_uses_logical_storage(model, field_name, field)
                || field_kind_uses_proto_extensions(&field.field_type, api_plan)
        })
}

fn field_kind_uses_proto_extensions(kind: &PlannedType, api_plan: &PlannedSpec) -> bool {
    match kind {
        PlannedType::List(value) => value_uses_proto_extensions(value, api_plan),
        PlannedType::Map(key, value) => {
            value_uses_proto_extensions(key, api_plan)
                || value_uses_proto_extensions(value, api_plan)
        }
        value => value_uses_proto_extensions(value, api_plan),
    }
}

fn value_uses_proto_extensions(value: &PlannedType, api_plan: &PlannedSpec) -> bool {
    match value {
        model_type @ (PlannedType::External(ExternalTypeSpec::Proto(
            PlannedProtoType::Message(_),
        ))
        | PlannedType::Record(_)) => {
            api_plan
                .records
                .get(model_type.model_full_name().expect("model-shaped value"))
                .is_some_and(|model| model_needs_to_proto_method(model))
                || (matches!(
                    model_type,
                    PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(_)))
                ) && dotnet_message_type(model_type)
                    != dotnet_proto_type_name_for_message(model_type))
        }
        PlannedType::Resource(_) => false,
        PlannedType::List(inner) => value_uses_proto_extensions(inner, api_plan),
        PlannedType::Map(key, value) => {
            value_uses_proto_extensions(key, api_plan)
                || value_uses_proto_extensions(value, api_plan)
        }
        PlannedType::External(ExternalTypeSpec::Alias {
            target: fallback, ..
        }) => value_uses_proto_extensions(fallback, api_plan),
        PlannedType::Result { ok, err } => {
            ok.as_deref()
                .is_some_and(|ok| value_uses_proto_extensions(ok, api_plan))
                || err
                    .as_deref()
                    .is_some_and(|err| value_uses_proto_extensions(err, api_plan))
        }
        PlannedType::Tuple(items) => items
            .iter()
            .any(|item| value_uses_proto_extensions(item, api_plan)),
        _ => false,
    }
}

fn field_type(field: &RecordFieldSpec<PlannedTypeFamily>, api_plan: &PlannedSpec) -> String {
    let base = high_level_field_kind_type(&field.field_type, api_plan);
    if field.required {
        base
    } else {
        nullable_type(&base)
    }
}

fn model_field_type(
    model: &PlannedModel,
    field_name: &str,
    field: &RecordFieldSpec<PlannedTypeFamily>,
    api_plan: &PlannedSpec,
) -> String {
    if model.function_for_args_field(field_name).is_some()
        && let Some(base) = function_args_parameter_type(model, field_name, field)
    {
        return if field.required {
            base
        } else {
            nullable_type(&base)
        };
    }
    field_type(field, api_plan)
}

fn high_level_field_kind_type(kind: &PlannedType, api_plan: &PlannedSpec) -> String {
    match kind {
        PlannedType::List(value) => {
            format!("IReadOnlyList<{}>", high_level_value_type(value, api_plan))
        }
        PlannedType::Map(key, value) => format!(
            "IReadOnlyDictionary<{}, {}>",
            high_level_value_type(key, api_plan),
            high_level_value_type(value, api_plan)
        ),
        value => high_level_value_type(value, api_plan),
    }
}

fn high_level_value_type(value: &PlannedType, api_plan: &PlannedSpec) -> String {
    match value {
        model_type @ (PlannedType::External(ExternalTypeSpec::Proto(
            PlannedProtoType::Message(_),
        ))
        | PlannedType::Record(_))
            if api_plan
                .records
                .contains_key(model_type.model_full_name().expect("model-shaped value")) =>
        {
            csharp_type_name(model_type.model_name().expect("model-shaped value"))
        }
        _ => dotnet_value_type(value),
    }
}

fn flattened_parameter_type(
    model: &PlannedModel,
    field_name: &str,
    field: &RecordFieldSpec<PlannedTypeFamily>,
    api_plan: &PlannedSpec,
    mode: FlattenedFunctionMode,
) -> String {
    if matches!(mode, FlattenedFunctionMode::Expression)
        && let Some(function) = &field.function
    {
        return function_expression_type(function);
    }
    if model.function_for_args_field(field_name).is_some() {
        let base = function_args_parameter_type(model, field_name, field)
            .unwrap_or_else(|| dotnet_field_kind_type(&field.field_type));
        return if field.required {
            base
        } else {
            nullable_type(&base)
        };
    }
    field_type(field, api_plan)
}

fn function_args_parameter_type(
    model: &PlannedModel,
    field_name: &str,
    field: &RecordFieldSpec<PlannedTypeFamily>,
) -> Option<String> {
    if let Some(field_type) = model.field_type(field_name)
        && !authored_type_is_direct_reference(field_type.without_option())
    {
        return Some(dotnet_function_args_wit_type(field_type));
    }
    function_args_proto_authored_type(field).map(dotnet_function_args_wit_type)
}

fn function_args_proto_authored_type(
    field: &RecordFieldSpec<PlannedTypeFamily>,
) -> Option<&PlannedType> {
    match &field.field_type {
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(proto))) => {
            proto.authored_type.as_deref()
        }
        _ => None,
    }
}

fn authored_type_is_direct_reference(authored_type: &PlannedType) -> bool {
    matches!(
        authored_type,
        TypeSpec::Record(_)
            | TypeSpec::Enum(_)
            | TypeSpec::Flags(_)
            | TypeSpec::Variant(_)
            | TypeSpec::Resource(_)
            | TypeSpec::External(ExternalTypeSpec::Proto(_))
    )
}

fn dotnet_function_args_wit_type(wit_type: &PlannedType) -> String {
    match wit_type.without_option() {
        TypeSpec::List(inner) => format!(
            "IReadOnlyCollection<{}>",
            dotnet_authored_type(inner.without_option())
        ),
        other => dotnet_authored_type(other),
    }
}

fn dotnet_authored_type(wit_type: &PlannedType) -> String {
    match wit_type {
        TypeSpec::Bool => "bool".to_string(),
        TypeSpec::Int(IntSpec::I32) => "int".to_string(),
        TypeSpec::Int(IntSpec::I64) => "long".to_string(),
        TypeSpec::Float => "double".to_string(),
        TypeSpec::String => "string".to_string(),
        TypeSpec::Bytes => "byte[]".to_string(),
        TypeSpec::Option(inner) => nullable_type(&dotnet_authored_type(inner)),
        TypeSpec::List(inner) => {
            format!("IReadOnlyList<{}>", dotnet_authored_type(inner))
        }
        TypeSpec::Tuple(items) => format!(
            "({})",
            items
                .iter()
                .map(dotnet_authored_type)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        TypeSpec::Map(key, value) => format!(
            "IReadOnlyDictionary<{}, {}>",
            dotnet_authored_type(key),
            dotnet_authored_type(value)
        ),
        TypeSpec::Result { ok, err } => format!(
            "NexusResult<{}, {}>",
            ok.as_ref()
                .map(|ok| dotnet_authored_type(ok))
                .unwrap_or_else(|| "object".to_string()),
            err.as_ref()
                .map(|err| dotnet_authored_type(err))
                .unwrap_or_else(|| "object".to_string())
        ),
        TypeSpec::External(ExternalTypeSpec::Proto(proto_name)) => {
            dotnet_proto_type_name_fallback(proto_name.full_name())
        }
        TypeSpec::External(ExternalTypeSpec::Json(json_type)) => {
            csharp_type_name(&json_type.model_name)
        }
        TypeSpec::Record(name) => csharp_type_name(&name.full_name),
        TypeSpec::Enum(name) => csharp_type_name(&name.full_name),
        TypeSpec::Flags(name) => csharp_type_name(&name.full_name),
        TypeSpec::Variant(name) => csharp_type_name(&name.full_name),
        TypeSpec::Resource(name) => csharp_type_name(&name.type_name),
        TypeSpec::External(ExternalTypeSpec::Alias {
            target, type_name, ..
        }) => type_name
            .for_language(Language::Dotnet)
            .map(str::to_string)
            .unwrap_or_else(|| dotnet_authored_type(target)),
    }
}

fn function_args_field_stores_proto(field: &RecordFieldSpec<PlannedTypeFamily>) -> bool {
    matches!(
        &field.field_type,
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(_)))
    )
}

fn function_args_field_uses_logical_storage(
    model: &PlannedModel,
    field_name: &str,
    field: &RecordFieldSpec<PlannedTypeFamily>,
) -> bool {
    model.function_for_args_field(field_name).is_some()
        && function_args_field_stores_proto(field)
        && function_args_parameter_type(model, field_name, field).is_some()
}

fn function_args_to_proto_converter(field: &RecordFieldSpec<PlannedTypeFamily>) -> Option<&str> {
    match &field.field_type {
        model_type @ PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(
            _,
        ))) => dotnet_to_proto_converter(model_type),
        _ => None,
    }
}

fn function_expression_type(function: &FunctionFieldSpec<PlannedTypeFamily>) -> String {
    if function_has_result_type_parameter(function) {
        "Expression<Func<TWorkflow, Task<TResult>>>".to_string()
    } else {
        "Expression<Func<TWorkflow, Task>>".to_string()
    }
}

fn flattened_nested_parameter_type(
    model: &PlannedModel,
    field_name: &str,
    field: &RecordFieldSpec<PlannedTypeFamily>,
    api_plan: &PlannedSpec,
) -> String {
    if let Some(annotation) = model
        .field_flattened_annotation(field_name)
        .and_then(|annotation| annotation.for_language(Language::Dotnet))
    {
        if field.required {
            annotation.to_string()
        } else {
            nullable_type(annotation)
        }
    } else {
        field_type(field, api_plan)
    }
}

fn resource_field_type(kind: &PlannedType, optional: bool) -> String {
    let base = dotnet_field_kind_type(kind);
    if optional { nullable_type(&base) } else { base }
}

fn resource_method_return_type(method: &PlannedResourceMethod) -> String {
    let Some(result) = &method.result else {
        return "void".to_string();
    };
    let base = match &result.kind {
        PlannedResourceMethodResultKind::Resource { type_name } => csharp_type_name(type_name),
        PlannedResourceMethodResultKind::Value(kind) => dotnet_field_kind_type(kind),
    };
    if result.optional {
        nullable_type(&base)
    } else {
        base
    }
}

fn resource_method_task_return_type(method: &PlannedResourceMethod) -> String {
    let return_type = resource_method_return_type(method);
    if return_type == "void" {
        "Task".to_string()
    } else {
        format!("Task<{return_type}>")
    }
}

fn dotnet_field_kind_type(kind: &PlannedType) -> String {
    match kind {
        PlannedType::List(value) => format!("IReadOnlyList<{}>", dotnet_value_type(value)),
        PlannedType::Map(key, value) => format!(
            "IReadOnlyDictionary<{}, {}>",
            dotnet_value_type(key),
            dotnet_value_type(value)
        ),
        value => dotnet_value_type(value),
    }
}

fn dotnet_value_type(value: &PlannedType) -> String {
    match value {
        PlannedType::Float => "double".to_string(),
        PlannedType::Int(IntSpec::I32) => "int".to_string(),
        PlannedType::Int(IntSpec::I64) => "long".to_string(),
        PlannedType::Bool => "bool".to_string(),
        PlannedType::String => "string".to_string(),
        PlannedType::Bytes => "byte[]".to_string(),
        PlannedType::Enum(enumeration) => csharp_type_name(&enumeration.name),
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(enumeration))) => {
            enumeration
                .replacement
                .as_ref()
                .and_then(dotnet_replacement_type_name)
                .unwrap_or_else(|| {
                    dotnet_proto_or_local_type(&enumeration.proto, Some(&enumeration.name))
                })
        }
        PlannedType::Flags(flags) => csharp_type_name(&flags.name),
        PlannedType::Variant(variant) => csharp_type_name(&variant.name),
        model_type @ (PlannedType::External(ExternalTypeSpec::Proto(
            PlannedProtoType::Message(_),
        ))
        | PlannedType::Record(_)) => dotnet_message_type(model_type),
        PlannedType::External(ExternalTypeSpec::Json(json_type)) => {
            csharp_type_name(&json_type.model_name)
        }
        PlannedType::Resource(resource) => csharp_type_name(&resource.type_name),
        PlannedType::Option(inner) => nullable_type(&dotnet_value_type(inner)),
        PlannedType::List(inner) => format!("IReadOnlyList<{}>", dotnet_value_type(inner)),
        PlannedType::Map(key, value) => format!(
            "IReadOnlyDictionary<{}, {}>",
            dotnet_value_type(key),
            dotnet_value_type(value)
        ),
        PlannedType::Tuple(items) => format!(
            "({})",
            items
                .iter()
                .map(dotnet_value_type)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        PlannedType::Result { ok, err } => format!(
            "NexusResult<{}, {}>",
            ok.as_ref()
                .map(|ok| dotnet_value_type(ok))
                .unwrap_or_else(|| "object".to_string()),
            err.as_ref()
                .map(|err| dotnet_value_type(err))
                .unwrap_or_else(|| "object".to_string())
        ),
        PlannedType::External(ExternalTypeSpec::Alias {
            type_name,
            target: fallback,
            ..
        }) => type_name
            .for_language(Language::Dotnet)
            .map(str::to_string)
            .unwrap_or_else(|| dotnet_value_type(fallback)),
    }
}

fn nullable_type(base: &str) -> String {
    if base.ends_with('?') {
        base.to_string()
    } else {
        format!("{base}?")
    }
}

fn field_kind_uses_result(kind: &PlannedType) -> bool {
    value_uses_result(kind)
}

fn value_uses_result(value: &PlannedType) -> bool {
    match value {
        PlannedType::Result { .. } => true,
        PlannedType::List(inner) => value_uses_result(inner),
        PlannedType::Map(key, value) => value_uses_result(key) || value_uses_result(value),
        PlannedType::Tuple(items) => items.iter().any(value_uses_result),
        PlannedType::External(ExternalTypeSpec::Alias {
            target: fallback, ..
        }) => value_uses_result(fallback),
        _ => false,
    }
}

fn support_fragment_path(fragment: &SupportFragmentSpec) -> Result<PathBuf> {
    let path = PathBuf::from(&fragment.path);
    if path.extension().and_then(|extension| extension.to_str()) != Some("cs") {
        return Err(Error::InvalidGeneratedPath {
            path,
            reason: ".NET support files must end with `.cs`".to_string(),
        });
    }
    let file_name = path
        .file_name()
        .ok_or_else(|| Error::InvalidGeneratedPath {
            path: path.clone(),
            reason: "support path must have a file name".to_string(),
        })?
        .to_os_string();
    Ok(PathBuf::from("Support").join(file_name))
}

fn dotnet_namespace(api_plan: &PlannedSpec) -> String {
    api_plan
        .services
        .first()
        .and_then(|service| service.namespace.for_language(Language::Dotnet))
        .map(ToOwned::to_owned)
        .or_else(|| {
            api_plan
                .services
                .first()
                .map(|service| format!("NexGen.{}", csharp_type_name(&service.name)))
        })
        .unwrap_or_else(|| "NexGen.Generated".to_string())
}

