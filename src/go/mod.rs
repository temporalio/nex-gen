#[derive(Debug, Clone)]
struct GoPackageContext {
    package_name: String,
    import_path: Option<String>,
}

impl GoPackageContext {
    fn new(api_plan: &ApiPlan, _options: &GoOptions) -> Self {
        let import_path = api_plan
            .services
            .first()
            .and_then(|service| service.namespace.for_language(Language::Go))
            .map(str::to_string);
        let package_name = import_path.as_ref().map_or_else(
            || {
                api_plan
                    .services
                    .first()
                    .map(|service| go_package_name(&service.endpoint))
                    .unwrap_or_else(|| "api".to_string())
            },
            |import_path| {
                import_path
                    .rsplit('/')
                    .next()
                    .filter(|segment| !segment.is_empty())
                    .map(go_package_name)
                    .unwrap_or_else(|| "api".to_string())
            },
        );

        Self {
            package_name,
            import_path,
        }
    }

    fn is_self_import(&self, import_path: &str) -> bool {
        self.import_path
            .as_deref()
            .is_some_and(|self_import| self_import == import_path)
    }

    fn go_type_expr(&self, type_expr: &str) -> String {
        let (import_path, code_expr) = parse_go_import(type_expr);
        if import_path
            .as_deref()
            .is_some_and(|import_path| self.is_self_import(import_path))
        {
            return self.unqualify_self_expr(&code_expr);
        }
        code_expr
    }

    fn workflow_context_type(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.Context")
    }

    fn workflow_future_type(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.Future")
    }

    fn workflow_nexus_operation_future_type(&self) -> String {
        self.qualified_expr(
            "go.temporal.io/sdk/workflow",
            "workflow.NexusOperationFuture",
        )
    }

    fn new_future(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.NewFuture")
    }

    fn new_nexus_client(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.NewNexusClient")
    }

    fn nexus_operation_options(&self) -> String {
        self.qualified_expr(
            "go.temporal.io/sdk/workflow",
            "workflow.NexusOperationOptions{}",
        )
    }

    fn qualified_expr(&self, import_path: &str, code_expr: &str) -> String {
        if self.is_self_import(import_path) {
            self.unqualify_self_expr(code_expr)
        } else {
            code_expr.to_string()
        }
    }

    fn unqualify_self_expr(&self, code_expr: &str) -> String {
        let qualifier = format!("{}.", self.package_name);
        code_expr.replace(&qualifier, "")
    }
}

/// Entry point for the Go code generator.
///
/// Walks the [`ApiPlan`] to collect all referenced enums, flags, variants, and
/// models, then renders them into a single service-named `.go` file inside a
/// directory output. The Go package name is derived from the first service
/// endpoint unless the first service declares `@nexus.namespace go="..."`.
pub(crate) fn generate(
    api_plan: &ApiPlan,
    support_fragments: &[SupportFragmentSpec],
    options: &GoOptions,
) -> Result<GeneratedFiles> {
    let package = GoPackageContext::new(api_plan, options);
    let mut enums = IndexMap::new();
    let mut flags = IndexMap::new();
    let mut variants = IndexMap::new();
    let mut models = IndexMap::new();
    let mut services = api_plan
        .services
        .iter()
        .map(|service| {
            let operations = service
                .operations
                .iter()
                .map(|operation| {
                    resolve_operation(
                        operation,
                        api_plan,
                        &mut enums,
                        &mut flags,
                        &mut variants,
                        &mut models,
                        &package,
                    )
                })
                .collect::<Result<Vec<_>>>()?;

            Ok(RenderedService {
                name: &service.name,
                wire_name: &service.wire_name,
                endpoint: service.endpoint.clone(),
                operations,
                resources: service.resources.clone(),
            })
        })
        .collect::<Result<Vec<_>>>()?;

    for service in &services {
        for resource in &service.resources {
            ensure_resource_field_types(
                resource,
                api_plan,
                &mut enums,
                &mut flags,
                &mut variants,
                &mut models,
                &package,
            )?;
        }
    }

    let mut imports = BTreeSet::new();

    // Re-scan all resolved type expressions to collect import paths.
    // Type expressions like "temporal.RetryPolicy" were produced by
    // resolve_go_type_annotation which stripped the full module path, but
    // we need to recover the imports from the original annotations.
    // We do this by re-parsing annotations from the ApiPlan.
    collect_imports_from_plan(api_plan, &mut imports);
    imports.retain(|import_path| !package.is_self_import(import_path));

    // Second pass: compute proto conversion metadata for proto-backed models
    // and collect the aliased proto imports they require.
    let mut proto_imports = GoImportCollector::default();
    populate_proto_conversions(api_plan, &mut models, &mut proto_imports, &package)?;
    populate_operation_bindings(api_plan, &mut services, &mut proto_imports, &package)?;

    let visibility = compute_go_visibility(api_plan, &enums, &flags, &variants, &models);
    apply_go_visibility(
        &visibility,
        &mut enums,
        &mut flags,
        &mut variants,
        &mut models,
        &mut services,
    );

    let needs_future_helpers = services.iter().any(service_uses_generated_future_helpers);
    let needs_function_name_inlining = services.iter().any(service_uses_function_name_inlining);

    // Operation wrapper functions require the workflow package.
    let has_operations = services.iter().any(|s| !s.operations.is_empty());
    if has_operations && !package.is_self_import("go.temporal.io/sdk/workflow") {
        imports.insert("go.temporal.io/sdk/workflow".to_string());
    }
    if needs_future_helpers {
        imports.insert("errors".to_string());
    }
    if needs_function_name_inlining {
        imports.insert("reflect".to_string());
        imports.insert("runtime".to_string());
        imports.insert("strings".to_string());
    }
    let output = render_file(
        &package,
        &imports,
        &proto_imports,
        enums.values().collect::<Vec<_>>().as_slice(),
        flags.values().collect::<Vec<_>>().as_slice(),
        variants.values().collect::<Vec<_>>().as_slice(),
        models.values().collect::<Vec<_>>().as_slice(),
        &services,
        api_plan,
        &visibility,
        needs_future_helpers,
    );

    let mut files = BTreeMap::new();
    files.insert(go_api_file_name(api_plan), output);

    // Emit hand-written support fragments (e.g. proto converter functions) in
    // one support file. Like the TypeScript backend, all fragments are emitted
    // unconditionally, even when nothing in the generated code references them.
    if !support_fragments.is_empty() {
        files.insert(
            PathBuf::from("support.go"),
            render_support_file(support_fragments, &package.package_name),
        );
    }

    Ok(GeneratedFiles::directory(files))
}

fn service_uses_generated_future_helpers(service: &RenderedService<'_>) -> bool {
    service.operations.iter().any(|operation| {
        operation.proto_binding.is_some() || operation_uses_native_future_adapter(operation)
    })
}

fn service_uses_function_name_inlining(service: &RenderedService<'_>) -> bool {
    service.operations.iter().any(|operation| {
        operation.unpacked_input.as_ref().is_some_and(|params| {
            params
                .iter()
                .any(|param| param.required && param.function.is_some())
        })
    })
}

fn operation_uses_native_future_adapter(operation: &RenderedOperation<'_>) -> bool {
    if operation.output_transform_expr.is_some() {
        return true;
    }
    operation.proto_binding.as_ref().is_some_and(|binding| {
        binding.output_from_proto.is_some() || binding.resource_return.is_some()
    })
}

/// Derives the primary Go output filename from the first service name
/// (`WorkflowService` -> `workflowservice.go`). Most WIT inputs export a single
/// service; for empty plans, keep the historical `api.go` fallback.
fn go_api_file_name(api_plan: &ApiPlan) -> PathBuf {
    let stem = api_plan
        .services
        .first()
        .map(|service| {
            service
                .name
                .chars()
                .filter(|c| c.is_ascii_alphanumeric())
                .collect::<String>()
                .to_lowercase()
        })
        .filter(|name| !name.is_empty())
        .unwrap_or_else(|| "api".to_string());
    PathBuf::from(format!("{stem}.go"))
}

fn render_support_file(fragments: &[SupportFragmentSpec], package_name: &str) -> String {
    if let [fragment] = fragments {
        return rewrite_support_package(&fragment.contents, package_name);
    }

    let mut prelude = String::new();
    let mut imports = BTreeSet::new();
    let mut bodies = Vec::new();
    for fragment in fragments {
        let parsed = parse_support_fragment(&fragment.contents);
        if prelude.is_empty() {
            prelude = parsed.prelude;
        } else if !parsed.prelude.trim().is_empty() {
            bodies.push(parsed.prelude.trim().to_string());
        }
        imports.extend(parsed.imports);
        if !parsed.body.trim().is_empty() {
            bodies.push(parsed.body.trim().to_string());
        }
    }

    let mut output = String::new();
    if !prelude.trim().is_empty() {
        output.push_str(prelude.trim_end());
        output.push('\n');
    }
    output.push_str("package ");
    output.push_str(package_name);
    output.push_str("\n\n");
    if !imports.is_empty() {
        output.push_str("import (\n");
        for import in imports {
            output.push('\t');
            output.push_str(&import);
            output.push('\n');
        }
        output.push_str(")\n\n");
    }
    output.push_str(&bodies.join("\n\n"));
    output.push('\n');
    output
}

/// Replaces the `package <name>` declaration in a Go support fragment with the
/// generated package name, preserving the rest of the file. If no package
/// declaration is found, the original contents are returned unchanged.
fn rewrite_support_package(contents: &str, package_name: &str) -> String {
    let mut result = String::with_capacity(contents.len());
    let mut replaced = false;
    for line in contents.lines() {
        if !replaced && line.trim_start().starts_with("package ") {
            result.push_str("package ");
            result.push_str(package_name);
            replaced = true;
        } else {
            result.push_str(line);
        }
        result.push('\n');
    }
    result
}

#[derive(Default)]
struct ParsedSupportFragment {
    prelude: String,
    imports: BTreeSet<String>,
    body: String,
}

fn parse_support_fragment(contents: &str) -> ParsedSupportFragment {
    let lines = contents.lines().collect::<Vec<_>>();
    let Some(package_index) = lines
        .iter()
        .position(|line| line.trim_start().starts_with("package "))
    else {
        return ParsedSupportFragment {
            body: contents.to_string(),
            ..Default::default()
        };
    };

    let mut parsed = ParsedSupportFragment {
        prelude: lines[..package_index].join("\n"),
        ..Default::default()
    };
    let mut index = package_index + 1;
    skip_blank_lines(&lines, &mut index);

    while index < lines.len() {
        let line = lines[index].trim_start();
        if line == "import (" {
            index += 1;
            while index < lines.len() && lines[index].trim() != ")" {
                let import = lines[index].trim();
                if !import.is_empty() {
                    parsed.imports.insert(import.to_string());
                }
                index += 1;
            }
            if index < lines.len() {
                index += 1;
            }
        } else if let Some(import) = line.strip_prefix("import ") {
            parsed.imports.insert(import.trim().to_string());
            index += 1;
        } else {
            break;
        }
        skip_blank_lines(&lines, &mut index);
    }

    parsed.body = lines[index..].join("\n");
    parsed
}

fn skip_blank_lines(lines: &[&str], index: &mut usize) {
    while *index < lines.len() && lines[*index].trim().is_empty() {
        *index += 1;
    }
}

/// Walks every field and method parameter of a resource to ensure their
/// referenced types (enums, flags, variants, models) have been resolved.
fn ensure_resource_field_types(
    resource: &PlannedResource,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<()> {
    for field in &resource.fields {
        ensure_resource_field_type(
            &field.kind,
            api_plan,
            enums,
            flags,
            variants,
            models,
            package,
        )?;
    }
    for method in &resource.methods {
        for param in &method.params {
            ensure_resource_field_type(
                &param.kind,
                api_plan,
                enums,
                flags,
                variants,
                models,
                package,
            )?;
        }
    }
    Ok(())
}

/// Resolves a single field kind (singular, repeated, or map) to ensure all
/// value types it references are present in the rendered type collections.
fn ensure_resource_field_type(
    kind: &PlannedFieldKind,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<()> {
    match kind {
        PlannedFieldKind::Singular(value) | PlannedFieldKind::Repeated(value) => {
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models, package)?;
        }
        PlannedFieldKind::Map { key, value } => {
            resolve_planned_value_type(key, api_plan, enums, flags, variants, models, package)?;
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models, package)?;
        }
    }
    Ok(())
}

/// Derives a valid Go package name from a Nexus endpoint string by stripping
/// non-alphanumeric characters and lowercasing (e.g. `"type-showcase"` becomes
/// `"typeshowcase"`).
pub(crate) fn go_package_name(endpoint: &str) -> String {
    endpoint
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
        .collect::<String>()
        .to_lowercase()
}

