/// Renders all collected types into a complete Go source file with a package
/// declaration, import block, and the generated-code header comment.
fn render_file(
    package_name: &str,
    imports: &BTreeSet<String>,
    proto_imports: &GoImportCollector,
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    services: &[RenderedService<'_>],
    api_plan: &ApiPlan,
) -> String {
    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push('\n');
    output.push_str("package ");
    output.push_str(package_name);
    output.push('\n');

    if !imports.is_empty() || !proto_imports.is_empty() {
        // Separate stdlib imports (no '.') from third-party imports (contain '.')
        let stdlib: Vec<_> = imports
            .iter()
            .filter(|p| !p.contains('.'))
            .collect();
        // Exclude any third-party path that is also emitted (aliased) by the
        // proto import collector to avoid duplicate import declarations.
        let third_party: Vec<_> = imports
            .iter()
            .filter(|p| p.contains('.'))
            .filter(|p| proto_imports.by_path.get(*p).is_none())
            .collect();

        output.push_str("\nimport (\n");
        for import_path in &stdlib {
            output.push('\t');
            output.push('"');
            output.push_str(import_path);
            output.push('"');
            output.push('\n');
        }
        if !stdlib.is_empty() && (!third_party.is_empty() || !proto_imports.is_empty()) {
            output.push('\n');
        }
        for import_path in &third_party {
            output.push('\t');
            output.push('"');
            output.push_str(import_path);
            output.push('"');
            output.push('\n');
        }
        // Aliased proto imports, emitted as `alias "path"` when the alias
        // differs from the path's final segment.
        for (path, alias) in proto_imports.paths() {
            output.push('\t');
            let default_alias = path.rsplit('/').next().unwrap_or(path);
            if alias != default_alias {
                output.push_str(alias);
                output.push(' ');
            }
            output.push('"');
            output.push_str(path);
            output.push('"');
            output.push('\n');
        }
        output.push_str(")\n");
    }

    // --- Service constants ---
    let has_services = !services.is_empty();
    if has_services {
        output.push('\n');
        for service in services {
            render_service_constants(&mut output, service);
        }
    }

    // --- Datatypes ---
    let has_datatypes =
        !enums.is_empty() || !flags.is_empty() || !variants.is_empty() || !models.is_empty();
    if has_datatypes {
        output.push_str("\n// --- Datatypes ---\n");
        for enumeration in enums {
            output.push('\n');
            render_enum(&mut output, enumeration);
        }
        for flag_set in flags {
            output.push('\n');
            render_flags(&mut output, flag_set);
        }
        for variant in variants {
            output.push('\n');
            render_variant(&mut output, variant);
        }
        for model in models {
            output.push('\n');
            render_model(&mut output, model);
        }
    }

    // --- Resources ---
    let has_resources = services.iter().any(|s| !s.resources.is_empty());
    if has_resources {
        output.push_str("\n// --- Resources ---\n");
        for service in services {
            for resource in &service.resources {
                output.push('\n');
                render_resource(&mut output, resource);
                render_resource_methods(&mut output, resource, &service.operations, api_plan);
            }
        }
    }

    // --- Operations (internal) ---
    let has_operations = services.iter().any(|s| !s.operations.is_empty());
    if has_operations {
        output.push_str("\n// --- Operations (internal) ---\n");
        for service in services {
            for operation in &service.operations {
                output.push('\n');
                render_operation_function(&mut output, operation);
            }
        }
    }

    // --- Operations (public API) ---
    if has_operations {
        output.push_str("\n// --- Operations (public API) ---\n");
        for service in services {
            for operation in &service.operations {
                if let Some(params) = &operation.unpacked_input {
                    let has_optional = params.iter().any(|p| !p.required);
                    if has_optional {
                        output.push('\n');
                        render_options_struct(&mut output, operation, params);
                    }
                    output.push('\n');
                    render_convenience_wrapper(&mut output, operation, params);
                } else {
                    // External input type — generate a simple forwarding wrapper
                    output.push('\n');
                    render_forwarding_wrapper(&mut output, operation);
                }
            }
        }
    }

    output
}

/// Renders a Go doc comment (`// ...`), wrapping each paragraph to the
/// format line length. Blank lines in the input are preserved as `//`
/// separator lines.
///
/// ```go
/// // Behavior when a workflow is currently running with the same ID. Set to
/// // use-existing for idempotent deduplication on workflow ID.
/// ```
fn render_go_doc_comment(output: &mut String, indent: &str, text: &str) {
    let max_width = GO_DOC_COMMENT_LINE_LENGTH.saturating_sub(indent.chars().count() + 3);
    for line in text.trim().lines() {
        let line = line.trim();
        if line.is_empty() {
            output.push_str(indent);
            output.push_str("//\n");
            continue;
        }
        let mut current = String::new();
        for word in line.split_whitespace() {
            let separator_width = usize::from(!current.is_empty());
            if !current.is_empty()
                && current.chars().count() + separator_width + word.chars().count() > max_width
            {
                output.push_str(indent);
                output.push_str("// ");
                output.push_str(&current);
                output.push('\n');
                current.clear();
            }
            if !current.is_empty() {
                current.push(' ');
            }
            current.push_str(word);
        }
        output.push_str(indent);
        output.push_str("// ");
        output.push_str(&current);
        output.push('\n');
    }
}

/// Renders the leading godoc comment for a struct field. Required fields are
/// prefixed with `Required.`; the prefix is folded onto the first line of the
/// field's `@nexus.doc`/WIT doc text when present.
///
/// ```go
/// // Required. Unique identifier for the workflow execution.
/// Id string
/// ```
fn render_field_doc_comment(output: &mut String, indent: &str, doc: Option<&str>, required: bool) {
    match (required, doc) {
        (true, Some(doc)) => {
            let trimmed = doc.trim();
            let combined = if trimmed.is_empty() {
                "Required.".to_string()
            } else {
                format!("Required. {trimmed}")
            };
            render_go_doc_comment(output, indent, &combined);
        }
        (true, None) => render_go_doc_comment(output, indent, "Required."),
        (false, Some(doc)) => render_go_doc_comment(output, indent, doc),
        (false, None) => {}
    }
}

/// Renders the godoc comment for an exported operation wrapper function from
/// the operation's `@nexus.doc` text and `returns=` text.
///
/// ```go
/// // Signal a workflow, starting it first if needed.
/// //
/// // Returns: A workflow handle to the started workflow.
/// ```
fn render_operation_doc_comment(output: &mut String, operation: &RenderedOperation<'_>) {
    let doc = operation.doc.map(str::trim).filter(|doc| !doc.is_empty());
    let return_doc = operation
        .return_doc
        .map(str::trim)
        .filter(|doc| !doc.is_empty());
    if let Some(doc) = doc {
        render_go_doc_comment(output, "", doc);
    }
    if let Some(return_doc) = return_doc {
        if doc.is_some() {
            output.push_str("//\n");
        }
        render_go_doc_comment(output, "", &format!("Returns: {return_doc}"));
    }
}

/// Renders a WIT enum as a Go named integer type with a `const` block.
///
/// ```go
/// type UserStatus int32
///
/// const (
///     UserStatusActive    UserStatus = 0
///     UserStatusSuspended UserStatus = 1
/// )
/// ```
fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("type ");
    output.push_str(&enumeration.name);
    output.push_str(" int32\n");

    if enumeration.values.is_empty() {
        return;
    }

    output.push_str("\nconst (\n");
    for value in &enumeration.values {
        output.push('\t');
        output.push_str(&enumeration.name);
        output.push_str(&value.name);
        output.push(' ');
        output.push_str(&enumeration.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push('\n');
    }
    output.push_str(")\n");
}

/// Renders a WIT flags type as a Go named integer type with bit-shifted
/// constants.
///
/// ```go
/// type UserCapability int32
///
/// const (
///     UserCapabilityReadProfile UserCapability = 1 << 0
///     UserCapabilityUpdateEmail UserCapability = 1 << 1
/// )
/// ```
fn render_flags(output: &mut String, flags: &RenderedFlags) {
    output.push_str("type ");
    output.push_str(&flags.name);
    output.push_str(" int32\n");

    if flags.flags.is_empty() {
        return;
    }

    output.push_str("\nconst (\n");
    for flag in &flags.flags {
        output.push('\t');
        output.push_str(&flags.name);
        output.push_str(&flag.name);
        output.push(' ');
        output.push_str(&flags.name);
        output.push_str(" = 1 << ");
        output.push_str(&flag.bit.to_string());
        output.push('\n');
    }
    output.push_str(")\n");
}

/// Renders a WIT variant as a Go sealed interface with concrete case structs.
///
/// ```go
/// type NotificationTarget interface {
///     isNotificationTarget()
/// }
///
/// type NotificationTargetEmail struct {
///     Value string
/// }
///
/// func (NotificationTargetEmail) isNotificationTarget() {}
///
/// type NotificationTargetNone struct{}
///
/// func (NotificationTargetNone) isNotificationTarget() {}
/// ```
fn render_variant(output: &mut String, variant: &RenderedVariant) {
    output.push_str("type ");
    output.push_str(&variant.name);
    output.push_str(" interface {\n");
    output.push('\t');
    output.push_str(&variant.marker_method);
    output.push_str("()\n");
    output.push_str("}\n");

    for case in &variant.cases {
        output.push('\n');
        output.push_str("type ");
        output.push_str(&case.struct_name);
        if let Some(payload_type) = &case.payload_type {
            output.push_str(" struct {\n");
            output.push_str("\tValue ");
            output.push_str(payload_type);
            output.push('\n');
            output.push_str("}\n");
        } else {
            output.push_str(" struct{}\n");
        }
        output.push('\n');
        output.push_str("func (");
        output.push_str(&case.struct_name);
        output.push_str(") ");
        output.push_str(&variant.marker_method);
        output.push_str("() {}\n");
    }
}

/// Renders a WIT record (or proto message) as a Go struct. Required fields
/// are annotated with a leading `// Required.` godoc comment.
///
/// ```go
/// type DeactivateRequest struct {
///     // Required.
///     UserId string
///     Reason string
/// }
/// ```
fn render_model(output: &mut String, model: &RenderedModel) {
    output.push_str("type ");
    output.push_str(&model.name);
    output.push_str(" struct {\n");

    if model.fields.is_empty() {
        output.push_str("}\n");
    } else {
        for field in &model.fields {
            render_field_doc_comment(output, "\t", field.doc.as_deref(), field.required);
            output.push('\t');
            output.push_str(&field.name);
            output.push(' ');
            output.push_str(&field.go_type);
            output.push('\n');
        }
        output.push_str("}\n");
    }

    if let Some(proto) = &model.proto {
        render_model_proto_methods(output, model, proto);
    }
}

/// Renders the `ToProto` method and `FromProto` constructor for a proto-backed
/// model.
///
/// ```go
/// func (m ActivityOptions) ToProto() *activity.ActivityOptions {
///     message := &activity.ActivityOptions{}
///     ...
///     return message
/// }
///
/// func ActivityOptionsFromProto(proto *activity.ActivityOptions) ActivityOptions {
///     value := ActivityOptions{}
///     ...
///     return value
/// }
/// ```
fn render_model_proto_methods(
    output: &mut String,
    model: &RenderedModel,
    proto: &RenderedModelProto,
) {
    // proto.proto_type is like "*activity.ActivityOptions"; the constructor
    // form drops the leading '*'.
    let proto_value_type = proto.proto_type.trim_start_matches('*');

    if proto.to_proto {
        output.push('\n');
        output.push_str("func (m ");
        output.push_str(&model.name);
        output.push_str(") ToProto() ");
        output.push_str(&proto.proto_type);
        output.push_str(" {\n");
        output.push_str("\tmessage := &");
        output.push_str(proto_value_type);
        output.push_str("{}\n");
        for field in &model.fields {
            if let Some(conversion) = &field.conversion {
                for line in &conversion.to_proto_lines {
                    output.push('\t');
                    output.push_str(line);
                    output.push('\n');
                }
            }
        }
        for sourced in &model.sourced_fields {
            for line in &sourced.to_proto_lines {
                output.push('\t');
                output.push_str(line);
                output.push('\n');
            }
        }
        output.push_str("\treturn message\n");
        output.push_str("}\n");
    }

    if proto.from_proto {
        output.push('\n');
        output.push_str("func ");
        output.push_str(&model.name);
        output.push_str("FromProto(proto ");
        output.push_str(&proto.proto_type);
        output.push_str(") ");
        output.push_str(&model.name);
        output.push_str(" {\n");
        output.push_str("\tvalue := ");
        output.push_str(&model.name);
        output.push_str("{}\n");
        for field in &model.fields {
            if let Some(conversion) = &field.conversion {
                for line in &conversion.from_proto_lines {
                    output.push('\t');
                    output.push_str(line);
                    output.push('\n');
                }
            }
        }
        output.push_str("\treturn value\n");
        output.push_str("}\n");
    }
}

/// Renders service and operation name constants.
///
/// ```go
/// const ServiceName = "UserService"
/// const Endpoint = "user-service"
///
/// const GetUserOp = "GetUser"
/// const UpdateEmailOp = "UpdateEmail"
/// ```
fn render_service_constants(output: &mut String, service: &RenderedService<'_>) {
    output.push_str("const ServiceName = \"");
    output.push_str(service.name);
    output.push_str("\"\n");
    output.push_str("const Endpoint = \"");
    output.push_str(&service.endpoint);
    output.push_str("\"\n");

    if !service.operations.is_empty() {
        output.push('\n');
        for operation in &service.operations {
            output.push_str("const ");
            output.push_str(&go_field_name(operation.name));
            output.push_str("Op = \"");
            output.push_str(operation.wire_name);
            output.push_str("\"\n");
        }
    }
}

/// Renders a WIT resource as a Go struct with its constructor fields.
///
/// ```go
/// type User struct {
///     // Required.
///     UserId string
///     // Required.
///     Email  string
/// }
/// ```
fn render_resource(output: &mut String, resource: &PlannedResource) {
    output.push_str("type ");
    output.push_str(&resource.type_name);
    output.push_str(" struct {\n");

    if resource.fields.is_empty() {
        output.push_str("}\n");
        return;
    }

    for field in &resource.fields {
        let field_name = go_field_name(&field.name);
        let go_type = resolve_resource_field_kind(&field.kind, field.optional);
        render_field_doc_comment(output, "\t", None, !field.optional);
        output.push('\t');
        output.push_str(&field_name);
        output.push(' ');
        output.push_str(&go_type);
        output.push('\n');
    }
    output.push_str("}\n");
}

/// Resolves a resource field's [`PlannedFieldKind`] to a Go type expression,
/// applying the same optionality rules as record fields: pointer for optional
/// struct types, plain type for optional scalars/interfaces.
fn resolve_resource_field_kind(kind: &PlannedFieldKind, optional: bool) -> String {
    match kind {
        PlannedFieldKind::Map { key, value } => {
            let key_type = resolve_resource_value_type(key);
            let value_type = resolve_resource_value_type(value);
            format!("map[{key_type}]{value_type}")
        }
        PlannedFieldKind::Repeated(value) => {
            let element_type = resolve_resource_value_type(value);
            format!("[]{element_type}")
        }
        PlannedFieldKind::Singular(value) => {
            let (base_type, _is_struct) = resolve_resource_value_type_with_struct_flag(value);
            if optional && type_needs_pointer_when_optional(value, &base_type) {
                format!("*{base_type}")
            } else {
                base_type
            }
        }
    }
}

/// Resolves a [`PlannedValueType`] to a Go type expression for use in resource
/// field declarations. This is a simplified version of
/// [`resolve_planned_value_type`] that doesn't register types into collections
/// (that's already done by [`ensure_resource_field_types`]).
fn resolve_resource_value_type(value: &PlannedValueType) -> String {
    resolve_resource_value_type_with_struct_flag(value).0
}

/// Like [`resolve_resource_value_type`] but also returns whether the type is a
/// struct (for optionality/pointer decisions).
fn resolve_resource_value_type_with_struct_flag(value: &PlannedValueType) -> (String, bool) {
    match value {
        PlannedValueType::Scalar(PlannedScalarType::Float) => ("float64".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Int32) => ("int32".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Int64) => ("int64".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Bool) => ("bool".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::String) => ("string".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Bytes) => ("[]byte".to_string(), false),
        PlannedValueType::Enum(enum_type) => {
            if let Some(replacement) = &enum_type.replacement
                && let Some(type_name) = go_replacement_type_name(replacement)
            {
                return (type_name, false);
            }
            (
                enum_type.name.clone().unwrap_or_else(|| "int32".to_string()),
                false,
            )
        }
        PlannedValueType::Flags(flags_type) => (flags_type.name.clone(), false),
        PlannedValueType::Variant(variant_type) => (variant_type.name.clone(), false),
        PlannedValueType::Message(message_type) => {
            if let Some(replacement) = &message_type.replacement
                && let Some(type_name) = go_replacement_type_name(replacement)
            {
                return (type_name, false);
            }
            if let Some(authored_type) = &message_type.authored_type {
                return (go_authored_type_annotation(authored_type), false);
            }
            (message_type.model_name.clone(), true)
        }
        // Mirrors `resolve_planned_value_type`: containers of tuples/results
        // instantiate the shared generic helper types, which were registered
        // by `ensure_resource_field_types`.
        PlannedValueType::Tuple(items) => {
            let args = items
                .iter()
                .map(resolve_resource_value_type)
                .collect::<Vec<_>>()
                .join(", ");
            (format!("Tuple{}[{args}]", items.len()), true)
        }
        PlannedValueType::Result { ok, err } => {
            let ok_type = ok
                .as_deref()
                .map(resolve_resource_value_type)
                .unwrap_or_else(|| "struct{}".to_string());
            let err_type = err
                .as_deref()
                .map(resolve_resource_value_type)
                .unwrap_or_else(|| "error".to_string());
            (format!("Result[{ok_type}, {err_type}]"), true)
        }
        PlannedValueType::External {
            type_name,
            fallback,
        } => {
            if let Some(annotation) = type_name.for_language(Language::Go) {
                let (_import, code_expr) = parse_go_import(annotation);
                (code_expr, false)
            } else {
                resolve_resource_value_type_with_struct_flag(fallback)
            }
        }
        PlannedValueType::Unknown => ("any".to_string(), false),
    }
}

/// Renders methods on a resource struct. Each method that is bound to an
/// operation delegates to the corresponding unexported operation function,
/// constructing the request from the receiver's fields and the method params.
///
/// ```go
/// func (u *User) UpdateEmail(ctx workflow.Context, email string) (*User, error) {
///     return updateEmail(ctx, UpdateEmailRequest{UserId: u.UserId, Email: email})
/// }
/// ```
///
/// Methods bound to `Stub` emit a panic placeholder.
fn render_resource_methods(
    output: &mut String,
    resource: &PlannedResource,
    operations: &[RenderedOperation<'_>],
    api_plan: &ApiPlan,
) {
    for method in &resource.methods {
        output.push('\n');
        let method_name = go_field_name(&method.name);

        match &method.binding {
            PlannedResourceMethodBindingSpec::Operation {
                operation_name,
                request_plan,
                ..
            } => {
                let operation = operations
                    .iter()
                    .find(|op| op.name == operation_name)
                    .expect("bound resource operation should exist on the service");

                // Method signature: func (u *Type) Method(ctx workflow.Context, params...) (return)
                output.push_str("func (u *");
                output.push_str(&resource.type_name);
                output.push_str(") ");
                output.push_str(&method_name);
                output.push_str("(ctx workflow.Context");
                for param in &method.params {
                    output.push_str(", ");
                    output.push_str(&go_unexported_name(&go_field_name(&param.name)));
                    output.push(' ');
                    output.push_str(&resolve_resource_field_kind(&param.kind, param.optional));
                }
                output.push_str(") ");

                // Return type
                let result_type = resolve_method_result_type(method);
                if let Some(ref rtype) = result_type {
                    output.push_str("(*");
                    output.push_str(rtype);
                    output.push_str(", error)");
                } else {
                    output.push_str("error");
                }
                output.push_str(" {\n");

                // Body: construct request and delegate
                let request_expr = render_request_plan(
                    request_plan,
                    go_field_name,
                    |name, value| format!("{name}: {value}"),
                    |msg_name, fields| {
                        // Look up the rendered model name; fall back to
                        // deriving it from the message name.
                        let type_name = api_plan
                            .models
                            .get(msg_name)
                            .map(|m| m.name.clone())
                            .unwrap_or_else(|| message_model_name(msg_name));
                        if fields.is_empty() {
                            format!("{type_name}{{}}")
                        } else {
                            format!("{type_name}{{{}}}", fields.join(", "))
                        }
                    },
                    |name| format!("u.{}", go_field_name(name)),
                    |name| go_unexported_name(&go_field_name(name)),
                );

                // If the method is void but the operation returns a value,
                // discard the value and return only the error.
                if result_type.is_none() && operation.output_type.is_some() {
                    output.push_str("\t_, err := ");
                    output.push_str(&operation.func_name);
                    output.push_str("(ctx, ");
                    output.push_str(&request_expr);
                    output.push_str(")\n");
                    output.push_str("\treturn err\n");
                } else {
                    output.push_str("\treturn ");
                    output.push_str(&operation.func_name);
                    output.push_str("(ctx, ");
                    output.push_str(&request_expr);
                    output.push_str(")\n");
                }
                output.push_str("}\n");
            }
            PlannedResourceMethodBindingSpec::Stub => {
                // Stub method -- emit a panic placeholder
                output.push_str("func (u *");
                output.push_str(&resource.type_name);
                output.push_str(") ");
                output.push_str(&method_name);
                output.push_str("(ctx workflow.Context");
                for param in &method.params {
                    output.push_str(", ");
                    output.push_str(&go_unexported_name(&go_field_name(&param.name)));
                    output.push(' ');
                    output.push_str(&resolve_resource_field_kind(&param.kind, param.optional));
                }
                output.push_str(") ");
                let result_type = resolve_method_result_type(method);
                if let Some(ref rtype) = result_type {
                    output.push_str("(*");
                    output.push_str(rtype);
                    output.push_str(", error)");
                } else {
                    output.push_str("error");
                }
                output.push_str(" {\n");
                output.push_str("\tpanic(\"");
                output.push_str(&resource.type_name);
                output.push('.');
                output.push_str(&method_name);
                output.push_str(" is not yet implemented\")\n");
                output.push_str("}\n");
            }
        }
    }
}

/// Resolves the Go return type for a resource method from its
/// [`PlannedResourceMethodResult`].
fn resolve_method_result_type(
    method: &crate::api_plan::PlannedResourceMethod,
) -> Option<String> {
    method.result.as_ref().map(|result| match &result.kind {
        PlannedResourceMethodResultKind::Resource { type_name } => type_name.clone(),
        PlannedResourceMethodResultKind::Value(kind) => resolve_resource_field_kind(kind, false),
    })
}

/// Renders an unexported operation wrapper function that creates a Nexus
/// client and executes the operation.
///
/// For operations returning a value:
/// ```go
/// func getUser(ctx workflow.Context, request GetUserRequest) (*User, error) {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, GetUserOp, request, workflow.NexusOperationOptions{})
///     var result User
///     if err := fut.Get(ctx, &result); err != nil {
///         return nil, err
///     }
///     return &result, nil
/// }
/// ```
///
/// For void operations:
/// ```go
/// func deactivate(ctx workflow.Context, request DeactivateRequest) error {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, DeactivateOp, request, workflow.NexusOperationOptions{})
///     return fut.Get(ctx, nil)
/// }
/// ```
fn render_operation_function(output: &mut String, operation: &RenderedOperation<'_>) {
    if let Some(binding) = &operation.proto_binding {
        render_operation_function_proto(output, operation, binding);
        return;
    }

    let op_const = format!("{}Op", go_field_name(operation.name));

    if let (Some(transform_expr), Some(transform_type)) = (
        operation.output_transform_expr,
        operation.output_transform_type.as_ref(),
    ) {
        output.push_str("func ");
        output.push_str(&operation.func_name);
        output.push_str("(ctx workflow.Context, request ");
        output.push_str(&operation.input_type);
        output.push_str(") (");
        output.push_str(transform_type);
        output.push_str(", error) {\n");
        output.push_str("\tc := workflow.NewNexusClient(Endpoint, ServiceName)\n");
        output.push_str("\tfut := c.ExecuteOperation(ctx, ");
        output.push_str(&op_const);
        output.push_str(", request, workflow.NexusOperationOptions{})\n");
        if let Some(raw_result_type) = &operation.raw_output_type {
            output.push_str("\tvar result ");
            output.push_str(raw_result_type);
            output.push('\n');
            output.push_str("\tif err := fut.Get(ctx, &result); err != nil {\n");
        } else {
            output.push_str("\tif err := fut.Get(ctx, nil); err != nil {\n");
        }
        output.push_str("\t\tvar zero ");
        output.push_str(transform_type);
        output.push('\n');
        output.push_str("\t\treturn zero, err\n");
        output.push_str("\t}\n");
        output.push_str("\treturn ");
        output.push_str(transform_expr);
        output.push('\n');
        output.push_str("}\n");
    } else if let Some(result_type) = &operation.output_type {
        // Operation with a return value
        output.push_str("func ");
        output.push_str(&operation.func_name);
        output.push_str("(ctx workflow.Context, request ");
        output.push_str(&operation.input_type);
        output.push_str(") (*");
        output.push_str(result_type);
        output.push_str(", error) {\n");
        output.push_str("\tc := workflow.NewNexusClient(Endpoint, ServiceName)\n");
        output.push_str("\tfut := c.ExecuteOperation(ctx, ");
        output.push_str(&op_const);
        output.push_str(", request, workflow.NexusOperationOptions{})\n");
        output.push_str("\tvar result ");
        output.push_str(result_type);
        output.push('\n');
        output.push_str("\tif err := fut.Get(ctx, &result); err != nil {\n");
        output.push_str("\t\treturn nil, err\n");
        output.push_str("\t}\n");
        output.push_str("\treturn &result, nil\n");
        output.push_str("}\n");
    } else {
        // Void operation
        output.push_str("func ");
        output.push_str(&operation.func_name);
        output.push_str("(ctx workflow.Context, request ");
        output.push_str(&operation.input_type);
        output.push_str(") error {\n");
        output.push_str("\tc := workflow.NewNexusClient(Endpoint, ServiceName)\n");
        output.push_str("\tfut := c.ExecuteOperation(ctx, ");
        output.push_str(&op_const);
        output.push_str(", request, workflow.NexusOperationOptions{})\n");
        output.push_str("\treturn fut.Get(ctx, nil)\n");
        output.push_str("}\n");
    }
}

/// Renders an operation function that serializes its request to proto before
/// the SDK call and deserializes the proto response afterwards, ensuring the
/// wire payload matches the proto encoding produced by the Python/TypeScript
/// bindings.
///
/// ```go
/// func activityOptionsOperation(ctx workflow.Context, request ActivityOptions) (*ActivityOptions, error) {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, ActivityOptionsOperationOp, request.ToProto(), workflow.NexusOperationOptions{})
///     var result activity.ActivityOptions
///     if err := fut.Get(ctx, &result); err != nil {
///         return nil, err
///     }
///     value := ActivityOptionsFromProto(&result)
///     return &value, nil
/// }
/// ```
fn render_operation_function_proto(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    binding: &OperationProtoBinding,
) {
    let op_const = format!("{}Op", go_field_name(operation.name));
    let resource_return = operation.output_resource_return.as_ref();

    output.push_str("func ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx workflow.Context, request ");
    output.push_str(&operation.input_type);
    output.push_str(") ");

    let returns_resource = resource_return.is_some() && binding.output_proto_type.is_some();
    let returns_value = operation.output_type.is_some() && binding.output_from_proto.is_some();

    if let (Some(_transform_expr), Some(transform_type)) = (
        operation.output_transform_expr,
        operation.output_transform_type.as_ref(),
    ) {
        output.push('(');
        output.push_str(transform_type);
        output.push_str(", error)");
    } else if let Some(result_type) = &operation.output_type {
        if returns_resource || returns_value {
            output.push_str("(*");
            output.push_str(result_type);
            output.push_str(", error)");
        } else {
            // Output proto type without a native conversion: should not happen
            // for proto bindings, but fall back to error-only.
            output.push_str("error");
        }
    } else {
        output.push_str("error");
    }
    output.push_str(" {\n");

    output.push_str("\tc := workflow.NewNexusClient(Endpoint, ServiceName)\n");
    if returns_resource {
        output.push_str("\trequestProto := ");
        output.push_str(&binding.input_to_proto);
        output.push('\n');
    }
    output.push_str("\tfut := c.ExecuteOperation(ctx, ");
    output.push_str(&op_const);
    output.push_str(", ");
    if returns_resource {
        output.push_str("requestProto");
    } else {
        output.push_str(&binding.input_to_proto);
    }
    output.push_str(", workflow.NexusOperationOptions{})\n");

    if let (Some(transform_expr), Some(transform_type)) = (
        operation.output_transform_expr,
        operation.output_transform_type.as_ref(),
    ) {
        if let Some(proto_value_type) = binding
            .output_proto_type
            .as_deref()
            .map(|value| value.trim_start_matches('*'))
        {
            output.push_str("\tvar result ");
            output.push_str(proto_value_type);
            output.push('\n');
            output.push_str("\tif err := fut.Get(ctx, &result); err != nil {\n");
        } else if let Some(raw_result_type) = &operation.raw_output_type {
            output.push_str("\tvar result ");
            output.push_str(raw_result_type);
            output.push('\n');
            output.push_str("\tif err := fut.Get(ctx, &result); err != nil {\n");
        } else {
            output.push_str("\tif err := fut.Get(ctx, nil); err != nil {\n");
        }
        output.push_str("\t\tvar zero ");
        output.push_str(transform_type);
        output.push('\n');
        output.push_str("\t\treturn zero, err\n");
        output.push_str("\t}\n");
        output.push_str("\treturn ");
        output.push_str(transform_expr);
        output.push('\n');
    } else if returns_value {
        let proto_value_type = binding
            .output_proto_type
            .as_deref()
            .expect("returns_value implies an output proto type")
            .trim_start_matches('*');
        let from_proto = binding
            .output_from_proto
            .as_deref()
            .expect("returns_value implies an output conversion");
        output.push_str("\tvar result ");
        output.push_str(proto_value_type);
        output.push('\n');
        output.push_str("\tif err := fut.Get(ctx, &result); err != nil {\n");
        output.push_str("\t\treturn nil, err\n");
        output.push_str("\t}\n");
        if binding.output_returns_pointer {
            // The converter already yields `*Native`; return it directly.
            output.push_str("\treturn ");
            output.push_str(from_proto);
            output.push_str(", nil\n");
        } else {
            // The converter yields a `Model` value; return its address.
            output.push_str("\tvalue := ");
            output.push_str(from_proto);
            output.push('\n');
            output.push_str("\treturn &value, nil\n");
        }
    } else if let (Some(resource_return), Some(proto_value_type)) = (
        resource_return,
        binding
            .output_proto_type
            .as_deref()
            .map(|value| value.trim_start_matches('*')),
    ) {
        output.push_str("\tvar result ");
        output.push_str(proto_value_type);
        output.push('\n');
        output.push_str("\tif err := fut.Get(ctx, &result); err != nil {\n");
        output.push_str("\t\treturn nil, err\n");
        output.push_str("\t}\n");
        for line in resource_return_local_lines(resource_return) {
            output.push('\t');
            output.push_str(&line);
            output.push('\n');
        }
        output.push_str("\treturn &");
        output.push_str(&resource_return.resource_type_name);
        output.push_str("{\n");
        for binding in &resource_return.bindings {
            output.push_str("\t\t");
            output.push_str(&go_field_name(&binding.field_name));
            output.push_str(": ");
            output.push_str(&resource_return_binding_expr_go(binding));
            output.push_str(",\n");
        }
        output.push_str("\t}, nil\n");
    } else {
        output.push_str("\treturn fut.Get(ctx, nil)\n");
    }
    output.push_str("}\n");
}

fn resource_return_local_lines(resource_return: &PlannedOperationResourceReturn) -> Vec<String> {
    resource_return
        .bindings
        .iter()
        .filter_map(|binding| {
            if !binding.optional {
                return None;
            }
            match &binding.source {
                ResolvedResourceBindingSource::ResultField {
                    proto_field_name, ..
                } => {
                    let local = resource_return_optional_local_name(binding);
                    let value_local = format!("{local}Value");
                    let proto_field = go_proto_field_name(proto_field_name);
                    Some(vec![
                        format!("{value_local} := result.Get{proto_field}()"),
                        format!("var {local} *string"),
                        format!("if {value_local} != \"\" {{"),
                        format!("\t{local} = &{value_local}"),
                        "}".to_string(),
                    ])
                }
                _ => None,
            }
        })
        .flatten()
        .collect()
}

fn resource_return_binding_expr_go(binding: &PlannedOperationResourceFieldBinding) -> String {
    match &binding.source {
        ResolvedResourceBindingSource::RequestField {
            field_name,
            proto_field_name,
            hidden,
        } => {
            if *hidden {
                let proto_field = go_proto_field_name(proto_field_name);
                format!("requestProto.Get{proto_field}()")
            } else {
                format!("request.{}", go_field_name(field_name))
            }
        }
        ResolvedResourceBindingSource::ResultField {
            proto_field_name, ..
        } => {
            if binding.optional {
                resource_return_optional_local_name(binding)
            } else {
                let proto_field = go_proto_field_name(proto_field_name);
                format!("result.Get{proto_field}()")
            }
        }
    }
}

fn resource_return_optional_local_name(binding: &PlannedOperationResourceFieldBinding) -> String {
    go_unexported_name(&go_field_name(&binding.field_name))
}

/// Renders an options struct for optional parameters of a convenience wrapper.
///
/// ```go
/// type GetUserOptions struct {
///     ConsistencyToken string
/// }
/// ```
fn render_options_struct(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
) {
    output.push_str("type ");
    output.push_str(&go_field_name(operation.name));
    output.push_str("Options struct {\n");
    for param in params.iter().filter(|p| !p.required) {
        if let Some(doc) = &param.doc {
            render_go_doc_comment(output, "\t", doc);
        }
        output.push('\t');
        if param.embed_in_options {
            output.push_str(param.go_type.trim_start_matches('*'));
        } else {
            output.push_str(&param.field_name);
            output.push(' ');
            output.push_str(&param.go_type);
        }
        output.push('\n');
    }
    output.push_str("}\n");
}

/// Renders an exported convenience wrapper that unpacks required fields as
/// positional arguments and optional fields into a required options struct.
///
/// The request struct is always constructed across multiple lines. The function
/// signature is also split across multiple lines when it has more than three
/// parameters (counting `ctx`).
///
/// ```go
/// func UpdateEmail(ctx workflow.Context, userId string, email string) (*User, error) {
///     return updateEmail(ctx, UpdateEmailRequest{
///         UserId: userId,
///         Email:  email,
///     })
/// }
/// ```
///
/// With more than three parameters:
/// ```go
/// func StartWorkflow(
///     ctx workflow.Context,
///     workflow string,
///     workflowId string,
///     taskQueue string,
///     opts StartWorkflowOptions,
/// ) (*StartedWorkflow, error) {
///     return startWorkflow(ctx, StartWorkflowRequest{
///         Workflow:           workflow,
///         Args:               opts.Args,
///         WorkflowId:         workflowId,
///         TaskQueue:          taskQueue,
///         WorkflowStartDelay: opts.WorkflowStartDelay,
///     })
/// }
/// ```
fn render_convenience_wrapper(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
) {
    let exported_name = go_field_name(operation.name);
    let has_optional = params.iter().any(|p| !p.required);

    render_operation_doc_comment(output, operation);

    // Build the list of signature parameters (after `ctx`): one per required
    // field, plus a trailing `opts` parameter when optional fields exist.
    let mut signature_params: Vec<(String, String)> = params
        .iter()
        .filter(|p| p.required)
        .map(|p| (p.param_name.clone(), p.go_type.clone()))
        .collect();
    if has_optional {
        signature_params.push(("opts".to_string(), format!("{exported_name}Options")));
    }

    // The signature is multi-line when it has more than 3 parameters total
    // (counting `ctx` plus the parameters above).
    let multiline_signature = signature_params.len() + 1 > 3;

    // Function signature
    output.push_str("func ");
    output.push_str(&exported_name);
    if multiline_signature {
        output.push_str("(\n\tctx workflow.Context,\n");
        for (name, ty) in &signature_params {
            output.push('\t');
            output.push_str(name);
            output.push(' ');
            output.push_str(ty);
            output.push_str(",\n");
        }
        output.push(')');
    } else {
        output.push_str("(ctx workflow.Context");
        for (name, ty) in &signature_params {
            output.push_str(", ");
            output.push_str(name);
            output.push(' ');
            output.push_str(ty);
        }
        output.push(')');
    }
    output.push(' ');

    // Return type
    if let Some(transform_type) = &operation.output_transform_type {
        output.push('(');
        output.push_str(transform_type);
        output.push_str(", error)");
    } else if let Some(result_type) = &operation.output_type {
        output.push_str("(*");
        output.push_str(result_type);
        output.push_str(", error)");
    } else {
        output.push_str("error");
    }
    output.push_str(" {\n");

    // Function body -- build the request as a multi-line struct literal,
    // sourcing required fields from positional args and optional fields from
    // opts.
    output.push_str("\treturn ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx, ");
    output.push_str(&operation.input_type);
    output.push_str("{\n");
    for param in params {
        output.push_str("\t\t");
        output.push_str(&param.field_name);
        output.push_str(": ");
        if param.required {
            output.push_str(&param.param_name);
        } else if param.embed_in_options {
            output.push('&');
            output.push_str("opts.");
            output.push_str(&param.field_name);
        } else {
            output.push_str("opts.");
            output.push_str(&param.field_name);
        }
        output.push_str(",\n");
    }
    output.push_str("\t})\n");

    output.push_str("}\n");
}

/// Renders an exported forwarding wrapper for operations whose input type is
/// an external/replacement type (no model to unpack). The wrapper simply
/// forwards to the unexported operation function.
///
/// ```go
/// func RetryPolicyOperation(ctx workflow.Context, request temporal.RetryPolicy) (*temporal.RetryPolicy, error) {
///     return retryPolicyOperation(ctx, request)
/// }
/// ```
fn render_forwarding_wrapper(output: &mut String, operation: &RenderedOperation<'_>) {
    let exported_name = go_field_name(operation.name);

    render_operation_doc_comment(output, operation);
    output.push_str("func ");
    output.push_str(&exported_name);
    output.push_str("(ctx workflow.Context, request ");
    output.push_str(&operation.input_type);
    output.push_str(") ");

    if let Some(transform_type) = &operation.output_transform_type {
        output.push('(');
        output.push_str(transform_type);
        output.push_str(", error)");
    } else if let Some(result_type) = &operation.output_type {
        output.push_str("(*");
        output.push_str(result_type);
        output.push_str(", error)");
    } else {
        output.push_str("error");
    }

    output.push_str(" {\n");
    output.push_str("\treturn ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx, request)\n");
    output.push_str("}\n");
}
