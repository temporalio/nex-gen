/// Renders an unexported operation wrapper function that creates a Nexus
/// client and executes the operation.
///
/// For operations returning a value:
/// ```go
/// func getUser(ctx workflow.Context, request GetUserRequest) (*User, error) {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, GetUserOp, request, workflow.NexusOperationOptions{})
///     var result User
///     if err := fut.Get(ctx, &result); err != nil {
///         return nil, err
///     }
///     return &result, nil
/// }
/// ```
///
/// For void operations:
/// ```go
/// func deactivate(ctx workflow.Context, request DeactivateRequest) error {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, DeactivateOp, request, workflow.NexusOperationOptions{})
///     return fut.Get(ctx, nil)
/// }
/// ```
fn render_operation_function(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    package: &GoPackageContext,
) {
    if let Some(binding) = &operation.proto_binding {
        render_operation_function_proto(output, service, operation, binding, package);
        return;
    }

    let endpoint = go_string_literal(&service.endpoint);
    let service_name = go_string_literal(service.wire_name);
    let operation_name = go_string_literal(operation.wire_name);

    output.push_str("func ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx ");
    output.push_str(&package.workflow_context_type());
    output.push_str(", request ");
    output.push_str(&operation.input_type);
    output.push_str(") ");
    render_operation_future_return_type(output, package);
    output.push_str(" {\n");
    output.push_str("\tc := ");
    output.push_str(&package.new_nexus_client());
    output.push('(');
    output.push_str(&endpoint);
    output.push_str(", ");
    output.push_str(&service_name);
    output.push_str(")\n");
    output.push_str("\tfut := c.ExecuteOperation(ctx, ");
    output.push_str(&operation_name);
    output.push_str(", request, ");
    output.push_str(&package.nexus_operation_options());
    output.push_str(")\n");
    if let (Some(transform_expr), Some(transform_type)) = (
        operation.output_transform_expr,
        operation.output_transform_type.as_ref(),
    ) {
        render_operation_future_adapter(output, package, transform_type, false, |output| {
            if let Some(raw_result_type) = &operation.raw_output_type {
                output.push_str("\t\tvar result ");
                output.push_str(raw_result_type);
                output.push('\n');
                output.push_str("\t\tif err := fut.Get(ctx, &result); err != nil {\n");
            } else {
                output.push_str("\t\tif err := fut.Get(ctx, nil); err != nil {\n");
            }
            output.push_str("\t\t\treturn err\n");
            output.push_str("\t\t}\n");
            output.push_str("\t\tvalue, err := ");
            output.push_str(transform_expr);
            output.push('\n');
            output.push_str("\t\tif err != nil {\n");
            output.push_str("\t\t\treturn err\n");
            output.push_str("\t\t}\n");
        });
    } else {
        output.push_str("\treturn fut\n");
    }
    output.push_str("}\n");
}

/// Renders an operation function that serializes its request to proto before
/// the SDK call and deserializes the proto response afterwards, ensuring the
/// wire payload matches the proto encoding produced by the Python/TypeScript
/// bindings.
///
/// ```go
/// func activityOptionsOperation(ctx workflow.Context, request ActivityOptions) (*ActivityOptions, error) {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, ActivityOptionsOperationOp, request.ToProto(), workflow.NexusOperationOptions{})
///     var result activity.ActivityOptions
///     if err := fut.Get(ctx, &result); err != nil {
///         return nil, err
///     }
///     value := ActivityOptionsFromProto(&result)
///     return &value, nil
/// }
/// ```
fn render_operation_function_proto(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    binding: &OperationProtoBinding,
    package: &GoPackageContext,
) {
    let endpoint = go_string_literal(&service.endpoint);
    let service_name = go_string_literal(service.wire_name);
    let operation_name = go_string_literal(operation.wire_name);

    output.push_str("func ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx ");
    output.push_str(&package.workflow_context_type());
    output.push_str(", request ");
    output.push_str(&operation.input_type);
    output.push_str(") ");
    render_operation_future_return_type(output, package);
    output.push_str(" {\n");

    output.push_str("\trequestProto, err := ");
    output.push_str(&binding.input_to_proto);
    output.push('\n');
    output.push_str("\tif err != nil {\n");
    output.push_str("\t\treturn nexGenFailedNexusOperationFuture(ctx, err)\n");
    output.push_str("\t}\n");
    output.push_str("\tc := ");
    output.push_str(&package.new_nexus_client());
    output.push('(');
    output.push_str(&endpoint);
    output.push_str(", ");
    output.push_str(&service_name);
    output.push_str(")\n");
    output.push_str("\tfut := c.ExecuteOperation(ctx, ");
    output.push_str(&operation_name);
    output.push_str(", requestProto");
    output.push_str(", ");
    output.push_str(&package.nexus_operation_options());
    output.push_str(")\n");

    if let (Some(transform_expr), Some(transform_type)) = (
        operation.output_transform_expr,
        operation.output_transform_type.as_ref(),
    ) {
        render_operation_future_adapter(output, package, transform_type, false, |output| {
            if let Some(proto_value_type) = binding
                .output_proto_type
                .as_deref()
                .map(|value| value.trim_start_matches('*'))
            {
                output.push_str("\t\tvar result ");
                output.push_str(proto_value_type);
                output.push('\n');
                output.push_str("\t\tif err := fut.Get(ctx, &result); err != nil {\n");
            } else if let Some(raw_result_type) = &operation.raw_output_type {
                output.push_str("\t\tvar result ");
                output.push_str(raw_result_type);
                output.push('\n');
                output.push_str("\t\tif err := fut.Get(ctx, &result); err != nil {\n");
            } else {
                output.push_str("\t\tif err := fut.Get(ctx, nil); err != nil {\n");
            }
            output.push_str("\t\t\treturn err\n");
            output.push_str("\t\t}\n");
            output.push_str("\t\tvalue, err := ");
            output.push_str(transform_expr);
            output.push('\n');
            output.push_str("\t\tif err != nil {\n");
            output.push_str("\t\t\treturn err\n");
            output.push_str("\t\t}\n");
        });
    } else if let (Some(output_type), Some(proto_value_type), Some(from_proto)) = (
        operation.output_type.as_ref(),
        binding
            .output_proto_type
            .as_deref()
            .map(|value| value.trim_start_matches('*')),
        binding.output_from_proto.as_deref(),
    ) {
        render_operation_future_adapter(
            output,
            package,
            output_type,
            binding.output_returns_pointer,
            |output| {
                output.push_str("\t\tvar result ");
                output.push_str(proto_value_type);
                output.push('\n');
                output.push_str("\t\tif err := fut.Get(ctx, &result); err != nil {\n");
                output.push_str("\t\t\treturn err\n");
                output.push_str("\t\t}\n");
                output.push_str("\t\tvalue, err := ");
                output.push_str(from_proto);
                output.push('\n');
                output.push_str("\t\tif err != nil {\n");
                output.push_str("\t\t\treturn err\n");
                output.push_str("\t\t}\n");
            },
        );
    } else if let (Some(resource_return), Some(proto_value_type)) = (
        binding.resource_return.as_ref(),
        binding
            .output_proto_type
            .as_deref()
            .map(|value| value.trim_start_matches('*')),
    ) {
        render_operation_future_adapter(
            output,
            package,
            &resource_return.resource_type_name,
            false,
            |output| {
                output.push_str("\t\tvar result ");
                output.push_str(proto_value_type);
                output.push('\n');
                output.push_str("\t\tif err := fut.Get(ctx, &result); err != nil {\n");
                output.push_str("\t\t\treturn err\n");
                output.push_str("\t\t}\n");
                for line in &resource_return.local_lines {
                    output.push_str("\t\t");
                    output.push_str(line);
                    output.push('\n');
                }
                output.push_str("\t\tvalue := ");
                output.push_str(&resource_return.resource_type_name);
                output.push_str("{\n");
                for initializer in &resource_return.field_initializers {
                    output.push_str("\t\t\t");
                    output.push_str(&initializer.field_name);
                    output.push_str(": ");
                    output.push_str(&initializer.expr);
                    output.push_str(",\n");
                }
                output.push_str("\t\t}\n");
            },
        );
    } else {
        output.push_str("\treturn fut\n");
    }
    output.push_str("}\n");
}

/// Renders an options struct for non-function parameters of a convenience wrapper.
///
/// ```go
/// type GetUserOptions struct {
///     UserId string
///     ConsistencyToken string
/// }
/// ```
fn render_options_struct(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
) {
    output.push_str("type ");
    output.push_str(&go_field_name(operation.name));
    output.push_str("Options struct {\n");
    for param in params.iter().filter(|p| param_belongs_in_options(p)) {
        render_options_field_doc_comment(output, param);
        output.push('\t');
        if param.embed_in_options {
            output.push_str(param.public_go_type.trim_start_matches('*'));
        } else {
            output.push_str(&param.field_name);
            output.push(' ');
            output.push_str(&param.public_go_type);
        }
        output.push('\n');
    }
    output.push_str("}\n");
}

fn render_options_field_doc_comment(output: &mut String, param: &RenderedUnpackedParam) {
    if param.required {
        render_field_doc_comment(output, "\t", param.doc.as_deref(), true);
    } else {
        render_go_doc_comment(output, "\t", "Optional.");
        if let Some(doc) = param.doc.as_deref() {
            render_go_doc_comment(output, "\t", doc);
        }
    }
}

fn render_empty_options_struct(output: &mut String, operation: &RenderedOperation<'_>) {
    output.push_str("type ");
    output.push_str(&go_field_name(operation.name));
    output.push_str("Options struct {\n}\n");
}

fn param_belongs_in_options(param: &RenderedUnpackedParam) -> bool {
    param.function.is_none() && param.function_args.is_none()
}

fn param_is_positional(param: &RenderedUnpackedParam) -> bool {
    !param_belongs_in_options(param)
}

fn function_type_parameter_name(param: &RenderedUnpackedParam) -> String {
    format!("{}F", param.field_name)
}

fn function_type_parameters(
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
    mode: WrapperMode<'_>,
) -> Vec<(String, String)> {
    let mut type_params = Vec::new();
    let unary_primary = mode.unary_primary;
    for param in params.iter().filter(|param| param.function.is_some()) {
        let function = param.function.as_ref().unwrap();
        if mode
            .with_args_primary_function
            .is_some_and(|primary| primary.field_name == param.field_name)
        {
            continue;
        }
        if unary_primary.is_some_and(|primary| primary.field_name == param.field_name) {
            type_params.push((primary_arg_type_parameter_name(param), "any".to_string()));
            type_params.push((primary_result_type_parameter_name(param), "any".to_string()));
            type_params.push((
                function_type_parameter_name(param),
                go_unary_function_constraint(param, function, package, visibility),
            ));
        } else {
            type_params.push((
                function_type_parameter_name(param),
                go_function_constraint(function, params, package, visibility),
            ));
        }
    }
    type_params
}

#[derive(Clone, Copy)]
struct WrapperMode<'a> {
    unary_primary: Option<&'a RenderedUnpackedParam>,
    with_args_primary_function: Option<&'a RenderedUnpackedParam>,
}

fn go_function_constraint(
    function: &FunctionFieldSpec,
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
) -> String {
    let args = match &function.args {
        FunctionArgsSpec::Fixed(args) => args
            .iter()
            .map(|arg| {
                let arg_field = arg.name.to_snake_case();
                params
                    .iter()
                    .find(|param| {
                        param
                            .field_name
                            .eq_ignore_ascii_case(&go_field_name(&arg_field))
                    })
                    .map(|param| param.go_type.clone())
                    .unwrap_or_else(|| {
                        go_authored_function_type_expr(&arg.field_type, package, visibility)
                    })
            })
            .collect::<Vec<_>>(),
        FunctionArgsSpec::Varargs { prefix, .. } => {
            let mut args = prefix
                .iter()
                .map(|arg| go_authored_function_type_expr(&arg.field_type, package, visibility))
                .collect::<Vec<_>>();
            let vararg_type = params
                .iter()
                .find(|param| {
                    param
                        .field_name
                        .eq_ignore_ascii_case(&go_field_name(&function.args_field))
                })
                .map(|param| go_variadic_element_type(&param.go_type))
                .unwrap_or_else(|| "any".to_string());
            args.push(format!("...{vararg_type}"));
            args
        }
    };
    let result_type = match &function.result {
        FunctionResultSpec::Wit(result) => {
            go_authored_function_type_expr(result, package, visibility)
        }
        FunctionResultSpec::Annotation(result) => result
            .for_language(Language::Go)
            .map(|result| package.go_type_expr(result))
            .map(|result| visibility.rewrite_go_expr(&result))
            .unwrap_or_else(|| "any".to_string()),
    };
    let function_constraint = format!("func({}) {}", args.join(", "), result_type);
    if let Some(alternate_type) = &function.alternate_type {
        let alternate_type = go_authored_function_type_expr(alternate_type, package, visibility);
        format!("interface{{ ~{alternate_type} | {function_constraint} }}")
    } else {
        format!("interface{{ ~{function_constraint} }}")
    }
}

fn go_unary_function_constraint(
    param: &RenderedUnpackedParam,
    function: &FunctionFieldSpec,
    package: &GoPackageContext,
    visibility: &GoVisibility,
) -> String {
    let mut args = match &function.args {
        FunctionArgsSpec::Varargs { prefix, .. } => prefix
            .iter()
            .map(|arg| go_authored_function_type_expr(&arg.field_type, package, visibility))
            .collect::<Vec<_>>(),
        FunctionArgsSpec::Fixed(args) => args
            .iter()
            .map(|arg| go_authored_function_type_expr(&arg.field_type, package, visibility))
            .collect::<Vec<_>>(),
    };
    args.push(primary_arg_type_parameter_name(param));
    let result_type = primary_result_type_parameter_name(param);
    format!("interface{{ ~func({}) {} }}", args.join(", "), result_type)
}

fn primary_arg_type_parameter_name(param: &RenderedUnpackedParam) -> String {
    format!("{}Arg", param.field_name)
}

fn primary_result_type_parameter_name(param: &RenderedUnpackedParam) -> String {
    format!("{}Result", param.field_name)
}

fn go_variadic_element_type(go_type: &str) -> String {
    go_type
        .strip_prefix("[]")
        .map(str::to_string)
        .unwrap_or_else(|| "any".to_string())
}

fn go_authored_function_type_expr(
    wit_type: &AuthoredFieldTypeSpec,
    package: &GoPackageContext,
    visibility: &GoVisibility,
) -> String {
    let expr = match wit_type {
        AuthoredFieldTypeSpec::Option(inner) => {
            format!(
                "*{}",
                go_authored_function_type_expr(inner, package, visibility)
            )
        }
        AuthoredFieldTypeSpec::List(inner) => {
            format!(
                "[]{}",
                go_authored_function_type_expr(inner, package, visibility)
            )
        }
        AuthoredFieldTypeSpec::Map(key, value) => format!(
            "map[{}]{}",
            go_authored_function_type_expr(key, package, visibility),
            go_authored_function_type_expr(value, package, visibility)
        ),
        AuthoredFieldTypeSpec::Alias {
            type_name, target, ..
        } => type_name
            .for_language(Language::Go)
            .map(|annotation| package.go_type_expr(annotation))
            .unwrap_or_else(|| go_authored_function_type_expr(target, package, visibility)),
        _ => go_authored_type_annotation(wit_type),
    };
    visibility.rewrite_go_expr(&expr)
}

fn primary_varargs_args_param(params: &[RenderedUnpackedParam]) -> Option<&RenderedUnpackedParam> {
    let primary_function = params.iter().find_map(|param| {
        let function = param.function.as_ref()?;
        if function.primary && matches!(function.args, FunctionArgsSpec::Varargs { .. }) {
            Some(function)
        } else {
            None
        }
    })?;
    params.iter().find(|param| {
        !param.required
            && param
                .function_args
                .as_ref()
                .is_some_and(|function| function == primary_function)
    })
}

fn primary_base_varargs_args_param(
    params: &[RenderedUnpackedParam],
) -> Option<&RenderedUnpackedParam> {
    if unary_primary_varargs_function_param(params).is_some() {
        return None;
    }
    let args_param = primary_varargs_args_param(params)?;
    if go_variadic_element_type(&args_param.go_type) == "string" {
        Some(args_param)
    } else {
        None
    }
}

fn primary_varargs_function_param(
    params: &[RenderedUnpackedParam],
) -> Option<&RenderedUnpackedParam> {
    params.iter().find(|param| {
        param.function.as_ref().is_some_and(|function| {
            function.primary && matches!(function.args, FunctionArgsSpec::Varargs { .. })
        })
    })
}

fn unary_primary_varargs_function_param(
    params: &[RenderedUnpackedParam],
) -> Option<&RenderedUnpackedParam> {
    let function_param = primary_varargs_function_param(params)?;
    let function = function_param.function.as_ref()?;
    let FunctionArgsSpec::Varargs { prefix, .. } = &function.args else {
        return None;
    };
    if prefix.is_empty() {
        return None;
    }
    let args_param = primary_varargs_args_param(params)?;
    if go_variadic_element_type(&args_param.go_type) == "any" {
        Some(function_param)
    } else {
        None
    }
}

fn render_operation_wrapper_return_type(output: &mut String, package: &GoPackageContext) {
    render_operation_future_return_type(output, package);
}

fn render_function_name_inlining(output: &mut String, params: &[RenderedUnpackedParam]) {
    for param in params {
        if param.function.is_some() {
            render_function_name_inline_assignment(output, param);
        }
    }
}

fn render_function_name_inline_assignment(output: &mut String, param: &RenderedUnpackedParam) {
    let name_var = function_name_local_var(param);
    output.push('\t');
    output.push_str(&name_var);
    output.push_str(" := \"\"\n");
    output.push_str("\tswitch rv := reflect.ValueOf(");
    output.push_str(&param.param_name);
    output.push_str("); rv.Kind() {\n");
    output.push_str("\tcase reflect.String:\n");
    output.push('\t');
    output.push('\t');
    output.push_str(&name_var);
    output.push_str(" = rv.String()\n");
    output.push_str("\tcase reflect.Func:\n");
    output.push_str("\t\tfullName := runtime.FuncForPC(rv.Pointer()).Name()\n");
    output.push_str("\t\telements := strings.Split(fullName, \".\")\n");
    output.push_str("\t\tshortName := elements[len(elements)-1]\n");
    output.push('\t');
    output.push('\t');
    output.push_str(&name_var);
    output.push_str(" = strings.TrimSuffix(shortName, \"-fm\")\n");
    output.push_str("\tdefault:\n");
    output.push_str("\t\tpanic(\"nex-gen function name requires string or function\")\n");
    output.push_str("\t}\n");
}

fn function_name_local_var(param: &RenderedUnpackedParam) -> String {
    format!("{}Name", param.param_name)
}

fn wrapper_input_docs<'a>(
    params: impl IntoIterator<Item = &'a RenderedUnpackedParam>,
) -> Vec<(String, String)> {
    params
        .into_iter()
        .filter_map(|param| {
            let doc = param.doc.as_deref()?.trim();
            if doc.is_empty() {
                None
            } else {
                Some((param.param_name.clone(), doc.to_string()))
            }
        })
        .collect()
}

fn render_signature(
    output: &mut String,
    exported_name: &str,
    type_params: &[(String, String)],
    signature_params: &[(String, String)],
    package: &GoPackageContext,
) {
    output.push_str("func ");
    output.push_str(exported_name);
    if !type_params.is_empty() {
        output.push('[');
        for (index, (name, constraint)) in type_params.iter().enumerate() {
            if index > 0 {
                output.push_str(", ");
            }
            output.push_str(name);
            output.push(' ');
            output.push_str(constraint);
        }
        output.push(']');
    }
    let multiline_signature = signature_params.len() + 1 > 3;
    if multiline_signature {
        output.push_str("(\n\tctx ");
        output.push_str(&package.workflow_context_type());
        output.push_str(",\n");
        for (name, ty) in signature_params {
            output.push('\t');
            output.push_str(name);
            output.push(' ');
            output.push_str(ty);
            output.push_str(",\n");
        }
        output.push(')');
    } else {
        output.push_str("(ctx ");
        output.push_str(&package.workflow_context_type());
        for (name, ty) in signature_params {
            output.push_str(", ");
            output.push_str(name);
            output.push(' ');
            output.push_str(ty);
        }
        output.push(')');
    }
}

fn render_public_default_punning_locals(output: &mut String, params: &[RenderedUnpackedParam]) {
    for param in params
        .iter()
        .filter(|param| param_belongs_in_options(param))
    {
        if let Some(zero) = &param.default_punning_zero {
            output.push_str("\tvar ");
            output.push_str(&param.param_name);
            output.push(' ');
            output.push_str(&param.go_type);
            output.push('\n');
            output.push_str("\tif opts.");
            output.push_str(&param.field_name);
            output.push_str(" != ");
            output.push_str(zero);
            output.push_str(" {\n\t\t");
            output.push_str(&param.param_name);
            output.push_str(" = &opts.");
            output.push_str(&param.field_name);
            output.push_str("\n\t}\n");
        }
    }
}

fn public_option_request_expr(param: &RenderedUnpackedParam) -> String {
    if param.default_punning_zero.is_some() {
        param.param_name.clone()
    } else if param.embed_in_options {
        format!("&opts.{}", param.field_name)
    } else {
        format!("opts.{}", param.field_name)
    }
}

fn positional_param_type(param: &RenderedUnpackedParam, mode: WrapperMode<'_>) -> Option<String> {
    if param.function.is_some() {
        if mode
            .with_args_primary_function
            .is_some_and(|primary| primary.field_name == param.field_name)
        {
            Some("any".to_string())
        } else {
            Some(function_type_parameter_name(param))
        }
    } else if mode.unary_primary.is_some()
        && primary_varargs_args_field_matches(param, mode.unary_primary.unwrap())
    {
        Some(primary_arg_type_parameter_name(mode.unary_primary.unwrap()))
    } else if param.function_args.is_some() {
        Some(param.public_go_type.clone())
    } else {
        None
    }
}

fn positional_param_name(param: &RenderedUnpackedParam, mode: WrapperMode<'_>) -> String {
    if mode.unary_primary.is_some()
        && primary_varargs_args_field_matches(param, mode.unary_primary.unwrap())
    {
        "arg".to_string()
    } else {
        param.param_name.clone()
    }
}

fn primary_varargs_args_field_matches(
    args_param: &RenderedUnpackedParam,
    function_param: &RenderedUnpackedParam,
) -> bool {
    let Some(args_function) = &args_param.function_args else {
        return false;
    };
    function_param
        .function
        .as_ref()
        .is_some_and(|function| args_function == function)
}

fn request_expr_for_param(
    param: &RenderedUnpackedParam,
    mode: WrapperMode<'_>,
    with_args_param: Option<&RenderedUnpackedParam>,
) -> String {
    if param.function.is_some() {
        function_name_local_var(param)
    } else if let Some(primary) = mode.unary_primary {
        if primary_varargs_args_field_matches(param, primary) {
            return format!("{}{{arg}}", param.go_type);
        }
        if param.function_args.is_some() {
            return param.param_name.clone();
        }
        public_option_request_expr(param)
    } else if with_args_param.is_some_and(|args_param| args_param.field_name == param.field_name) {
        "args".to_string()
    } else if param.function_args.is_some() {
        param.param_name.clone()
    } else {
        public_option_request_expr(param)
    }
}

fn render_operation_request_call(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
    mode: WrapperMode<'_>,
    with_args_param: Option<&RenderedUnpackedParam>,
) {
    render_public_default_punning_locals(output, params);
    render_function_name_inlining(output, params);
    output.push_str("\treturn ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx, ");
    output.push_str(&operation.input_type);
    output.push_str("{\n");
    for param in params {
        output.push_str("\t\t");
        output.push_str(&param.field_name);
        output.push_str(": ");
        output.push_str(&request_expr_for_param(param, mode, with_args_param));
        output.push_str(",\n");
    }
    output.push_str("\t})\n");
}

/// Renders an exported convenience wrapper that unpacks required fields as
/// positional arguments and optional fields into a required options struct.
///
/// The request struct is always constructed across multiple lines. The function
/// signature is also split across multiple lines when it has more than three
/// parameters (counting `ctx`).
///
/// ```go
/// func UpdateEmail(ctx workflow.Context, userId string, email string) (*User, error) {
///     return updateEmail(ctx, UpdateEmailRequest{
///         UserId: userId,
///         Email:  email,
///     })
/// }
/// ```
///
/// With more than three parameters:
/// ```go
/// func StartWorkflow(
///     ctx workflow.Context,
///     workflow string,
///     workflowId string,
///     taskQueue string,
///     opts StartWorkflowOptions,
/// ) (*StartedWorkflow, error) {
///     return startWorkflow(ctx, StartWorkflowRequest{
///         Workflow:           workflow,
///         Args:               opts.Args,
///         WorkflowId:         workflowId,
///         TaskQueue:          taskQueue,
///         WorkflowStartDelay: opts.WorkflowStartDelay,
///     })
/// }
/// ```
fn render_convenience_wrapper(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
) {
    let exported_name = go_field_name(operation.name);
    let unary_primary = unary_primary_varargs_function_param(params);
    let default_varargs_param = primary_base_varargs_args_param(params);
    let mode = WrapperMode {
        unary_primary,
        with_args_primary_function: None,
    };
    let type_params = function_type_parameters(params, package, visibility, mode);

    let input_docs = wrapper_input_docs(params.iter().filter(|p| param_is_positional(p)));
    render_operation_doc_comment(output, operation, &input_docs);

    let mut signature_params: Vec<(String, String)> =
        vec![("opts".to_string(), format!("{exported_name}Options"))];
    signature_params.extend(
        params
            .iter()
            .filter(|p| param_is_positional(p))
            .filter(|p| {
                !default_varargs_param
                    .is_some_and(|args_param| args_param.field_name == p.field_name)
            })
            .filter_map(|p| {
                Some((
                    positional_param_name(p, mode),
                    positional_param_type(p, mode)?,
                ))
            }),
    );
    if let Some(args_param) = default_varargs_param {
        signature_params.push((
            "args".to_string(),
            format!("...{}", go_variadic_element_type(&args_param.go_type)),
        ));
    }

    render_signature(
        output,
        &exported_name,
        &type_params,
        &signature_params,
        package,
    );
    output.push(' ');

    render_operation_wrapper_return_type(output, package);
    output.push_str(" {\n");

    render_operation_request_call(output, operation, params, mode, default_varargs_param);
    output.push_str("}\n");
}

fn render_with_args_convenience_wrapper(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
) {
    let exported_name = format!("{}WithArgs", go_field_name(operation.name));
    let base_exported_name = go_field_name(operation.name);
    let args_param = primary_varargs_args_param(params)
        .expect("WithArgs wrapper requires a primary varargs args param");
    let vararg_type = go_variadic_element_type(&args_param.go_type);
    let primary_function = primary_varargs_function_param(params);
    let mode = WrapperMode {
        unary_primary: None,
        with_args_primary_function: if unary_primary_varargs_function_param(params).is_some() {
            primary_function
        } else {
            None
        },
    };
    let type_params = function_type_parameters(params, package, visibility, mode);

    let input_docs = wrapper_input_docs(
        params
            .iter()
            .filter(|p| param_is_positional(p) && p.field_name != args_param.field_name)
            .chain(std::iter::once(args_param)),
    );
    render_operation_doc_comment(output, operation, &input_docs);

    let mut signature_params: Vec<(String, String)> =
        vec![("opts".to_string(), format!("{base_exported_name}Options"))];
    signature_params.extend(
        params
            .iter()
            .filter(|p| param_is_positional(p) && p.field_name != args_param.field_name)
            .filter_map(|p| {
                Some((
                    positional_param_name(p, mode),
                    positional_param_type(p, mode)?,
                ))
            }),
    );
    signature_params.push(("args".to_string(), format!("...{vararg_type}")));

    render_signature(
        output,
        &exported_name,
        &type_params,
        &signature_params,
        package,
    );
    output.push(' ');
    render_operation_wrapper_return_type(output, package);
    output.push_str(" {\n");

    render_operation_request_call(output, operation, params, mode, Some(args_param));
    output.push_str("}\n");
}

/// Renders an exported forwarding wrapper for operations whose input type is
/// an external/replacement type (no model to unpack). The wrapper simply
/// forwards to the unexported operation function.
///
/// ```go
/// func RetryPolicyOperation(ctx workflow.Context, opts RetryPolicyOperationOptions, request temporal.RetryPolicy) (*temporal.RetryPolicy, error) {
///     return retryPolicyOperation(ctx, request)
/// }
/// ```
fn render_forwarding_wrapper(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    package: &GoPackageContext,
) {
    let exported_name = go_field_name(operation.name);

    render_operation_doc_comment(output, operation, &[]);
    output.push_str("func ");
    output.push_str(&exported_name);
    output.push_str("(ctx ");
    output.push_str(&package.workflow_context_type());
    output.push_str(", opts ");
    output.push_str(&exported_name);
    output.push_str("Options, request ");
    output.push_str(&operation.input_type);
    output.push_str(") ");

    render_operation_wrapper_return_type(output, package);

    output.push_str(" {\n");
    output.push_str("\treturn ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx, request)\n");
    output.push_str("}\n");
}
