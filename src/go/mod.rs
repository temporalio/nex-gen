/// A resolved Nexus service ready for rendering. Currently used to drive type
/// collection; service-level code generation (clients, handlers) is not yet
/// implemented.
#[derive(Debug)]
struct RenderedService<'a> {
    /// UpperCamelCase service name (e.g. `"TypeShowcase"`).
    name: &'a str,
    /// Nexus endpoint identifier (e.g. `"type-showcase"`).
    endpoint: String,
    /// Operations belonging to this service.
    operations: Vec<RenderedOperation<'a>>,
    /// Resources belonging to this service.
    resources: Vec<PlannedResource>,
}

/// A resolved Nexus operation with enough information to render the operation
/// constant and an unexported caller function.
#[derive(Debug)]
struct RenderedOperation<'a> {
    /// UpperCamelCase operation name (e.g. `"GetUser"`).
    name: &'a str,
    /// Wire-format operation name (e.g. `"GetUser"`).
    wire_name: &'a str,
    /// Doc text for the operation (from `@nexus.doc`), rendered as a godoc
    /// comment on the exported wrapper function.
    doc: Option<&'a str>,
    /// Return-value doc text (from `@nexus.doc returns=`), rendered as a
    /// `Returns:` paragraph in the wrapper's godoc comment.
    return_doc: Option<&'a str>,
    /// Unexported Go function name (e.g. `"getUser"`).
    func_name: String,
    /// Go type for the request parameter (e.g. `"GetUserRequest"`).
    input_type: String,
    /// Go type for the result, or `None` for void operations.
    /// For resource-returning operations this is the resource type name
    /// (e.g. `"User"`).
    output_type: Option<String>,
    /// Go type for the raw operation result before applying an output
    /// transform. This is only distinct from `output_type` for transformed
    /// operations.
    raw_output_type: Option<String>,
    /// Go expression for an `@nexus.output-transform`, if one is configured.
    /// The expression is rendered with `request` and raw `result` in scope and
    /// must evaluate to `(output_transform_type, error)`.
    output_transform_expr: Option<&'a str>,
    /// Go return type for an `@nexus.output-transform`, with any embedded
    /// import path stripped from the WIT annotation.
    output_transform_type: Option<String>,
    /// Unpacked input parameters for the exported convenience wrapper, or
    /// `None` when the input type is an external/replacement type that cannot
    /// be unpacked into individual arguments.
    unpacked_input: Option<Vec<RenderedUnpackedParam>>,
    /// Resource-return binding, when the operation output is a proto response
    /// used to construct a native resource handle.
    output_resource_return: Option<PlannedOperationResourceReturn>,
    /// Proto serialization binding for the request/response, populated in a
    /// second pass when the input/output messages are proto-backed. When
    /// present, the operation function converts native values to/from proto and
    /// types the SDK call in terms of the proto messages.
    proto_binding: Option<OperationProtoBinding>,
}

/// Proto serialization binding for an operation's request and response,
/// allowing the generated operation function to convert native values to/from
/// proto before/after the SDK call.
#[derive(Debug)]
struct OperationProtoBinding {
    /// Expression converting the native `request` value to its proto form.
    input_to_proto: String,
    /// Proto type expression for the response, or `None` for void operations.
    output_proto_type: Option<String>,
    /// Expression converting the proto response (bound to `&result`) to its
    /// native form. `None` for void operations.
    output_from_proto: Option<String>,
    /// Whether `output_from_proto` already evaluates to a pointer (override
    /// converters return `*Native`) or to a value that must be addressed
    /// (generated model converters return `Model`).
    output_returns_pointer: bool,
}

/// A single parameter in an unpacked convenience wrapper function signature.
#[derive(Debug)]
struct RenderedUnpackedParam {
    /// Exported Go field name used when setting the request struct field
    /// (e.g. `"UserId"`).
    field_name: String,
    /// Doc text for the field (from `@nexus.doc`), rendered as a godoc
    /// comment on the options struct field for optional parameters.
    doc: Option<String>,
    /// Unexported Go parameter name used in the function signature
    /// (e.g. `"userId"`).
    param_name: String,
    /// Go type expression (e.g. `"string"`, `"UserProfile"`).
    go_type: String,
    /// Whether this parameter is required (positional argument) or optional
    /// (placed in the options struct).
    required: bool,
    /// Whether this optional parameter should be embedded as a value in the
    /// generated options struct because its model is marked `flatten-in-api`.
    embed_in_options: bool,
}

/// A WIT enum rendered as a Go `type <Name> int32` with associated constants.
#[derive(Debug)]
struct RenderedEnum {
    /// Go type name (e.g. `"UserStatus"`).
    name: String,
    /// Ordered enum variants with their numeric values.
    values: Vec<RenderedEnumValue>,
}

/// A single variant of a [`RenderedEnum`].
#[derive(Debug)]
struct RenderedEnumValue {
    /// UpperCamelCase variant name (e.g. `"Active"`).
    name: String,
    /// Numeric value assigned in the WIT definition.
    number: i32,
}

/// A WIT flags type rendered as a Go `type <Name> int32` with bit-mask
/// constants.
#[derive(Debug)]
struct RenderedFlags {
    /// Go type name (e.g. `"UserCapability"`).
    name: String,
    /// Individual flag definitions.
    flags: Vec<RenderedFlag>,
}

/// A single flag within a [`RenderedFlags`] set.
#[derive(Debug)]
struct RenderedFlag {
    /// UpperCamelCase flag name (e.g. `"ReadProfile"`).
    name: String,
    /// Zero-based bit position (`1 << bit`).
    bit: usize,
}

/// A WIT variant rendered as a Go sealed interface with concrete case structs.
///
/// The interface carries an unexported marker method to prevent external
/// implementations. Each case becomes a struct that implements the interface.
#[derive(Debug)]
struct RenderedVariant {
    /// Go interface type name (e.g. `"NotificationTarget"`).
    name: String,
    /// Unexported marker method name (e.g. `"isNotificationTarget"`).
    marker_method: String,
    /// Ordered variant cases.
    cases: Vec<RenderedVariantCase>,
}

/// A single case of a [`RenderedVariant`], rendered as a Go struct that
/// implements the variant's sealed interface.
#[derive(Debug)]
struct RenderedVariantCase {
    /// Go struct name combining variant and case (e.g. `"NotificationTargetEmail"`).
    struct_name: String,
    /// Go type of the payload field, or `None` for payload-less cases.
    payload_type: Option<String>,
}

/// A WIT record (or proto message) rendered as a Go struct. Also used for
/// generated tuple structs.
#[derive(Debug)]
struct RenderedModel {
    /// Go type name (e.g. `"UserProfile"`, `"Coordinates"`).
    name: String,
    /// Struct fields in declaration order.
    fields: Vec<RenderedField>,
    /// The proto type info for proto-backed models, used by the conversion pass
    /// to derive `ToProto`/`FromProto`. `None` for WIT-native models and
    /// tuple/result helper structs.
    proto_info: Option<PlannedTypeInfo>,
    /// Proto serialization metadata, present only for proto-backed models that
    /// the planner marked as needing `ToProto`/`FromProto` conversion.
    proto: Option<RenderedModelProto>,
    /// Sourced fields (write-only, value derived from a source expression)
    /// emitted in `ToProto` after the regular fields.
    sourced_fields: Vec<RenderedSourcedField>,
}

/// Proto serialization metadata for a [`RenderedModel`].
#[derive(Debug)]
struct RenderedModelProto {
    /// Whether to emit a `FromProto` constructor.
    from_proto: bool,
    /// Whether to emit a `ToProto` method.
    to_proto: bool,
    /// The Go proto type expression (e.g. `"common.ActivityOptions"`) the
    /// model converts to/from, qualified with the resolved import alias.
    proto_type: String,
}

/// A single field of a [`RenderedModel`].
#[derive(Debug)]
struct RenderedField {
    /// Exported Go field name in UpperCamelCase (e.g. `"UserId"`, `"First"`).
    name: String,
    /// Doc text for the field (from `@nexus.doc`), rendered as a godoc
    /// comment above the struct field.
    doc: Option<String>,
    /// Go type expression (e.g. `"string"`, `"*PostalAddress"`, `"[]string"`).
    go_type: String,
    /// Whether the field is required in the WIT definition. Rendered as a
    /// leading `// Required.` godoc comment on the generated Go struct field.
    required: bool,
    /// Proto conversion metadata, present when the owning model is
    /// proto-backed. `None` for tuple/result helper structs.
    conversion: Option<RenderedFieldConversion>,
}

/// Per-field proto conversion metadata, carrying the lines/expressions needed
/// to populate the field in `ToProto` and read it in `FromProto`.
#[derive(Debug)]
struct RenderedFieldConversion {
    /// Lines that assign this field into the `message` proto value, given a
    /// receiver `m`.
    to_proto_lines: Vec<String>,
    /// Lines that compute this field from `proto`, binding the result to the
    /// struct field of the value under construction.
    from_proto_lines: Vec<String>,
}

/// A sourced field rendered for `ToProto`.
#[derive(Debug)]
struct RenderedSourcedField {
    to_proto_lines: Vec<String>,
}

/// The result of resolving a [`PlannedValueType`] to a Go type expression.
/// Carries enough information to decide whether an optional field should use
/// a pointer (`*T`) or its zero value.
#[derive(Debug, Clone)]
struct ResolvedGoType {
    /// Go type expression (e.g. `"string"`, `"PostalAddress"`, `"[]string"`).
    type_expr: String,
    /// `true` when the resolved type is a struct (message/record/tuple).
    ///
    /// Optionality is now expressed uniformly with pointers (see
    /// [`type_needs_pointer_when_optional`]), so this flag is retained only for
    /// descriptive completeness of the resolved type.
    #[allow(dead_code)]
    is_struct: bool,
}

