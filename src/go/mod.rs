/// Maps a [`PlannedValueType`] to a [`ResolvedGoType`], registering any
/// newly-encountered compound types (enums, flags, variants, models) in the
/// corresponding `IndexMap` collections along the way.
///
/// Tuples are not supported in this context (inside lists, maps, or other
/// containers). They are only supported as direct record fields, where
/// [`build_field`] generates a named struct before calling this function.
fn resolve_planned_value_type(
    value_type: &PlannedValueType,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<ResolvedGoType> {
    match value_type {
        PlannedValueType::Scalar(PlannedScalarType::Float) => Ok(ResolvedGoType {
            type_expr: "float64".to_string(),
            is_struct: false,
        }),
        PlannedValueType::Scalar(PlannedScalarType::Int32) => Ok(ResolvedGoType {
            type_expr: "int32".to_string(),
            is_struct: false,
        }),
        PlannedValueType::Scalar(PlannedScalarType::Int64) => Ok(ResolvedGoType {
            type_expr: "int64".to_string(),
            is_struct: false,
        }),
        PlannedValueType::Scalar(PlannedScalarType::Bool) => Ok(ResolvedGoType {
            type_expr: "bool".to_string(),
            is_struct: false,
        }),
        PlannedValueType::Scalar(PlannedScalarType::String) => Ok(ResolvedGoType {
            type_expr: "string".to_string(),
            is_struct: false,
        }),
        PlannedValueType::Scalar(PlannedScalarType::Bytes) => Ok(ResolvedGoType {
            type_expr: "[]byte".to_string(),
            is_struct: false,
        }),
        PlannedValueType::Enum(enum_type) => {
            if let Some(replacement) = &enum_type.replacement
                && let Some(type_name) = go_replacement_type_name(replacement, package)
            {
                return Ok(ResolvedGoType {
                    type_expr: type_name,
                    is_struct: false,
                });
            }
            if let (Some(info), Some(name)) = (&enum_type.info, &enum_type.name) {
                if let Some(planned_enum) = api_plan.enums.get(&info.full_name) {
                    ensure_rendered_enum(planned_enum, enums);
                }
                Ok(ResolvedGoType {
                    type_expr: name.clone(),
                    is_struct: false,
                })
            } else {
                Ok(ResolvedGoType {
                    type_expr: "int32".to_string(),
                    is_struct: false,
                })
            }
        }
        PlannedValueType::Flags(flags_type) => {
            if let Some(planned_flags) = api_plan.flags.get(&flags_type.info.full_name) {
                ensure_rendered_flags(planned_flags, flags);
            }
            Ok(ResolvedGoType {
                type_expr: flags_type.name.clone(),
                is_struct: false,
            })
        }
        PlannedValueType::Variant(variant_type) => {
            if let Some(planned_variant) = api_plan.variants.get(&variant_type.info.full_name) {
                ensure_rendered_variant(
                    planned_variant,
                    api_plan,
                    enums,
                    flags,
                    variants,
                    models,
                    package,
                )?;
            }
            // Interfaces have nil zero value, so no pointer needed for optional fields.
            Ok(ResolvedGoType {
                type_expr: variant_type.name.clone(),
                is_struct: false,
            })
        }
        PlannedValueType::Message(message_type) => {
            if let Some(replacement) = &message_type.replacement
                && let Some(type_name) = go_replacement_type_name(replacement, package)
            {
                return Ok(ResolvedGoType {
                    type_expr: type_name,
                    is_struct: false,
                });
            }
            if let Some(authored_type) = &message_type.authored_type {
                return Ok(ResolvedGoType {
                    type_expr: go_authored_type_annotation(authored_type),
                    is_struct: false,
                });
            }
            ensure_rendered_model(
                message_type,
                api_plan,
                enums,
                flags,
                variants,
                models,
                package,
            )?;
            Ok(ResolvedGoType {
                type_expr: message_type.model_name.clone(),
                is_struct: true,
            })
        }
        // Tuples and results inside containers (lists, maps, variant payloads,
        // resource fields) instantiate shared generic helper types; direct
        // record fields keep their field-named structs (see `build_field`).
        PlannedValueType::Tuple(items) => {
            let type_name = ensure_generic_tuple(items.len(), models)?;
            let args = items
                .iter()
                .map(|item| {
                    resolve_planned_value_type(
                        item, api_plan, enums, flags, variants, models, package,
                    )
                    .map(|resolved| resolved.type_expr)
                })
                .collect::<Result<Vec<_>>>()?;
            Ok(ResolvedGoType {
                type_expr: format!("{type_name}[{}]", args.join(", ")),
                is_struct: true,
            })
        }
        PlannedValueType::Result { ok, err } => {
            ensure_generic_result(models);
            let ok_type = match ok {
                Some(ok) => {
                    resolve_planned_value_type(
                        ok, api_plan, enums, flags, variants, models, package,
                    )?
                    .type_expr
                }
                None => "struct{}".to_string(),
            };
            let err_type = match err {
                Some(err) => {
                    resolve_planned_value_type(
                        err, api_plan, enums, flags, variants, models, package,
                    )?
                    .type_expr
                }
                None => "error".to_string(),
            };
            Ok(ResolvedGoType {
                type_expr: format!("Result[{ok_type}, {err_type}]"),
                is_struct: true,
            })
        }
        PlannedValueType::External {
            type_name,
            fallback,
        } => {
            if let Some(annotation) = type_name.for_language(Language::Go) {
                Ok(ResolvedGoType {
                    type_expr: package.go_type_expr(annotation),
                    is_struct: false,
                })
            } else {
                resolve_planned_value_type(
                    fallback, api_plan, enums, flags, variants, models, package,
                )
            }
        }
        PlannedValueType::Unknown => Ok(ResolvedGoType {
            type_expr: "any".to_string(),
            is_struct: false,
        }),
    }
}

/// Returns the Go type code expression from a [`TypeReplacementSpec`], if one
/// was specified for the Go language. The import path (if embedded in the
/// annotation) is stripped and will be collected separately by
/// [`collect_imports`].
fn go_replacement_type_name(
    replacement: &TypeReplacementSpec,
    package: &GoPackageContext,
) -> Option<String> {
    replacement
        .type_name
        .for_language(Language::Go)
        .map(|annotation| package.go_type_expr(annotation))
}

/// Translates a WIT authored field type (used in `@nexus.type` directives)
/// into a Go type expression. Tuples and results are deferred and represented
/// as `any`.
fn go_authored_type_annotation(wit_type: &AuthoredFieldTypeSpec) -> String {
    match wit_type {
        AuthoredFieldTypeSpec::Bool => "bool".to_string(),
        AuthoredFieldTypeSpec::Int => "int64".to_string(),
        AuthoredFieldTypeSpec::Float => "float64".to_string(),
        AuthoredFieldTypeSpec::String => "string".to_string(),
        AuthoredFieldTypeSpec::Bytes => "[]byte".to_string(),
        AuthoredFieldTypeSpec::Option(inner) => {
            format!("*{}", go_authored_type_annotation(inner))
        }
        AuthoredFieldTypeSpec::List(inner) => {
            format!("[]{}", go_authored_type_annotation(inner))
        }
        AuthoredFieldTypeSpec::Tuple(_) => "any".to_string(),
        AuthoredFieldTypeSpec::Map(key, value) => format!(
            "map[{}]{}",
            go_authored_type_annotation(key),
            go_authored_type_annotation(value)
        ),
        AuthoredFieldTypeSpec::Result { .. } => "any".to_string(),
        AuthoredFieldTypeSpec::Alias {
            type_name, target, ..
        } => type_name
            .for_language(Language::Go)
            .map(str::to_string)
            .unwrap_or_else(|| go_authored_type_annotation(target)),
        AuthoredFieldTypeSpec::Proto(proto_name) => proto_name
            .rsplit('.')
            .next()
            .unwrap_or(proto_name)
            .to_string(),
        AuthoredFieldTypeSpec::Record(name)
        | AuthoredFieldTypeSpec::Enum(name)
        | AuthoredFieldTypeSpec::Flags(name)
        | AuthoredFieldTypeSpec::Variant(name)
        | AuthoredFieldTypeSpec::Resource(name) => name
            .rsplit('.')
            .next()
            .unwrap_or(name)
            .to_upper_camel_case(),
    }
}

