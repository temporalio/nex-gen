fn render_variant(output: &mut String, variant: &crate::api_plan::PlannedVariant) {
    output.push_str("public abstract class ");
    output.push_str(&csharp_type_name(&variant.name));
    output.push_str("\n{\n");
    output.push_str("    private ");
    output.push_str(&csharp_type_name(&variant.name));
    output.push_str("() { }\n\n");
    for case in &variant.cases {
        let case_name = csharp_type_name(&case.name);
        output.push_str("    public sealed class ");
        output.push_str(&case_name);
        output.push_str(" : ");
        output.push_str(&csharp_type_name(&variant.name));
        output.push_str("\n    {\n");
        if let Some(payload) = &case.payload {
            let payload_type = dotnet_value_type(payload);
            output.push_str("        public ");
            output.push_str(&case_name);
            output.push('(');
            output.push_str(&payload_type);
            output.push_str(" value) => Value = value;\n\n");
            output.push_str("        public ");
            output.push_str(&payload_type);
            output.push_str(" Value { get; }\n");
        } else {
            output.push_str("        public ");
            output.push_str(&case_name);
            output.push_str("() { }\n");
        }
        output.push_str("    }\n\n");
    }
    output.push_str("}\n\n");
}

fn render_model(output: &mut String, model: &PlannedModel, api_plan: &ApiPlan) {
    render_xml_summary(output, "", dotnet_doc(model.generated_model.doc()));
    output.push_str(model_access(model, api_plan));
    output.push_str(" class ");
    output.push_str(&csharp_type_name(&model.name));
    output.push_str("\n{\n");
    for field in &model.fields {
        render_field_xml_doc(output, "    ", field);
        output.push_str("    public ");
        if field.required {
            output.push_str("required ");
        }
        output.push_str(&field_type(field, api_plan));
        output.push(' ');
        output.push_str(&field_property_name(field));
        output.push_str(" { get; init; }");
        output.push('\n');
    }
    if model_needs_to_proto_method(model) {
        if !model.fields.is_empty() {
            output.push('\n');
        }
        render_model_to_proto_method(output, model, api_plan);
    }
    output.push_str("}\n\n");
}

fn model_access(model: &PlannedModel, api_plan: &ApiPlan) -> &'static str {
    if api_plan.services.iter().any(|service| {
        service.operations.iter().any(|operation| {
            operation.input.info.full_name == model.info.full_name
                && operation_has_flattened_convenience(operation, model, api_plan)
        })
    }) {
        "internal"
    } else {
        "public"
    }
}

fn render_resource(output: &mut String, resource: &PlannedResource) {
    let type_name = csharp_type_name(&resource.type_name);
    output.push_str("public class ");
    output.push_str(&type_name);
    output.push_str("\n{\n");
    output.push_str("    public ");
    output.push_str(&type_name);
    output.push('(');
    for (index, field) in resource.fields.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&resource_field_type(&field.kind, field.optional));
        output.push(' ');
        output.push_str(&csharp_parameter_name(&field.name));
    }
    output.push_str(")\n    {\n");
    for field in &resource.fields {
        output.push_str("        ");
        output.push_str(&csharp_type_name(&field.name));
        output.push_str(" = ");
        output.push_str(&csharp_parameter_name(&field.name));
        output.push_str(";\n");
    }
    output.push_str("    }\n\n");
    for field in &resource.fields {
        output.push_str("    public ");
        output.push_str(&resource_field_type(&field.kind, field.optional));
        output.push(' ');
        output.push_str(&csharp_type_name(&field.name));
        output.push_str(" { get; }\n");
    }
    if !resource.fields.is_empty() && !resource.methods.is_empty() {
        output.push('\n');
    }
    for method in &resource.methods {
        render_resource_method(output, method);
    }
    output.push_str("}\n\n");
}

fn render_resource_method(output: &mut String, method: &PlannedResourceMethod) {
    let return_type = resource_method_return_type(method);
    output.push_str("    public ");
    output.push_str(&return_type);
    output.push(' ');
    output.push_str(&csharp_type_name(&method.name));
    output.push('(');
    for (index, param) in method.params.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&resource_field_type(&param.kind, param.optional));
        output.push(' ');
        output.push_str(&csharp_parameter_name(&param.name));
    }
    output.push(')');
    output.push_str(" => throw new NotSupportedException(\"Resource methods require a bound Nexus client.\");\n\n");
}

