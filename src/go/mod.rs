/// Lazily inserts a [`RenderedEnum`] into the collection if one does not
/// already exist for the given planned enum's full name.
fn ensure_rendered_enum(planned_enum: &PlannedEnum, enums: &mut IndexMap<String, RenderedEnum>) {
    enums
        .entry(planned_enum.info.full_name.clone())
        .or_insert_with(|| RenderedEnum {
            name: planned_enum.name.clone(),
            values: planned_enum
                .values
                .iter()
                .map(|value| RenderedEnumValue {
                    name: value.name.clone(),
                    number: value.number,
                })
                .collect(),
        });
}

/// Lazily inserts a [`RenderedFlags`] into the collection if one does not
/// already exist for the given planned flags' full name.
fn ensure_rendered_flags(
    planned_flags: &PlannedFlags,
    flags: &mut IndexMap<String, RenderedFlags>,
) {
    flags
        .entry(planned_flags.info.full_name.clone())
        .or_insert_with(|| RenderedFlags {
            name: planned_flags.name.clone(),
            flags: planned_flags
                .flags
                .iter()
                .map(|flag| RenderedFlag {
                    name: flag.name.clone(),
                    bit: flag.bit,
                })
                .collect(),
        });
}

/// Lazily inserts a [`RenderedVariant`] into the collection, recursively
/// resolving payload types for each case. Each case becomes a concrete struct
/// implementing the variant's sealed interface.
fn ensure_rendered_variant(
    planned_variant: &PlannedVariant,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<()> {
    if variants.contains_key(&planned_variant.info.full_name) {
        return Ok(());
    }

    let variant_name = &planned_variant.name;
    let mut cases = Vec::new();
    for case in &planned_variant.cases {
        let case_suffix = go_field_name(&case.name);
        let payload_type = case
            .payload
            .as_ref()
            .map(|payload| {
                resolve_planned_value_type(
                    payload, api_plan, enums, flags, variants, models, package,
                )
                .map(|resolved| resolved.type_expr)
            })
            .transpose()?;
        cases.push(RenderedVariantCase {
            struct_name: format!("{variant_name}{case_suffix}"),
            payload_type,
        });
    }
    variants.insert(
        planned_variant.info.full_name.clone(),
        RenderedVariant {
            name: variant_name.clone(),
            marker_method: format!("is{variant_name}"),
            cases,
        },
    );
    Ok(())
}

/// Returns the proto type info for a message that should receive generated
/// `ToProto`/`FromProto` methods: a proto-backed message that is not replaced
/// by a native type or an authored type, and whose descriptor carries a
/// `go_package`.
fn proto_backed_info(message: &PlannedMessageType) -> Option<PlannedTypeInfo> {
    if message.replacement.is_some() || message.authored_type.is_some() {
        return None;
    }
    if message.source != PlannedMessageSource::Proto {
        return None;
    }
    if message.info.go_package.is_none() {
        return None;
    }
    Some(message.info.clone())
}

/// Lazily inserts a [`RenderedModel`] for a message type.
///
/// A placeholder with an empty field list is inserted first to break cycles
/// in recursive types, then fields are resolved and back-patched.
fn ensure_rendered_model(
    message: &PlannedMessageType,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<()> {
    let Some(planned_model) = api_plan.models.get(&message.info.full_name) else {
        // The planner may skip models for output types with transforms or
        // resource returns. Generate a minimal empty struct so the type
        // is at least defined.
        if !models.contains_key(&message.info.full_name) {
            models.insert(
                message.info.full_name.clone(),
                RenderedModel {
                    name: message.model_name.clone(),
                    fields: Vec::new(),
                    proto_info: proto_backed_info(message),
                    proto: None,
                    sourced_fields: Vec::new(),
                },
            );
        }
        return Ok(());
    };

    if models.contains_key(&message.info.full_name) {
        return Ok(());
    }

    models.insert(
        message.info.full_name.clone(),
        RenderedModel {
            name: planned_model.name.clone(),
            fields: Vec::new(),
            proto_info: proto_backed_info(message),
            proto: None,
            sourced_fields: Vec::new(),
        },
    );

    let fields = planned_model
        .fields
        .iter()
        .map(|field| build_field(field, api_plan, enums, flags, variants, models, package))
        .collect::<Result<Vec<_>>>()?;

    models
        .get_mut(&message.info.full_name)
        .expect("model should be inserted before recursive field resolution")
        .fields = fields;
    Ok(())
}

/// Converts a [`PlannedField`] into a [`RenderedField`] by resolving its type
/// to a Go type expression.
///
/// - Required fields use the plain type and are annotated with a leading
///   `// Required.` godoc comment.
/// - Optional struct-typed fields use a pointer (`*PostalAddress`) since a
///   zero-value struct is ambiguous.
/// - Optional scalar/enum/flags/interface fields use the plain type (the zero
///   value represents absence).
/// - Maps and slices are always reference-like and need no pointer.
/// - Tuple fields generate a named struct with ordinal field names (`First`,
///   `Second`, etc.) and are treated as struct types for optionality purposes.
fn build_field(
    field: &PlannedField,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<RenderedField> {
    let field_name = go_field_name(&field.authored_name);

    let go_type = match &field.kind {
        PlannedFieldKind::Map { key, value } => {
            let key_type =
                resolve_planned_value_type(key, api_plan, enums, flags, variants, models, package)?;
            let value_type = resolve_planned_value_type(
                value, api_plan, enums, flags, variants, models, package,
            )?;
            format!("map[{}]{}", key_type.type_expr, value_type.type_expr)
        }
        PlannedFieldKind::Repeated(value) => {
            let element_type = resolve_planned_value_type(
                value, api_plan, enums, flags, variants, models, package,
            )?;
            format!("[]{}", element_type.type_expr)
        }
        PlannedFieldKind::Singular(PlannedValueType::Tuple(items)) => {
            let struct_name = build_tuple_struct(
                &field_name,
                items,
                api_plan,
                enums,
                flags,
                variants,
                models,
                package,
            )?;
            if !field.required {
                format!("*{struct_name}")
            } else {
                struct_name
            }
        }
        PlannedFieldKind::Singular(PlannedValueType::Result { ok, err }) => {
            let struct_name = build_result_struct(
                &field_name,
                ok.as_deref(),
                err.as_deref(),
                api_plan,
                enums,
                flags,
                variants,
                models,
                package,
            )?;
            if !field.required {
                format!("*{struct_name}")
            } else {
                struct_name
            }
        }
        PlannedFieldKind::Singular(value) => {
            let resolved = resolve_planned_value_type(
                value, api_plan, enums, flags, variants, models, package,
            )?;
            if !field.required && type_needs_pointer_when_optional(value, &resolved.type_expr) {
                format!("*{}", resolved.type_expr)
            } else {
                resolved.type_expr
            }
        }
    };

    Ok(RenderedField {
        name: field_name,
        doc: field
            .doc
            .as_ref()
            .and_then(|doc| doc.for_language(Language::Go))
            .map(str::to_string),
        go_type,
        required: field.required,
        conversion: None,
    })
}

/// Returns `true` when an optional singular field of this value type must be
/// rendered as a pointer (`*T`) so that absence is representable as `nil`.
///
/// Pointers are used for every value-like type -- scalars, enums, flags,
/// messages, and override/replacement types -- so that "unset" is distinct from
/// "set to the zero value". Types whose zero value is already `nil` need no
/// pointer: variants (interfaces) and any `any`-typed value.
fn type_needs_pointer_when_optional(value: &PlannedValueType, type_expr: &str) -> bool {
    if matches!(
        value,
        PlannedValueType::Variant(_) | PlannedValueType::Unknown
    ) {
        return false;
    }
    if matches!(
        type_expr,
        "client.VersioningOverride" | "temporal.SearchAttributes"
    ) {
        return false;
    }
    // Already-nilable Go types (`any`, slices, maps) represent absence directly.
    if type_expr == "any" || type_expr.starts_with("[]") || type_expr.starts_with("map[") {
        return false;
    }
    true
}

/// Key prefix for generic helper models in the rendered-model map, chosen so
/// it can never collide with a WIT record or proto message full name.
const GENERIC_MODEL_KEY_PREFIX: &str = "nex-gen::generic::";

/// Ensures the generic tuple helper type for the given arity is rendered
/// (e.g. `type Tuple2[T1, T2 any] struct { First T1; Second T2 }`) and returns
/// its Go type name (`Tuple2`).
fn ensure_generic_tuple(
    arity: usize,
    models: &mut IndexMap<String, RenderedModel>,
) -> Result<String> {
    if arity == 0 || arity > TUPLE_FIELD_NAMES.len() {
        return Err(Error::UnsupportedGoType {
            context: format!("tuple with {arity} element(s)"),
            reason: format!(
                "tuples are supported with 1 to {} elements",
                TUPLE_FIELD_NAMES.len()
            ),
        });
    }

    let type_name = format!("Tuple{arity}");
    let key = format!("{GENERIC_MODEL_KEY_PREFIX}{type_name}");
    if !models.contains_key(&key) {
        let params = (1..=arity)
            .map(|index| format!("T{index}"))
            .collect::<Vec<_>>()
            .join(", ");
        let fields = (0..arity)
            .map(|index| RenderedField {
                name: TUPLE_FIELD_NAMES[index].to_string(),
                doc: None,
                go_type: format!("T{}", index + 1),
                required: false,
                conversion: None,
            })
            .collect();
        models.insert(
            key,
            RenderedModel {
                name: format!("{type_name}[{params} any]"),
                fields,
                proto_info: None,
                proto: None,
                sourced_fields: Vec::new(),
            },
        );
    }
    Ok(type_name)
}

/// Ensures the generic result helper type is rendered:
/// `type Result[T, E any] struct { Result T; Error E }`.
fn ensure_generic_result(models: &mut IndexMap<String, RenderedModel>) {
    let key = format!("{GENERIC_MODEL_KEY_PREFIX}Result");
    if !models.contains_key(&key) {
        models.insert(
            key,
            RenderedModel {
                name: "Result[T, E any]".to_string(),
                fields: vec![
                    RenderedField {
                        name: "Result".to_string(),
                        doc: None,
                        go_type: "T".to_string(),
                        required: false,
                        conversion: None,
                    },
                    RenderedField {
                        name: "Error".to_string(),
                        doc: None,
                        go_type: "E".to_string(),
                        required: false,
                        conversion: None,
                    },
                ],
                proto_info: None,
                proto: None,
                sourced_fields: Vec::new(),
            },
        );
    }
}

/// Generates a named Go struct for a tuple type, using ordinal field names
/// (`First`, `Second`, ..., `Tenth`). The struct name is derived from the
/// parent field name.
///
/// Returns an error if the tuple has more than 10 elements or if a struct with
/// the same name but different fields already exists.
fn build_tuple_struct(
    field_name: &str,
    items: &[PlannedValueType],
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<String> {
    if items.len() > TUPLE_FIELD_NAMES.len() {
        return Err(Error::UnsupportedGoType {
            context: format!("tuple with {} elements", items.len()),
            reason: format!(
                "Go code generation supports tuples with at most {} elements",
                TUPLE_FIELD_NAMES.len()
            ),
        });
    }

    let struct_name = field_name.to_string();

    let fields = items
        .iter()
        .zip(TUPLE_FIELD_NAMES.iter())
        .map(|(item, &ordinal_name)| {
            let resolved = resolve_planned_value_type(
                item, api_plan, enums, flags, variants, models, package,
            )?;
            Ok(RenderedField {
                name: ordinal_name.to_string(),
                doc: None,
                go_type: resolved.type_expr,
                required: true,
                conversion: None,
            })
        })
        .collect::<Result<Vec<_>>>()?;

    // Check for conflicts: same name but different field types.
    if let Some(existing) = models.get(&struct_name) {
        let existing_types: Vec<&str> =
            existing.fields.iter().map(|f| f.go_type.as_str()).collect();
        let new_types: Vec<&str> = fields.iter().map(|f| f.go_type.as_str()).collect();
        if existing_types != new_types {
            return Err(Error::UnsupportedGoType {
                context: format!("tuple struct `{struct_name}`"),
                reason: format!(
                    "a tuple struct named `{struct_name}` already exists with different element types"
                ),
            });
        }
    } else {
        models.insert(
            struct_name.clone(),
            RenderedModel {
                name: struct_name.clone(),
                fields,
                proto_info: None,
                proto: None,
                sourced_fields: Vec::new(),
            },
        );
    }

    Ok(struct_name)
}

/// Generates a named Go struct for a WIT `result<ok, err>` type. The struct
/// name is derived from the parent field name. The `Result` field holds the
/// ok value and the `Error` field holds the error value. When no error type
/// is specified in the WIT, the Go built-in `error` interface is used.
///
/// Returns an error if a struct with the same name but different fields
/// already exists.
fn build_result_struct(
    field_name: &str,
    ok: Option<&PlannedValueType>,
    err: Option<&PlannedValueType>,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    package: &GoPackageContext,
) -> Result<String> {
    let struct_name = field_name.to_string();

    let mut fields = Vec::new();

    if let Some(ok_type) = ok {
        let resolved =
            resolve_planned_value_type(ok_type, api_plan, enums, flags, variants, models, package)?;
        fields.push(RenderedField {
            name: "Result".to_string(),
            doc: None,
            go_type: resolved.type_expr,
            required: true,
            conversion: None,
        });
    }

    let error_type = if let Some(err_type) = err {
        resolve_planned_value_type(err_type, api_plan, enums, flags, variants, models, package)?
            .type_expr
    } else {
        "error".to_string()
    };
    fields.push(RenderedField {
        name: "Error".to_string(),
        doc: None,
        go_type: error_type,
        required: true,
        conversion: None,
    });

    // Check for conflicts: same name but different field types.
    if let Some(existing) = models.get(&struct_name) {
        let existing_types: Vec<&str> =
            existing.fields.iter().map(|f| f.go_type.as_str()).collect();
        let new_types: Vec<&str> = fields.iter().map(|f| f.go_type.as_str()).collect();
        if existing_types != new_types {
            return Err(Error::UnsupportedGoType {
                context: format!("result struct `{struct_name}`"),
                reason: format!(
                    "a result struct named `{struct_name}` already exists with different element types"
                ),
            });
        }
    } else {
        models.insert(
            struct_name.clone(),
            RenderedModel {
                name: struct_name.clone(),
                fields,
                proto_info: None,
                proto: None,
                sourced_fields: Vec::new(),
            },
        );
    }

    Ok(struct_name)
}

/// Converts a PascalCase name to an unexported Go identifier by lowercasing
/// the first character (e.g. `"GetUser"` becomes `"getUser"`).
fn go_unexported_name(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        None => String::new(),
        Some(first) => {
            let mut result = first.to_lowercase().to_string();
            result.push_str(chars.as_str());
            go_ident(&result)
        }
    }
}

/// Converts a WIT field name (kebab-case) to an exported Go field name
/// (UpperCamelCase), escaping Go keywords with a trailing underscore.
fn go_field_name(name: &str) -> String {
    let camel = name.to_upper_camel_case();
    go_ident(&camel)
}

/// Returns the identifier unchanged unless it is a Go keyword, in which case
/// a trailing underscore is appended.
fn go_ident(name: &str) -> String {
    if is_go_keyword(name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// Parses a Go type expression that may contain an embedded import path.
///
/// Returns `(import_path, code_expr)` where `import_path` is the Go import
/// path to add to the `import` block (if any), and `code_expr` is the type
/// expression to use in generated Go code.
///
/// # Syntax
///
/// - `"go.temporal.io/sdk/temporal.RetryPolicy"` → import `"go.temporal.io/sdk/temporal"`,
///   code `"temporal.RetryPolicy"`
/// - `"time.Duration"` → import `"time"`, code `"time.Duration"`
/// - `"string"` → no import, code `"string"`
/// - `"map[string]any"` → no import, code `"map[string]any"`
fn parse_go_import(type_expr: &str) -> (Option<String>, String) {
    // Case 0: explicit import path with ':' separator, e.g.
    // "go.temporal.io/api/enums/v1:enums.WorkflowIdReusePolicy"
    // This handles packages where the directory name differs from the
    // declared Go package name (e.g. enums/v1 declares `package enums`).
    if let Some(colon) = type_expr.find(':') {
        let import_path = &type_expr[..colon];
        let code_expr = &type_expr[colon + 1..];
        return (Some(import_path.to_string()), code_expr.to_string());
    }

    // Case 1: contains '/' -- this is a full Go module path like
    // "go.temporal.io/sdk/temporal.RetryPolicy"
    if let Some(last_slash) = type_expr.rfind('/') {
        // Find the next '.' after the last '/' -- that separates the import
        // path from the type name.
        if let Some(dot_offset) = type_expr[last_slash..].find('.') {
            let split = last_slash + dot_offset;
            let import_path = &type_expr[..split];
            let pkg_name = &type_expr[last_slash + 1..split];
            let type_name = &type_expr[split + 1..];
            return (
                Some(import_path.to_string()),
                format!("{pkg_name}.{type_name}"),
            );
        }
    }

    // Case 2: no '/' but looks like "pkg.Type" where pkg is all lowercase
    // (e.g. "time.Duration")
    if let Some(dot) = type_expr.find('.') {
        let prefix = &type_expr[..dot];
        if !prefix.is_empty()
            && prefix.chars().all(|c| c.is_ascii_lowercase() || c == '_')
            && type_expr[dot + 1..]
                .chars()
                .next()
                .is_some_and(|c| c.is_ascii_uppercase())
        {
            return (Some(prefix.to_string()), type_expr.to_string());
        }
    }

    // Case 3: no import needed (builtins, map[K]V, any, etc.)
    (None, type_expr.to_string())
}

/// Walks the [`ApiPlan`] and collects Go import paths from any `@nexus.type`
/// annotations that embed a module path (e.g. `go.temporal.io/sdk/temporal.RetryPolicy`).
fn collect_imports_from_plan(api_plan: &ApiPlan, imports: &mut BTreeSet<String>) {
    for model in api_plan.models.values() {
        for field in &model.fields {
            collect_imports_from_value_type(&field.kind, imports);
            if field.required
                && let Some(function) = &field.function
            {
                collect_imports_from_function(function, imports);
            }
        }
    }
    for service in &api_plan.services {
        for operation in &service.operations {
            collect_imports_from_message_type(&operation.input, imports);
            if let PlannedOperationOutput::Message(output) = &operation.output {
                collect_imports_from_message_type(output, imports);
            }
            if let Some(transform) = &operation.output_transform {
                if let (Some(annotation), Some(_expr)) = (
                    transform.type_name.for_language(Language::Go),
                    transform.transform.for_language(Language::Go),
                ) {
                    let (import_path, _) = parse_go_import(annotation);
                    if let Some(path) = import_path {
                        imports.insert(path);
                    }
                }
            }
        }
    }
}

fn collect_imports_from_function(function: &FunctionFieldSpec, imports: &mut BTreeSet<String>) {
    match &function.args {
        FunctionArgsSpec::Varargs { prefix, .. } => {
            for arg in prefix {
                collect_imports_from_authored_type(&arg.field_type, imports);
            }
        }
        FunctionArgsSpec::Fixed(args) => {
            for arg in args {
                collect_imports_from_authored_type(&arg.field_type, imports);
            }
        }
    }
    match &function.result {
        FunctionResultSpec::Wit(result) => collect_imports_from_authored_type(result, imports),
        FunctionResultSpec::Annotation(result) => {
            if let Some(annotation) = result.for_language(Language::Go) {
                let (import_path, _) = parse_go_import(annotation);
                if let Some(path) = import_path {
                    imports.insert(path);
                }
            }
        }
    }
}

fn collect_imports_from_authored_type(
    wit_type: &AuthoredFieldTypeSpec,
    imports: &mut BTreeSet<String>,
) {
    match wit_type {
        AuthoredFieldTypeSpec::Option(inner) | AuthoredFieldTypeSpec::List(inner) => {
            collect_imports_from_authored_type(inner, imports);
        }
        AuthoredFieldTypeSpec::Tuple(items) => {
            for item in items {
                collect_imports_from_authored_type(item, imports);
            }
        }
        AuthoredFieldTypeSpec::Map(key, value) => {
            collect_imports_from_authored_type(key, imports);
            collect_imports_from_authored_type(value, imports);
        }
        AuthoredFieldTypeSpec::Result { ok, err } => {
            if let Some(ok) = ok.as_deref() {
                collect_imports_from_authored_type(ok, imports);
            }
            if let Some(err) = err.as_deref() {
                collect_imports_from_authored_type(err, imports);
            }
        }
        AuthoredFieldTypeSpec::Alias {
            type_name, target, ..
        } => {
            if let Some(annotation) = type_name.for_language(Language::Go) {
                let (import_path, _) = parse_go_import(annotation);
                if let Some(path) = import_path {
                    imports.insert(path);
                }
            } else {
                collect_imports_from_authored_type(target, imports);
            }
        }
        _ => {}
    }
}

/// Collects Go imports from a message type's replacement or authored type.
fn collect_imports_from_message_type(message: &PlannedMessageType, imports: &mut BTreeSet<String>) {
    if let Some(replacement) = &message.replacement {
        if let Some(annotation) = replacement.type_name.for_language(Language::Go) {
            let (import_path, _) = parse_go_import(annotation);
            if let Some(path) = import_path {
                imports.insert(path);
            }
        }
    }
}

/// Collects Go imports from value types within a field kind.
fn collect_imports_from_value_type(kind: &PlannedFieldKind, imports: &mut BTreeSet<String>) {
    match kind {
        PlannedFieldKind::Singular(value) | PlannedFieldKind::Repeated(value) => {
            collect_imports_from_planned_value(value, imports);
        }
        PlannedFieldKind::Map { key, value } => {
            collect_imports_from_planned_value(key, imports);
            collect_imports_from_planned_value(value, imports);
        }
    }
}

/// Recursively collects Go imports from a planned value type.
fn collect_imports_from_planned_value(value: &PlannedValueType, imports: &mut BTreeSet<String>) {
    match value {
        PlannedValueType::External {
            type_name,
            fallback,
        } => {
            if let Some(annotation) = type_name.for_language(Language::Go) {
                let (import_path, _) = parse_go_import(annotation);
                if let Some(path) = import_path {
                    imports.insert(path);
                }
            } else {
                collect_imports_from_planned_value(fallback, imports);
            }
        }
        PlannedValueType::Enum(enum_type) => {
            if let Some(replacement) = &enum_type.replacement {
                if let Some(annotation) = replacement.type_name.for_language(Language::Go) {
                    let (import_path, _) = parse_go_import(annotation);
                    if let Some(path) = import_path {
                        imports.insert(path);
                    }
                }
            }
        }
        PlannedValueType::Message(message_type) => {
            if let Some(replacement) = &message_type.replacement {
                if let Some(annotation) = replacement.type_name.for_language(Language::Go) {
                    let (import_path, _) = parse_go_import(annotation);
                    if let Some(path) = import_path {
                        imports.insert(path);
                    }
                }
            }
        }
        PlannedValueType::Tuple(items) => {
            for item in items {
                collect_imports_from_planned_value(item, imports);
            }
        }
        PlannedValueType::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_imports_from_planned_value(ok, imports);
            }
            if let Some(err) = err {
                collect_imports_from_planned_value(err, imports);
            }
        }
        _ => {}
    }
}

/// Returns `true` if `name` is a Go language keyword.
fn is_go_keyword(name: &str) -> bool {
    matches!(
        name,
        "break"
            | "case"
            | "chan"
            | "const"
            | "continue"
            | "default"
            | "defer"
            | "else"
            | "fallthrough"
            | "for"
            | "func"
            | "go"
            | "goto"
            | "if"
            | "import"
            | "interface"
            | "map"
            | "package"
            | "range"
            | "return"
            | "select"
            | "struct"
            | "switch"
            | "type"
            | "var"
    )
}

