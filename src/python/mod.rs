fn render_python_module_imports_with_indent(
    output: &mut String,
    module_imports: &BTreeSet<String>,
    indent: &str,
) {
    for import in module_imports {
        output.push_str(indent);
        if let Some(relative_import) = import.strip_prefix('.') {
            output.push_str("from . import ");
            output.push_str(relative_import.trim_start_matches('.'));
            output.push('\n');
        } else {
            output.push_str("import ");
            output.push_str(import);
            output.push('\n');
        }
    }
}

fn body_uses_python_module_path(body: &str, module_path: &str) -> bool {
    let dotted_module = format!("{module_path}.");
    body.match_indices(&dotted_module).any(|(index, _)| {
        let previous = body[..index].chars().next_back();
        !previous.is_some_and(|character| is_python_identifier_char(character) || character == '.')
    })
}

fn used_python_module_imports(body: &str, module_imports: &BTreeSet<String>) -> BTreeSet<String> {
    module_imports
        .iter()
        .filter(|module_import| body_uses_python_module_path(body, module_import))
        .cloned()
        .collect()
}

fn is_python_identifier_char(character: char) -> bool {
    character.is_ascii_alphanumeric() || character == '_'
}

fn body_uses_python_symbol(body: &str, symbol: &str) -> bool {
    body.match_indices(symbol).any(|(index, _)| {
        let previous = body[..index].chars().next_back();
        let next = body[index + symbol.len()..].chars().next();
        !previous.is_some_and(|character| is_python_identifier_char(character) || character == '.')
            && !next.is_some_and(is_python_identifier_char)
    })
}

fn used_python_symbol_imports(body: &str, candidates: &[String]) -> Vec<String> {
    candidates
        .iter()
        .filter(|candidate| body_uses_python_symbol(body, candidate))
        .cloned()
        .collect()
}

fn render_named_python_import(output: &mut String, module: &str, names: &[String]) {
    if names.is_empty() {
        return;
    }

    if names.len() == 1 {
        output.push_str("from ");
        output.push_str(module);
        output.push_str(" import ");
        output.push_str(&names[0]);
        output.push('\n');
        return;
    }

    output.push_str("from ");
    output.push_str(module);
    output.push_str(" import (\n");
    for name in names {
        output.push_str("    ");
        output.push_str(name);
        output.push_str(",\n");
    }
    output.push_str(")\n");
}

fn top_level_python_symbols(source: &str) -> BTreeSet<String> {
    let mut symbols = BTreeSet::new();

    for line in source.lines() {
        let line = line.trim_end();
        if line.is_empty()
            || line.starts_with(' ')
            || line.starts_with('\t')
            || line.starts_with('#')
            || line.starts_with('@')
            || line.starts_with("import ")
            || line.starts_with("from ")
        {
            continue;
        }

        if let Some(name) = line
            .strip_prefix("def ")
            .and_then(|line| line.split('(').next())
        {
            symbols.insert(name.trim().to_string());
            continue;
        }
        if let Some(name) = line
            .strip_prefix("class ")
            .and_then(|line| line.split(['(', ':']).next())
        {
            symbols.insert(name.trim().to_string());
            continue;
        }
        if let Some((name, _)) = line.split_once('=') {
            let name = name.trim();
            if !name.is_empty() && name.chars().all(is_python_identifier_char) {
                symbols.insert(name.to_string());
            }
        }
    }

    symbols
}

fn support_export_names(support_fragments: &[SupportFragmentSpec]) -> Vec<String> {
    support_fragments
        .iter()
        .flat_map(|fragment| top_level_python_symbols(&fragment.contents))
        .filter(|name| !name.starts_with('_'))
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect()
}

fn render_optional_python_imports(
    output: &mut String,
    body: &str,
    module_imports: &BTreeSet<String>,
    language_imports: &[LanguageImportSpec],
) -> bool {
    let simple_imports = [
        ("import collections.abc\n", "collections.abc"),
        ("import dataclasses\n", "dataclasses"),
        ("import enum\n", "enum"),
        ("import typing\n", "typing"),
        ("import typing_extensions\n", "typing_extensions"),
    ];

    let mut wrote_any = false;
    for (import_line, module_path) in simple_imports {
        if body_uses_python_module_path(body, module_path) {
            output.push_str(import_line);
            wrote_any = true;
        }
    }
    let used_module_imports = used_python_module_imports(body, module_imports);
    wrote_any |=
        render_language_python_imports(output, body, language_imports, &used_module_imports);

    if !used_module_imports.is_empty() {
        render_python_module_imports(output, &used_module_imports);
        wrote_any = true;
    }

    wrote_any
}

fn render_language_python_imports(
    output: &mut String,
    body: &str,
    language_imports: &[LanguageImportSpec],
    skipped_module_imports: &BTreeSet<String>,
) -> bool {
    let mut module_imports = BTreeSet::new();
    let mut named_imports = BTreeMap::<String, BTreeSet<String>>::new();
    for import in language_imports {
        let used = match import.import_style {
            LanguageImportStyle::Module | LanguageImportStyle::Namespace => {
                body_uses_python_module_path(body, &import.reference)
            }
            LanguageImportStyle::Named => body_uses_python_module_path(body, &import.reference),
        };
        if !used {
            continue;
        }

        match import.import_style {
            LanguageImportStyle::Module | LanguageImportStyle::Namespace => {
                if !skipped_module_imports.contains(&import.module) {
                    module_imports.insert(import.module.clone());
                }
            }
            LanguageImportStyle::Named => {
                named_imports
                    .entry(import.module.clone())
                    .or_default()
                    .insert(
                        import
                            .name
                            .clone()
                            .unwrap_or_else(|| import.reference.clone()),
                    );
            }
        }
    }

    if module_imports.is_empty() && named_imports.is_empty() {
        return false;
    }

    render_python_module_imports(output, &module_imports);
    for (module, names) in named_imports {
        render_named_python_import(
            &mut *output,
            &module,
            &names.into_iter().collect::<Vec<_>>(),
        );
    }
    true
}

fn render_models_module(
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    support_names: &[String],
    language_imports: &[LanguageImportSpec],
) -> String {
    let mut module_imports = BTreeSet::new();
    if models
        .iter()
        .any(|model| model.source == PlannedMessageSource::Wit)
    {
        module_imports.insert("nex_gen_runtime".to_string());
    }
    for model in models {
        if let Some(proto_module_path) = &model.proto_module_path {
            module_imports.insert(proto_module_path.clone());
        }
        for field in &model.fields {
            module_imports.extend(field.imports.module_imports.iter().cloned());
        }
    }
    let mut body = String::new();
    if !enums.is_empty() {
        if !body.is_empty() {
            body.push_str("\n\n");
        }
        for (index, enumeration) in enums.iter().enumerate() {
            render_enum(&mut body, enumeration);
            if index + 1 != enums.len() {
                body.push_str("\n\n");
            }
        }
    }

    if !flags.is_empty() {
        if !body.is_empty() {
            body.push_str("\n\n");
        }
        for (index, flag_set) in flags.iter().enumerate() {
            render_flags(&mut body, flag_set);
            if index + 1 != flags.len() {
                body.push_str("\n\n");
            }
        }
    }

    if !models.is_empty() {
        if !body.is_empty() {
            body.push_str("\n\n");
        }
        for (index, model) in models.iter().enumerate() {
            render_model(&mut body, model);
            if index + 1 != models.len() {
                body.push_str("\n\n");
            }
        }
    }

    if !variants.is_empty() {
        if !body.is_empty() {
            body.push_str("\n\n");
        }
        for (index, variant) in variants.iter().enumerate() {
            render_variant(&mut body, variant);
            if index + 1 != variants.len() {
                body.push_str("\n\n");
            }
        }
    }

    render_nexus_type_registrations(&mut body, models);

    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    let wrote_imports =
        render_optional_python_imports(&mut output, &body, &module_imports, language_imports);
    let used_support_names = used_python_symbol_imports(&body, support_names);
    if !used_support_names.is_empty() {
        if wrote_imports {
            output.push('\n');
        }
        render_named_python_import(&mut output, "._support", &used_support_names);
    }
    if !body.is_empty() {
        output.push('\n');
        output.push('\n');
        output.push_str(&body);
    }

    output
}

fn render_nexus_type_registrations(output: &mut String, models: &[&RenderedModel]) {
    if !models
        .iter()
        .any(|model| model.source == PlannedMessageSource::Wit)
    {
        return;
    }
    if !output.is_empty() {
        output.push_str("\n\n");
    }
    for model in models
        .iter()
        .filter(|model| model.source == PlannedMessageSource::Wit)
    {
        output.push_str("nex_gen_runtime.register_nexus_type(");
        output.push_str(&model.name);
        output.push_str(", ");
        output.push_str(&python_string_literal(&model.full_name));
        output.push_str(")\n");
    }
}

