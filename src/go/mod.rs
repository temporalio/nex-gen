/// Resolves a planned operation by ensuring all types referenced by its input
/// and output messages are present in the rendered type collections, and
/// returns a [`RenderedOperation`] carrying the operation metadata.
fn resolve_operation<'a>(
    operation: &'a PlannedOperation,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) -> Result<RenderedOperation<'a>> {
    resolve_message_types(&operation.input, api_plan, enums, flags, variants, models)?;
    let input_type = resolve_message_go_type(&operation.input);
    let go_output_transform = operation.output_transform.as_ref().and_then(|transform| {
        Some((
            transform.type_name.for_language(Language::Go)?,
            transform.transform.for_language(Language::Go)?,
        ))
    });
    let raw_output_type = if go_output_transform.is_some() {
        match &operation.output {
            PlannedOperationOutput::Message(output) => {
                if go_proto_ref(&output.info).is_some() {
                    None
                } else {
                    resolve_message_types(output, api_plan, enums, flags, variants, models)?;
                    Some(resolve_message_go_type(output))
                }
            }
            PlannedOperationOutput::Resource { type_name } => Some(type_name.clone()),
            PlannedOperationOutput::None => None,
        }
    } else {
        None
    };

    let output_type = match &operation.output {
        PlannedOperationOutput::Message(output) => {
            if let Some(resource_return) = &operation.output_resource_return {
                // The operation returns a resource constructed from the proto
                // response -- use the resource type name.
                Some(resource_return.resource_type_name.clone())
            } else if let Some((transform_type, _)) = go_output_transform {
                // Output transforms expose their transformed type to callers,
                // while the raw operation output is still resolved below for
                // result decoding.
                Some(go_type_expr(transform_type))
            } else {
                resolve_message_types(output, api_plan, enums, flags, variants, models)?;
                Some(resolve_message_go_type(output))
            }
        }
        PlannedOperationOutput::Resource { type_name } => Some(type_name.clone()),
        PlannedOperationOutput::None => None,
    };

    // Build unpacked input params from the rendered model, if the input type
    // is a generated model (not an external/replacement type).
    let unpacked_input = models.get(&operation.input.info.full_name).map(|model| {
        let planned_fields = api_plan
            .models
            .get(&operation.input.info.full_name)
            .map(|planned_model| planned_model.fields.as_slice());
        model
            .fields
            .iter()
            .enumerate()
            .map(|(index, field)| {
                let planned_field = planned_fields.and_then(|fields| fields.get(index));
                RenderedUnpackedParam {
                    field_name: field.name.clone(),
                    doc: field.doc.clone(),
                    param_name: go_unexported_name(&field.name),
                    go_type: field.go_type.clone(),
                    required: field.required,
                    embed_in_options: planned_field.is_some_and(|planned_field| {
                        !planned_field.required
                            && field_kind_is_flattened_message(&planned_field.kind, api_plan)
                    }),
                }
            })
            .collect()
    });

    Ok(RenderedOperation {
        name: operation.name.as_str(),
        wire_name: operation.wire_name.as_str(),
        doc: operation.doc.for_language(Language::Go),
        return_doc: operation.return_doc.for_language(Language::Go),
        func_name: go_unexported_name(&operation.name),
        input_type,
        output_type,
        raw_output_type,
        output_transform_expr: go_output_transform.map(|(_, expr)| expr),
        output_transform_type: go_output_transform.map(|(type_name, _)| go_type_expr(type_name)),
        unpacked_input,
        output_resource_return: operation.output_resource_return.clone(),
        proto_binding: None,
    })
}

fn field_kind_is_flattened_message(kind: &PlannedFieldKind, api_plan: &ApiPlan) -> bool {
    let PlannedFieldKind::Singular(PlannedValueType::Message(message)) = kind else {
        return false;
    };
    api_plan
        .models
        .get(&message.info.full_name)
        .is_some_and(|model| model.flatten_in_api)
}

/// Computes the proto binding for an operation message: the proto type
/// expression and the native<->proto conversion expressions. Returns `None`
/// when the message is not proto-backed or cannot be converted.
fn operation_message_binding(
    message: &PlannedMessageType,
    operation_name: &str,
    direction: &str,
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
) -> Result<Option<(String, GoValueConversion)>> {
    // Messages without proto descriptor info (WIT-native records) are sent
    // natively rather than through proto -- not a proto binding at all.
    let Some(proto_ref) = go_proto_ref(&message.info) else {
        return Ok(None);
    };
    let alias = imports.register(&proto_ref);
    let proto_type = format!("*{}", proto_ref.qualified(&alias));
    let conversion = go_message_conversion(message, api_plan, imports).map_err(|reason| {
        Error::UnsupportedGoProtoConversion {
            context: format!("operation `{operation_name}` {direction}"),
            reason,
        }
    })?;
    Ok(Some((proto_type, conversion)))
}

fn operation_message_proto_type(
    message: &PlannedMessageType,
    imports: &mut GoImportCollector,
) -> Option<String> {
    let proto_ref = go_proto_ref(&message.info)?;
    let alias = imports.register(&proto_ref);
    Some(format!("*{}", proto_ref.qualified(&alias)))
}

/// Populates proto bindings on operations whose input/output messages are
/// proto-backed, registering required imports.
fn populate_operation_bindings(
    api_plan: &ApiPlan,
    services: &mut [RenderedService<'_>],
    imports: &mut GoImportCollector,
) -> Result<()> {
    for (service, planned_service) in services.iter_mut().zip(api_plan.services.iter()) {
        for (rendered_op, planned_op) in service
            .operations
            .iter_mut()
            .zip(planned_service.operations.iter())
        {
            let Some((_input_proto_type, input_conv)) = operation_message_binding(
                &planned_op.input,
                &planned_op.name,
                "input",
                api_plan,
                imports,
            )?
            else {
                continue;
            };
            // Override converters take a pointer to the native value; generated
            // model converters use a value receiver (`request.ToProto()`).
            let input_arg = match input_conv.kind {
                GoConversionKind::OverrideConverter => "&request".to_string(),
                _ => "request".to_string(),
            };
            let input_to_proto = (input_conv.to_proto)(&input_arg);
            let has_go_output_transform =
                planned_op
                    .output_transform
                    .as_ref()
                    .is_some_and(|transform| {
                        transform.type_name.for_language(Language::Go).is_some()
                            && transform.transform.for_language(Language::Go).is_some()
                    });

            let (output_proto_type, output_from_proto, output_returns_pointer) =
                match &planned_op.output {
                    PlannedOperationOutput::Message(output) => {
                        if planned_op.output_resource_return.is_some() {
                            let Some(proto_type) = operation_message_proto_type(output, imports)
                            else {
                                continue;
                            };
                            (Some(proto_type), None, false)
                        } else if has_go_output_transform {
                            (operation_message_proto_type(output, imports), None, false)
                        } else {
                            match operation_message_binding(
                                output,
                                &planned_op.name,
                                "output",
                                api_plan,
                                imports,
                            )? {
                                Some((proto_type, conv)) => {
                                    // `result` is declared as a proto value;
                                    // converters take a pointer to the proto message.
                                    let from = (conv.from_proto)("&result");
                                    let returns_pointer =
                                        conv.kind == GoConversionKind::OverrideConverter;
                                    (Some(proto_type), Some(from), returns_pointer)
                                }
                                None => continue,
                            }
                        }
                    }
                    PlannedOperationOutput::Resource { .. } => continue,
                    PlannedOperationOutput::None => (None, None, false),
                };

            rendered_op.proto_binding = Some(OperationProtoBinding {
                input_to_proto,
                output_proto_type,
                output_from_proto,
                output_returns_pointer,
            });
        }
    }
    Ok(())
}

/// Resolves a [`PlannedMessageType`] to its Go type expression, accounting for
/// type replacements and authored types. Used for operation input/output types.
fn resolve_message_go_type(message: &PlannedMessageType) -> String {
    if let Some(replacement) = &message.replacement {
        if let Some(type_name) = go_replacement_type_name(replacement) {
            return type_name;
        }
    }
    if let Some(authored_type) = &message.authored_type {
        return go_authored_type_annotation(authored_type);
    }
    message.model_name.clone()
}

/// Ensures a message type and all of its transitive field types are resolved.
/// Messages with type replacements or authored types are skipped because they
/// map to externally-defined Go types rather than generated structs.
fn resolve_message_types(
    message: &PlannedMessageType,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) -> Result<()> {
    if message.replacement.is_some() || message.authored_type.is_some() {
        return Ok(());
    }

    ensure_rendered_model(message, api_plan, enums, flags, variants, models)
}

