/// Describes how a single value (a field element, map value, etc.) converts
/// between its native Go representation and its proto representation.
///
/// Each direction is expressed as a closure over an input expression so the
/// same logic can be reused for singular fields, slice elements, and map
/// values. Conversions never touch raw bytes -- they translate between the
/// native value and a Go proto struct that the Temporal SDK serializes.
struct GoValueConversion {
    /// The structural shape of the conversion, which determines how the line
    /// builders handle pointers and dereferencing.
    kind: GoConversionKind,
    /// Produces the native expression from a proto expression.
    from_proto: Box<dyn Fn(&str) -> String>,
    /// Produces the proto expression from a native expression.
    to_proto: Box<dyn Fn(&str) -> String>,
}

/// Classifies a value conversion so the line builders know how to bridge
/// pointer/value mismatches between the native field and the converter.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum GoConversionKind {
    /// No conversion: native and proto share the same scalar Go type. The
    /// `from_proto`/`to_proto` closures are the identity.
    Scalar,
    /// A cast between a named Go type and a proto enum type (value to value),
    /// e.g. `enums.WorkflowIdReusePolicy(x)`.
    Enum,
    /// A hand-written override converter pair that is pointer-based on both the
    /// native and proto sides: `FromProto(*Proto) *Native` and
    /// `ToProto(*Native) *Proto`, each returning `nil` for `nil` input. The
    /// converter owns nil passthrough; the caller supplies/consumes pointers.
    OverrideConverter,
    /// A generated model converter: `FromProto(*Proto) Model` (value result)
    /// and `(Model) ToProto() *Proto` (value receiver). The native side is a
    /// value, the proto side is a pointer.
    ModelConverter,
}

/// Default Go `FromProto` converter name for an override/replacement type,
/// derived from the type's leaf name (e.g. `temporal.api.common.v1.RetryPolicy`
/// becomes `RetryPolicyFromProto`).
fn go_default_from_proto_name(full_name: &str) -> String {
    format!("{}FromProto", leaf_upper_camel(full_name))
}

/// Default Go `ToProto` converter name (e.g. `RetryPolicyToProto`).
fn go_default_to_proto_name(full_name: &str) -> String {
    format!("{}ToProto", leaf_upper_camel(full_name))
}

/// Returns the UpperCamelCase leaf segment of a dotted name.
fn leaf_upper_camel(full_name: &str) -> String {
    full_name
        .rsplit('.')
        .next()
        .unwrap_or(full_name)
        .to_upper_camel_case()
}

/// Resolves the Go converter function name for a replacement's `from` proto
/// direction, honoring an explicit `from-go=` override if present.
fn go_from_proto_converter(full_name: &str, replacement: &TypeReplacementSpec) -> String {
    replacement
        .from_proto
        .for_language(Language::Go)
        .map(str::to_string)
        .unwrap_or_else(|| go_default_from_proto_name(full_name))
}

/// Resolves the Go converter function name for a replacement's `to` proto
/// direction, honoring an explicit `to-go=` override if present.
fn go_to_proto_converter(full_name: &str, replacement: &TypeReplacementSpec) -> String {
    replacement
        .to_proto
        .for_language(Language::Go)
        .map(str::to_string)
        .unwrap_or_else(|| go_default_to_proto_name(full_name))
}

/// The result of building a Go proto conversion: either the conversion, or a
/// human-readable reason why the value cannot be converted. Callers attach
/// model/field context and fail generation -- unconvertible values must never
/// be silently omitted from the wire format.
type GoConversionResult<T> = std::result::Result<T, String>;

/// Builds the [`GoValueConversion`] for a single planned value type, registering
/// any proto imports it requires in `imports`.
fn go_value_conversion(
    value: &PlannedValueType,
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
) -> GoConversionResult<GoValueConversion> {
    match value {
        PlannedValueType::Scalar(_) => Ok(GoValueConversion {
            kind: GoConversionKind::Scalar,
            from_proto: Box::new(|expr| expr.to_string()),
            to_proto: Box::new(|expr| expr.to_string()),
        }),
        PlannedValueType::Enum(enum_type) => go_enum_conversion(enum_type, imports),
        PlannedValueType::Message(message_type) => {
            go_message_conversion(message_type, api_plan, imports)
        }
        // The planner never produces these inside proto-backed models today;
        // if it ever does, fail loudly instead of dropping data.
        PlannedValueType::Flags(_) => Err("flags values have no Go proto conversion".to_string()),
        PlannedValueType::Variant(_) => {
            Err("variant values have no Go proto conversion".to_string())
        }
        PlannedValueType::Tuple(_) => Err("tuple values have no Go proto conversion".to_string()),
        PlannedValueType::Result { .. } => {
            Err("result values have no Go proto conversion".to_string())
        }
        PlannedValueType::External { .. } => {
            Err("externally-typed values (via `@nexus.type`) have no Go proto conversion"
                .to_string())
        }
        PlannedValueType::Unknown => {
            Err("the proto type could not be resolved from the provided descriptors".to_string())
        }
    }
}

/// Returns the Go type expression for a planned scalar value.
fn go_scalar_type_expr(scalar: &PlannedScalarType) -> &'static str {
    match scalar {
        PlannedScalarType::Float => "float64",
        PlannedScalarType::Int32 => "int32",
        PlannedScalarType::Int64 => "int64",
        PlannedScalarType::Bool => "bool",
        PlannedScalarType::String => "string",
        PlannedScalarType::Bytes => "[]byte",
    }
}

/// Returns the Go type expression for the proto-side representation of a map
/// key or value (e.g. `string` or `*common.Payload`), registering any proto
/// import it requires. Returns a reason when the value has no proto-side Go
/// type (mirroring [`go_value_conversion`]).
fn go_proto_value_type(
    value: &PlannedValueType,
    imports: &mut GoImportCollector,
) -> GoConversionResult<String> {
    match value {
        PlannedValueType::Scalar(scalar) => Ok(go_scalar_type_expr(scalar).to_string()),
        PlannedValueType::Enum(enum_type) => {
            let info = enum_type
                .info
                .as_ref()
                .ok_or_else(|| "the enum has no proto descriptor info".to_string())?;
            let proto_ref = go_proto_ref(info).ok_or_else(|| {
                format!(
                    "proto enum `{}` has no `go_package` option in its descriptor",
                    info.full_name
                )
            })?;
            let alias = imports.register(&proto_ref);
            Ok(proto_ref.qualified(&alias))
        }
        PlannedValueType::Message(message) => {
            let proto_ref = go_proto_ref(&message.info).ok_or_else(|| {
                format!(
                    "proto message `{}` has no `go_package` option in its descriptor",
                    message.info.full_name
                )
            })?;
            let alias = imports.register(&proto_ref);
            Ok(format!("*{}", proto_ref.qualified(&alias)))
        }
        _ => Err("the value has no proto-side Go type".to_string()),
    }
}

/// Builds a conversion for an enum value. Replacement enums backed by a proto
/// enum cast through the proto enum type; generated enums cast directly.
fn go_enum_conversion(
    enum_type: &PlannedEnumType,
    imports: &mut GoImportCollector,
) -> GoConversionResult<GoValueConversion> {
    // Native Go enum type expression (replacement type or generated name).
    let native_type = if let Some(replacement) = &enum_type.replacement {
        go_replacement_type_name(replacement).ok_or_else(|| {
            "the type-replaced enum has no `go=` annotation in its `@nexus.type` directive"
                .to_string()
        })?
    } else {
        enum_type
            .name
            .clone()
            .ok_or_else(|| "the enum has no generated Go name".to_string())?
    };

    // The proto enum type, derived from the descriptor.
    let info = enum_type
        .info
        .as_ref()
        .ok_or_else(|| "the enum has no proto descriptor info".to_string())?;
    let proto_ref = go_proto_ref(info).ok_or_else(|| {
        format!(
            "proto enum `{}` has no `go_package` option in its descriptor",
            info.full_name
        )
    })?;
    let alias = imports.register(&proto_ref);
    let proto_type = proto_ref.qualified(&alias);

    let native_for_cast = native_type.clone();
    Ok(GoValueConversion {
        kind: GoConversionKind::Enum,
        from_proto: Box::new(move |expr| format!("{native_for_cast}(int32({expr}))")),
        to_proto: Box::new(move |expr| format!("{proto_type}({expr})")),
    })
}

/// Builds a conversion for a message value: a generated model (via its
/// `FromProto`/`ToProto`), a replacement type (via override converters), or an
/// authored type (via default-named converters).
fn go_message_conversion(
    message: &PlannedMessageType,
    _api_plan: &ApiPlan,
    _imports: &mut GoImportCollector,
) -> GoConversionResult<GoValueConversion> {
    // Replacement type: use override converter functions (hand-written in the
    // support file).
    if let Some(replacement) = &message.replacement {
        if go_replacement_type_name(replacement).is_some() {
            let from = go_from_proto_converter(&message.info.full_name, replacement);
            let to = go_to_proto_converter(&message.info.full_name, replacement);
            return Ok(GoValueConversion {
                kind: GoConversionKind::OverrideConverter,
                from_proto: Box::new(move |expr| format!("{from}({expr})")),
                to_proto: Box::new(move |expr| format!("{to}({expr})")),
            });
        }
    }

    // Authored type: default-named converter functions.
    if message.authored_type.is_some() {
        let from = go_default_from_proto_name(&message.info.full_name);
        let to = go_default_to_proto_name(&message.info.full_name);
        return Ok(GoValueConversion {
            kind: GoConversionKind::OverrideConverter,
            from_proto: Box::new(move |expr| format!("{from}({expr})")),
            to_proto: Box::new(move |expr| format!("{to}({expr})")),
        });
    }

    // A type-replaced message without a `go=` annotation has no Go-side type
    // to convert through; its generated model was never planned, so falling
    // through to the model converter would reference a function that does not
    // exist.
    if message.replacement.is_some() {
        return Err(format!(
            "type-replaced message `{}` has no `go=` annotation in its `@nexus.type` directive",
            message.info.full_name
        ));
    }

    // Generated proto-backed model: use its own ToProto/FromProto. Generated
    // models keep value-based `FromProto(*Proto) Model` / `(Model) ToProto()`
    // shapes, so they behave like a pointer converter only on the proto side.
    if message.source == PlannedMessageSource::Proto {
        let model_name = message.model_name.clone();
        return Ok(GoValueConversion {
            kind: GoConversionKind::ModelConverter,
            from_proto: Box::new(move |expr| format!("{model_name}FromProto({expr})")),
            to_proto: Box::new(|expr| format!("{expr}.ToProto()")),
        });
    }

    // WIT-native nested model: not serialized through proto.
    Err(format!(
        "WIT-native record `{}` has no proto conversion",
        message.model_name
    ))
}

/// Computes the proto field accessor name on a Go proto struct from the WIT
/// proto field name (snake_case -> UpperCamelCase, e.g. `task_queue` ->
/// `TaskQueue`).
fn go_proto_field_name(proto_name: &str) -> String {
    proto_name.to_upper_camel_case()
}

/// Populates proto conversion metadata for every proto-backed model that was
/// rendered, registering required imports in `imports`. Runs as a second pass
/// after all rendered types are collected so the conversion logic can reference
/// model names without threading the import collector through type resolution.
fn populate_proto_conversions(
    api_plan: &ApiPlan,
    models: &mut IndexMap<String, RenderedModel>,
    imports: &mut GoImportCollector,
) -> Result<()> {
    // Process every rendered model that carries proto type info. Empty response
    // models (skipped by the planner) still get trivial conversions so that
    // operation bindings referencing them resolve.
    let full_names: Vec<String> = models.keys().cloned().collect();
    for full_name in full_names {
        let Some(proto_info) = models
            .get(&full_name)
            .and_then(|model| model.proto_info.clone())
        else {
            continue;
        };

        // Capabilities default to bidirectional when the planner produced no
        // model entry (e.g. an empty response struct). Otherwise honor the
        // planned capabilities.
        let capabilities = api_plan
            .models
            .get(&full_name)
            .map(|planned| planned.capabilities)
            .unwrap_or(crate::generator::ModelCapabilities::BIDIRECTIONAL);
        if !capabilities.from_proto && !capabilities.to_proto {
            continue;
        }

        let proto_ref =
            go_proto_ref(&proto_info).ok_or_else(|| Error::UnsupportedGoProtoConversion {
                context: format!("model `{}`", proto_info.full_name),
                reason: "its proto descriptor has no `go_package` option".to_string(),
            })?;
        let alias = imports.register(&proto_ref);
        let proto_type = proto_ref.qualified(&alias);

        let native_field_types: Vec<String> = models
            .get(&full_name)
            .map(|model| model.fields.iter().map(|f| f.go_type.clone()).collect())
            .unwrap_or_default();
        let (field_conversions, sourced) = match api_plan.models.get(&full_name) {
            Some(planned_model) => (
                build_field_conversions(planned_model, &native_field_types, api_plan, imports)?,
                build_sourced_conversions(planned_model, api_plan, imports)?,
            ),
            None => (Vec::new(), Vec::new()),
        };

        let model = models
            .get_mut(&full_name)
            .expect("model key came from the map");
        model.proto = Some(RenderedModelProto {
            from_proto: capabilities.from_proto,
            to_proto: capabilities.to_proto,
            proto_type: format!("*{proto_type}"),
        });
        model.sourced_fields = sourced;
        // Attach per-field conversions by matching exported field names.
        for (rendered_field, conversion) in model.fields.iter_mut().zip(field_conversions) {
            rendered_field.conversion = Some(conversion);
        }
    }
    Ok(())
}

/// Builds per-field conversion metadata for a proto-backed model, in field
/// declaration order (matching the rendered struct fields).
/// `native_field_types` carries the rendered Go type expression of each field,
/// in the same order, for conversions that need to construct native values
/// (e.g. `make` for map fields).
fn build_field_conversions(
    planned_model: &PlannedModel,
    native_field_types: &[String],
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
) -> Result<Vec<RenderedFieldConversion>> {
    planned_model
        .fields
        .iter()
        .enumerate()
        .map(|(index, field)| {
            let native_go_type = native_field_types
                .get(index)
                .map(String::as_str)
                .unwrap_or("");
            build_field_conversion(field, native_go_type, api_plan, imports).map_err(|reason| {
                Error::UnsupportedGoProtoConversion {
                    context: format!("field `{}.{}`", field.owner_name, field.authored_name),
                    reason,
                }
            })
        })
        .collect()
}

/// Builds the conversion lines for a single field. Returns the reason when the
/// field cannot be converted; the caller fails generation rather than omitting
/// the field from proto serialization.
fn build_field_conversion(
    field: &PlannedField,
    native_go_type: &str,
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
) -> GoConversionResult<RenderedFieldConversion> {
    let proto_field = go_proto_field_name(&field.proto_name);
    let go_field = go_field_name(&field.authored_name);
    let receiver = format!("m.{go_field}");

    match &field.kind {
        PlannedFieldKind::Singular(value) => {
            let conversion = go_value_conversion(value, api_plan, imports)?;
            // Any value with a conversion (scalar, enum, message, override) is
            // rendered as a pointer when optional, matching `build_field`.
            let field_is_pointer = !field.required;
            let to_lines =
                singular_to_proto_lines(&conversion, &receiver, &proto_field, field_is_pointer);
            let from_lines =
                singular_from_proto_lines(&conversion, &proto_field, &go_field, field_is_pointer);
            Ok(RenderedFieldConversion {
                to_proto_lines: to_lines,
                from_proto_lines: from_lines,
            })
        }
        PlannedFieldKind::Repeated(value) => {
            let conversion = go_value_conversion(value, api_plan, imports)?;
            let to_lines = repeated_to_proto_lines(&conversion, &receiver, &proto_field);
            let from_lines = repeated_from_proto_lines(&conversion, &proto_field, &go_field);
            Ok(RenderedFieldConversion {
                to_proto_lines: to_lines,
                from_proto_lines: from_lines,
            })
        }
        PlannedFieldKind::Map { key, value } => {
            // Map keys are always scalars; only the value may need conversion.
            let conversion = go_value_conversion(value, api_plan, imports)?;
            let key_type =
                go_proto_value_type(key, imports).map_err(|reason| format!("map key: {reason}"))?;
            let value_type = go_proto_value_type(value, imports)
                .map_err(|reason| format!("map value: {reason}"))?;
            let proto_map_type = format!("map[{key_type}]{value_type}");
            let to_lines =
                map_to_proto_lines(&conversion, &proto_map_type, &receiver, &proto_field);
            let from_lines =
                map_from_proto_lines(&conversion, native_go_type, &proto_field, &go_field);
            Ok(RenderedFieldConversion {
                to_proto_lines: to_lines,
                from_proto_lines: from_lines,
            })
        }
    }
}

/// `ToProto` lines for a singular field.
///
/// `field_is_pointer` indicates whether the native struct field is rendered as
/// a pointer (an optional field). The generated code bridges the pointer/value
/// mismatch with the converter while delegating all nil handling either to a
/// guard here or to the converter's nil passthrough.
fn singular_to_proto_lines(
    conversion: &GoValueConversion,
    receiver: &str,
    proto_field: &str,
    field_is_pointer: bool,
) -> Vec<String> {
    let assign = |converted: &str| format!("message.{proto_field} = {converted}");
    match conversion.kind {
        // Override converters are nil-safe and pointer-based on the native
        // side, so they need no guard: pass the pointer (optional) or the
        // address of the value (required) straight through.
        GoConversionKind::OverrideConverter => {
            let arg = if field_is_pointer {
                receiver.to_string()
            } else {
                format!("&{receiver}")
            };
            vec![assign(&(conversion.to_proto)(&arg))]
        }
        // Scalars, enums, and generated models convert a value. For optional
        // (pointer) fields, guard against nil and dereference.
        GoConversionKind::Scalar | GoConversionKind::Enum | GoConversionKind::ModelConverter => {
            if field_is_pointer {
                let converted = (conversion.to_proto)(&format!("(*{receiver})"));
                vec![
                    format!("if {receiver} != nil {{"),
                    format!("\t{}", assign(&converted)),
                    "}".to_string(),
                ]
            } else {
                vec![assign(&(conversion.to_proto)(receiver))]
            }
        }
    }
}

/// `FromProto` lines for a singular field, assigning into `value.<go_field>`.
fn singular_from_proto_lines(
    conversion: &GoValueConversion,
    proto_field: &str,
    go_field: &str,
    field_is_pointer: bool,
) -> Vec<String> {
    let getter = format!("proto.Get{proto_field}()");
    match conversion.kind {
        // Override converters return a pointer (`*Native`) and pass nil
        // through. For optional fields, assign directly; for required fields,
        // dereference with a zero fallback when present.
        GoConversionKind::OverrideConverter => {
            let converted = (conversion.from_proto)(&getter);
            if field_is_pointer {
                vec![format!("value.{go_field} = {converted}")]
            } else {
                vec![
                    format!("if converted := {converted}; converted != nil {{"),
                    format!("\tvalue.{go_field} = *converted"),
                    "}".to_string(),
                ]
            }
        }
        // Generated models return a value, but only construct it when the proto
        // message is present so an absent optional stays nil.
        GoConversionKind::ModelConverter => {
            let converted = (conversion.from_proto)(&getter);
            if field_is_pointer {
                vec![
                    format!("if {getter} != nil {{"),
                    format!("\tconverted := {converted}"),
                    format!("\tvalue.{go_field} = &converted"),
                    "}".to_string(),
                ]
            } else {
                vec![format!("value.{go_field} = {converted}")]
            }
        }
        // Scalars and enums convert a value directly. Proto scalar fields carry
        // no presence information, so an optional field is always populated.
        GoConversionKind::Scalar | GoConversionKind::Enum => {
            let converted = (conversion.from_proto)(&getter);
            if field_is_pointer {
                vec![
                    format!("converted := {converted}"),
                    format!("value.{go_field} = &converted"),
                ]
            } else {
                vec![format!("value.{go_field} = {converted}")]
            }
        }
    }
}

/// `ToProto` lines for a repeated field.
fn repeated_to_proto_lines(
    conversion: &GoValueConversion,
    receiver: &str,
    proto_field: &str,
) -> Vec<String> {
    let converted = (conversion.to_proto)("item");
    vec![
        format!("for _, item := range {receiver} {{"),
        format!("\tmessage.{proto_field} = append(message.{proto_field}, {converted})"),
        "}".to_string(),
    ]
}

/// `FromProto` lines for a repeated field.
fn repeated_from_proto_lines(
    conversion: &GoValueConversion,
    proto_field: &str,
    go_field: &str,
) -> Vec<String> {
    let converted = (conversion.from_proto)("item");
    vec![
        format!("for _, item := range proto.Get{proto_field}() {{"),
        format!("\tvalue.{go_field} = append(value.{go_field}, {converted})"),
        "}".to_string(),
    ]
}

/// `ToProto` lines for a map field. `proto_map_type` is the Go type expression
/// of the proto struct's map field (e.g. `map[string]string`).
fn map_to_proto_lines(
    conversion: &GoValueConversion,
    proto_map_type: &str,
    receiver: &str,
    proto_field: &str,
) -> Vec<String> {
    // Override converters are pointer-based on the native side; the range
    // value variable is addressable, so pass its address.
    let converted = match conversion.kind {
        GoConversionKind::OverrideConverter => (conversion.to_proto)("&v"),
        _ => (conversion.to_proto)("v"),
    };
    vec![
        format!("if len({receiver}) > 0 {{"),
        format!("\tmessage.{proto_field} = make({proto_map_type}, len({receiver}))"),
        format!("\tfor k, v := range {receiver} {{"),
        format!("\t\tmessage.{proto_field}[k] = {converted}"),
        "\t}".to_string(),
        "}".to_string(),
    ]
}

/// `FromProto` lines for a map field. `native_map_type` is the Go type
/// expression of the native struct's map field (e.g. `map[string]string`).
fn map_from_proto_lines(
    conversion: &GoValueConversion,
    native_map_type: &str,
    proto_field: &str,
    go_field: &str,
) -> Vec<String> {
    let getter = format!("proto.Get{proto_field}()");
    let converted = (conversion.from_proto)("v");
    let mut lines = vec![
        format!("if len({getter}) > 0 {{"),
        format!("\tvalue.{go_field} = make({native_map_type}, len({getter}))"),
        format!("\tfor k, v := range {getter} {{"),
    ];
    match conversion.kind {
        // Override converters return a pointer and pass nil through; only
        // present values land in the native map.
        GoConversionKind::OverrideConverter => {
            lines.push(format!(
                "\t\tif converted := {converted}; converted != nil {{"
            ));
            lines.push(format!("\t\t\tvalue.{go_field}[k] = *converted"));
            lines.push("\t\t}".to_string());
        }
        _ => {
            lines.push(format!("\t\tvalue.{go_field}[k] = {converted}"));
        }
    }
    lines.push("\t}".to_string());
    lines.push("}".to_string());
    lines
}

/// Builds `ToProto` lines for sourced (write-only) fields.
fn build_sourced_conversions(
    planned_model: &PlannedModel,
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
) -> Result<Vec<RenderedSourcedField>> {
    planned_model
        .sourced_fields
        .iter()
        .map(|sourced| {
            build_sourced_conversion(sourced, api_plan, imports).map_err(|reason| {
                Error::UnsupportedGoProtoConversion {
                    context: format!(
                        "sourced field `{}.{}`",
                        planned_model.name, sourced.proto_name
                    ),
                    reason,
                }
            })
        })
        .collect()
}

fn build_sourced_conversion(
    sourced: &PlannedSourcedField,
    api_plan: &ApiPlan,
    imports: &mut GoImportCollector,
) -> GoConversionResult<RenderedSourcedField> {
    let proto_field = go_proto_field_name(&sourced.proto_name);
    let source_expr = &sourced.source_expr;
    match &sourced.kind {
        PlannedFieldKind::Singular(value) => {
            let conversion = go_value_conversion(value, api_plan, imports)?;
            match conversion.kind {
                // Override converters need the address of the sourced value, so
                // bind it to a local first (Go forbids taking the address of a
                // call expression).
                GoConversionKind::OverrideConverter => {
                    let converted = (conversion.to_proto)("&sourced");
                    Ok(RenderedSourcedField {
                        to_proto_lines: vec![
                            format!("sourced := {source_expr}"),
                            format!("message.{proto_field} = {converted}"),
                        ],
                    })
                }
                _ => {
                    let converted = (conversion.to_proto)(source_expr);
                    Ok(RenderedSourcedField {
                        to_proto_lines: vec![format!("message.{proto_field} = {converted}")],
                    })
                }
            }
        }
        PlannedFieldKind::Repeated(value) => {
            let conversion = go_value_conversion(value, api_plan, imports)?;
            let converted = (conversion.to_proto)("item");
            Ok(RenderedSourcedField {
                to_proto_lines: vec![
                    format!("for _, item := range {source_expr} {{"),
                    format!("\tmessage.{proto_field} = append(message.{proto_field}, {converted})"),
                    "}".to_string(),
                ],
            })
        }
        PlannedFieldKind::Map { key, value } => {
            let conversion = go_value_conversion(value, api_plan, imports)?;
            let key_type =
                go_proto_value_type(key, imports).map_err(|reason| format!("map key: {reason}"))?;
            let value_type = go_proto_value_type(value, imports)
                .map_err(|reason| format!("map value: {reason}"))?;
            let proto_map_type = format!("map[{key_type}]{value_type}");
            // Bind the source expression to a field-unique local so it is
            // evaluated once and the lines cannot collide with other sourced
            // fields in the same `ToProto` body.
            let local = format!("sourced{proto_field}");
            let mut to_proto_lines = vec![format!("{local} := {source_expr}")];
            to_proto_lines.extend(map_to_proto_lines(
                &conversion,
                &proto_map_type,
                &local,
                &proto_field,
            ));
            Ok(RenderedSourcedField { to_proto_lines })
        }
    }
}

