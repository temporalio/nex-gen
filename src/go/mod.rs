/// A reference to a Go protobuf type, derived from a proto descriptor's
/// `go_package` file option and the type's fully-qualified name.
///
/// For example, a message `temporal.api.common.v1.RetryPolicy` whose file
/// declares `go_package = "go.temporal.io/api/common/v1;common"` yields:
/// `import_path = "go.temporal.io/api/common/v1"`, `alias = "common"`,
/// `type_name = "RetryPolicy"`.
#[derive(Debug, Clone)]
struct GoProtoRef {
    /// Go import path (e.g. `"go.temporal.io/api/common/v1"`).
    import_path: String,
    /// Package alias declared in the `go_package` option (e.g. `"common"`).
    /// Falls back to the last path segment when no alias is present.
    alias: String,
    /// The exported Go type name within the package (e.g. `"RetryPolicy"`).
    /// Nested proto types are joined with `_` per protoc-gen-go conventions.
    type_name: String,
}

impl GoProtoRef {
    /// Renders the qualified Go type expression as `<alias>.<TypeName>`.
    fn qualified(&self, alias: &str) -> String {
        format!("{alias}.{}", self.type_name)
    }
}

/// Parses a proto `go_package` option of the form `<import path>[;<alias>]`.
/// Returns `(import_path, alias)`. When no `;alias` suffix is present, the
/// alias defaults to the final path segment.
fn parse_go_package_option(go_package: &str) -> (String, String) {
    if let Some((path, alias)) = go_package.split_once(';') {
        (path.to_string(), alias.to_string())
    } else {
        let alias = go_package
            .rsplit('/')
            .next()
            .unwrap_or(go_package)
            .to_string();
        (go_package.to_string(), alias)
    }
}

/// Derives a [`GoProtoRef`] for a proto message or enum from its planned type
/// info. Returns `None` when the descriptor lacks a `go_package` option (in
/// which case proto serialization cannot be generated for the type).
fn go_proto_ref(info: &PlannedTypeInfo) -> Option<GoProtoRef> {
    let go_package = info.go_package.as_deref()?;
    let (import_path, alias) = parse_go_package_option(go_package);
    // The type name is the fully-qualified name with the package prefix
    // stripped. Nested types (separated by `.`) are joined with `_` to match
    // protoc-gen-go's generated identifiers.
    let relative = if info.package.is_empty() {
        info.full_name.as_str()
    } else {
        info.full_name
            .strip_prefix(&format!("{}.", info.package))
            .unwrap_or(&info.full_name)
    };
    let type_name = relative.replace('.', "_");
    Some(GoProtoRef {
        import_path,
        alias,
        type_name,
    })
}

/// Collects and de-duplicates Go proto imports, assigning a unique alias to
/// each import path. When two distinct import paths request the same alias
/// (e.g. two `v1` packages both aliased `enums`), later ones are suffixed with
/// a numeric disambiguator.
#[derive(Debug, Default)]
struct GoImportCollector {
    /// Map from import path to the resolved (possibly disambiguated) alias.
    by_path: IndexMap<String, String>,
    /// Set of aliases already in use, to detect collisions.
    used_aliases: BTreeSet<String>,
}

impl GoImportCollector {
    /// Registers an import for the given [`GoProtoRef`], returning the alias to
    /// use when referencing types from that package.
    fn register(&mut self, proto_ref: &GoProtoRef) -> String {
        if let Some(existing) = self.by_path.get(&proto_ref.import_path) {
            return existing.clone();
        }
        let mut alias = proto_ref.alias.clone();
        if self.used_aliases.contains(&alias) {
            let mut counter = 2;
            loop {
                let candidate = format!("{}{counter}", proto_ref.alias);
                if !self.used_aliases.contains(&candidate) {
                    alias = candidate;
                    break;
                }
                counter += 1;
            }
        }
        self.used_aliases.insert(alias.clone());
        self.by_path
            .insert(proto_ref.import_path.clone(), alias.clone());
        alias
    }

    /// Registers a plain (non-proto) import path with an explicit alias-free
    /// reference, used for stdlib and SDK imports collected elsewhere.
    fn paths(&self) -> impl Iterator<Item = (&String, &String)> {
        self.by_path.iter()
    }

    fn is_empty(&self) -> bool {
        self.by_path.is_empty()
    }
}

