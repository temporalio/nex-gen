impl PythonImports {
    fn extend(&mut self, other: &Self) {
        self.module_imports
            .extend(other.module_imports.iter().cloned());
    }
}

fn python_default_from_proto_name(name: &str) -> String {
    format!(
        "{}_from_proto",
        name.rsplit('.')
            .next()
            .expect("converter name source should have a final segment")
            .to_snake_case()
    )
}

fn python_default_to_proto_name(name: &str) -> String {
    format!(
        "{}_to_proto",
        name.rsplit('.')
            .next()
            .expect("converter name source should have a final segment")
            .to_snake_case()
    )
}

fn python_from_proto_converter(name: &str, replacement: &TypeReplacementSpec) -> String {
    replacement
        .from_proto
        .for_language(crate::language::Language::Python)
        .map(str::to_string)
        .unwrap_or_else(|| python_default_from_proto_name(name))
}

fn python_to_proto_converter(name: &str, replacement: &TypeReplacementSpec) -> String {
    replacement
        .to_proto
        .for_language(crate::language::Language::Python)
        .map(str::to_string)
        .unwrap_or_else(|| python_default_to_proto_name(name))
}

fn python_replacement_type_name(replacement: &TypeReplacementSpec) -> Option<String> {
    replacement
        .type_name
        .for_language(Language::Python)
        .map(str::to_string)
}

fn python_function_result_annotation(result: &FunctionResultSpec) -> String {
    match result {
        FunctionResultSpec::Annotation(annotation) => annotation
            .for_language(Language::Python)
            .unwrap_or("typing.Any")
            .to_string(),
        FunctionResultSpec::Wit(wit_type) => python_authored_type_annotation(wit_type),
    }
}

fn python_authored_type_annotation(wit_type: &AuthoredFieldTypeSpec) -> String {
    match wit_type {
        AuthoredFieldTypeSpec::Bool => "bool".to_string(),
        AuthoredFieldTypeSpec::Int => "int".to_string(),
        AuthoredFieldTypeSpec::Float => "float".to_string(),
        AuthoredFieldTypeSpec::String => "str".to_string(),
        AuthoredFieldTypeSpec::Bytes => "bytes".to_string(),
        AuthoredFieldTypeSpec::Option(inner) => {
            format!("{} | None", python_authored_type_annotation(inner))
        }
        AuthoredFieldTypeSpec::List(inner) => {
            format!(
                "collections.abc.Sequence[{}]",
                python_authored_type_annotation(inner)
            )
        }
        AuthoredFieldTypeSpec::Tuple(items) => format!(
            "tuple[{}]",
            items
                .iter()
                .map(python_authored_type_annotation)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        AuthoredFieldTypeSpec::Map(key, value) => format!(
            "collections.abc.Mapping[{}, {}]",
            python_authored_type_annotation(key),
            python_authored_type_annotation(value)
        ),
        AuthoredFieldTypeSpec::Result { ok, err } => python_result_annotation(
            ok.as_ref()
                .map(|ok| python_authored_type_annotation(ok).to_string()),
            err.as_ref()
                .map(|err| python_authored_type_annotation(err).to_string()),
        ),
        AuthoredFieldTypeSpec::Alias {
            type_name, target, ..
        } => type_name
            .for_language(Language::Python)
            .map(str::to_string)
            .unwrap_or_else(|| python_authored_type_annotation(target)),
        AuthoredFieldTypeSpec::Proto(proto_name) => proto_name
            .rsplit('.')
            .next()
            .unwrap_or(proto_name)
            .to_string(),
        AuthoredFieldTypeSpec::Record(name)
        | AuthoredFieldTypeSpec::Enum(name)
        | AuthoredFieldTypeSpec::Flags(name)
        | AuthoredFieldTypeSpec::Variant(name)
        | AuthoredFieldTypeSpec::Resource(name) => name
            .rsplit('.')
            .next()
            .unwrap_or(name)
            .to_upper_camel_case(),
    }
}

fn python_function_args(args: &FunctionArgsSpec) -> RenderedFunctionArgs {
    match args {
        FunctionArgsSpec::Varargs { prefix, .. } => RenderedFunctionArgs::Varargs {
            prefix: prefix
                .iter()
                .map(|arg| RenderedFunctionArg {
                    name: python_field_name(&arg.name),
                    annotation: python_authored_type_annotation(&arg.field_type),
                })
                .collect(),
        },
        FunctionArgsSpec::Fixed(args) => RenderedFunctionArgs::Typed {
            parameters: args
                .iter()
                .map(|arg| RenderedFunctionArg {
                    name: python_field_name(&arg.name),
                    annotation: python_authored_type_annotation(&arg.field_type),
                })
                .collect(),
        },
    }
}

fn python_function_args_field_annotation(args: &FunctionArgsSpec) -> String {
    match python_function_args(args) {
        RenderedFunctionArgs::Varargs { .. } => "list[typing.Any]".to_string(),
        RenderedFunctionArgs::Typed { parameters } => python_function_args_list_annotation(
            parameters
                .iter()
                .map(|parameter| parameter.annotation.as_str())
                .collect::<Vec<_>>()
                .as_slice(),
        ),
    }
}

fn python_function_arg_field_annotation(function: &FunctionFieldSpec, field_name: &str) -> String {
    match &function.args {
        FunctionArgsSpec::Varargs { .. } => "list[typing.Any]".to_string(),
        FunctionArgsSpec::Fixed(args) => args
            .iter()
            .find(|arg| arg.name.to_snake_case() == field_name)
            .map(|arg| python_authored_type_annotation(&arg.field_type))
            .unwrap_or_else(|| python_function_args_field_annotation(&function.args)),
    }
}

fn python_function_args_list_annotation(annotations: &[&str]) -> String {
    let Some(first) = annotations.first() else {
        return "list[typing.Any]".to_string();
    };
    if annotations.iter().all(|annotation| annotation == first) {
        format!("list[{first}]")
    } else {
        "list[typing.Any]".to_string()
    }
}

fn python_result_annotation(ok: Option<String>, err: Option<String>) -> String {
    let ok_case = if let Some(ok) = ok {
        format!("tuple[typing.Literal[\"ok\"], {ok}]")
    } else {
        "tuple[typing.Literal[\"ok\"]]".to_string()
    };
    let err_case = if let Some(err) = err {
        format!("tuple[typing.Literal[\"err\"], {err}]")
    } else {
        "tuple[typing.Literal[\"err\"]]".to_string()
    };
    format!("{ok_case} | {err_case}")
}

fn resolve_operation<'a>(
    operation: &'a PlannedOperation,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) -> Result<RenderedOperation<'a>> {
    let (input_ref, input_module_path) = operation_service_ref(&operation.input, "models");
    let input_conversion = resolve_message_value_conversion(
        &operation.input,
        None,
        api_plan,
        enums,
        flags,
        variants,
        models,
    );
    let output_transform = operation.output_transform.as_ref();
    let output_resource_return = operation.output_resource_return.clone();
    let (output_ref, output_module_path, output_annotation_default) = match &operation.output {
        PlannedOperationOutput::Message(output) => {
            let (output_ref, output_module_path) = operation_service_ref(output, "models");
            if output_transform.is_none()
                && output_resource_return.is_none()
                && !operation.output_direct_result
            {
                resolve_message_value_conversion(
                    output, None, api_plan, enums, flags, variants, models,
                );
            }
            let annotation =
                resolve_output_annotation(output, api_plan, enums, flags, variants, models);
            (output_ref, output_module_path, annotation)
        }
        PlannedOperationOutput::Resource { type_name } => (
            type_name.clone(),
            Some("._resources".to_string()),
            type_name.clone(),
        ),
        PlannedOperationOutput::None => ("None".to_string(), None, "None".to_string()),
    };
    let overload_output_annotation = output_transform
        .and_then(|transform| {
            transform
                .type_name
                .for_language(crate::language::Language::Python)
                .map(str::to_string)
        })
        .or_else(|| {
            output_resource_return
                .as_ref()
                .map(|resource| resource.resource_type_name.clone())
        })
        .unwrap_or(output_annotation_default);
    let unpacked_input = if matches!(
        input_conversion.kind,
        MessageValueConversionKind::GeneratedModel { .. } | MessageValueConversionKind::NativeModel
    ) {
        Some(build_unpacked_input(
            &operation.input.info.full_name,
            models,
            api_plan,
        )?)
    } else {
        None
    };
    let output_type_parameters = unpacked_input
        .iter()
        .flat_map(|unpacked_input| &unpacked_input.functions)
        .filter_map(|function| function.result_type_parameter.clone())
        .filter(|name| python_annotation_uses_identifier(&overload_output_annotation, name))
        .collect::<BTreeSet<_>>();
    let output_annotation =
        erase_python_type_parameters(&overload_output_annotation, &output_type_parameters);
    let output_type_expr = if output_transform.is_some() || output_resource_return.is_some() {
        output_ref.clone()
    } else {
        output_annotation.clone()
    };
    Ok(RenderedOperation {
        name: operation.name.as_str(),
        wire_name: operation.wire_name.as_str(),
        attr_name: python_ident(&operation.name.to_snake_case()),
        doc: operation
            .doc
            .for_language(Language::Python)
            .map(str::to_string),
        return_doc: operation
            .return_doc
            .for_language(Language::Python)
            .map(str::to_string),
        input_ref,
        input_module_path,
        output_ref,
        output_module_path,
        input_annotation: input_conversion.annotation.clone(),
        input_to_proto_expr: input_conversion.to_proto_expr("request"),
        output_annotation,
        overload_output_annotation,
        output_type_parameters,
        output_type_expr,
        output_transform_expr: output_transform.and_then(|transform| {
            transform
                .transform
                .for_language(crate::language::Language::Python)
                .map(str::to_string)
        }),
        output_resource_return,
        output_direct_result: operation.output_direct_result,
        output_none: matches!(operation.output, PlannedOperationOutput::None),
        unpacked_input,
    })
}

fn operation_service_ref(
    message: &PlannedMessageType,
    _native_module: &str,
) -> (String, Option<String>) {
    match message.source {
        PlannedMessageSource::Proto => {
            let reference = message_python_ref(&message.info)
                .expect("descriptor messages should have a Python reference");
            (reference.type_ref, Some(reference.module_path))
        }
        PlannedMessageSource::Wit => (
            format!("{_native_module}.{}", message.model_name),
            Some(format!(".{_native_module}")),
        ),
    }
}

fn resolve_output_annotation(
    message: &PlannedMessageType,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) -> String {
    match message.source {
        PlannedMessageSource::Proto => {
            message_python_ref(&message.info)
                .expect("descriptor messages should have a Python reference")
                .type_ref
        }
        PlannedMessageSource::Wit => {
            let conversion = resolve_message_value_conversion(
                message, None, api_plan, enums, flags, variants, models,
            );
            conversion.annotation
        }
    }
}

fn build_unpacked_input(
    input_full_name: &str,
    models: &IndexMap<String, RenderedModel>,
    api_plan: &ApiPlan,
) -> Result<RenderedUnpackedInput> {
    let model = models
        .get(input_full_name)
        .expect("input model should be rendered before building unpacked input");
    let planned_model = api_plan
        .models
        .get(input_full_name)
        .expect("planned input model should exist");

    let mut parameters = Vec::new();
    let mut request_fields = Vec::new();
    let mut flattened_messages = Vec::new();
    let mut parameter_sources = BTreeMap::<String, String>::new();

    for (planned_field, rendered_field) in planned_model.fields.iter().zip(model.fields.iter()) {
        if let Some(flattened) =
            build_flattened_message(planned_field, rendered_field, models, api_plan)
        {
            request_fields.push(RenderedUnpackedRequestField {
                attr_name: flattened.local_name.clone(),
                value_expr: flattened.local_name.clone(),
                default_kind: PythonFieldDefaultKind::Required,
            });
            for child in &flattened.fields {
                register_unpacked_parameter_name(
                    &mut parameter_sources,
                    &child.value_expr,
                    &format!("{}.{}", flattened.local_name, child.attr_name),
                    &model.name,
                )?;
                parameters.push(RenderedUnpackedInputField {
                    attr_name: child.value_expr.clone(),
                    annotation: child.annotation.clone(),
                    default_kind: child.default_kind.clone(),
                    doc: child.doc.clone(),
                });
            }
            flattened_messages.push(flattened);
            continue;
        }

        register_unpacked_parameter_name(
            &mut parameter_sources,
            &rendered_field.attr_name,
            &rendered_field.attr_name,
            &model.name,
        )?;
        parameters.push(RenderedUnpackedInputField {
            attr_name: rendered_field.attr_name.clone(),
            annotation: rendered_field.annotation.clone(),
            default_kind: rendered_field.default_kind.clone(),
            doc: planned_field
                .doc
                .as_ref()
                .and_then(|doc| doc.for_language(Language::Python))
                .map(str::to_string),
        });
        request_fields.push(RenderedUnpackedRequestField {
            attr_name: rendered_field.attr_name.clone(),
            value_expr: rendered_field.attr_name.clone(),
            default_kind: rendered_field.default_kind.clone(),
        });
    }

    Ok(RenderedUnpackedInput {
        model_name: model.name.clone(),
        parameters,
        request_fields,
        flattened_messages,
        functions: planned_model
            .generated_model
            .functions
            .iter()
            .map(|(field_name, function)| {
                let result_annotation = python_function_result_annotation(&function.result);
                let result_type_parameters = function
                    .result_type_parameter
                    .iter()
                    .cloned()
                    .collect::<BTreeSet<_>>();
                let erased_result_annotation =
                    erase_python_type_parameters(&result_annotation, &result_type_parameters);
                let args = python_function_args(&function.args);
                let alternate_annotation = function
                    .alternate_type
                    .as_ref()
                    .map(python_authored_type_annotation);
                RenderedFunctionField {
                    callable_field_name: planned_model
                        .generated_model
                        .field_name_override(field_name)
                        .map(python_field_name)
                        .unwrap_or_else(|| python_field_name(field_name)),
                    args_field_name: planned_model
                        .generated_model
                        .field_name_override(&function.args_field)
                        .map(python_field_name)
                        .unwrap_or_else(|| python_field_name(&function.args_field)),
                    args: args.clone(),
                    primary: function.primary,
                    callable_annotation: python_function_annotation_from_args(
                        &args,
                        alternate_annotation.as_deref(),
                        &erased_result_annotation,
                    ),
                    result_annotation,
                    erased_result_annotation,
                    result_type_parameter: function.result_type_parameter.clone(),
                    alternate_annotation,
                }
            })
            .collect(),
    })
}

fn register_unpacked_parameter_name(
    parameter_sources: &mut BTreeMap<String, String>,
    parameter_name: &str,
    source: &str,
    model_name: &str,
) -> Result<()> {
    if let Some(conflicting_field) = parameter_sources.get(parameter_name) {
        return Err(Error::FlattenedApiFieldConflict {
            type_name: model_name.to_string(),
            field: parameter_name.to_string(),
            conflicting_field: conflicting_field.clone(),
        });
    }
    parameter_sources.insert(parameter_name.to_string(), source.to_string());
    Ok(())
}

fn build_flattened_message(
    planned_field: &PlannedField,
    rendered_field: &RenderedField,
    models: &IndexMap<String, RenderedModel>,
    api_plan: &ApiPlan,
) -> Option<RenderedFlattenedMessage> {
    let PlannedFieldKind::Singular(PlannedValueType::Message(message_type)) = &planned_field.kind
    else {
        return None;
    };
    let nested_planned_model = api_plan.models.get(&message_type.info.full_name)?;
    if !nested_planned_model.flatten_in_api {
        return None;
    }
    let nested_rendered_model = models.get(&message_type.info.full_name)?;

    Some(RenderedFlattenedMessage {
        local_name: rendered_field.attr_name.clone(),
        model_name: nested_rendered_model.name.clone(),
        required: planned_field.required,
        fields: nested_planned_model
            .fields
            .iter()
            .zip(nested_rendered_model.fields.iter())
            .map(
                |(nested_planned_field, nested_rendered_field)| RenderedFlattenedMessageField {
                    attr_name: nested_rendered_field.attr_name.clone(),
                    annotation: nested_planned_model
                        .generated_model
                        .field_flattened_annotation(&nested_planned_field.proto_name)
                        .and_then(|annotation| annotation.for_language(Language::Python))
                        .map(|annotation| {
                            if nested_planned_field.required {
                                annotation.to_string()
                            } else {
                                format!("{annotation} | None")
                            }
                        })
                        .unwrap_or_else(|| nested_rendered_field.annotation.clone()),
                    value_expr: nested_rendered_field.attr_name.clone(),
                    default_kind: if nested_planned_field.required {
                        PythonFieldDefaultKind::Required
                    } else {
                        nested_rendered_field.default_kind.clone()
                    },
                    doc: nested_planned_field
                        .doc
                        .as_ref()
                        .and_then(|doc| doc.for_language(Language::Python))
                        .map(str::to_string),
                },
            )
            .collect(),
    })
}

fn resolve_message_value_conversion(
    message: &PlannedMessageType,
    proto_ref_override: Option<&str>,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) -> MessageValueConversion {
    if let Some(language_override) = &message.replacement
        && let Some(type_name) = python_replacement_type_name(language_override)
    {
        return MessageValueConversion {
            annotation: type_name,
            kind: MessageValueConversionKind::Override {
                from_proto: python_from_proto_converter(&message.info.full_name, language_override),
                to_proto: python_to_proto_converter(&message.info.full_name, language_override),
            },
            imports: PythonImports::default(),
        };
    }
    if let Some(authored_type) = &message.authored_type {
        return MessageValueConversion {
            annotation: python_authored_type_annotation(authored_type),
            kind: MessageValueConversionKind::Override {
                from_proto: python_default_from_proto_name(&message.info.full_name),
                to_proto: python_default_to_proto_name(&message.info.full_name),
            },
            imports: PythonImports::default(),
        };
    }

    ensure_rendered_model(
        message,
        proto_ref_override,
        api_plan,
        enums,
        flags,
        variants,
        models,
    );
    let kind = if message.source == PlannedMessageSource::Wit {
        MessageValueConversionKind::NativeModel
    } else {
        MessageValueConversionKind::GeneratedModel {
            model_name: message.model_name.clone(),
        }
    };

    MessageValueConversion {
        annotation: models
            .get(&message.info.full_name)
            .expect("planned model should be rendered")
            .name
            .clone(),
        kind,
        imports: PythonImports::default(),
    }
}

fn ensure_rendered_model(
    message: &PlannedMessageType,
    proto_ref_override: Option<&str>,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) {
    let planned_model = api_plan
        .models
        .get(&message.info.full_name)
        .unwrap_or_else(|| panic!("planned model should exist for {}", message.info.full_name));

    if let Some(existing) = models.get_mut(&message.info.full_name) {
        if let Some(proto_ref) = proto_ref_override {
            existing.proto_ref = Some(proto_ref.to_string());
            existing.proto_module_path = Some(module_path(proto_ref).to_string());
        }
        return;
    }

    let (proto_ref, proto_module_path) = if message.source == PlannedMessageSource::Proto {
        (
            Some(
                proto_ref_override
                    .map(str::to_string)
                    .or_else(|| {
                        message_python_ref(&planned_model.info).map(|reference| reference.type_ref)
                    })
                    .expect("descriptor messages should have a Python reference"),
            ),
            Some(
                proto_ref_override
                    .map(module_path)
                    .map(str::to_string)
                    .or_else(|| {
                        message_python_ref(&planned_model.info)
                            .map(|reference| reference.module_path)
                    })
                    .expect("descriptor messages should have a Python module path"),
            ),
        )
    } else {
        (None, None)
    };

    models.insert(
        message.info.full_name.clone(),
        RenderedModel {
            full_name: message.info.full_name.clone(),
            name: planned_model.name.clone(),
            source: message.source,
            proto_ref,
            proto_module_path,
            capabilities: planned_model.capabilities,
            fields: Vec::new(),
            sourced_fields: Vec::new(),
        },
    );

    let fields = planned_model
        .fields
        .iter()
        .map(|field| build_field(field, api_plan, enums, flags, variants, models))
        .collect();

    let sourced_fields = planned_model
        .sourced_fields
        .iter()
        .map(|field| build_sourced_field(field, api_plan, enums, flags, variants, models))
        .collect();

    models
        .get_mut(&message.info.full_name)
        .expect("model should be inserted before recursive field resolution")
        .fields = fields;
    models
        .get_mut(&message.info.full_name)
        .expect("model should be inserted before recursive field resolution")
        .sourced_fields = sourced_fields;
}

fn ensure_rendered_enum(planned_enum: &PlannedEnum, enums: &mut IndexMap<String, RenderedEnum>) {
    enums
        .entry(planned_enum.info.full_name.clone())
        .or_insert_with(|| RenderedEnum {
            name: planned_enum.name.clone(),
            values: planned_enum
                .values
                .iter()
                .map(|value| RenderedEnumValue {
                    name: value.name.clone(),
                    number: value.number,
                })
                .collect(),
        });
}

fn ensure_rendered_flags(
    planned_flags: &PlannedFlags,
    flags: &mut IndexMap<String, RenderedFlags>,
) {
    flags
        .entry(planned_flags.info.full_name.clone())
        .or_insert_with(|| RenderedFlags {
            name: planned_flags.name.clone(),
            flags: planned_flags
                .flags
                .iter()
                .map(|flag| RenderedFlag {
                    name: flag.name.clone(),
                    bit: flag.bit,
                })
                .collect(),
        });
}

fn ensure_rendered_variant(
    planned_variant: &PlannedVariant,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) {
    if variants.contains_key(&planned_variant.info.full_name) {
        return;
    }

    let cases = planned_variant
        .cases
        .iter()
        .map(|case| RenderedVariantCase {
            name: case.name.clone(),
            payload_annotation: case.payload.as_ref().map(|payload| {
                resolve_planned_value_type(payload, api_plan, enums, flags, variants, models)
                    .annotation
            }),
        })
        .collect();
    variants.insert(
        planned_variant.info.full_name.clone(),
        RenderedVariant {
            name: planned_variant.name.clone(),
            cases,
        },
    );
}

fn build_field(
    field: &PlannedField,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) -> RenderedField {
    let attr_name = python_field_name(&field.authored_name);

    if let PlannedFieldKind::Map { key, value } = &field.kind {
        let key_type = resolve_planned_value_type(key, api_plan, enums, flags, variants, models);
        let value_type =
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models);
        let mut imports = key_type.imports.clone();
        imports.extend(&value_type.imports);
        return RenderedField {
            attr_name: attr_name.clone(),
            annotation: python_field_annotation(
                field,
                format!("dict[{}, {}]", key_type.annotation, value_type.annotation),
                false,
            ),
            default_kind: PythonFieldDefaultKind::EmptyDict,
            default_expr: Some("dataclasses.field(default_factory=dict)".to_string()),
            from_proto_setup_lines: Vec::new(),
            from_proto_expr: map_value_from_proto_expr(&value_type, &field.proto_name),
            to_proto_lines: map_value_to_proto_lines(&value_type, &attr_name, &field.proto_name),
            imports,
        };
    }

    let (resolved_type, repeated) = match &field.kind {
        PlannedFieldKind::Singular(value) => (
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models),
            false,
        ),
        PlannedFieldKind::Repeated(value) => (
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models),
            true,
        ),
        PlannedFieldKind::Map { .. } => unreachable!("handled above"),
    };
    let model_name = field.owner_name.clone();

    if repeated {
        return RenderedField {
            attr_name: attr_name.clone(),
            annotation: python_field_annotation(
                field,
                format!("list[{}]", resolved_type.annotation),
                false,
            ),
            default_kind: PythonFieldDefaultKind::EmptyList,
            default_expr: Some("dataclasses.field(default_factory=list)".to_string()),
            from_proto_setup_lines: Vec::new(),
            from_proto_expr: repeated_from_proto_expr(&resolved_type, &field.proto_name),
            to_proto_lines: repeated_to_proto_lines(&resolved_type, &attr_name, &field.proto_name),
            imports: resolved_type.imports,
        };
    }

    if let Some(default_value) = &field.default_value {
        let default_expr = enum_default_expr(&resolved_type, &default_value.enum_case);
        return RenderedField {
            attr_name: attr_name.clone(),
            annotation: python_field_annotation(field, resolved_type.annotation.clone(), false),
            default_kind: PythonFieldDefaultKind::Expression(default_expr.clone()),
            default_expr: Some(default_expr),
            from_proto_setup_lines: Vec::new(),
            from_proto_expr: defaulted_enum_from_proto_expr(
                &resolved_type,
                &field.proto_name,
                field,
                &default_value.enum_case,
            ),
            to_proto_lines: required_to_proto_lines(&attr_name, &field.proto_name, &resolved_type),
            imports: resolved_type.imports,
        };
    }

    if field.required {
        return RenderedField {
            attr_name: attr_name.clone(),
            annotation: python_field_annotation(field, resolved_type.annotation.clone(), false),
            default_kind: PythonFieldDefaultKind::Required,
            default_expr: None,
            from_proto_setup_lines: required_from_proto_setup_lines(
                &model_name,
                &attr_name,
                &field.proto_name,
                field,
                &resolved_type,
            ),
            from_proto_expr: attr_name.clone(),
            to_proto_lines: match &field.role {
                PlannedFieldRole::Function(function_field)
                    if function_field.converter.is_some() =>
                {
                    required_function_to_proto_lines(
                        &attr_name,
                        &field.proto_name,
                        &resolved_type,
                        function_field
                            .converter
                            .as_deref()
                            .expect("function converter should be present"),
                    )
                }
                _ => required_to_proto_lines(&attr_name, &field.proto_name, &resolved_type),
            },
            imports: resolved_type.imports,
        };
    }

    RenderedField {
        attr_name: attr_name.clone(),
        annotation: python_field_annotation(field, resolved_type.annotation.clone(), true),
        default_kind: PythonFieldDefaultKind::None,
        default_expr: Some("None".to_string()),
        from_proto_setup_lines: Vec::new(),
        from_proto_expr: optional_from_proto_expr(&resolved_type, &field.proto_name, field),
        to_proto_lines: match &field.role {
            PlannedFieldRole::Function(function_field) if function_field.converter.is_some() => {
                optional_function_to_proto_lines(
                    &attr_name,
                    &field.proto_name,
                    &resolved_type,
                    function_field
                        .converter
                        .as_deref()
                        .expect("function converter should be present"),
                )
            }
            _ => optional_to_proto_lines(&resolved_type, &attr_name, &field.proto_name),
        },
        imports: resolved_type.imports,
    }
}

fn build_sourced_field(
    field: &PlannedSourcedField,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) -> RenderedSourcedField {
    let source_expr = field.source_expr.to_string();
    if let PlannedFieldKind::Map { value, .. } = &field.kind {
        let value_type =
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models);
        return RenderedSourcedField {
            to_proto_lines: sourced_map_value_to_proto_lines(
                &value_type,
                &source_expr,
                &field.proto_name,
            ),
        };
    }

    let (resolved_type, repeated) = match &field.kind {
        PlannedFieldKind::Singular(value) => (
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models),
            false,
        ),
        PlannedFieldKind::Repeated(value) => (
            resolve_planned_value_type(value, api_plan, enums, flags, variants, models),
            true,
        ),
        PlannedFieldKind::Map { .. } => unreachable!("handled above"),
    };
    let source_expr = field.source_expr.to_string();
    if repeated {
        return RenderedSourcedField {
            to_proto_lines: sourced_repeated_to_proto_lines(
                &resolved_type,
                &source_expr,
                &field.proto_name,
            ),
        };
    }

    RenderedSourcedField {
        to_proto_lines: sourced_optional_to_proto_lines(
            &resolved_type,
            &source_expr,
            &field.proto_name,
        ),
    }
}

fn python_field_annotation(
    field: &PlannedField,
    default_base_annotation: String,
    is_optional: bool,
) -> String {
    if let PlannedFieldRole::FunctionArgs(function) = &field.role {
        let args_annotation = python_function_arg_field_annotation(function, &field.proto_name);
        return if is_optional {
            format!("{args_annotation} | None")
        } else {
            args_annotation
        };
    }

    if let Some(annotation) = &field.annotation_override {
        if let Some(annotation) = annotation.for_language(Language::Python) {
            return annotation.to_string();
        }
    }

    if let PlannedFieldRole::Function(function) = &field.role {
        let result_annotation = erase_python_type_parameters(
            &python_function_result_annotation(&function.result),
            &function
                .result_type_parameter
                .iter()
                .cloned()
                .collect::<BTreeSet<_>>(),
        );
        return python_function_annotation_from_args(
            &python_function_args(&function.args),
            function
                .alternate_type
                .as_ref()
                .map(python_authored_type_annotation)
                .as_deref(),
            &result_annotation,
        );
    }

    if is_optional {
        format!("{default_base_annotation} | None")
    } else {
        default_base_annotation
    }
}

fn python_function_field_annotation(
    function: &FunctionFieldSpec,
    alternate_annotation: Option<String>,
) -> String {
    let result_annotation = erase_python_type_parameters(
        &python_function_result_annotation(&function.result),
        &function
            .result_type_parameter
            .iter()
            .cloned()
            .collect::<BTreeSet<_>>(),
    );
    python_function_annotation_from_args(
        &python_function_args(&function.args),
        alternate_annotation.as_deref(),
        &result_annotation,
    )
}

fn python_function_annotation_from_args(
    args: &RenderedFunctionArgs,
    alternate_annotation: Option<&str>,
    result_annotation: &str,
) -> String {
    let callable_annotation = match args {
        RenderedFunctionArgs::Varargs { .. } => {
            format!("collections.abc.Callable[..., {}]", result_annotation)
        }
        RenderedFunctionArgs::Typed { parameters } => format!(
            "collections.abc.Callable[[{}], {}]",
            parameters
                .iter()
                .map(|parameter| parameter.annotation.clone())
                .collect::<Vec<_>>()
                .join(", "),
            result_annotation
        ),
    };
    if let Some(alternate_annotation) = alternate_annotation {
        format!("{alternate_annotation} | {callable_annotation}")
    } else {
        callable_annotation
    }
}

fn resolve_planned_value_type(
    value_type: &PlannedValueType,
    api_plan: &ApiPlan,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
) -> ResolvedFieldType {
    match value_type {
        PlannedValueType::Scalar(PlannedScalarType::Float) => ResolvedFieldType {
            annotation: "float".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            message_conversion: None,
            enum_conversion: None,
        },
        PlannedValueType::Scalar(PlannedScalarType::Int32 | PlannedScalarType::Int64) => {
            ResolvedFieldType {
                annotation: "int".to_string(),
                imports: PythonImports::default(),
                kind: ResolvedFieldKind::Scalar,
                message_conversion: None,
                enum_conversion: None,
            }
        }
        PlannedValueType::Scalar(PlannedScalarType::Bool) => ResolvedFieldType {
            annotation: "bool".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            message_conversion: None,
            enum_conversion: None,
        },
        PlannedValueType::Scalar(PlannedScalarType::String) => ResolvedFieldType {
            annotation: "str".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            message_conversion: None,
            enum_conversion: None,
        },
        PlannedValueType::Scalar(PlannedScalarType::Bytes) => ResolvedFieldType {
            annotation: "bytes".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            message_conversion: None,
            enum_conversion: None,
        },
        PlannedValueType::Enum(enum_type) => {
            if let Some(replacement) = &enum_type.replacement
                && let Some(type_name) = python_replacement_type_name(replacement)
            {
                ResolvedFieldType {
                    annotation: type_name,
                    imports: PythonImports::default(),
                    kind: ResolvedFieldKind::Enum,
                    message_conversion: None,
                    enum_conversion: enum_type.info.as_ref().map(|info| EnumValueConversion {
                        from_proto: python_from_proto_converter(&info.full_name, replacement),
                        to_proto: python_to_proto_converter(&info.full_name, replacement),
                    }),
                }
            } else if let (Some(info), Some(name)) = (&enum_type.info, &enum_type.name) {
                if let Some(planned_enum) = api_plan.enums.get(&info.full_name) {
                    ensure_rendered_enum(planned_enum, enums);
                }
                let mut imports = PythonImports::default();
                if let Some(reference) = enum_python_ref(info) {
                    imports.module_imports.insert(reference.module_path);
                }
                ResolvedFieldType {
                    annotation: name.clone(),
                    imports,
                    kind: ResolvedFieldKind::Enum,
                    message_conversion: None,
                    enum_conversion: None,
                }
            } else {
                ResolvedFieldType {
                    annotation: "int".to_string(),
                    imports: PythonImports::default(),
                    kind: ResolvedFieldKind::Enum,
                    message_conversion: None,
                    enum_conversion: None,
                }
            }
        }
        PlannedValueType::Flags(flags_type) => {
            if let Some(planned_flags) = api_plan.flags.get(&flags_type.info.full_name) {
                ensure_rendered_flags(planned_flags, flags);
            }
            ResolvedFieldType {
                annotation: flags_type.name.clone(),
                imports: PythonImports::default(),
                kind: ResolvedFieldKind::Scalar,
                message_conversion: None,
                enum_conversion: None,
            }
        }
        PlannedValueType::Variant(variant_type) => {
            if let Some(planned_variant) = api_plan.variants.get(&variant_type.info.full_name) {
                ensure_rendered_variant(planned_variant, api_plan, enums, flags, variants, models);
            }
            ResolvedFieldType {
                annotation: variant_type.name.clone(),
                imports: PythonImports::default(),
                kind: ResolvedFieldKind::Scalar,
                message_conversion: None,
                enum_conversion: None,
            }
        }
        PlannedValueType::Message(message_type) => {
            let conversion = if let Some(replacement) = &message_type.replacement
                && let Some(type_name) = python_replacement_type_name(replacement)
            {
                MessageValueConversion {
                    annotation: type_name,
                    kind: MessageValueConversionKind::Override {
                        from_proto: python_from_proto_converter(
                            &message_type.info.full_name,
                            replacement,
                        ),
                        to_proto: python_to_proto_converter(
                            &message_type.info.full_name,
                            replacement,
                        ),
                    },
                    imports: PythonImports::default(),
                }
            } else if let Some(authored_type) = &message_type.authored_type {
                MessageValueConversion {
                    annotation: python_authored_type_annotation(authored_type),
                    kind: MessageValueConversionKind::Override {
                        from_proto: python_default_from_proto_name(&message_type.info.full_name),
                        to_proto: python_default_to_proto_name(&message_type.info.full_name),
                    },
                    imports: PythonImports::default(),
                }
            } else {
                ensure_rendered_model(message_type, None, api_plan, enums, flags, variants, models);
                let model = models
                    .get(&message_type.info.full_name)
                    .expect("planned model should be rendered");
                MessageValueConversion {
                    annotation: model.name.clone(),
                    kind: MessageValueConversionKind::GeneratedModel {
                        model_name: message_type.model_name.clone(),
                    },
                    imports: PythonImports::default(),
                }
            };
            ResolvedFieldType {
                annotation: conversion.annotation.clone(),
                imports: conversion.imports.clone(),
                kind: ResolvedFieldKind::Message,
                message_conversion: Some(conversion),
                enum_conversion: None,
            }
        }
        PlannedValueType::Tuple(items) => ResolvedFieldType {
            annotation: format!(
                "tuple[{}]",
                items
                    .iter()
                    .map(|item| {
                        resolve_planned_value_type(item, api_plan, enums, flags, variants, models)
                            .annotation
                    })
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            message_conversion: None,
            enum_conversion: None,
        },
        PlannedValueType::Result { ok, err } => {
            let ok = ok
                .as_ref()
                .map(|ok| resolve_planned_value_type(ok, api_plan, enums, flags, variants, models));
            let err = err.as_ref().map(|err| {
                resolve_planned_value_type(err, api_plan, enums, flags, variants, models)
            });
            let mut imports = PythonImports::default();
            if let Some(ok) = &ok {
                imports.extend(&ok.imports);
            }
            if let Some(err) = &err {
                imports.extend(&err.imports);
            }
            ResolvedFieldType {
                annotation: python_result_annotation(
                    ok.as_ref().map(|ok| ok.annotation.clone()),
                    err.as_ref().map(|err| err.annotation.clone()),
                ),
                imports,
                kind: ResolvedFieldKind::Scalar,
                message_conversion: None,
                enum_conversion: None,
            }
        }
        PlannedValueType::External {
            type_name,
            fallback,
        } => {
            let mut resolved =
                resolve_planned_value_type(fallback, api_plan, enums, flags, variants, models);
            if let Some(annotation) = type_name.for_language(Language::Python) {
                resolved.annotation = annotation.to_string();
            }
            resolved
        }
        PlannedValueType::Unknown => ResolvedFieldType {
            annotation: "object".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Unknown,
            message_conversion: None,
            enum_conversion: None,
        },
    }
}

