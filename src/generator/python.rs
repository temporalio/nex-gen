fn resource_bound_operations<'a>(
    service: &'a RenderedService<'a>,
    resource: &'a PlannedResource,
) -> Vec<ResourceBoundOperation<'a>> {
    resource
        .methods
        .iter()
        .filter_map(|method| match &method.binding {
            PlannedResourceMethodBindingSpec::Operation { operation_name, .. } => {
                Some(ResourceBoundOperation {
                    operation: service
                        .operations
                        .iter()
                        .find(|operation| operation.name == operation_name)
                        .expect("bound resource operation should exist on the service"),
                })
            }
            PlannedResourceMethodBindingSpec::Stub => None,
        })
        .collect()
}

fn render_resource_module_file(
    service: &RenderedService<'_>,
    resource: &PlannedResource,
    bound_operations: &[ResourceBoundOperation<'_>],
    model_names: &[String],
    resource_names: &[String],
    support_names: &[String],
    language_imports: &[LanguageImportSpec],
) -> String {
    let mut module_imports = bound_operations
        .iter()
        .flat_map(|bound_operation| {
            [
                bound_operation
                    .operation
                    .input
                    .as_ref()
                    .and_then(|input| input.module_path.clone()),
                bound_operation.operation.output_module_path.clone(),
            ]
        })
        .flatten()
        .collect::<BTreeSet<_>>();
    module_imports.insert("nex_gen_runtime".to_string());

    let mut body = String::new();
    let function_fields = bound_operations
        .iter()
        .filter_map(|bound_operation| bound_operation.operation.unpacked_input.as_ref())
        .flat_map(|unpacked_input| unpacked_input.functions.iter().cloned())
        .collect::<Vec<_>>();
    let output_type_parameters = bound_operations
        .iter()
        .flat_map(|bound_operation| bound_operation.operation.output_type_parameters.iter())
        .cloned()
        .collect::<BTreeSet<_>>();
    if !function_fields.is_empty() {
        render_function_type_parameter_definitions(
            &mut body,
            &function_fields,
            &output_type_parameters,
        );
        body.push_str("\n\n");
    }
    render_resource(&mut body, resource, bound_operations);
    if !bound_operations.is_empty() {
        body.push_str("\n\n");
        for (index, bound_operation) in bound_operations.iter().enumerate() {
            render_operation_functions(&mut body, service, bound_operation.operation);
            if index + 1 != bound_operations.len() {
                body.push_str("\n\n");
            }
        }
    }
    if !service.delay_load_temporalio_workflow {
        module_imports.insert("temporalio.workflow".to_string());
    }
    body.push_str("\n\n");
    body.push_str("nex_gen_runtime.register_nexus_type(");
    body.push_str(&resource.type_name);
    body.push_str(", ");
    body.push_str(&python_string_literal(&python_resource_type_id(
        service, resource,
    )));
    body.push_str(")\n");

    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    let type_checking_names = temporalio_workflow_type_checking_names(&body);
    let body_for_imports =
        if service.delay_load_temporalio_workflow && !type_checking_names.is_empty() {
            format!("{body}\ntyping.TYPE_CHECKING")
        } else {
            body.clone()
        };
    let skipped_language_modules = delayed_temporalio_workflow_skipped_language_modules(service);
    let wrote_imports = render_optional_python_imports_with_skipped_language_modules(
        &mut output,
        &body_for_imports,
        &module_imports,
        language_imports,
        &skipped_language_modules,
    );
    if wrote_imports && service.delay_load_temporalio_workflow && !type_checking_names.is_empty() {
        output.push('\n');
    }
    let wrote_type_checking_imports =
        render_temporalio_workflow_type_checking_imports(&mut output, service, &body);
    if wrote_imports || wrote_type_checking_imports {
        output.push('\n');
    }
    let used_model_names = used_python_symbol_imports(&body, model_names);
    if !used_model_names.is_empty() {
        render_named_python_import(&mut output, "..models", &used_model_names);
    }
    let used_resource_names = used_python_symbol_imports(&body, resource_names)
        .into_iter()
        .filter(|name| name != &resource.type_name)
        .collect::<Vec<_>>();
    if !used_resource_names.is_empty() {
        render_named_python_import(&mut output, ".", &used_resource_names);
    }
    let used_support_names = used_python_symbol_imports(&body, support_names);
    if !used_support_names.is_empty() {
        render_named_python_import(&mut output, ".._support", &used_support_names);
    }
    if !body.is_empty() {
        output.push('\n');
        output.push('\n');
        output.push_str(&body);
    }
    output
}

fn render_service_module(services: &[RenderedService<'_>]) -> String {
    let mut module_imports = BTreeSet::new();
    let mut model_type_imports = BTreeSet::new();
    let resource_modules = services
        .iter()
        .flat_map(|service| service.resources.iter())
        .map(|resource| (resource.type_name.clone(), resource_module_name(resource)))
        .collect::<BTreeMap<_, _>>();
    let mut resource_type_imports = BTreeMap::new();
    for service in services {
        for operation in &service.operations {
            if let Some(input_module_path) = operation
                .input
                .as_ref()
                .and_then(|input| input.module_path.as_ref())
            {
                if input_module_path == ".models" {
                    if let Some(type_name) =
                        operation_input_type_ref(operation).strip_prefix("models.")
                    {
                        model_type_imports.insert(type_name.to_string());
                    }
                } else {
                    module_imports.insert(input_module_path.clone());
                }
            }
            if let Some(output_module_path) = &operation.output_module_path {
                if output_module_path == "._resources" {
                    if let Some(module_name) = resource_modules.get(&operation.output_ref) {
                        resource_type_imports
                            .insert(operation.output_ref.clone(), module_name.clone());
                    }
                } else if output_module_path == ".models" {
                    if let Some(type_name) = operation.output_ref.strip_prefix("models.") {
                        model_type_imports.insert(type_name.to_string());
                    }
                } else {
                    module_imports.insert(output_module_path.clone());
                }
            }
        }
    }

    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    output.push_str("from nexusrpc import Operation, service\n");
    let uses_typing = services
        .iter()
        .flat_map(|service| service.operations.iter())
        .any(|operation| {
            operation_input_type_ref(operation).contains("typing.")
                || operation.output_ref.contains("typing.")
        });
    if uses_typing {
        output.push_str("import typing\n");
    }
    if !module_imports.is_empty()
        || !model_type_imports.is_empty()
        || !resource_type_imports.is_empty()
    {
        if uses_typing {
            output.push('\n');
        }
        render_python_module_imports(&mut output, &module_imports);
        render_named_python_import(
            &mut output,
            ".models",
            &model_type_imports.into_iter().collect::<Vec<_>>(),
        );
        for (resource_type_name, module_name) in &resource_type_imports {
            render_named_python_import(
                &mut output,
                &format!("._resources.{module_name}"),
                std::slice::from_ref(resource_type_name),
            );
        }
    }
    if !services.is_empty() {
        output.push_str("\n\n");
        for (index, service) in services.iter().enumerate() {
            render_service_definition(&mut output, service);
            if index + 1 != services.len() {
                output.push_str("\n\n");
            }
        }
    }

    output
}

fn render_operation_module(
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    model_names: &[String],
    resource_names: &[String],
    support_names: &[String],
    language_imports: &[LanguageImportSpec],
) -> String {
    let mut module_imports = BTreeSet::new();
    if let Some(input_module_path) = operation
        .input
        .as_ref()
        .and_then(|input| input.module_path.as_ref())
    {
        module_imports.insert(input_module_path.clone());
    }
    if let Some(output_module_path) = &operation.output_module_path {
        module_imports.insert(output_module_path.clone());
    }

    let mut body = String::new();
    if let Some(unpacked_input) = &operation.unpacked_input
        && !unpacked_input.functions.is_empty()
    {
        render_function_type_parameter_definitions(
            &mut body,
            &unpacked_input.functions,
            &operation.output_type_parameters,
        );
        body.push_str("\n\n");
    }
    render_operation_functions(&mut body, service, operation);
    if !service.delay_load_temporalio_workflow {
        module_imports.insert("temporalio.workflow".to_string());
    }

    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    let type_checking_names = temporalio_workflow_type_checking_names(&body);
    let body_for_imports =
        if service.delay_load_temporalio_workflow && !type_checking_names.is_empty() {
            format!("{body}\ntyping.TYPE_CHECKING")
        } else {
            body.clone()
        };
    let skipped_language_modules = delayed_temporalio_workflow_skipped_language_modules(service);
    let wrote_imports = render_optional_python_imports_with_skipped_language_modules(
        &mut output,
        &body_for_imports,
        &module_imports,
        language_imports,
        &skipped_language_modules,
    );
    if wrote_imports && service.delay_load_temporalio_workflow && !type_checking_names.is_empty() {
        output.push('\n');
    }
    let wrote_type_checking_imports =
        render_temporalio_workflow_type_checking_imports(&mut output, service, &body);
    if wrote_imports || wrote_type_checking_imports {
        output.push('\n');
    }
    let used_model_names = used_python_symbol_imports(&body, model_names);
    render_named_python_import(&mut output, "..models", &used_model_names);
    let used_resource_names = used_python_symbol_imports(&body, resource_names);
    if !used_resource_names.is_empty() {
        render_named_python_import(&mut output, ".._resources", &used_resource_names);
    }
    let used_support_names = used_python_symbol_imports(&body, support_names);
    if !used_support_names.is_empty() {
        render_named_python_import(&mut output, ".._support", &used_support_names);
    }
    output.push('\n');
    output.push('\n');
    output.push_str(&body);
    output
}

