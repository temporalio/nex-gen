/// Renders all collected types into a complete Go source file with a package
/// declaration, import block, and the generated-code header comment.
fn render_file(
    package_name: &str,
    imports: &BTreeSet<String>,
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    services: &[RenderedService<'_>],
) -> String {
    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push('\n');
    output.push_str("package ");
    output.push_str(package_name);
    output.push('\n');

    if !imports.is_empty() {
        // Separate stdlib imports (no '.') from third-party imports (contain '.')
        let stdlib: Vec<_> = imports
            .iter()
            .filter(|p| !p.contains('.'))
            .collect();
        let third_party: Vec<_> = imports
            .iter()
            .filter(|p| p.contains('.'))
            .collect();

        output.push_str("\nimport (\n");
        for import_path in &stdlib {
            output.push('\t');
            output.push('"');
            output.push_str(import_path);
            output.push('"');
            output.push('\n');
        }
        if !stdlib.is_empty() && !third_party.is_empty() {
            output.push('\n');
        }
        for import_path in &third_party {
            output.push('\t');
            output.push('"');
            output.push_str(import_path);
            output.push('"');
            output.push('\n');
        }
        output.push_str(")\n");
    }

    for service in services {
        output.push('\n');
        render_service_constants(&mut output, service);
    }

    for enumeration in enums {
        output.push('\n');
        render_enum(&mut output, enumeration);
    }

    for flag_set in flags {
        output.push('\n');
        render_flags(&mut output, flag_set);
    }

    for variant in variants {
        output.push('\n');
        render_variant(&mut output, variant);
    }

    for model in models {
        output.push('\n');
        render_model(&mut output, model);
    }

    for service in services {
        for resource in &service.resources {
            output.push('\n');
            render_resource(&mut output, resource);
        }
    }

    for service in services {
        for operation in &service.operations {
            output.push('\n');
            render_operation_function(&mut output, operation);
        }
    }

    for service in services {
        for operation in &service.operations {
            if let Some(params) = &operation.unpacked_input {
                let has_optional = params.iter().any(|p| !p.required);
                if has_optional {
                    output.push('\n');
                    render_options_struct(&mut output, operation, params);
                }
                output.push('\n');
                render_convenience_wrapper(&mut output, operation, params);
            }
        }
    }

    output
}

/// Renders a WIT enum as a Go named integer type with a `const` block.
///
/// ```go
/// type UserStatus int32
///
/// const (
///     UserStatusActive    UserStatus = 0
///     UserStatusSuspended UserStatus = 1
/// )
/// ```
fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("type ");
    output.push_str(&enumeration.name);
    output.push_str(" int32\n");

    if enumeration.values.is_empty() {
        return;
    }

    output.push_str("\nconst (\n");
    for value in &enumeration.values {
        output.push('\t');
        output.push_str(&enumeration.name);
        output.push_str(&value.name);
        output.push(' ');
        output.push_str(&enumeration.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push('\n');
    }
    output.push_str(")\n");
}

/// Renders a WIT flags type as a Go named integer type with bit-shifted
/// constants.
///
/// ```go
/// type UserCapability int32
///
/// const (
///     UserCapabilityReadProfile UserCapability = 1 << 0
///     UserCapabilityUpdateEmail UserCapability = 1 << 1
/// )
/// ```
fn render_flags(output: &mut String, flags: &RenderedFlags) {
    output.push_str("type ");
    output.push_str(&flags.name);
    output.push_str(" int32\n");

    if flags.flags.is_empty() {
        return;
    }

    output.push_str("\nconst (\n");
    for flag in &flags.flags {
        output.push('\t');
        output.push_str(&flags.name);
        output.push_str(&flag.name);
        output.push(' ');
        output.push_str(&flags.name);
        output.push_str(" = 1 << ");
        output.push_str(&flag.bit.to_string());
        output.push('\n');
    }
    output.push_str(")\n");
}

/// Renders a WIT variant as a Go sealed interface with concrete case structs.
///
/// ```go
/// type NotificationTarget interface {
///     isNotificationTarget()
/// }
///
/// type NotificationTargetEmail struct {
///     Value string
/// }
///
/// func (NotificationTargetEmail) isNotificationTarget() {}
///
/// type NotificationTargetNone struct{}
///
/// func (NotificationTargetNone) isNotificationTarget() {}
/// ```
fn render_variant(output: &mut String, variant: &RenderedVariant) {
    output.push_str("type ");
    output.push_str(&variant.name);
    output.push_str(" interface {\n");
    output.push('\t');
    output.push_str(&variant.marker_method);
    output.push_str("()\n");
    output.push_str("}\n");

    for case in &variant.cases {
        output.push('\n');
        output.push_str("type ");
        output.push_str(&case.struct_name);
        if let Some(payload_type) = &case.payload_type {
            output.push_str(" struct {\n");
            output.push_str("\tValue ");
            output.push_str(payload_type);
            output.push('\n');
            output.push_str("}\n");
        } else {
            output.push_str(" struct{}\n");
        }
        output.push('\n');
        output.push_str("func (");
        output.push_str(&case.struct_name);
        output.push_str(") ");
        output.push_str(&variant.marker_method);
        output.push_str("() {}\n");
    }
}

/// Renders a WIT record (or proto message) as a Go struct. Required fields
/// are annotated with a trailing `// required` comment.
///
/// ```go
/// type DeactivateRequest struct {
///     UserId string // required
///     Reason string
/// }
/// ```
fn render_model(output: &mut String, model: &RenderedModel) {
    output.push_str("type ");
    output.push_str(&model.name);
    output.push_str(" struct {\n");

    if model.fields.is_empty() {
        output.push_str("}\n");
        return;
    }

    for field in &model.fields {
        output.push('\t');
        output.push_str(&field.name);
        output.push(' ');
        output.push_str(&field.go_type);
        if field.required {
            output.push_str(" // required");
        }
        output.push('\n');
    }
    output.push_str("}\n");
}

/// Renders service and operation name constants.
///
/// ```go
/// const ServiceName = "UserService"
/// const Endpoint = "user-service"
///
/// const GetUserOp = "GetUser"
/// const UpdateEmailOp = "UpdateEmail"
/// ```
fn render_service_constants(output: &mut String, service: &RenderedService<'_>) {
    output.push_str("const ServiceName = \"");
    output.push_str(service.name);
    output.push_str("\"\n");
    output.push_str("const Endpoint = \"");
    output.push_str(&service.endpoint);
    output.push_str("\"\n");

    if !service.operations.is_empty() {
        output.push('\n');
        for operation in &service.operations {
            output.push_str("const ");
            output.push_str(&go_field_name(operation.name));
            output.push_str("Op = \"");
            output.push_str(operation.wire_name);
            output.push_str("\"\n");
        }
    }
}

/// Renders a WIT resource as a Go struct with its constructor fields.
///
/// ```go
/// type User struct {
///     UserId string // required
///     Email  string // required
/// }
/// ```
fn render_resource(output: &mut String, resource: &PlannedResource) {
    output.push_str("type ");
    output.push_str(&resource.type_name);
    output.push_str(" struct {\n");

    if resource.fields.is_empty() {
        output.push_str("}\n");
        return;
    }

    for field in &resource.fields {
        let field_name = go_field_name(&field.name);
        let go_type = resolve_resource_field_kind(&field.kind, field.optional);
        output.push('\t');
        output.push_str(&field_name);
        output.push(' ');
        output.push_str(&go_type);
        if !field.optional {
            output.push_str(" // required");
        }
        output.push('\n');
    }
    output.push_str("}\n");
}

/// Resolves a resource field's [`PlannedFieldKind`] to a Go type expression,
/// applying the same optionality rules as record fields: pointer for optional
/// struct types, plain type for optional scalars/interfaces.
fn resolve_resource_field_kind(kind: &PlannedFieldKind, optional: bool) -> String {
    match kind {
        PlannedFieldKind::Map { key, value } => {
            let key_type = resolve_resource_value_type(key);
            let value_type = resolve_resource_value_type(value);
            format!("map[{key_type}]{value_type}")
        }
        PlannedFieldKind::Repeated(value) => {
            let element_type = resolve_resource_value_type(value);
            format!("[]{element_type}")
        }
        PlannedFieldKind::Singular(value) => {
            let (base_type, is_struct) = resolve_resource_value_type_with_struct_flag(value);
            if optional && is_struct {
                format!("*{base_type}")
            } else {
                base_type
            }
        }
    }
}

/// Resolves a [`PlannedValueType`] to a Go type expression for use in resource
/// field declarations. This is a simplified version of
/// [`resolve_planned_value_type`] that doesn't register types into collections
/// (that's already done by [`ensure_resource_field_types`]).
fn resolve_resource_value_type(value: &PlannedValueType) -> String {
    resolve_resource_value_type_with_struct_flag(value).0
}

/// Like [`resolve_resource_value_type`] but also returns whether the type is a
/// struct (for optionality/pointer decisions).
fn resolve_resource_value_type_with_struct_flag(value: &PlannedValueType) -> (String, bool) {
    match value {
        PlannedValueType::Scalar(PlannedScalarType::Float) => ("float64".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Int32) => ("int32".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Int64) => ("int64".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Bool) => ("bool".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::String) => ("string".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Bytes) => ("[]byte".to_string(), false),
        PlannedValueType::Enum(enum_type) => {
            if let Some(replacement) = &enum_type.replacement
                && let Some(type_name) = go_replacement_type_name(replacement)
            {
                return (type_name, false);
            }
            (
                enum_type.name.clone().unwrap_or_else(|| "int32".to_string()),
                false,
            )
        }
        PlannedValueType::Flags(flags_type) => (flags_type.name.clone(), false),
        PlannedValueType::Variant(variant_type) => (variant_type.name.clone(), false),
        PlannedValueType::Message(message_type) => {
            if let Some(replacement) = &message_type.replacement
                && let Some(type_name) = go_replacement_type_name(replacement)
            {
                return (type_name, false);
            }
            if let Some(authored_type) = &message_type.authored_type {
                return (go_authored_type_annotation(authored_type), false);
            }
            (message_type.model_name.clone(), true)
        }
        PlannedValueType::Tuple(_) => ("any".to_string(), false),
        PlannedValueType::Result { .. } => ("any".to_string(), false),
        PlannedValueType::External {
            type_name,
            fallback,
        } => {
            if let Some(annotation) = type_name.for_language(Language::Go) {
                let (_import, code_expr) = parse_go_import(annotation);
                (code_expr, false)
            } else {
                resolve_resource_value_type_with_struct_flag(fallback)
            }
        }
        PlannedValueType::Unknown => ("any".to_string(), false),
    }
}

/// Renders an unexported operation wrapper function that creates a Nexus
/// client and executes the operation.
///
/// For operations returning a value:
/// ```go
/// func getUser(ctx workflow.Context, request GetUserRequest) (*User, error) {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, GetUserOp, request, workflow.NexusOperationOptions{})
///     var result User
///     if err := fut.Get(ctx, &result); err != nil {
///         return nil, err
///     }
///     return &result, nil
/// }
/// ```
///
/// For void operations:
/// ```go
/// func deactivate(ctx workflow.Context, request DeactivateRequest) error {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, DeactivateOp, request, workflow.NexusOperationOptions{})
///     return fut.Get(ctx, nil)
/// }
/// ```
fn render_operation_function(output: &mut String, operation: &RenderedOperation<'_>) {
    let op_const = format!("{}Op", go_field_name(operation.name));

    if let Some(result_type) = &operation.output_type {
        // Operation with a return value
        output.push_str("func ");
        output.push_str(&operation.func_name);
        output.push_str("(ctx workflow.Context, request ");
        output.push_str(&operation.input_type);
        output.push_str(") (*");
        output.push_str(result_type);
        output.push_str(", error) {\n");
        output.push_str("\tc := workflow.NewNexusClient(Endpoint, ServiceName)\n");
        output.push_str("\tfut := c.ExecuteOperation(ctx, ");
        output.push_str(&op_const);
        output.push_str(", request, workflow.NexusOperationOptions{})\n");
        output.push_str("\tvar result ");
        output.push_str(result_type);
        output.push('\n');
        output.push_str("\tif err := fut.Get(ctx, &result); err != nil {\n");
        output.push_str("\t\treturn nil, err\n");
        output.push_str("\t}\n");
        output.push_str("\treturn &result, nil\n");
        output.push_str("}\n");
    } else {
        // Void operation
        output.push_str("func ");
        output.push_str(&operation.func_name);
        output.push_str("(ctx workflow.Context, request ");
        output.push_str(&operation.input_type);
        output.push_str(") error {\n");
        output.push_str("\tc := workflow.NewNexusClient(Endpoint, ServiceName)\n");
        output.push_str("\tfut := c.ExecuteOperation(ctx, ");
        output.push_str(&op_const);
        output.push_str(", request, workflow.NexusOperationOptions{})\n");
        output.push_str("\treturn fut.Get(ctx, nil)\n");
        output.push_str("}\n");
    }
}

/// Renders an options struct for optional parameters of a convenience wrapper.
///
/// ```go
/// type GetUserOptions struct {
///     ConsistencyToken string
/// }
/// ```
fn render_options_struct(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
) {
    output.push_str("type ");
    output.push_str(&go_field_name(operation.name));
    output.push_str("Options struct {\n");
    for param in params.iter().filter(|p| !p.required) {
        output.push('\t');
        output.push_str(&param.field_name);
        output.push(' ');
        output.push_str(&param.go_type);
        output.push('\n');
    }
    output.push_str("}\n");
}

/// Renders an exported convenience wrapper that unpacks required fields as
/// positional arguments and optional fields into a variadic options struct.
///
/// When all fields are required:
/// ```go
/// func UpdateEmail(ctx workflow.Context, userId string, email string) (*User, error) {
///     return updateEmail(ctx, UpdateEmailRequest{UserId: userId, Email: email})
/// }
/// ```
///
/// When optional fields exist:
/// ```go
/// func GetUser(ctx workflow.Context, userId string, opts ...GetUserOptions) (*User, error) {
///     request := GetUserRequest{UserId: userId}
///     if len(opts) > 0 {
///         request.ConsistencyToken = opts[0].ConsistencyToken
///     }
///     return getUser(ctx, request)
/// }
/// ```
fn render_convenience_wrapper(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
) {
    let exported_name = go_field_name(operation.name);
    let has_optional = params.iter().any(|p| !p.required);

    // Function signature
    output.push_str("func ");
    output.push_str(&exported_name);
    output.push_str("(ctx workflow.Context");
    for param in params.iter().filter(|p| p.required) {
        output.push_str(", ");
        output.push_str(&param.param_name);
        output.push(' ');
        output.push_str(&param.go_type);
    }
    if has_optional {
        output.push_str(", opts ...");
        output.push_str(&exported_name);
        output.push_str("Options");
    }
    output.push_str(") ");

    // Return type
    if let Some(result_type) = &operation.output_type {
        output.push_str("(*");
        output.push_str(result_type);
        output.push_str(", error)");
    } else {
        output.push_str("error");
    }
    output.push_str(" {\n");

    // Function body
    if has_optional {
        // Build request incrementally
        output.push_str("\trequest := ");
        output.push_str(&operation.input_type);
        output.push('{');
        let required_params: Vec<_> = params.iter().filter(|p| p.required).collect();
        for (i, param) in required_params.iter().enumerate() {
            output.push_str(&param.field_name);
            output.push_str(": ");
            output.push_str(&param.param_name);
            if i + 1 < required_params.len() {
                output.push_str(", ");
            }
        }
        output.push_str("}\n");

        // Apply optional fields from opts
        output.push_str("\tif len(opts) > 0 {\n");
        for param in params.iter().filter(|p| !p.required) {
            output.push_str("\t\trequest.");
            output.push_str(&param.field_name);
            output.push_str(" = opts[0].");
            output.push_str(&param.field_name);
            output.push('\n');
        }
        output.push_str("\t}\n");

        // Call unexported function
        output.push_str("\treturn ");
        output.push_str(&operation.func_name);
        output.push_str("(ctx, request)\n");
    } else {
        // All required -- inline the request construction
        output.push_str("\treturn ");
        output.push_str(&operation.func_name);
        output.push_str("(ctx, ");
        output.push_str(&operation.input_type);
        output.push('{');
        let required_params: Vec<_> = params.iter().filter(|p| p.required).collect();
        for (i, param) in required_params.iter().enumerate() {
            output.push_str(&param.field_name);
            output.push_str(": ");
            output.push_str(&param.param_name);
            if i + 1 < required_params.len() {
                output.push_str(", ");
            }
        }
        output.push_str("})\n");
    }

    output.push_str("}\n");
}
