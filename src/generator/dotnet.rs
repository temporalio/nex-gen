fn enum_value_name(name: &str) -> String {
    name.trim_start_matches(|ch: char| ch == '_' || ch.is_ascii_digit())
        .trim_start_matches("UNSPECIFIED")
        .trim_start_matches('_')
        .to_string()
}

pub(in crate::generator) fn csharp_type_name(name: &str) -> String {
    csharp_ident(&name.to_upper_camel_case())
}

fn csharp_parameter_name(name: &str) -> String {
    csharp_ident(&name.to_lower_camel_case())
}

fn csharp_ident(name: &str) -> String {
    let candidate = if name.is_empty() {
        "Value".to_string()
    } else if name
        .chars()
        .next()
        .is_some_and(|ch| ch == '_' || ch.is_ascii_alphabetic())
    {
        name.to_string()
    } else {
        format!("_{name}")
    };
    if CSHARP_KEYWORDS.contains(&candidate.as_str()) {
        format!("@{candidate}")
    } else {
        candidate
    }
}

fn csharp_string_literal(value: &str) -> String {
    format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('\n', "\\n")
            .replace('\r', "\\r")
    )
}

