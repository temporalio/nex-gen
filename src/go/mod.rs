/// A resolved Nexus service ready for rendering. Currently used to drive type
/// collection; service-level code generation (clients, handlers) is not yet
/// implemented.
#[derive(Debug)]
struct RenderedService<'a> {
    /// UpperCamelCase service name (e.g. `"TypeShowcase"`).
    name: &'a str,
    /// Nexus endpoint identifier (e.g. `"type-showcase"`).
    endpoint: String,
    /// Operations belonging to this service.
    operations: Vec<RenderedOperation<'a>>,
    /// Resources belonging to this service.
    resources: Vec<PlannedResource>,
}

/// A resolved Nexus operation with enough information to render the operation
/// constant and an unexported caller function.
#[derive(Debug)]
struct RenderedOperation<'a> {
    /// UpperCamelCase operation name (e.g. `"GetUser"`).
    name: &'a str,
    /// Wire-format operation name (e.g. `"GetUser"`).
    wire_name: &'a str,
    /// Unexported Go function name (e.g. `"getUser"`).
    func_name: String,
    /// Go type for the request parameter (e.g. `"GetUserRequest"`).
    input_type: String,
    /// Go type for the result, or `None` for void operations.
    /// For resource-returning operations this is the resource type name
    /// (e.g. `"User"`).
    output_type: Option<String>,
    /// Unpacked input parameters for the exported convenience wrapper, or
    /// `None` when the input type is an external/replacement type that cannot
    /// be unpacked into individual arguments.
    unpacked_input: Option<Vec<RenderedUnpackedParam>>,
}

/// A single parameter in an unpacked convenience wrapper function signature.
#[derive(Debug)]
struct RenderedUnpackedParam {
    /// Exported Go field name used when setting the request struct field
    /// (e.g. `"UserId"`).
    field_name: String,
    /// Unexported Go parameter name used in the function signature
    /// (e.g. `"userId"`).
    param_name: String,
    /// Go type expression (e.g. `"string"`, `"UserProfile"`).
    go_type: String,
    /// Whether this parameter is required (positional argument) or optional
    /// (placed in the options struct).
    required: bool,
}

/// A WIT enum rendered as a Go `type <Name> int32` with associated constants.
#[derive(Debug)]
struct RenderedEnum {
    /// Go type name (e.g. `"UserStatus"`).
    name: String,
    /// Ordered enum variants with their numeric values.
    values: Vec<RenderedEnumValue>,
}

/// A single variant of a [`RenderedEnum`].
#[derive(Debug)]
struct RenderedEnumValue {
    /// UpperCamelCase variant name (e.g. `"Active"`).
    name: String,
    /// Numeric value assigned in the WIT definition.
    number: i32,
}

/// A WIT flags type rendered as a Go `type <Name> int32` with bit-mask
/// constants.
#[derive(Debug)]
struct RenderedFlags {
    /// Go type name (e.g. `"UserCapability"`).
    name: String,
    /// Individual flag definitions.
    flags: Vec<RenderedFlag>,
}

/// A single flag within a [`RenderedFlags`] set.
#[derive(Debug)]
struct RenderedFlag {
    /// UpperCamelCase flag name (e.g. `"ReadProfile"`).
    name: String,
    /// Zero-based bit position (`1 << bit`).
    bit: usize,
}

/// A WIT variant rendered as a Go sealed interface with concrete case structs.
///
/// The interface carries an unexported marker method to prevent external
/// implementations. Each case becomes a struct that implements the interface.
#[derive(Debug)]
struct RenderedVariant {
    /// Go interface type name (e.g. `"NotificationTarget"`).
    name: String,
    /// Unexported marker method name (e.g. `"isNotificationTarget"`).
    marker_method: String,
    /// Ordered variant cases.
    cases: Vec<RenderedVariantCase>,
}

/// A single case of a [`RenderedVariant`], rendered as a Go struct that
/// implements the variant's sealed interface.
#[derive(Debug)]
struct RenderedVariantCase {
    /// Go struct name combining variant and case (e.g. `"NotificationTargetEmail"`).
    struct_name: String,
    /// Go type of the payload field, or `None` for payload-less cases.
    payload_type: Option<String>,
}

/// A WIT record (or proto message) rendered as a Go struct. Also used for
/// generated tuple structs.
#[derive(Debug)]
struct RenderedModel {
    /// Go type name (e.g. `"UserProfile"`, `"Coordinates"`).
    name: String,
    /// Struct fields in declaration order.
    fields: Vec<RenderedField>,
}

/// A single field of a [`RenderedModel`].
#[derive(Debug)]
struct RenderedField {
    /// Exported Go field name in UpperCamelCase (e.g. `"UserId"`, `"First"`).
    name: String,
    /// Go type expression (e.g. `"string"`, `"*PostalAddress"`, `"[]string"`).
    go_type: String,
    /// Whether the field is required in the WIT definition. Rendered as a
    /// `// required` trailing comment in the generated Go struct.
    required: bool,
}

/// The result of resolving a [`PlannedValueType`] to a Go type expression.
/// Carries enough information to decide whether an optional field should use
/// a pointer (`*T`) or its zero value.
#[derive(Debug, Clone)]
struct ResolvedGoType {
    /// Go type expression (e.g. `"string"`, `"PostalAddress"`, `"[]string"`).
    type_expr: String,
    /// `true` when the resolved type is a struct (message/record/tuple) and an
    /// optional field of this type should use a pointer to distinguish the
    /// zero value from absence. Interfaces, slices, and maps are `false`
    /// because their zero value (`nil`) already represents absence.
    is_struct: bool,
}

