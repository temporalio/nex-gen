const GENERATED_HEADER: &str = "// Generated by nex-gen. DO NOT EDIT!";

pub(crate) fn generate(
    api_plan: &ApiPlan,
    support_fragments: &[SupportFragmentSpec],
    _language_imports: &[LanguageImportSpec],
) -> Result<GeneratedFiles> {
    let namespace = dotnet_namespace(api_plan);
    let mut files = BTreeMap::<PathBuf, String>::new();
    files.insert(
        "Models.cs".into(),
        render_models_file(
            &namespace,
            api_plan.enums.values().collect::<Vec<_>>().as_slice(),
            api_plan.flags.values().collect::<Vec<_>>().as_slice(),
            api_plan.variants.values().collect::<Vec<_>>().as_slice(),
            api_plan.models.values().collect::<Vec<_>>().as_slice(),
            api_plan,
        ),
    );
    files.insert(
        "Service.cs".into(),
        render_service_file(&namespace, api_plan),
    );
    if api_plan
        .services
        .iter()
        .any(|service| !service.operations.is_empty())
    {
        files.insert(
            "Operations.cs".into(),
            render_operations_file(&namespace, api_plan),
        );
    }
    if api_plan
        .services
        .iter()
        .any(|service| !service.resources.is_empty())
    {
        files.insert(
            "Resources.cs".into(),
            render_resources_file(&namespace, api_plan),
        );
    }
    for fragment in support_fragments {
        files.insert(support_fragment_path(fragment)?, fragment.contents.clone());
    }
    Ok(GeneratedFiles::directory(files))
}

fn render_models_file(
    namespace: &str,
    enums: &[&PlannedEnum],
    flags: &[&PlannedFlags],
    variants: &[&crate::api_plan::PlannedVariant],
    models: &[&PlannedModel],
    api_plan: &ApiPlan,
) -> String {
    let needs_result = models.iter().any(|model| {
        model
            .fields
            .iter()
            .any(|field| field_kind_uses_result(&field.kind))
    });
    let mut output = generated_file_prelude(namespace, &["System", "System.Collections.Generic"]);
    if needs_result {
        render_result_helper(&mut output);
    }
    for enumeration in enums {
        render_enum(&mut output, enumeration);
    }
    for flag_set in flags {
        render_flags(&mut output, flag_set);
    }
    for variant in variants {
        render_variant(&mut output, variant);
    }
    for model in models {
        render_model(&mut output, model, api_plan);
    }
    output
}

fn render_service_file(namespace: &str, api_plan: &ApiPlan) -> String {
    let mut output = generated_file_prelude(namespace, &["NexusRpc"]);
    for service in &api_plan.services {
        output.push_str("[NexusService(");
        output.push_str(&csharp_string_literal(&service.wire_name));
        output.push_str(")]\n");
        output.push_str("internal interface I");
        output.push_str(&csharp_type_name(&service.name));
        output.push_str("\n{\n");
        for operation in &service.operations {
            render_service_operation(&mut output, operation, api_plan);
        }
        output.push_str("}\n\n");
    }
    output
}

fn render_operations_file(namespace: &str, api_plan: &ApiPlan) -> String {
    let mut output = generated_file_prelude(
        namespace,
        &[
            "System",
            "System.Collections.Generic",
            "System.Linq",
            "System.Linq.Expressions",
            "System.Reflection",
            "System.Threading.Tasks",
            "Google.Protobuf.WellKnownTypes",
            "Temporalio.Converters",
            "Temporalio.Workflows",
        ],
    );
    for service in &api_plan.services {
        render_operations_class(&mut output, service, api_plan);
    }
    output
}

fn render_resources_file(namespace: &str, api_plan: &ApiPlan) -> String {
    let mut output = generated_file_prelude(namespace, &["System", "System.Collections.Generic"]);
    for service in &api_plan.services {
        for resource in &service.resources {
            render_resource(&mut output, resource);
        }
    }
    output
}

fn generated_file_prelude(namespace: &str, imports: &[&str]) -> String {
    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push_str("\n#nullable enable\n");
    output.push_str("#pragma warning disable CS1591\n\n");
    for import in imports {
        output.push_str("using ");
        output.push_str(import);
        output.push_str(";\n");
    }
    if !imports.is_empty() {
        output.push('\n');
    }
    output.push_str("namespace ");
    output.push_str(namespace);
    output.push_str(";\n\n");
    output
}

fn dotnet_doc(spec: &crate::spec::LanguageStringSpec) -> Option<&str> {
    spec.for_language(Language::Dotnet)
}

fn render_operation_xml_doc(
    output: &mut String,
    indent: &str,
    operation: &PlannedOperation,
    api_plan: &ApiPlan,
) {
    let return_doc = match operation.output {
        PlannedOperationOutput::None => None,
        _ => dotnet_doc(&operation.return_doc),
    };
    let request_doc = api_plan
        .models
        .get(&operation.input.info.full_name)
        .and_then(|model| dotnet_doc(model.generated_model.doc()));
    render_xml_doc(
        output,
        indent,
        dotnet_doc(&operation.doc),
        request_doc
            .map(|doc| vec![("request", doc)])
            .unwrap_or_default(),
        return_doc,
    );
}

fn render_operation_summary_xml_doc(
    output: &mut String,
    indent: &str,
    operation: &PlannedOperation,
) {
    let return_doc = match operation.output {
        PlannedOperationOutput::None => None,
        _ => dotnet_doc(&operation.return_doc),
    };
    render_xml_doc(
        output,
        indent,
        dotnet_doc(&operation.doc),
        Vec::new(),
        return_doc,
    );
}

fn render_field_xml_doc(output: &mut String, indent: &str, field: &PlannedField) {
    render_xml_summary(output, indent, field.doc.as_ref().and_then(dotnet_doc));
}

fn render_xml_summary(output: &mut String, indent: &str, summary: Option<&str>) {
    render_xml_doc(output, indent, summary, Vec::new(), None);
}

fn render_xml_doc(
    output: &mut String,
    indent: &str,
    summary: Option<&str>,
    params: Vec<(&str, &str)>,
    returns: Option<&str>,
) {
    if summary.is_none() && params.is_empty() && returns.is_none() {
        return;
    }
    if let Some(summary) = summary {
        output.push_str(indent);
        output.push_str("/// <summary>\n");
        render_xml_doc_text(output, indent, summary);
        output.push_str(indent);
        output.push_str("/// </summary>\n");
    }
    for (name, doc) in params {
        output.push_str(indent);
        output.push_str("/// <param name=\"");
        output.push_str(name);
        output.push_str("\">");
        output.push_str(&xml_doc_escape(doc.trim()));
        output.push_str("</param>\n");
    }
    if let Some(returns) = returns {
        output.push_str(indent);
        output.push_str("/// <returns>");
        output.push_str(&xml_doc_escape(returns.trim()));
        output.push_str("</returns>\n");
    }
}

fn render_xml_doc_text(output: &mut String, indent: &str, text: &str) {
    for line in text.trim().lines() {
        output.push_str(indent);
        output.push_str("/// ");
        output.push_str(&xml_doc_escape(line.trim()));
        output.push('\n');
    }
}

fn xml_doc_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn render_service_operation(output: &mut String, operation: &PlannedOperation, api_plan: &ApiPlan) {
    render_operation_summary_xml_doc(output, "    ", operation);
    output.push_str("    [NexusOperation(");
    output.push_str(&csharp_string_literal(&operation.wire_name));
    output.push_str(")]\n");
    output.push_str("    ");
    output.push_str(&operation_raw_return_type(operation));
    output.push(' ');
    output.push_str(&csharp_type_name(&operation.name));
    output.push('(');
    if operation_has_input(operation, api_plan) {
        output.push_str(&operation_raw_input_type(&operation.input));
        output.push_str(" request");
    }
    output.push_str(");\n\n");
}

fn render_operations_class(output: &mut String, service: &PlannedService, api_plan: &ApiPlan) {
    let service_type = format!("I{}", csharp_type_name(&service.name));
    for operation in &service.operations {
        render_operation_options_type(output, operation, api_plan);
    }
    output.push_str("public static class ");
    output.push_str(&csharp_type_name(&format!("{}Operations", service.name)));
    output.push_str("\n{\n");
    for operation in &service.operations {
        render_operation_extension(
            output,
            operation,
            api_plan,
            &service_type,
            &service.endpoint,
        );
    }
    render_expression_helpers_if_needed(output, service, api_plan);
    output.push_str("}\n\n");
}

fn render_operation_extension(
    output: &mut String,
    operation: &PlannedOperation,
    api_plan: &ApiPlan,
    service_type: &str,
    endpoint: &str,
) {
    let method_name = format!("{}Async", csharp_type_name(&operation.name));
    let raw_return = operation_raw_return_type(operation);
    let high_level_return = operation_return_type(operation);
    let has_input = operation_has_input(operation, api_plan);
    let raw_input_type = operation_raw_input_type(&operation.input);
    let high_level_input_type = operation_input_type(&operation.input, api_plan);

    if high_level_input_type == raw_input_type || !operation_requires_high_level_request(operation)
    {
        render_operation_request_extension(
            output,
            operation,
            service_type,
            &method_name,
            has_input,
            &raw_input_type,
            &raw_return,
            &high_level_return,
            RequestArgumentKind::Raw,
            endpoint,
            api_plan,
        );
    }

    if has_input && high_level_input_type != raw_input_type {
        render_operation_request_extension(
            output,
            operation,
            service_type,
            &method_name,
            has_input,
            &high_level_input_type,
            &raw_return,
            &high_level_return,
            RequestArgumentKind::HighLevel,
            endpoint,
            api_plan,
        );
    }

    if let Some(model) = api_plan.models.get(&operation.input.info.full_name)
        && operation_has_flattened_convenience(operation, model, api_plan)
    {
        render_operation_flattened_extension(
            output,
            operation,
            &method_name,
            model,
            &raw_return,
            &high_level_return,
            api_plan,
        );
    }
}

#[derive(Clone, Copy)]
enum RequestArgumentKind {
    Raw,
    HighLevel,
}

fn render_operation_request_extension(
    output: &mut String,
    operation: &PlannedOperation,
    service_type: &str,
    method_name: &str,
    has_input: bool,
    input_type: &str,
    raw_return: &str,
    high_level_return: &str,
    request_kind: RequestArgumentKind,
    endpoint: &str,
    api_plan: &ApiPlan,
) {
    render_operation_xml_doc(output, "    ", operation, api_plan);
    output.push_str("    ");
    output.push_str(operation_request_method_access(
        operation,
        request_kind,
        api_plan,
    ));
    output.push_str(" static ");
    if raw_return == "void" {
        output.push_str("async Task ");
    } else {
        output.push_str("async Task<");
        output.push_str(high_level_return);
        output.push_str("> ");
    }
    output.push_str(&method_name);
    output.push('(');
    if has_input {
        output.push_str(&input_type);
        output.push_str(" request");
    }
    output.push_str(")\n    {\n");
    output.push_str("        var client = Workflow.CreateNexusWorkflowClient<");
    output.push_str(service_type);
    output.push_str(">(");
    output.push_str(&csharp_string_literal(endpoint));
    output.push_str(");\n");
    if matches!(request_kind, RequestArgumentKind::HighLevel) {
        output.push_str("        var protoRequest = request.ToProto();\n");
    }
    if raw_return == "void" {
        output.push_str("        await client.ExecuteNexusOperationAsync(svc => svc.");
    } else {
        output.push_str("        var result = await client.ExecuteNexusOperationAsync<");
        output.push_str(&raw_return);
        output.push_str(">(svc => svc.");
    }
    output.push_str(&csharp_type_name(&operation.name));
    output.push('(');
    if has_input {
        if matches!(request_kind, RequestArgumentKind::HighLevel) {
            output.push_str("protoRequest");
        } else {
            output.push_str("request");
        }
    }
    output.push(')');
    output.push_str(").ConfigureAwait(true);\n");
    if raw_return == "void" {
        output.push_str("    }\n\n");
        return;
    }
    if operation.output_transform.is_some() || operation.output_resource_return.is_some() {
        output.push_str("        return ");
        output.push_str(&operation_transform_expression(
            operation,
            "request",
            "protoRequest",
            "result",
            api_plan,
        ));
        output.push_str(";\n");
    } else {
        output.push_str("        return result;\n");
    }
    output.push_str("    }\n\n");
}

fn operation_request_method_access(
    operation: &PlannedOperation,
    request_kind: RequestArgumentKind,
    api_plan: &ApiPlan,
) -> &'static str {
    let raw_input_type = operation_raw_input_type(&operation.input);
    let high_level_input_type = operation_input_type(&operation.input, api_plan);
    if (matches!(request_kind, RequestArgumentKind::HighLevel)
        || high_level_input_type == raw_input_type)
        && api_plan
            .models
            .get(&operation.input.info.full_name)
            .is_some_and(|model| operation_has_flattened_convenience(operation, model, api_plan))
    {
        "private"
    } else {
        "public"
    }
}

fn operation_requires_high_level_request(operation: &PlannedOperation) -> bool {
    operation.output_transform.is_some() || operation.output_resource_return.is_some()
}

fn operation_has_flattened_convenience(
    _operation: &PlannedOperation,
    model: &PlannedModel,
    _api_plan: &ApiPlan,
) -> bool {
    !model.fields.is_empty() && model_function_fields_flattenable(model)
}

fn model_function_fields_flattenable(model: &PlannedModel) -> bool {
    let mut has_function_fields = false;
    for field in &model.fields {
        if let Some(function) = &field.function {
            has_function_fields = true;
            if function.name_extractor.is_none() {
                return false;
            }
        }
    }
    !has_function_fields || model_has_extractable_function_fields(model)
}

fn render_operation_flattened_overload(
    output: &mut String,
    operation: &PlannedOperation,
    method_name: &str,
    model: &PlannedModel,
    raw_return: &str,
    high_level_return: &str,
    api_plan: &ApiPlan,
    overload: &FlattenedOverload,
) {
    render_flattened_method_signature(
        output,
        operation,
        method_name,
        raw_return,
        high_level_return,
        model,
        api_plan,
        overload,
    );
    render_flattened_method_body(output, operation, model, api_plan, overload);
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum FlattenedFunctionMode {
    String,
    Expression,
}

struct FlattenedOverload {
    function_modes: Vec<(String, FlattenedFunctionMode)>,
}

impl FlattenedOverload {
    fn function_mode(&self, field: &PlannedField) -> FlattenedFunctionMode {
        self.function_modes
            .iter()
            .find_map(|(field_name, mode)| (field_name == &field.proto_name).then_some(*mode))
            .unwrap_or(FlattenedFunctionMode::String)
    }

    fn has_expression_functions(&self) -> bool {
        self.function_modes
            .iter()
            .any(|(_, mode)| matches!(mode, FlattenedFunctionMode::Expression))
    }
}

fn flattened_overloads(model: &PlannedModel) -> Vec<FlattenedOverload> {
    let function_fields = model
        .fields
        .iter()
        .filter(|field| field.function.is_some())
        .collect::<Vec<_>>();
    if function_fields.is_empty() {
        return vec![FlattenedOverload {
            function_modes: Vec::new(),
        }];
    }
    (0..(1usize << function_fields.len()))
        .map(|mask| FlattenedOverload {
            function_modes: function_fields
                .iter()
                .enumerate()
                .map(|(index, field)| {
                    let mode = if mask & (1usize << index) == 0 {
                        FlattenedFunctionMode::String
                    } else {
                        FlattenedFunctionMode::Expression
                    };
                    (field.proto_name.clone(), mode)
                })
                .collect(),
        })
        .collect()
}

fn render_flattened_method_signature(
    output: &mut String,
    operation: &PlannedOperation,
    method_name: &str,
    raw_return: &str,
    high_level_return: &str,
    model: &PlannedModel,
    api_plan: &ApiPlan,
    overload: &FlattenedOverload,
) {
    render_operation_summary_xml_doc(output, "    ", operation);
    output.push_str("    public static ");
    if raw_return == "void" {
        output.push_str("Task ");
    } else {
        output.push_str("Task<");
        output.push_str(high_level_return);
        output.push_str("> ");
    }
    output.push_str(method_name);
    render_flattened_generic_parameters(output, model, overload);
    output.push('(');
    let mut has_parameters = false;
    render_flattened_parameters(output, model, api_plan, overload, &mut has_parameters);
    if model_has_options_fields(model, api_plan) {
        render_parameter_separator(output, &mut has_parameters);
        output.push_str(&operation_options_type_name(operation));
        if model_options_required(model, api_plan) {
            output.push_str(" options");
        } else {
            output.push_str("? options = null");
        }
    }
    output.push_str(")\n    {\n");
}

fn render_flattened_parameters(
    output: &mut String,
    model: &PlannedModel,
    api_plan: &ApiPlan,
    overload: &FlattenedOverload,
    has_parameters: &mut bool,
) {
    for field in &model.fields {
        if field.function.is_none() {
            continue;
        }
        if let Some(nested_model) = flattened_nested_model(field, api_plan) {
            for nested_field in &nested_model.fields {
                if nested_field.function.is_none() {
                    continue;
                }
                let nested_required = field.required && nested_field.required;
                render_parameter_separator(output, has_parameters);
                output.push_str(&flattened_nested_parameter_type(
                    nested_model,
                    nested_field,
                    api_plan,
                ));
                output.push(' ');
                output.push_str(&csharp_parameter_name(&nested_field.authored_name));
                if !nested_required {
                    output.push_str(" = null");
                }
            }
            continue;
        }
        render_parameter_separator(output, has_parameters);
        output.push_str(&flattened_parameter_type(
            field,
            api_plan,
            overload.function_mode(field),
        ));
        output.push(' ');
        output.push_str(&csharp_parameter_name(&field.authored_name));
        if !field.required {
            output.push_str(" = null");
        }
    }
}

fn render_parameter_separator(output: &mut String, has_parameters: &mut bool) {
    if *has_parameters {
        output.push_str(", ");
    } else {
        *has_parameters = true;
    }
}

fn render_flattened_generic_parameters(
    output: &mut String,
    model: &PlannedModel,
    overload: &FlattenedOverload,
) {
    if !overload.has_expression_functions() {
        return;
    }
    let mut generics = vec!["TWorkflow".to_string()];
    if model.fields.iter().any(|field| {
        matches!(
            overload.function_mode(field),
            FlattenedFunctionMode::Expression
        ) && field
            .function
            .as_ref()
            .is_some_and(function_has_result_type_parameter)
    }) {
        generics.push("TResult".to_string());
    }
    output.push('<');
    output.push_str(&generics.join(", "));
    output.push('>');
}

fn render_flattened_method_body(
    output: &mut String,
    operation: &PlannedOperation,
    model: &PlannedModel,
    api_plan: &ApiPlan,
    overload: &FlattenedOverload,
) {
    let options_required = model_options_required(model, api_plan);
    for field in &model.fields {
        if field.function.is_some()
            && matches!(
                overload.function_mode(field),
                FlattenedFunctionMode::Expression
            )
        {
            output.push_str("        var (");
            output.push_str(&csharp_parameter_name(&format!(
                "{}Method",
                field.authored_name
            )));
            output.push_str(", ");
            output.push_str(&csharp_parameter_name(&format!(
                "{}Args",
                field.authored_name
            )));
            output.push_str(") = ExtractCall(");
            output.push_str(&csharp_parameter_name(&field.authored_name));
            output.push_str(");\n");
        }
    }
    output.push_str("        var request = new ");
    output.push_str(&csharp_type_name(&model.name));
    output.push_str("\n        {\n");
    for field in &model.fields {
        output.push_str("            ");
        output.push_str(&field_property_name(field));
        output.push_str(" = ");
        if let Some(nested_model) = flattened_nested_model(field, api_plan) {
            output.push_str(&nested_model_init_expr(
                field,
                nested_model,
                options_required,
            ));
        } else if field.function.is_some()
            && matches!(
                overload.function_mode(field),
                FlattenedFunctionMode::Expression
            )
        {
            output.push_str(&function_name_expression(field));
        } else if field.function_args
            && function_args_field_mode(model, field, overload)
                .is_some_and(|mode| matches!(mode, FlattenedFunctionMode::Expression))
        {
            let function_field = model
                .fields
                .iter()
                .find(|candidate| {
                    candidate
                        .function
                        .as_ref()
                        .is_some_and(|function| function.arg_fields.contains(&field.proto_name))
                })
                .expect("function args field should have a function field");
            output.push_str(&csharp_parameter_name(&format!(
                "{}Args",
                function_field.authored_name
            )));
        } else if field.function.is_none() {
            output.push_str(&option_field_expr(field, options_required));
        } else {
            output.push_str(&csharp_parameter_name(&field.authored_name));
        }
        output.push_str(",\n");
    }
    output.push_str("        };\n");
    output.push_str("        return ");
    output.push_str(&csharp_type_name(&operation.name));
    output.push_str("Async(request);\n");
    output.push_str("    }\n\n");
}

fn function_name_expression(field: &PlannedField) -> String {
    let method_var = csharp_parameter_name(&format!("{}Method", field.authored_name));
    let extractor = field
        .function
        .as_ref()
        .and_then(|function| function.name_extractor.as_deref())
        .expect("expression overloads require function name extractors");
    format!("{extractor}({method_var})")
}

fn function_args_field_mode(
    model: &PlannedModel,
    args_field: &PlannedField,
    overload: &FlattenedOverload,
) -> Option<FlattenedFunctionMode> {
    model
        .fields
        .iter()
        .find(|candidate| {
            candidate
                .function
                .as_ref()
                .is_some_and(|function| function.arg_fields.contains(&args_field.proto_name))
        })
        .map(|function_field| overload.function_mode(function_field))
}

fn flattened_nested_model<'a>(
    field: &PlannedField,
    api_plan: &'a ApiPlan,
) -> Option<&'a PlannedModel> {
    let PlannedFieldKind::Singular(PlannedValueType::Message(message)) = &field.kind else {
        return None;
    };
    let nested_model = api_plan.models.get(&message.info.full_name)?;
    nested_model.flatten_in_api.then_some(nested_model)
}

fn render_operation_options_type(
    output: &mut String,
    operation: &PlannedOperation,
    api_plan: &ApiPlan,
) {
    let Some(model) = api_plan.models.get(&operation.input.info.full_name) else {
        return;
    };
    if !operation_has_flattened_convenience(operation, model, api_plan)
        || !model_has_options_fields(model, api_plan)
    {
        return;
    }

    render_xml_summary(output, "", dotnet_doc(&operation.doc));
    output.push_str("public class ");
    output.push_str(&operation_options_type_name(operation));
    output.push_str("\n{\n");
    for field in &model.fields {
        if let Some(nested_model) = flattened_nested_model(field, api_plan) {
            for nested_field in &nested_model.fields {
                if nested_field.function.is_some() {
                    continue;
                }
                render_field_xml_doc(output, "    ", nested_field);
                output.push_str("    public ");
                if field.required && nested_field.required {
                    output.push_str("required ");
                }
                output.push_str(&flattened_nested_parameter_type(
                    nested_model,
                    nested_field,
                    api_plan,
                ));
                output.push(' ');
                output.push_str(&field_property_name(nested_field));
                output.push_str(" { get; set; }");
                output.push('\n');
            }
            continue;
        }
        if field.function.is_some() {
            continue;
        }
        let field_type = flattened_parameter_type(field, api_plan, FlattenedFunctionMode::String);
        render_field_xml_doc(output, "    ", field);
        output.push_str("    public ");
        if field.required {
            output.push_str("required ");
        }
        output.push_str(&field_type);
        output.push(' ');
        output.push_str(&field_property_name(field));
        output.push_str(" { get; set; }");
        output.push('\n');
    }
    output.push_str("}\n\n");
}

fn operation_options_type_name(operation: &PlannedOperation) -> String {
    csharp_type_name(&format!("{}Options", operation.name))
}

fn model_has_options_fields(model: &PlannedModel, api_plan: &ApiPlan) -> bool {
    model.fields.iter().any(|field| {
        if let Some(nested_model) = flattened_nested_model(field, api_plan) {
            nested_model
                .fields
                .iter()
                .any(|nested_field| nested_field.function.is_none())
        } else {
            field.function.is_none()
        }
    })
}

fn model_options_required(model: &PlannedModel, api_plan: &ApiPlan) -> bool {
    model.fields.iter().any(|field| {
        if let Some(nested_model) = flattened_nested_model(field, api_plan) {
            field.required
                && nested_model
                    .fields
                    .iter()
                    .any(|nested_field| nested_field.required && nested_field.function.is_none())
        } else {
            field.required && field.function.is_none()
        }
    })
}

fn nested_model_init_expr(
    field: &PlannedField,
    model: &PlannedModel,
    options_required: bool,
) -> String {
    let checks = model
        .fields
        .iter()
        .filter(|nested_field| nested_field.function.is_none())
        .map(|nested_field| {
            format!(
                "{} != null",
                option_nested_field_expr(field, nested_field, options_required)
            )
        })
        .collect::<Vec<_>>()
        .join(" || ");
    let assignments = model
        .fields
        .iter()
        .filter(|nested_field| nested_field.function.is_none())
        .map(|nested_field| {
            let value_expr = option_nested_field_expr(field, nested_field, options_required);
            format!("{} = {}", field_property_name(nested_field), value_expr)
        })
        .collect::<Vec<_>>()
        .join(", ");
    if field.required {
        format!("new {} {{ {assignments} }}", csharp_type_name(&model.name))
    } else {
        format!(
            "{checks} ? new {} {{ {assignments} }} : null",
            csharp_type_name(&model.name)
        )
    }
}

fn option_field_expr(field: &PlannedField, options_required: bool) -> String {
    if options_required || field.required {
        format!("options.{}", field_property_name(field))
    } else {
        format!("options?.{}", field_property_name(field))
    }
}

fn option_nested_field_expr(
    field: &PlannedField,
    nested_field: &PlannedField,
    options_required: bool,
) -> String {
    if options_required || (field.required && nested_field.required) {
        format!("options.{}", field_property_name(nested_field))
    } else {
        format!("options?.{}", field_property_name(nested_field))
    }
}

fn function_has_result_type_parameter(function: &FunctionFieldSpec) -> bool {
    function.result_type_parameter.is_some()
}

fn render_operation_flattened_extension(
    output: &mut String,
    operation: &PlannedOperation,
    method_name: &str,
    model: &PlannedModel,
    raw_return: &str,
    high_level_return: &str,
    api_plan: &ApiPlan,
) {
    for overload in flattened_overloads(model) {
        render_operation_flattened_overload(
            output,
            operation,
            method_name,
            model,
            raw_return,
            high_level_return,
            api_plan,
            &overload,
        );
    }
}

fn model_has_extractable_function_fields(model: &PlannedModel) -> bool {
    let mut has_function_fields = false;
    for field in &model.fields {
        if let Some(function) = &field.function {
            has_function_fields = true;
            if function.name_extractor.is_none() {
                return false;
            }
        }
    }
    has_function_fields
}

